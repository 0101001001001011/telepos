import 'dart:convert';
import 'dart:io';

import 'package:flutter_test/flutter_test.dart';

/// Строки возврата переведены во всех пяти словарях, а не только в русском.
///
/// # Тринадцатый случай «правка без пробы», и он мой
///
/// Круг правки нашёл, что я завёл три ключа возврата в казахский, киргизский
/// и узбекский — и **не охранял их ничем**: поиска по ним в `test/` не было
/// ни одного. Вернуть русскую строку можно было при полностью зелёном наборе,
/// а для кассира русский текст в казахском словаре — ровно то же, что
/// отсутствующий ключ.
///
/// Соседний сторож (`section_keys_test.dart`) проверяет **одиннадцать чужих**
/// ключей мастера настройки, и его проверка «не осталось русским» смотрит
/// только на `en` и `uz`: **казахский и киргизский на копию русского не
/// проверяются вовсе**. Расширять его я не стал — он про свою работу и свой
/// список; здесь список возврата и своя проверка, зато полная по языкам.
///
/// # Что считается непереведённым
///
/// Копия русской строки. Это самая частая форма пропущенного перевода:
/// «ключ есть, строка не пустая» его пропускает, потому что строка **есть**.
///
/// Предел назван прямо: сторож не отличает перевод от бессмыслицы на нужном
/// алфавите — он ловит только «не тронуто». Проверять качество перевода
/// нечем, и притворяться, что можно, было бы хуже отсутствия сторожа.
const _refundKeys = [
  // Отказ кассы на операции возврата — задача 20, круг правки блокера.
  'refundRefused',
  // Обрыв подписки на черновик — та же задача, круг правки живого прогона.
  'refundConnectionLost',
  'refundConnectionLostHint',
  // Сертификаты при возврате — решения заказчика 2026-09-16. Оба отказа
  // читает кассир у кассы, и русская строка в казахском словаре для него
  // ровно то же, что отсутствующий ключ.
  'errorCertificateCashRefundRefused',
  'errorCertificatePaysCertificate',
];

const _locales = ['en', 'ru', 'kk', 'ky', 'uz'];

Map<String, dynamic> _arb(String locale) =>
    jsonDecode(File('assets/i18n/intl_$locale.arb').readAsStringSync())
        as Map<String, dynamic>;

void main() {
  test('разбор словарей что-то нашёл', () {
    // Без этого проверки ниже зелены на пустых картах: переименование файла
    // сняло бы охрану молча.
    for (final locale in _locales) {
      expect(
        _arb(locale).length,
        greaterThan(1000),
        reason: 'словарь $locale разобран не был',
      );
    }
  });

  for (final locale in _locales) {
    test('в $locale есть строки возврата и они не пустые', () {
      final map = _arb(locale);
      for (final key in _refundKeys) {
        expect(
          map.containsKey(key),
          isTrue,
          reason:
              '$locale: нет ключа $key — кассир увидит имя ключа вместо '
              'причины отказа',
        );
        expect(
          (map[key] as String).trim(),
          isNotEmpty,
          reason: '$locale: $key пустой',
        );
      }
    });
  }

  test('строка возврата не осталась непереведённым русским', () {
    final ru = _arb('ru');
    // Все четыре нерусских языка, а не два: у соседнего сторожа `kk` и `ky`
    // выпадали из этой проверки, и найдено это было тем же кругом.
    for (final locale in ['en', 'kk', 'ky', 'uz']) {
      final map = _arb(locale);
      for (final key in _refundKeys) {
        expect(
          map[key],
          isNot(ru[key]),
          reason:
              '$locale: $key совпадает с русским — перевода нет. Для кассира '
              'это то же самое, что отсутствующий ключ',
        );
      }
    }
  });

  test('подстановка причины сохранена во всех языках', () {
    // `refundRefused` показывает **текст кассы**: потеряй перевод `{reason}`
    // — и отказ снова станет безымянным, ровно тем «Ошибка», ради ухода от
    // которой ключ и заводился.
    for (final locale in _locales) {
      expect(
        _arb(locale)['refundRefused'] as String,
        contains('{reason}'),
        reason: '$locale: причина отказа выпала из строки',
      );
    }
  });
}
