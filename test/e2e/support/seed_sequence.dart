/// Уникальный хвост для посева проб — задача 40.
///
/// Прежний посев брал уникальность из часов:
/// `'SO-TEST-${DateTime.now().microsecondsSinceEpoch}'`. Под Windows
/// `DateTime.now()` идёт шагом около миллисекунды, то есть «микросекунды» —
/// это миллисекунды, умноженные на тысячу, и два посева внутри одной
/// миллисекунды давали один номер: `UNIQUE constraint failed:
/// service_orders.order_number`. Краснота выглядела чувствительностью к
/// нагрузке и один раз была на неё списана, а была детерминирована.
library;

var _last = 0;

/// Следующее значение счётчика процесса.
///
/// Счётчик, а не часы: часы вообще не источник уникальности, они лишь
/// выглядят им, пока разрешение достаточно мелкое. Измерено на этой машине
/// (Windows 11): десять тысяч вызовов часов подряд дали **четыре** разных
/// значения.
///
/// Файлы проб живут каждый в своём изоляте, а база у каждого — своя, в
/// памяти, поэтому счётчику процесса не с кем столкнуться.
int nextSeed() => ++_last;
