/// Закрепляет `AppRoutes.publicRoutes` — правка «второй порядок» закрытия
/// долга безопасности (2026-08-22), пункт 2.
///
/// # Почему это отдельный сторож, а не строка в другом файле
///
/// Одна запись в `AppRoutes.publicRoutes` гасит **оба** сторожа разом —
/// десктопный (`app_router.dart`, `redirect`) и браузерный
/// (`setup_router.dart`, `redirect`) читают этот список раньше, чем проверяют
/// вход: `if (AppRoutes.publicRoutes.contains(currentPath)) return null;`.
/// Маршрут в этом списке достижим **без входа** — не просто без права, а
/// вообще без сеанса. До этой правки состав списка не был закреплён ни одним
/// тестом на настоящий список: `test/unit/migration/startup_flow_test.dart`
/// заводил **собственную локальную копию** из четырёх записей (без
/// `/network-settings`, добавленного позже) и проверял её же — такой тест не
/// может покраснеть, что бы ни стало с настоящим `AppRoutes.publicRoutes`, и
/// копия уже устарела на момент разбора.
///
/// # Обоснование каждой записи
///
/// | Маршрут | Почему достижим без входа |
/// |---|---|
/// | `/` (splash) | заставка сама решает, куда вести дальше — обязана
/// открыться до того, как известно, есть ли сеанс |
/// | `/login` | экран входа — вести на него после отказа входа можно, только
/// если он сам достижим без входа |
/// | `/initial-setup` | мастер первого запуска — на кассе без единого
/// пользователя входить ещё не в кого |
/// | `/restore-or-new` | развилка «восстановить бэкап / завести заново» —
/// тот же мастер, до первого пользователя |
/// | `/network-settings` | кнопка Wi-Fi стоит на каждом шаге мастера
/// (докстринг `setup_router.dart`) — без сети мастер не подключится к
/// серверу, а мастер идёт до первого пользователя |
///
/// Ни один из пяти не открывает данные кассы и не совершает операцию —
/// первые четыре ведут мастер до появления первого пользователя (после
/// которого войти уже есть в кого), пятый — системная настройка сети,
/// нужная самому мастеру, а не кассе.
library;

import 'package:flutter_test/flutter_test.dart';
import 'package:telepos/app/router/app_routes.dart';

/// Обоснование каждой записи — параллельно списку в докстринге файла, но
/// как данные теста: гарантирует, что у КАЖДОЙ строки `publicRoutes` есть
/// обоснование, а не только у тех, что попали в докстринг руками.
const _justifications = <String, String>{
  AppRoutes.splash:
      'заставка сама решает, куда вести дальше — обязана открыться до того, '
      'как известно, есть ли сеанс',
  AppRoutes.login:
      'экран входа — вести на него после отказа входа можно, только если он '
      'сам достижим без входа',
  AppRoutes.initialSetup:
      'мастер первого запуска — на кассе без единого пользователя входить '
      'ещё не в кого',
  AppRoutes.restoreOrNew:
      'развилка «восстановить бэкап / завести заново» — тот же мастер, до '
      'первого пользователя',
  AppRoutes.networkSettings:
      'кнопка Wi-Fi стоит на каждом шаге мастера — без сети мастер не '
      'подключится к серверу',
};

/// Маршруты, которым в `publicRoutes` заведомо не место — прямая
/// противоположность тому, ради чего заведена вся эта волна правок
/// (шестая/седьмая фазы «замка кассы»): попадание любого из них в этот
/// список означало бы, что данные или операция кассы открылись без входа
/// вовсе, не просто без права.
const _mustStayPrivate = <String>[
  AppRoutes.sale,
  AppRoutes.shift,
  AppRoutes.userManagement,
  AppRoutes.authSettings,
  AppRoutes.sessions,
  AppRoutes.terminalServiceSettings,
  AppRoutes.logJournal,
  AppRoutes.applianceSettings,
  AppRoutes.hardwareSettings,
  AppRoutes.settings,
];

void main() {
  test(
    'publicRoutes — ровно пять записей, каждая с обоснованием выше',
    () {
      expect(
        AppRoutes.publicRoutes.toSet(),
        _justifications.keys.toSet(),
        reason:
            'Новый маршрут в publicRoutes без записи в _justifications (и '
            'наоборот) красит именно этот тест — состав списка обязан быть '
            'решением, а не тихим пробелом: одна строка здесь гасит вход '
            'целиком, не только право.',
      );
    },
  );

  test('каждое обоснование непустое', () {
    for (final entry in _justifications.entries) {
      expect(
        entry.value.trim(),
        isNotEmpty,
        reason: '${entry.key} обязан иметь обоснование, а не пустую строку',
      );
    }
  });

  test(
    'ни один маршрут, читающий данные или совершающий операцию кассы, не '
    'попал в publicRoutes',
    () {
      final leaked = _mustStayPrivate
          .where(AppRoutes.publicRoutes.contains)
          .toList();
      expect(
        leaked,
        isEmpty,
        reason:
            'Эти маршруты обязаны требовать вход — попадание любого из них '
            'сюда означает, что данные кассы стали достижимы без сеанса '
            'вовсе, а не только без права: $leaked',
      );
    },
  );

  test(
    'publicRoutes не содержит дублей',
    () {
      expect(
        AppRoutes.publicRoutes.length,
        AppRoutes.publicRoutes.toSet().length,
      );
    },
  );
}
