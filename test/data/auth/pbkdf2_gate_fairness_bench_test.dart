/// Измерение стены `Pbkdf2Gate` на настоящих величинах прода — не тест на
/// «зелёное», а источник чисел для `fairqueue-and-perms-report.md`. Печатает
/// измеренное время ожидания честной попытки (другая QUIC-сессия) при заливе
/// в 10⁴ чужих попыток, разложенных на 1/10/200 сессий одного нападающего.
///
/// # Правка А БЛОКЕРА закрытия долга безопасности (2026-08-22)
///
/// До этой правки `Pbkdf2Gate` держал одну общую FIFO-очередь — залп в 10⁴
/// попыток одного нападающего вставал в ту же очередь, что и попытка
/// честного кассира: `throttle-cap-report.md` посчитал цену нападающему
/// (~17 минут на 10⁴ значений при `maxConcurrent: 2`, ~206 мс на проверку) —
/// это было ОДНО И ТО ЖЕ число, посчитанное с двух сторон одной очереди: те
/// же ~17 минут ждала бы и честная попытка, вставшая в тот же хвост.
///
/// Очередь стала круговой по ключу справедливости (QUIC-сессия) — этот файл
/// измеряет, сколько теперь реально ждёт честная попытка (отдельная сессия),
/// пришедшая ПОСЛЕ того, как нападающий уже выстроил свою очередь (худший
/// случай из задания, не средний).
///
/// Время виртуальное (`fake_async`), длительность одной проверки PBKDF2 —
/// настоящая измеренная величина прода (~206 мс, `pin_credential.dart`,
/// измерено 2026-08-02) — 10⁴ настоящих PBKDF2-деривации заняли бы порядка
/// получаса реального времени, прогон набора не может себе этого позволить
/// (тот же довод, что и у `login_throttle_wall_bench_test.dart`).
/// `fake_async` виртуализирует таймер (`Future.delayed`, здесь стоит вместо
/// настоящего PBKDF2), не подменяет саму очередь — `Pbkdf2Gate` здесь
/// настоящий.
library;

import 'dart:async';

import 'package:fake_async/fake_async.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:telepos/data/auth/pbkdf2_gate.dart';

void main() {
  const totalAttackerAttempts = 10000;
  const perCheck = Duration(milliseconds: 206);

  /// Заводит [attackerSessions] сессий нападающего, суммарно
  /// [totalAttackerAttempts] попыток, ВСЕ вставшие в очередь до того, как
  /// приходит единственная честная попытка (другая сессия) — худший случай:
  /// очередь нападающего уже выстроена целиком.
  ///
  /// Возвращает виртуальное время до того, как честная попытка получила
  /// ответ.
  Duration honestWait({required int attackerSessions}) {
    Duration? wait;
    fakeAsync((async) {
      final gate = Pbkdf2Gate(maxConcurrent: 2);
      Future<void> pbkdf2ish() => Future<void>.delayed(perCheck);

      final perSession = totalAttackerAttempts ~/ attackerSessions;
      for (var s = 0; s < attackerSessions; s++) {
        for (var i = 0; i < perSession; i++) {
          unawaited(gate.run(pbkdf2ish, key: 'attacker$s'));
        }
      }

      // Честная попытка — своя сессия, приходит последней по времени, когда
      // очередь нападающего уже вся выстроена.
      unawaited(
        gate.run(pbkdf2ish, key: 'honest').then((_) {
          wait = async.elapsed;
        }),
      );

      async.elapse(const Duration(hours: 6));
    });
    return wait!;
  }

  test(
    'измеренное ожидание честной сессии при заливе 10⁴ на 1/10/200 сессий '
    'нападающего',
    () {
      final w1 = honestWait(attackerSessions: 1);
      final w10 = honestWait(attackerSessions: 10);
      final w200 = honestWait(attackerSessions: 200);

      void report(String label, Duration d) {
        // ignore: avoid_print
        print('$label: ${d.inMilliseconds} мс (${d.inSeconds} с)');
      }

      report('1 чужая сессия  ', w1);
      report('10 чужих сессий ', w10);
      report('200 чужих сессий', w200);

      // Свойство, которое доказывает правку: ожидание растёт с числом
      // РАЗЛИЧНЫХ сессий нападающего (это и есть цена кругового обхода —
      // честная сессия должна дождаться своей очереди среди N ключей), но
      // остаётся на порядки меньше цены общей FIFO-очереди по числу ПОПЫТОК
      // (которая была бы ~10⁴ × 206мс / 2 ≈ 17 минут при ЛЮБОМ раскладе
      // сессий — то самое число из `throttle-cap-report.md`, посчитанное
      // как цена нападающему, а на деле — и цена честному тоже).
      const oldSharedFifoWait = Duration(milliseconds: 1030000); // ~17 мин

      for (final (label, wait) in [
        ('1', w1),
        ('10', w10),
        ('200', w200),
      ]) {
        expect(
          wait,
          lessThan(oldSharedFifoWait),
          reason:
              'при $label чужих сессиях честная попытка обязана ждать '
              'меньше, чем стоила бы общая FIFO-очередь по числу попыток '
              '(~17 минут) — иначе круговая раздача не работает, и залп '
              'снова держит честного кассира временем, зависящим от '
              'ПОПЫТОК нападающего, а не от числа его СЕССИЙ',
        );
      }

      // Растёт с числом сессий — не константа: с 1 сессией у нападающего
      // честная сессия — вторая в обходе (ждёт свой ход почти сразу), с 200
      // — двухсотпервая.
      expect(
        w1,
        lessThan(w10),
        reason: 'больше сессий нападающего — больше очередь до честного',
      );
      expect(w10, lessThan(w200));
    },
  );
}
