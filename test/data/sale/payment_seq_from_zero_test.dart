/// `Payments.seq` считается **от нуля на каждой попытке оплаты**.
///
/// # Зачем это отдельный сторож
///
/// Оговорку оставила задача 8 у объявления уникального ключа, и она
/// точна: новый ключ `{receiptNo, posId, seq}` защищает от двойного
/// взятия денег **только пока `seq` считается от нуля**. Подготовка чека
/// снимает платежи прошлой попытки (`paymentDao.deleteBySale`), и тогда
/// оба гонщика получают 0, 1, 2… и сталкиваются. `seq`, продолжающий
/// нумерацию прошлой попытки («максимум + 1»), превращает ключ в
/// **украшение**: гонщики получат разные номера и не столкнутся никогда.
///
/// И — это главное — **узнать об этом было бы неоткуда**. Набор остался
/// бы полностью зелёным: `payment_claim_race_test` проходит и так, и так,
/// потому что впереди ключа стоит заслон по состоянию чека
/// (`_stateClaimedForPayment`), и до столкновения дело не доходит на
/// счастливом пути. Ключ — страховка второго ряда, и проверить страховку
/// можно только спросив про неё прямо.
///
/// # Почему сторож здесь — на форму, а не на поведение
///
/// Сторож на поведение есть, и он в другом месте: `seq == [0, 1]` после
/// оплаты проверяют `local_payment_service_debt_toggle_test` (долг) и
/// `local_payment_service_test` (наличные с картой на один счёт). Он
/// нужен, но **дефекта он бы не поймал**: подготовка чека снимает платежи
/// прошлой попытки, и «максимум + 1» над пустой таблицей даёт те же 0, 1.
/// Поведение у верного и у порченого кода совпадает на всём счастливом
/// пути; расходятся они только под гонкой, которую набор не воспроизводит
/// надёжно.
///
/// Поэтому здесь сторож **на форму**: в дереве не должно быть ни одного
/// вычисления `seq` через максимум. И, раз он текстовый, он обязан
/// доказать, что умеет краснеть, — на подсадках, включая ту, что записана
/// в три строки.
library;

import 'dart:convert';
import 'dart:io';

import 'package:flutter_test/flutter_test.dart';

void main() {
  test('в дереве нет вычисления seq через максимум', () {
    // Сторож на форму. Читает исходники: `MAX(seq)`, `seq.max()`,
    // `maxSeq`, `seq + 1` — любое из них означало бы, что нумерация
    // продолжает чужую попытку.
    final hits = <String>[];

    for (final entity in Directory('lib').listSync(recursive: true)) {
      if (entity is! File || !entity.path.endsWith('.dart')) continue;
      if (entity.path.endsWith('.g.dart')) continue;
      final text = entity.readAsStringSync();
      // Смотрим только там, где речь о строках оплаты: `seq` есть и у
      // заказ-нарядов, и там «максимум + 1» законен — это номер строки
      // документа, а не защита от гонки.
      if (!text.contains('payments')) continue;
      final code = _codeOnly(text);
      for (final pattern in _forbidden) {
        if (pattern.hasMatch(code)) {
          hits.add('${entity.path}: ${pattern.pattern}');
        }
      }
    }

    expect(
      hits,
      isEmpty,
      reason: 'seq обязан считаться от нуля на каждой попытке — иначе '
          'уникальный ключ {receiptNo, posId, seq} становится украшением '
          'молча (оговорка задачи 8 у Payments.uniqueKeys)',
    );
  });

  group('сторож способен покраснеть — проверено на подсадках', () {
    // Сторож, не умеющий краснеть, — не сторож. Каждая строка ниже —
    // подсаженный дефект: так он выглядел бы в коде.
    test('однострочная форма ловится', () {
      expect(_matches('SELECT MAX(seq) + 1 FROM payments'), isTrue);
      expect(_matches('final n = maxSeq + 1;'), isTrue);
      expect(_matches('payments.seq.max()'), isTrue);
    });

    test('верная нумерация счётчиком дефектом НЕ считается', () {
      // Обратный полюс, и он стоил круга правки. Первая редакция
      // запрещала `seq + 1` — и покраснела на настоящем верном коде
      // `PaymentRepositoryImpl.insertPayments`, который нумерует пакет
      // от нуля счётчиком. Сторож, краснеющий на правильном решении,
      // хуже отсутствующего: его снимают вместе с защитой.
      expect(_matches('nextSeq[group] = seq + 1;'), isFalse);
      expect(_matches('seq: Value(index),'), isFalse);
    });

    test('форма, РАЗБИТАЯ НА ТРИ СТРОКИ, ловится тоже', () {
      // Прямой урок этой работы: сторож, шедший построчно, пропустил
      // копию, записанную в три строки. Здесь текст сначала сводится к
      // одной строке ([_codeOnly]), и разрыв перестаёт быть укрытием.
      expect(
        _matches('''
final next =
    (await maxOf(payments.seq))
        + 1;
'''),
        isTrue,
      );
    });

    test('прячущийся в комментарии дефектом не считается', () {
      // Обратный полюс: докстринг у самого ключа **описывает** запрещённую
      // форму — он обязан её называть, иначе оговорку не прочитать.
      // Сторож, краснеющий на объяснении, отключают в первый же день.
      expect(_matches('// nothing here about MAX(seq) + 1 at all'), isFalse);
      expect(_matches('/// `seq`, продолжающий нумерацию («максимум + 1»)'),
          isFalse);
    });

    test('чужой seq мимо оплаты не задевается', () {
      // Заказ-наряды нумеруют строки документа тем же словом, и
      // «максимум + 1» там законен. Отбор — по упоминанию `payments` в
      // файле; здесь проверяется, что отбор вообще что-то отбирает.
      expect(
        File('lib/data/database/daos/service_order_dao.dart')
            .readAsStringSync()
            .contains('payments'),
        isFalse,
      );
    });
  });
}

/// Исходник без комментариев и без переводов строк.
///
/// Оба преобразования обязательны, и оба измерены на этой же работе.
/// **Комментарии** — потому что докстринг у `Payments.uniqueKeys`
/// описывает запрещённую форму словами и обязан её называть. **Перевод
/// строки** — потому что сторож, шедший построчно, уже однажды пропустил
/// копию, записанную в три строки.
String _codeOnly(String source) {
  final withoutLineComments = const LineSplitter()
      .convert(source)
      .map((line) {
        final at = line.indexOf('//');
        return at < 0 ? line : line.substring(0, at);
      })
      .join(' ');
  return withoutLineComments
      .replaceAll(RegExp(r'/\*.*?\*/', dotAll: true), ' ')
      .replaceAll(RegExp(r'\s+'), ' ');
}

/// Запрещена **не арифметика, а чтение максимума**.
///
/// Первая редакция запрещала `seq + 1` и покраснела на верном коде:
/// `PaymentRepositoryImpl.insertPayments` нумерует пакет счётчиком
/// (`nextSeq[group] = seq + 1`), и это ровно та нумерация от нуля,
/// которую сторож обязан защищать. Сторож, запрещающий правильное
/// решение, — не сторож, а препятствие: его снимут, и вместе с ним
/// уйдёт защита.
///
/// Дефект — в **источнике** числа: `MAX` из таблицы, `seq.max()`,
/// `maxSeq`, `maxOf(payments.seq)`. Отсюда и выражения: слово `max`
/// рядом со словом `seq`, в любом порядке и в любом написании.
final _forbidden = <RegExp>[
  RegExp(r'\bmax\w*\b[^;]{0,40}\bseq\b', caseSensitive: false),
  RegExp(r'\bseq\b[^;]{0,40}\bmax\w*\b', caseSensitive: false),
  // Третье выражение — не украшение. Первые два пропускают **одно
  // слово**: в `maxSeq` слово `seq` не отделено границей, `\w*` съедает
  // его целиком, и «максимум» с «номером» оказываются одним
  // идентификатором. Пропуск найден подсадкой, а не рассуждением.
  RegExp(r'max\w*seq', caseSensitive: false),
];

bool _matches(String source) {
  final code = _codeOnly(source);
  return _forbidden.any((p) => p.hasMatch(code));
}
