/// Измерение стены `LoginThrottle` на настоящих величинах прода — не тест
/// на «зелёное», а источник чисел для `throttle-cap-report.md`. Печатает
/// измеренную стоимость подбора 10⁴ значений PIN для последовательного
/// нападающего и для параллельного на 20/100/1000 одновременных «потоков»
/// (в терминах этого файла — не настоящих ОС-потоков, а параллельных
/// вызывающих циклов, каждый из которых ждёт свой ответ, прежде чем послать
/// следующую попытку: модель нападающего с несколькими открытыми
/// соединениями, каждое из которых честно ждёт сервер).
///
/// Время виртуальное (`fake_async`) — величины прода настоящие (`baseDelay`
/// = 1 с, `maxDelay` = 30 с, без масштабирования 1:1000): 10⁴ неудач при
/// потолке 30 с стоили бы ~83 часа настоящего времени прогона набора, чего
/// этот файл себе позволить не может. `fake_async` виртуализирует таймер
/// (`Timer`/`Future.delayed`), не подменяет саму очередь — `LoginThrottle`
/// здесь настоящий, без `sleep:`/`clock:` подмены.
///
/// # Правка 1 БЛОКЕРА закрытия долга (2026-08-22): утверждение перевёрнуто
///
/// До этой правки `LoginThrottle` держал очередь по ключу (`_queueTail`,
/// снята), и этот файл утверждал обратное тому, что утверждает теперь:
/// параллельный подбор стоил **не дешевле** последовательного, потому что
/// каждая попытка вставала в общий хвост чужих, ещё не доигравших ожиданий.
/// Разбор нашёл в этом самую цену: то же самое, чем очередь удорожала
/// параллельного нападающего, удорожало и честную попытку, вставшую в тот
/// же хвост, — 200 чужих неудач держали её 1 ч 36 мин, 10⁴ — 83 часа
/// (`login_throttle.dart`, докстринг класса, «БЛОКЕР»; измерено поимённо
/// `login_throttle_test.dart`, группа «правка 1 БЛОКЕРА»).
///
/// Очередь снята, и параллельный подбор снова дешевле последовательного —
/// **сознательно**, не регрессия: throughput нападающего теперь ограничен
/// не этим классом, а `Pbkdf2Gate` (`lib/data/auth/pbkdf2_gate.dart`),
/// который этот файл не измеряет — он зовёт только
/// [LoginThrottle.penalizeFailure], никогда `LocalAuthRepository.login()`.
/// Числа ниже — цена **этой** стены в изоляции: то, что осталось после
/// снятия очереди, не полная цена подбора на настоящей кассе (та зависит
/// ещё и от предела `Pbkdf2Gate`, посчитана отдельно в
/// `throttle-cap-report.md`).
library;

import 'dart:async';

import 'package:fake_async/fake_async.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:telepos/backend/login_throttle.dart';

void main() {
  const totalGuesses = 10000;

  /// Прогоняет [totalGuesses] неудач по одному ключу, разложенных на
  /// [workers] одновременных «потоков» нападающего (1 — честно
  /// последовательно, один за другим). Каждый «поток» сам по себе
  /// последователен — ждёт свою попытку, прежде чем послать следующую, —
  /// параллелизм только между потоками. Возвращает виртуальное время до
  /// того, как доиграла самая последняя из них — общую стену атаки.
  Duration bruteForce(int workers) {
    Duration? wall;
    fakeAsync((async) {
      final throttle = LoginThrottle();
      final perWorker = totalGuesses ~/ workers;
      final extra = totalGuesses % workers;
      var remaining = totalGuesses;

      Future<void> worker(int count) async {
        for (var i = 0; i < count; i++) {
          await throttle.penalizeFailure(terminalId: 1, userId: 1);
          remaining--;
          if (remaining == 0) wall = async.elapsed;
        }
      }

      for (var w = 0; w < workers; w++) {
        final count = perWorker + (w < extra ? 1 : 0);
        if (count > 0) unawaited(worker(count));
      }

      async.elapse(const Duration(days: 5));
    });
    return wall!;
  }

  test(
    'измеренная стоимость подбора 10⁴ PIN: последовательно и параллельно '
    'на 20/100/1000 потоков',
    () {
      final sequential = bruteForce(1);
      final w20 = bruteForce(20);
      final w100 = bruteForce(100);
      final w1000 = bruteForce(1000);

      void report(String label, Duration d) {
        final h = d.inSeconds / 3600;
        // ignore: avoid_print
        print(
          '$label: ${d.inSeconds} с (${h.toStringAsFixed(2)} ч, '
          '${d.inMilliseconds} мс)',
        );
      }

      report('последовательно (1 поток)', sequential);
      report('параллельно, 20 потоков  ', w20);
      report('параллельно, 100 потоков ', w100);
      report('параллельно, 1000 потоков', w1000);

      // Не изменилось правкой 1 БЛОКЕРА: последовательный нападающий сам
      // ждёт каждый ответ, прежде чем послать следующую попытку — очередь
      // класса тут ни при чём, цена целиком в `_delayForCount`, который не
      // трогали. 299791 секунда (83 ч 16 мин) — точное число, посчитанное
      // аналитически (докстринг `LoginThrottle`): сумма `_delayForCount(c)`
      // по всем c = 0..9999 при умолчаниях класса (graceFailures: 2,
      // baseDelay: 1с, maxDelay: 30с) — льгота на первые три (счёт 0, 1, 2),
      // затем 1+2+4+8+16 с на четвёртую-восьмую неудачи, дальше потолок 30с
      // на оставшиеся 9992.
      expect(
        sequential,
        const Duration(seconds: 299791),
        reason:
            'выключенный или ослабленный замок обязан провалить именно эту '
            'проверку — разница с самим собой (старая формулировка) '
            'проходила бы и на нуле',
      );

      // Главное утверждение правки 1 БЛОКЕРА — перевёрнутое: параллельный
      // подбор обязан быть ДЕШЕВЛЕ последовательного, а не тем же самым.
      // Дороже он был бы только если бы очередь по ключу вернулась — то
      // есть если бы честная попытка снова начала наследовать сумму чужих
      // задержек, а не только максимум своей.
      //
      // Числа не произвольны: при W потоках, каждый из которых ждёт свой
      // ответ, глобальный счёт неудач по ключу растёт на каждую попытку
      // любого потока, и после ~8 неудач (льгота + удвоение до потолка)
      // каждая следующая попытка любого потока стоит ровно [maxDelay] (30
      // с) — а таких попыток на поток остаётся ~totalGuesses / W. Отсюда и
      // измеренные 15000 с (20 потоков), 3000 с (100), 300 с (1000): все
      // три — множители 30 с × (10000 / W), с точностью до ошибки
      // округления `~/`.
      for (final (workers, wall) in [(20, w20), (100, w100), (1000, w1000)]) {
        expect(
          wall,
          lessThan(sequential),
          reason:
              'параллельный подбор на $workers потоков обязан быть дешевле '
              'последовательного — иначе очередь по ключу вернулась, и с '
              'ней вернулся блокер (честная попытка снова наследует сумму '
              'чужих задержек)',
        );
      }
    },
  );
}
