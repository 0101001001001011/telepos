import 'package:telepos/core/constants/permission_keys.dart';
import 'package:telepos/domain/discount/discount_policy.dart';

/// Полномочия «всё разрешено» для проб, которым скидка нужна как **фон**, а
/// не как предмет.
///
/// Задача 12 сделала [DiscountAuthority] обязательным доводом трёх команд
/// корзины — и правильно сделала: забыть довод нельзя по сборке. Но
/// тридцать с лишним проб, назначающих скидку по дороге к чему-то другому
/// (копейка в фискальном конверте, слияние строк, акции, снимок по проводу),
/// про право и предел не спрашивают вовсе. Собирать в каждой свой довод
/// значило бы размножить решение, которое у всех одно.
///
/// **Роль — владелец (0), и это не «поудобнее».** У владельца нет своей
/// строки в `DiscountLimits`, значит действует умолчание миграции — сто
/// процентов. То есть проба, взявшая этот довод, ведёт себя ровно как касса
/// **до** задачи 12: предел не мешает, право есть. Ни одна из них поэтому не
/// перестала проверять то, что проверяла.
///
/// Пробы, для которых предмет — сам предел, этим доводом **не**
/// пользуются: `test/data/sale/discount_authority_test.dart` строит свои
/// роли и наборы прав руками, иначе проверял бы удобство, а не правило.
const fullDiscountAuthority = DiscountAuthority(
  roleIndex: 0,
  // `op.deferSale` — с задачи 28 корзина читает и его: откладывание и подъём
  // стали командами с правом, и фон «всё разрешено» обязан его нести.
  //
  // `op.issueCertificate` — с ревизии второго фронта 2026-09-19:
  // `CertificateIssuer.issue` стал требовать полномочий доводом, а девяносто
  // восемь проб выпускают бумажку **по дороге** к чему-то другому (оплата
  // сертификатом, возврат, итоги смены, фискальный конверт) и про право не
  // спрашивают вовсе.
  //
  // **Умолчаний роли у этого ключа нет** (докстринг
  // `PermissionKeys.opIssueCertificate`): он не достаётся никому «сам собой»,
  // и здесь назван поимённо, как и прочие. Роль 0 — владелец, а владелец в
  // продукте получает `allPermissions` в обход таблицы; фон «всё разрешено»
  // этим и является.
  permissions: {
    PermissionKeys.opSellDiscount,
    PermissionKeys.opEditPrice,
    PermissionKeys.opDeferSale,
    PermissionKeys.opIssueCertificate,
  },
);
