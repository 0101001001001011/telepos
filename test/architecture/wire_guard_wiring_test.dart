@Tags(['architecture'])
library;

/// Сторож на **подключение** сторожа — круг правки 4 задачи 19 «Продажи с
/// браузерного терминала».
///
/// Сверка «место сеанса == место сессии сейчас» (`WireGuard._boundTerminalId`)
/// существует в продукте ровно одной строкой: `main.dart` передаёт
/// `boundTerminalId: server.operations.terminalForSessionKey` в
/// `wireGuardForTill`. Довод необязателен по построению (см. его докстринг:
/// наборы, проверяющие другие ветки сторожа, не обязаны поднимать карту
/// привязок), и это значит, что **единственную строку, которой охрана вообще
/// действует, можно удалить молча**.
///
/// Измерено разбором круга 4, а не предположено: с закомментированной строкой
/// `test/architecture/ test/backend/` дают **282 passed, 0 failed**, а
/// `dart analyze` — ноль ошибок. То есть до этой пробы у охраны не было
/// красного состояния на своём собственном подключении.
///
/// Проверка текстовая, потому что проверяемое — сборка процесса: `main.dart`
/// под тестом не поднимается (у него `runApp`, окно, FFI и живой QUIC), и
/// единственный способ утверждать что-то о его строках — читать их. Тот же
/// приём и тот же довод, что у `local_api_always_starts_test.dart` рядом.
import 'dart:io';

import 'package:flutter_test/flutter_test.dart';

/// Комментарии и строковые литералы здесь не выкусываются: проверяется
/// наличие вызова, а спрятать его в комментарий и считать подключённым —
/// ошибка, которую эта проба и обязана поймать. Поэтому ищется строка,
/// **не начинающаяся** с `//`.
List<String> _codeLines(String path) => File(path)
    .readAsLinesSync()
    .map((line) => line.trim())
    .where((line) => !line.startsWith('//') && !line.startsWith('///'))
    .toList();

void main() {
  test('main.dart подключает сторожу карту привязок сессий', () {
    final lines = _codeLines('lib/main.dart');

    expect(
      lines.any((l) => l.contains('wireGuardForTill(')),
      isTrue,
      reason:
          'сторож провода собирается в main.dart — если сборка переехала, '
          'эту пробу надо переписать под новое место, а не снять',
    );
    expect(
      lines.any(
        (l) => l.contains(
          'boundTerminalId: server.operations.terminalForSessionKey',
        ),
      ),
      isTrue,
      reason:
          'без этого довода сторож не сверяет место сеанса с местом сессии, '
          'и токен, предъявленный после перепривязки, снова годится: круг '
          'правки 3 задачи 19, дыра доводила до чужих денег. Довод '
          'необязателен по построению (наборы других веток сторожа не '
          'поднимают карту привязок), поэтому его пропажу не поймает ни '
          'сборка, ни один другой тест',
    );
  });

  test('сборка сторожа умеет принимать эту карту', () {
    // Обратная половина: проба выше ищет строку в `main.dart`, и если бы
    // довод исчез из самой сборки, она краснела бы там же — но по неверной
    // причине («забыли в main»), уводя разбирающего не туда. Здесь названо
    // прямо: довод обязан существовать в `wireGuardForTill`.
    final lines = _codeLines('lib/backend/till_wire_guard.dart');

    expect(
      lines.any((l) => l.contains('boundTerminalId')),
      isTrue,
      reason:
          'сборка сторожа перестала принимать карту привязок — тогда и '
          'проверять в main.dart нечего, и обе пробы надо переписывать вместе',
    );
  });
}
