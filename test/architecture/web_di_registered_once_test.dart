import 'dart:io';

import 'package:flutter_test/flutter_test.dart';

/// Один контракт в браузерном контейнере регистрируется ровно один раз.
///
/// # Что это стоило: терминал не запускался вовсе
///
/// Живая приёмка 2026-09-07, первая же загрузка страницы на сведённом
/// дереве. Вкладка открывается, заголовок ставится, дальше ничего: главный
/// поток занят, снимок не снимается, в консоли одна строка —
///
/// ```
/// [TelePOS] uncaught: Invalid argument(s):
///   Type minified:b7L is already registered inside GetIt.
/// ```
///
/// `SessionAdmin` был зарегистрирован дважды: строкой из задачи «второй
/// порядок» (с полным докстрингом, объясняющим, зачем биндинг заведён) и
/// голой копией той же строки семнадцатью строками ниже. `GetIt` бросает на
/// втором `registerLazySingleton` того же типа, исключение уходит наружу из
/// `_run()` до `runApp`, и браузерный терминал не поднимается **никакой** —
/// ни продажи, ни возврата, ни входа.
///
/// # Почему это не поймала ни одна имеющаяся проверка
///
/// Дефекта **не было ни в одной из двенадцати ветвей** — измерено счётом по
/// каждой вершине: везде одна регистрация, две только у слияния. Внёс его
/// коммит слияния `55605da`, и внёс молча: строки разошлись на семнадцать
/// строк, поэтому текстового конфликта не возникло и разрешать было нечего.
///
/// `flutter build web` собирается — это отказ во время работы, а не при
/// сборке. Полный набор зелён — `main_web.dart` держит регистрацию внутри
/// `_run()`, а `_run()` тянет `dart:js_interop` и `WtSession.openFromDocument`
/// и на Dart VM не исполняется вовсе. `flutter test --platform chrome` на
/// этом дереве не поднимается (проверено 2026-09-07).
///
/// Значит остаётся текстовый сторож, и он обязан честно назвать границу.
///
/// # Чего этот сторож НЕ доказывает
///
/// Он читает исходник, а не поднимает контейнер. Он не увидит двойную
/// регистрацию, собранную в цикле или пришедшую из другого файла, и не
/// скажет, что каждый контракт, нужный экранам, **зарегистрирован**, — только
/// что ни один не зарегистрирован дважды. Обратную сторону («экран просит
/// контракт, которого нет») сторожит `browser_routes_test.dart`.
void main() {
  test('в lib/web/main_web.dart каждый контракт регистрируется один раз', () {
    final source = File('lib/web/main_web.dart').readAsStringSync();

    // `..registerLazySingleton<Contract>(`, `..registerSingleton<Contract>(`,
    // `..registerFactory<Contract>(` — форма каскада, которой написан
    // контейнер. Обобщённые доводы (`<Foo<Bar>>`) здесь не встречаются; если
    // встретятся, выражение их не разберёт и сторож промолчит — поэтому
    // ниже отдельно проверяется, что он вообще что-то нашёл.
    final pattern = RegExp(
      r'\.\.register(?:LazySingleton|Singleton|Factory)<(\w+)>',
    );

    final seen = <String, int>{};
    for (final match in pattern.allMatches(source)) {
      final contract = match.group(1)!;
      seen[contract] = (seen[contract] ?? 0) + 1;
    }

    // Сторож, ничего не нашедший, зелен по недосмотру, а не по порядку:
    // достаточно переименовать метод регистрации, и он замолчит навсегда.
    expect(
      seen.length,
      greaterThan(15),
      reason:
          'Сторож не нашёл регистраций в main_web.dart — значит форма записи '
          'контейнера изменилась, и он больше ничего не проверяет. Поправить '
          'выражение, а не порог.',
    );

    final duplicates = <String, int>{
      for (final entry in seen.entries)
        if (entry.value > 1) entry.key: entry.value,
    };

    expect(
      duplicates,
      isEmpty,
      reason:
          'Контракт зарегистрирован в GetIt дважды. Это не предупреждение: '
          'GetIt бросает на второй регистрации, исключение уходит из _run() '
          'до runApp, и браузерный терминал не запускается вовсе — ни один '
          'экран. Снять лишнюю строку, оставив ту, при которой есть довод.',
    );
  });
}
