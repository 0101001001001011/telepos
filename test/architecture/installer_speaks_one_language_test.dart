/// Установщик говорит на одном языке — на своём.
///
/// # Чем это оплачено
///
/// Найдено при подготовке съёмки главы 2 (2026-09-23), **до камеры**.
///
/// Установщик английский целиком: имя продукта, лицензия, порождённая из
/// `LICENSE` в корне, стандартные диалоги WiX. И при этом пять строк в
/// `TelePOS.wxs` были русскими — на любой машине, в любой стране:
///
/// * подпись обоих ярлыков («Касса TelePOS») — её видит каждый, кто наводит
///   мышь на значок;
/// * описание пакета — Windows показывает его в свойствах файла;
/// * `ARPCOMMENTS` — список установленных программ;
/// * два сообщения об отказе: не та разрядность и тихая установка без прав.
///
/// Последние два хуже прочих: их читают ровно тогда, когда что-то пошло не
/// так, то есть человеку и без того непросто.
///
/// # Почему здесь один язык, а не словарь
///
/// Установщик работает **до того, как касса заведена**. Ни страны, ни
/// выбранного языка ещё нет и взяться им неоткуда: выбор языка — шаг
/// мастера, а мастер запускается после установки. Подставлять сюда словарь
/// значило бы выбирать язык по тому, чего никто не называл.
///
/// Поэтому правило простое: **в установщике нет кириллицы в строках,
/// которые показываются человеку**. Комментарии разработчика — сколько
/// угодно, их читаем мы.
library;

import 'dart:io';

import 'package:flutter_test/flutter_test.dart';

final _cyrillic = RegExp('[Ѐ-ӿ]');

/// Свойства WiX, чьё значение видит человек.
///
/// Список поимённый, а не «все атрибуты»: в `Id`, `Guid` и `Target`
/// кириллицы быть и не может, а перечисление именно видимых говорит, что
/// проверяется, — и заставляет подумать, добавляя новое.
const _visible = [
  'Description',
  'DowngradeErrorMessage',
  'Message',
  'ARPCOMMENTS',
];

void main() {
  test('в установщике нет русских строк, которые видит человек', () {
    final source = File(
      'installer/windows/TelePOS.wxs',
    ).readAsLinesSync();

    final offenders = <String>[];
    for (var i = 0; i < source.length; i++) {
      final line = source[i];
      final code = line.trimLeft();
      // Комментарии XML — наши, и по-русски в них сказано больше.
      if (code.startsWith('<!--') || code.startsWith('*') ||
          code.startsWith('-->')) {
        continue;
      }
      if (!_cyrillic.hasMatch(line)) continue;

      final visible = _visible.any(
        (attr) =>
            line.contains('$attr="') ||
            line.contains('Id="$attr"'),
      );
      if (visible) offenders.add('${i + 1}: ${line.trim()}');
    }

    expect(
      offenders,
      isEmpty,
      reason:
          'установщик английский целиком, а эти строки его читателю говорят '
          'по-русски:\n${offenders.join('\n')}',
    );
  });
}
