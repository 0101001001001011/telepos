/// Сторож на правило денег на проводе (задача 6 плана «Продажа с
/// браузерного терминала», инвариант I159, `global-constraints.md`): деньги
/// — `Decimal` P18,S3, и по проводу едут **строкой**, никогда числом.
///
/// **Правило вводится этим сторожем впервые.** До этой задачи ни одна
/// операция провода деньги не возила: `ProgressFrame.value` (`wire_frame
/// .dart`) — единственное число в кадрах провода сегодня — это доля хода
/// выполнения от 0 до 1, не деньги, и лежит под ключом `value`, а не под
/// именем денежного поля. Значит у этого сторожа нет узла сравнения «было
/// зелено, стало красно» — его правота доказывается не историей прогонов, а
/// прямой диверсией (задача 6, круги правки 3–5).
///
/// # Три прежних круга и почему каждый не устоял
///
/// **Круг 1** искал денежный ключ из закрытого списка со значением, «не
/// похожим на строку». Переразбор задач 7/9/12/14 нашёл, что список имён
/// закрыт и отстаёт.
///
/// **Круг 2** добавил вторую сеть — «значение похоже на double» — и
/// диверсия поймала только две формы из пяти: голая ссылка, выражение,
/// целый литерал и `roundToDouble()` проходили мимо.
///
/// **Круг 3** перевернул проверку на «значение — буквально вызов
/// `wireMoney(...)`, и ничем иным» — единственная дверь вместо списка
/// запрещённых форм. Переразбор проверил **и это** диверсией и нашёл, что
/// regex `^wireMoney\(.*\)$` заякорен только по краям: `.*` в середине —
/// жадный и не считает скобки, поэтому проходили молча **склейка**
/// (`wireMoney(a) + wireMoney(b)`) и **цепочка** (`wireMoney(x)
/// .toString()`) — обе начинаются на `wireMoney(` и заканчиваются на `)`,
/// но лишний текст между истинным концом вызова и концом строки оставался
/// невидим для незаякоренной середины. Регекс заменён на подсчёт скобок —
/// [_isExactWireMoneyCall].
///
/// # Круг 4 (эта правка): подсчёт скобок не отличает код от комментария
///
/// Подсчёт скобок круга 3 умел находить настоящий конец вызова, но считал
/// **все** символы `(`/`)` в тексте, включая те, что живут внутри
/// комментария или строкового литерала. Переразбор показал диверсией, что
/// смайлика в доводах достаточно:
///
/// ```dart
/// 'price': wireMoney(x, // :)
/// ) + wireMoney(y)
/// ```
///
/// Счётчик закрывает вызов на скобке из смайлика `:)` — глубина уходит в
/// ноль раньше времени, извлечение значения ([_valueAfter], круг 3)
/// обрывается прямо там, и вся склейка `) + wireMoney(y)` остаётся не
/// увиденной вовсе. На приёме `Decimal.parse` результат такой склейки не
/// прочитал бы (это не число) — чек развалился бы, а сторож зелёный.
/// Проект русскоязычный, смайлики в комментариях — дело обычное, форма не
/// экзотическая.
///
/// **Правка:** обе функции, считающие скобки — [_valueAfter] и
/// [_isExactWireMoneyCall] (через общий [_skipCommentOrString]) — теперь
/// пропускают содержимое строчных (`//`) и блочных (`/* */`) комментариев
/// и строковых литератов (`'...'`/`"..."`, с учётом `\`-экранирования) при
/// подсчёте скобок и запятой, копируя их текст в результат **без изменения
/// глубины**. Дальше в тексте — настоящий код, и настоящая закрывающая
/// скобка находится там, где её видит компилятор Dart, а не там, где её
/// увидел наивный счётчик.
///
/// # Круг 5 (эта правка): три формы настоящего Dart, разобранные неверно
///
/// Круг 4 закрыл смайлик и обычный комментарий, но сам разбор комментариев
/// и строк внутри [_skipCommentOrString] был написан для простого случая:
/// одиночная кавычка, обычное экранирование, комментарий без вложенности.
/// Переразбор проверил три формы, все подтверждённые компилятором Dart как
/// валидные, и все три ловят разбор на этом упрощении — **в безопасную
/// сторону** (красят законный код, не пропускают нарушение, см. заголовок
/// файла):
/// 1. **Тройная кавычка с апострофом внутри** (`'''it's ok'''`) — прежний
///    разбор строк не знал о тройной кавычке вовсе и принимал одиночный
///    апостроф внутри за настоящую закрывающую кавычку, после чего терял
///    синхронизацию с текстом дальше.
/// 2. **Сырая строка с `\` перед закрывающей кавычкой** (`r'\'`) — прежний
///    разбор не смотрел на префикс `r` и всегда трактовал `\` как начало
///    экранирования, «проглатывая» настоящую закрывающую кавычку и убегая
///    искать следующую. Эта форма буквально жила в прежней версии этой же
///    функции (`text[j] == r'\''`).
/// 3. **Вложенный блочный комментарий** (`/* /* */ */` — Dart это
///    допускает) — прежний разбор искал первую попавшуюся `*/`, то есть
///    внутреннюю, и выходил «в код» раньше настоящего конца комментария.
///
/// **Правка:** [_skipCommentOrString] теперь смотрит на символ перед
/// кавычкой (`r`) и на две кавычки после первой (тройная форма) при разборе
/// строк, и ведёт счётчик вложенности, а не ищет первую закрывающую пару,
/// при разборе блочных комментариев.
///
/// **Что остаётся красным нарочно, не по недосмотру** (не тронуто этой
/// правкой, подтверждено заново). Тернарный выбор (`cond ? wireMoney(a) :
/// wireMoney(b)`) не проходит эту проверку — значение не начинается с
/// `wireMoney(` вовсе, и это **правильно**: годная замена —
/// `wireMoney(cond ? a : b)`, дверь внутри, а не снаружи, и она и так лучше
/// по стилю. Собственный маленький помощник, зовущий дверь внутри
/// (`_encodeMoney(x)`), тоже не проходит — сторож не умеет заглянуть в
/// тело вызванной функции и не притворяется, что умеет: если бы он считал
/// такую форму допустимой без проверки, это была бы ровно та дыра, ради
/// закрытия которой единственная дверь и заводилась.
///
/// # Круг 6 (задача 9): ключ искался в сыром тексте, а значение — в коде
///
/// Круг 5 закрыл разбор строк и комментариев в [_valueAfter] и
/// [_isExactWireMoneyCall] — но сам **поиск ключа** остался
/// `_moneyKeyPattern.allMatches(source)`, то есть шёл по сырому тексту мимо
/// [_skipCommentOrString]. Асимметрия была замечена в круге 5 и оставлена
/// долгом «закрыть при следующей правке этого файла»; правит его задача 9,
/// расширяя каталог операций.
///
/// Цена долга: закомментированный старый код с денежным ключом
/// (`// 'price': line.price,`) считался настоящей находкой. Направление
/// ошибки безопасное — красит законный код, не пропускает нарушение, — но
/// вредное именно для сторожа: он краснеет на месте, где нарушения нет, и
/// разбирающий ищет несуществующее. Задача 9 первой заводит в
/// `lib/domain/wire/` длинные докстринги, в которых пример кадра — обычное
/// дело.
///
/// **Правка:** [_moneyKeysInCode] идёт по тексту слева направо тем же
/// [_skipCommentOrString], что и обе прежние функции: комментарий
/// пропускается всегда, а на кавычке сначала пробуется сам ключ
/// (`matchAsPrefix`, якорь ровно здесь) — совпал, значит это поле кадра; не
/// совпал, значит обычный литерал, и он пропускается целиком. Безусловно
/// пропускать строки нельзя: ключ **сам** строковый литерал.
///
/// Пять тестов группы «круг 6»: ключ в строчном комментарии, в блочном, в
/// строковом литерале — не находки; настоящая находка **после**
/// комментария по-прежнему находится (иначе «починка» могла бы ослепить
/// сторож целиком и первый тест прошёл бы на сторожe, не находящем ничего);
/// тот же ключ в комментарии и в коде рядом — находка ровно одна.
///
/// # Круг 6б (круг правки 1 задачи 9): два денежных имени ехали вне списка
///
/// Разбор нашёл диверсией: `'totalDiscount': view.totalDiscount.toDouble()`
/// в кодеке оставлял **242 теста зелёными**. Причина — в самом якоре:
/// шаблон требует кавычку с **обеих** сторон имени, поэтому `'total'`
/// никогда не совпадёт с `'totalDiscount'` (после `total` идёт `D`, а не
/// закрывающая кавычка). Длинное имя не покрывалось коротким и проходило
/// мимо сторожа целиком; круговой обмен его тоже не ловил — `total`,
/// `subtotal` и `totalDiscount` производные геттеры `CartView`, они
/// пишутся на провод и не читаются обратно.
///
/// Дописаны **два** имени: `totalDiscount` (деньги по любому чтению) и
/// `stock` (остаток — `Decimal`, ехавший через дверь и не проверявшийся).
/// Решение задачи 6 было «предел не закрывать», то есть не заводить
/// открытый список, а не «имена не дописывать»: список остаётся закрытым,
/// но полным по тому, что на проводе действительно есть сегодня.
///
/// Побочно та же якорная кавычка делает список **безопасным к порядку**:
/// перечисление не может съесть соседа префиксом.
///
/// **Заведена обратная проверка — [moneyKeysOutsideList].** Полноту списка
/// доказать нельзя (сторож не знает типов), но одну сторону — можно: если
/// автор сам положил значение через дверь, поле денежное по его же
/// признанию, и имя обязано быть в списке. Именно она нашла бы `stock` без
/// диверсии. Побочное следствие: `stock` пришлось свести с тернарного
/// выбора на условный ключ в `productSearchResultToWireJson` — тернарный
/// вариант красен нарочно (см. выше).
///
/// Денежные ключи — тот же закрытый список, что и в кругах 1–3, плюс два
/// имени круга 6б: `price`, `total`, `totalDiscount`, `amount`, `discount`,
/// `quantity`, `subtotal`, `percent`, `stock`, `change`, `cashReceived`,
/// `claimedChange`. Список **закрыт** (открывать его заказчик просил не
/// здесь) — но не отстаёт: последние три имени принадлежат оплате (задача
/// 14) и на проводе сегодня не встречаются, остальные девять покрывают всё,
/// что везут `cart_codec.dart` и `sale_ops.dart`.
///
/// # Круг 7 (круг правки 2 задачи 9): сторож над сторожем сам не краснел
///
/// Обратная проверка [moneyKeysOutsideList], заведённая кругом 6б, звалась
/// **из единственного теста и только по настоящему дереву**, где обязана
/// вернуть пусто. Диверсия переразбора — прибить её к пустому списку —
/// оставила **32 теста из 32 зелёными**: механизм, заведённый ради того,
/// чтобы закрытый список не отставал молча, сам умирал молча. Ровно то, что
/// запрещает правило «проверка обязана краснеть».
///
/// Заведены синтетические пробы теми же формами, что у прямой сети (группа
/// «обратная проверка краснеет и молчит по делу»): дверь под новым именем —
/// находка; дверь под именем из списка — молчит; поле мимо двери с именем
/// вне списка — молчит, это признанный предел; тернарный выбор под именем
/// вне списка — **невидим обеим сетям**, и та же форма под именем из списка
/// краснеет прямой, то есть предел ровно в имени, а не в форме.
///
/// **Область расширена на `lib/backend/`.** Прежняя была выбрана по месту,
/// где кадры *описаны*, а не где *пишутся*, и структурно не могла найти
/// того, что снаружи. Переразбор нашёл `till_operations.dart:711` —
/// `'price': price?.sellingPrice?.toString()`, ответ `sale.ping`,
/// единственной операции продажи, реально летающей по проводу сегодня.
/// Значение было верное, дефекта денег не было; дефект был в том, что на
/// кассовой стороне двери не существовало **ни одной строкой**, а задача 10
/// напишет там девять таких же полей руками. Обработчик проведён через
/// дверь, область расширена — подробности в [_wireDirs].
///
/// **Почему `'price': null` в ветке «товар не найден» пришлось убрать
/// ключом, а не значением.** Сторож не умеет отличить «цены нет по
/// существу» от «цену забыли положить дверью» — и не должен: это ровно то
/// различение, на котором ломались круги 1–2. Ответ `sale.ping` теперь не
/// несёт ключа вовсе, а `ProductProbe` читает его `as String?`, для
/// которого отсутствие и пустое значение — одно и то же. Тот же приём, что
/// у `stock` в `productSearchResultToWireJson`.
///
/// # Круг 8 (круг правки 3 задачи 9): область не сторожилась ничем
///
/// Тот же класс, что круг 7, этажом выше: сторожился **разбор**, но не
/// **область**. Диверсия переразбора: свести [_wireDirs] к одному каталогу
/// провода — **36 из 36 зелёных**; свести к одному каталогу кассы — тоже 36
/// из 36. Проверка «обход не пуст» стоит с порогом в пять файлов, а каждый
/// каталог по отдельности его перебивает; «денежные поля вообще есть»
/// проходит по любому из двух.
///
/// Цена: завтрашняя уборка списка каталогов молча вывела бы из-под охраны
/// девять денежных полей, которые напишет задача 10 в
/// `till_operations.dart`, — и ни одна проба этого не заметила бы.
///
/// **Правка — одна проба** («обход накрывает КАЖДЫЙ каталог области»),
/// утверждающая наличие **конкретного файла из каждого каталога**, а не
/// число файлов: число перебивается чем угодно, имя — нет. Обе встречные
/// диверсии теперь краснеют и называют пропавший каталог поимённо.
///
/// **Почему ключ ищется только в кавычках, а не как любое двоеточие
/// `quantity:`.** Кадр провода — `Map<String, Object?>` с текстовыми
/// ключами в кавычках — это то, что на самом деле сериализуется в JSON и
/// уезжает по сети. Именованный довод конструктора domain-типа пишется без
/// кавычек вокруг имени и не является картой, идущей по проводу.
///
/// **Честно о пределе.** Раздел переписывался четырежды (круги 3, 4, 5, 6)
/// и трижды переразбор находил в нём то, что не было проверено на дереве, а
/// было заявлено на веру. Эта версия — по состоянию на круг 6, и в ней
/// оставлено только то, что проверено обходом или тестом при написании
/// именно этой правки:
/// - **Список денежных имён закрыт.** Переименованный или новый денежный
///   ключ вне списка (`price|total|totalDiscount|amount|discount|
///   quantity|subtotal|percent|stock|change|cashReceived|claimedChange`)
///   не проверяется этим
///   сторожем вовсе. Не трогается этой правкой по прямому указанию — не
///   потому что предел закрыт, а потому что решение отложено осознанно.
/// - **Шаблон ключа не отличает `'ключ': значение` внутри `Map`-литерала от
///   `case 'ключ':` внутри `switch`.** Проверено обходом заново при
///   написании круга 6: `grep -rnE "case\s+['\"](<денежные имена>)['\"]"
///   lib/domain/wire/*.dart` не находит ни одной такой метки — коллизии нет
///   нигде в дереве сегодня. `case 'progress':` (`wire_frame.dart`)
///   существует, но `progress` не входит в денежный список, так что он не
///   пример коллизии, а пример того, что коллизии сегодня негде
///   случиться. Появись когда-нибудь денежное имя как метка `case` — этот
///   сторож её не отличит от настоящего поля. Круг 6 этого не меняет:
///   `case` — код, а не комментарий, и пропуск комментариев его не
///   касается.
/// - **Внутрь вызванной функции сторож не заглядывает.** Проверено тестом:
///   «остаётся красным нарочно: собственная обёртка над дверью»
///   (`_encodeMoney(x)`, ниже в этом файле) краснеет — если бы `wireMoney`
///   сама была реализована неправильно, ни один текстовый разбор снаружи
///   этого бы не увидел; `wire_money_test.dart` (круг правки 3) существует
///   именно потому, что тело двери проверяется отдельно, не этим файлом.
/// - **Ложный запрет: пробел перед скобкой.** `wireMoney (a)` (пробел между
///   именем и `(`) — валидный Dart, но [_wireMoneyCallStart] требует `(`
///   вплотную и покрасит такой вызов. Найдено переразбором круга 4, не
///   исправлено сознательно — стандартный стиль Dart и `dart format` не
///   производят такого пробела, а руками написать и не заметить эту форму
///   практически недостижимо. Не проверено обходом (такого вызова в
///   дереве сегодня нет и не может быть найдено поиском «отсутствия»), а
///   выведено из формы регулярного выражения — это рассуждение, а не
///   находка.
/// - **Разбор комментариев и строк не проверен на произвольном Dart, только
///   на формах, названных переразбором.** [_skipCommentOrString] умеет
///   `//`, вложенные `/* */`, обычные/сырые/тройные кавычки — каждая форма
///   подтверждена тестом (шесть тестов круга 4–5, по два на форму: сама
///   форма и та же форма со склейкой). Строковая интерполяция с вложенной
///   строкой того же типа кавычек (`'a${foo('b')}c'`) проверена одним
///   рукописным примером при подготовке этой правки — результат обеих
///   сторон (сама форма чиста, склейка после нее краснеет) корректен для
///   **этого** примера; исчерпывающего перебора всех форм интерполяции не
///   проводилось, и это не заявляется как доказанное для всех случаев —
///   только для проверенного.
///
/// - **Разбор ключа проверен на комментариях и литералах, но не на
///   произвольном Dart.** Пять форм круга 6 покрыты тестами; исчерпывающего
///   перебора не было, и это не заявляется. Известная форма, которую разбор
///   ключа **не** отличает от кода: денежный ключ в строке, собранной
