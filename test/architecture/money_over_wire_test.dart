        };
        ''';

        expect(moneyFieldsNotUsingWireMoney(source), isEmpty);
      },
    );
  });

  // Круг 5: три формы, найденные переразбором как настоящий, компилятором
  // подтверждённый Dart, которые круг 4 разбирал неверно. Все три — в
  // сторону «краснит законный код», не «пропускает нарушение» (см.
  // докстринг файла): направление ошибки безопасное, чинится не потому что
  // горит, а потому что дёшево. Для каждой формы — пара тестов: сама форма
  // одна (обязана проходить, законный код) и та же форма со склейкой после
  // вызова (обязана краснеть, ровно как остальные диверсии выше).
  group('круг 5: три формы, ранее разбиравшиеся неверно', () {
    void expectLegitPasses(String label, String legitCall) {
      test('$label: форма одна — законный код, проходит', () {
        final hits = moneyFieldsNotUsingWireMoney(
          frameWith('amount', legitCall),
        );
        expect(
          hits,
          isEmpty,
          reason: '$legitCall — валидный Dart, вызов двери целиком; не офендер',
        );
      });
    }

    void expectConcatenationReddens(String label, String legitCall) {
      test('$label: та же форма со склейкой после — краснеет', () {
        final value = '$legitCall + wireMoney(other)';
        final hits = moneyFieldsNotUsingWireMoney(frameWith('amount', value));
        expect(
          hits,
          isNotEmpty,
          reason:
              'после настоящего конца вызова $legitCall добавлена склейка '
              '"+ wireMoney(other)" — обязана быть увидена, а не потеряна '
              'из-за desync внутри строки/комментария',
        );
      });
    }

    // Форма 1: тройная кавычка с апострофом внутри содержимого.
    expectLegitPasses(
      'тройная кавычка с апострофом внутри',
      "wireMoney('''it's ok''')",
    );
    expectConcatenationReddens(
      'тройная кавычка с апострофом внутри',
      "wireMoney('''it's ok''')",
    );

    // Форма 2: сырая строка с бэкслэшем перед закрывающей кавычкой — сама
    // форма, найденная переразбором буквально в прежней версии этого файла.
    expectLegitPasses(
      'сырая строка с бэкслэшем перед кавычкой',
      r"wireMoney(r'\')",
    );
    expectConcatenationReddens(
      'сырая строка с бэкслэшем перед кавычкой',
      r"wireMoney(r'\')",
    );

    // Форма 3: вложенный блочный комментарий — Dart его допускает. Скобка
    // `)` намеренно стоит внутри вложенного комментария, после внутренней
    // `*/`, но до настоящей внешней: счётчик без вложенности принял бы
    // внутреннюю `*/` за конец всего комментария, вышел бы «в код» раньше
    // времени и засчитал бы эту `)` как настоящую закрывающую скобку вызова
    // — здесь эта скобка ничего не значит, это текст комментария.
    expectLegitPasses(
      'вложенный блочный комментарий',
      'wireMoney(/* a /* b */ ) c */ x)',
    );
    expectConcatenationReddens(
      'вложенный блочный комментарий',
      'wireMoney(/* a /* b */ ) c */ x)',
    );
  });
}
