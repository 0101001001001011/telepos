final _anyKeyPattern = RegExp(r'''(["'])([A-Za-z_][A-Za-z0-9_]*)\1\s*:''');

/// Ключи, чьё значение — вызов [wireMoney], но которых **нет** в списке
/// денежных имён.
///
/// **Сторож над сторожем, круг правки 1 задачи 9.** Список имён закрыт по
/// решению заказчика, и до этой правки его отставание обнаруживалось только
/// диверсией снаружи: `totalDiscount` и `stock` ехали деньгами и не
/// проверялись вовсе. Прямо доказать полноту списка нельзя (сторож не знает
/// типов), но одну сторону — можно: если автор сам положил значение через
/// дверь, то поле денежное **по его же признанию**, и имя обязано быть в
/// списке. Расхождение здесь значит «список отстал», а не «код нарушил».
///
/// **Честно о пределе — круг правки 2 переписал этот абзац после того, как
/// переразбор нашёл его неточным.** Прежняя формулировка («невидимо то, что
/// положено **не** через дверь») называла предел уже, чем он есть. Видит эта
/// проверка ровно одну форму — **точный** вызов двери; невидимо всё
/// остальное, **включая формы, где дверь позвана**:
/// - тернарный выбор — `'surcharge': cond ? wireMoney(a) : wireMoney(b)`;
///   переразбор вписал его в дерево, и не увидела **ни одна из двух сетей**:
///   прямая молчит (имени `surcharge` нет в списке), обратная молчит
///   (значение — не точный вызов). Ровно эта форма и заставила свести
///   `stock` с тернарного на условный ключ;
/// - собственная обёртка — `'surcharge': _encodeMoney(x)`, даже если внутри
///   стоит [wireMoney];
/// - значение мимо двери вовсе — `'surcharge': x.toDouble()`.
///
/// То есть новое денежное имя попадает под охрану **только если автор
/// написал его самой прямой формой**. Закрыть это текстовым разбором нельзя
/// — нужен тип, то есть разбор Dart. Записано пределом, не починено.
///
/// Проверки на саму эту функцию — группа «обратная проверка краснеет и
/// молчит по делу» ниже: без них она была прибита к пустому списку и
/// **32 теста из 32 оставались зелёными** (диверсия переразбора круга 2).
List<String> moneyKeysOutsideList(String source) => [
  for (final found in _keysInCode(source, _anyKeyPattern))
    if (_isExactWireMoneyCall(_valueAfter(source, found.valueStart)) &&
        !_moneyKeyPattern.hasMatch("'${found.key}':"))
      found.key,
];

/// Каждое найденное в [source] денежное поле, чьё значение — не буквальный
/// вызов [wireMoney] и ничего больше — как `'ключ=значение'`, одна запись
/// на находку. Принимает готовый текст, а не файл: позволяет проверить саму
/// логику на синтетическом примере отдельно от реального дерева.
List<String> moneyFieldsNotUsingWireMoney(String source) {
  final hits = <String>[];
  for (final found in _moneyKeysInCode(source)) {
    final value = _valueAfter(source, found.valueStart);
    if (!_isExactWireMoneyCall(value)) {
      hits.add('${found.key}=$value');
    }
  }
  return hits;
}

/// Обёртка [moneyFieldsNotUsingWireMoney] над файлом.
List<String> moneyFieldsNotUsingWireMoneyIn(File file) =>
    moneyFieldsNotUsingWireMoney(file.readAsStringSync());

/// Синтетический кадр с одним денежным полем — общий для всех
/// диверсионных проверок ниже (круги 3-5), чтобы не поднимать `lib/` ради
/// проверки самого механизма разбора.
String frameWith(String key, String value) =>
    '''
      Map<String, Object?> _encode() => {
        '$key': $value,
      };
      ''';

