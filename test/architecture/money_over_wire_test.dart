/// Символ, из которого строится идентификатор Dart — используется только
/// чтобы отличить префикс `r` сырой строки от последней буквы обычного
/// идентификатора, оканчивающегося на «r» (круг 5).
final _identifierCharPattern = RegExp(r'[A-Za-z0-9_]');

/// Если в [text], начиная с индекса [i], стоит строчный комментарий (`//`),
/// блочный комментарий (`/* ... */`, с поддержкой вложенности — Dart её
/// допускает) или строковый литерал (`'...'`/`"..."`, обычный, сырой
/// (`r'...'`/`r"..."`) или тройной (`'''...'''`/`"""..."""`, с апострофом
/// внутри как обычным содержимым)), возвращает индекс сразу за его концом
/// — иначе `null`. Общий приём для [_valueAfter] и [_isExactWireMoneyCall]:
/// скобки/запятая **внутри** любой из этих форм не должны участвовать в
/// подсчёте глубины.
///
/// **Круг 5: три формы, подтверждённые переразбором как настоящий Dart,
/// которые версия круга 4 разбирала неверно** (все три — в сторону
/// «краснит законный код», не в сторону «пропускает нарушение», см.
/// докстринг файла):
/// - тройная кавычка (`'''it's ok'''`) — прежняя версия не знала о ней
///   вовсе и принимала одиночный апостроф внутри за конец строки, после
///   чего разбор терял синхронизацию с реальным текстом;
/// - сырая строка перед закрывающей кавычкой (`r'\'`) — прежняя версия не
///   смотрела на префикс `r` и трактовала `\` как начало экранирования
///   всегда, «проглатывая» настоящую закрывающую кавычку и убегая искать
///   следующую (эта форма буквально жила в этом же файле — `r'\'` в
///   прежней версии этой самой функции, `text[j] == r'\''` до этой правки);
/// - вложенный блочный комментарий — Dart допускает `/* /* */ */`, прежняя
///   версия останавливалась на первой попавшейся `*/`, то есть на
///   внутренней, а не на настоящей внешней.
int? _skipCommentOrString(String text, int i) {
  final ch = text[i];
  final next = i + 1 < text.length ? text[i + 1] : '';
  if (ch == '/' && next == '/') {
    var j = i;
    while (j < text.length && text[j] != '\n') {
      j++;
    }
    return j; // сам '\n' не поглощён — им займётся обычная обработка символа
  }
  if (ch == '/' && next == '*') {
    // Круг 5: счётчик вложенности, а не первая закрывающая пара — Dart
    // допускает `/* /* */ */`, и внутренняя `*/` не завершает комментарий.
    var depth = 1;
    var j = i + 2;
    while (j < text.length && depth > 0) {
      if (text[j] == '/' && j + 1 < text.length && text[j + 1] == '*') {
        depth++;
        j += 2;
        continue;
      }
      if (text[j] == '*' && j + 1 < text.length && text[j + 1] == '/') {
        depth--;
        j += 2;
        continue;
      }
      j++;
    }
    return j;
  }
  if (ch == "'" || ch == '"') {
    final quote = ch;
    // Круг 5: префикс `r` — сырая строка, в ней `\` не экранирует ничего и
    // остаётся обычным символом содержимого. Отличается от последней буквы
    // обычного идентификатора («…r») требованием, что перед этим «r» не
    // стоит ещё один символ идентификатора.
    final isRaw =
        i > 0 &&
        text[i - 1] == 'r' &&
        (i < 2 || !_identifierCharPattern.hasMatch(text[i - 2]));
    // Круг 5: тройная кавычка — отдельный вид строки, закрывается тремя
    // подряд теми же кавычками, а не одной; одиночная кавычка внутри —
    // обычное содержимое (ровно то, что переразбор показал на `it's`).
    final isTriple =
        i + 2 < text.length && text[i + 1] == quote && text[i + 2] == quote;
    if (isTriple) {
      var j = i + 3;
      while (j < text.length) {
        if (!isRaw && text[j] == r'\' && j + 1 < text.length) {
          j += 2;
          continue;
        }
        if (text[j] == quote &&
            j + 1 < text.length &&
            text[j + 1] == quote &&
            j + 2 < text.length &&
            text[j + 2] == quote) {
          return j + 3;
        }
        j++;
      }
      return text.length;
    }
    var j = i + 1;
    while (j < text.length && text[j] != quote) {
      // Экранированный символ (`\'`, `\"`, `\\`, ...) — оба символа не
      // должны быть спутаны с настоящей закрывающей кавычкой. В сырой
      // строке (`isRaw`) этого не происходит — `\` там не экранирует.
      j += (!isRaw && text[j] == r'\' && j + 1 < text.length) ? 2 : 1;
    }
    return j < text.length ? j + 1 : text.length; // включая закрывающую кавычку
  }
  return null;
}

/// Значение поля прямо после найденного `'ключ':` — до первой запятой или
/// закрывающей скобки/фигурной/квадратной скобки на глубине 0 относительно
/// самого значения (вложенные скобки самого значения — вызов `wireMoney(
/// ...)`, списки, вложенные вызовы — считаются и не обрывают извлечение
/// раньше времени). Комментарии и строковые литералы копируются в
/// результат текстом, но их содержимое не влияет на подсчёт глубины/запятой
/// (круг 4, [_skipCommentOrString]) — иначе `// :)` внутри довода обрывает
/// извлечение раньше настоящего конца значения.
String _valueAfter(String source, int start) {
  var i = start;
  var depth = 0;
  final buffer = StringBuffer();
  while (i < source.length) {
    final skipTo = _skipCommentOrString(source, i);
    if (skipTo != null) {
      buffer.write(source.substring(i, skipTo));
      i = skipTo;
      continue;
    }
    final ch = source[i];
    if (ch == '(' || ch == '[' || ch == '{') {
      depth++;
    } else if (ch == ')' || ch == ']' || ch == '}') {
      if (depth == 0) break; // закрытие охватывающего map-литерала
      depth--;
    } else if (ch == ',' && depth == 0) {
      break;
    }
    buffer.write(ch);
    i++;
  }
  return buffer.toString().trim();
}

/// `true`, если [value] — буквально `wireMoney(...)` целиком: начинается с
/// `wireMoney(`, скобки внутри сбалансированы (комментарии и строковые
/// литералы не участвуют в подсчёте — [_skipCommentOrString]), и **после
/// закрывающей скобки самого вызова не остаётся ни одного символа**.
///
/// Круг 3 заменил регекс `^wireMoney\(.*\)$` (заякорен по краям, жаден в
/// середине) подсчётом скобок. Круг 4 научил этот подсчёт пропускать
/// комментарии/строки — иначе смайлик `// :)` внутри довода закрывал бы
/// вызов раньше времени и, как ни парадоксально, ровно из-за этого
/// склейка `wireMoney(x, // :)\n) + wireMoney(y)` проходила бы как «точное
/// совпадение»: `_valueAfter` обрывался бы на том же смайлике, отдавая
/// сюда усечённый текст без хвоста `+ wireMoney(y)` вовсе.
bool _isExactWireMoneyCall(String value) {
  final match = _wireMoneyCallStart.firstMatch(value);
  if (match == null) return false;
  var depth = 1;
  var i = match.end;
  while (i < value.length) {
    final skipTo = _skipCommentOrString(value, i);
    if (skipTo != null) {
      i = skipTo;
      continue;
    }
    final ch = value[i];
    if (ch == '(') depth++;
    if (ch == ')') {
      depth--;
      if (depth == 0) {
        i++;
        break;
      }
    }
    i++;
  }
  // depth != 0 — скобки вызова не закрылись внутри значения вовсе (не
  // должно происходить, раз _valueAfter уже сбалансировала внешние скобки
  // map-литерала, но при рассинхронизации отказ безопаснее пропуска).
  // i != value.length — после конца вызова остался текст: склейка,
  // `.toString()`, что угодно ещё.
  return depth == 0 && i == value.length;
}

/// Каждый денежный ключ [source], стоящий **в коде**, и место сразу за его
/// двоеточием.
///
/// **Круг 6 (задача 9): долг круга 5, закрытый здесь.** До этой правки ключ
/// искался `_moneyKeyPattern.allMatches(source)` — по сырому тексту файла,
/// мимо [_skipCommentOrString], через который уже шёл поиск **значения**
/// ([_valueAfter], круг 4). Асимметрия стоила ровно того, что видно:
/// закомментированный старый код с денежным ключом (`// 'price': line
/// .price,`) считался настоящей находкой, и разбирающий шёл искать
/// нарушение в файле, где нарушения нет. Направление ошибки безопасное —
/// красит законный код, не пропускает нарушение, — но чинится дёшево, а
/// задача 9 первой заводит в `lib/domain/wire/` длинные докстринги, где
/// пример кадра в комментарии — дело обычное.
///
/// Разбор идёт слева направо. На кавычке сначала пробуется сам ключ
/// (`matchAsPrefix` — якорь ровно в этой позиции, а не «где-нибудь
/// дальше»): совпал — это настоящее поле кадра; не совпал — это обычный
/// строковый литерал, и он пропускается целиком вместе с содержимым.
/// Комментарий пропускается всегда. Ключ **сам по себе строковый литерал**
/// — потому пропуск строк и не может быть здесь безусловным, как для
/// комментариев.
Iterable<({String key, int valueStart})> _keysInCode(
  String source,
  RegExp pattern,
) sync* {
  var i = 0;
  while (i < source.length) {
    final ch = source[i];
    if (ch == "'" || ch == '"') {
      final match = pattern.matchAsPrefix(source, i);
      if (match != null) {
        yield (key: match.group(2)!, valueStart: match.end);
        i = match.end;
        continue;
      }
    }
    final skipTo = _skipCommentOrString(source, i);
    if (skipTo != null && skipTo > i) {
      i = skipTo;
      continue;
    }
    i++;
  }
}

Iterable<({String key, int valueStart})> _moneyKeysInCode(String source) =>
    _keysInCode(source, _moneyKeyPattern);

