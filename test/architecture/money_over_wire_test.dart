  });

  group('круг 6 (задача 9): ключ ищется в коде, а не в сыром тексте', () {
    // Долг круга 5, записанный в журнал задачи 6 и закрытый здесь: поиск
    // ЗНАЧЕНИЯ шёл через пропуск комментариев и строк ([_valueAfter]), а
    // поиск самого КЛЮЧА — по сырому тексту (`_moneyKeyPattern.allMatches`).
    // Значит закомментированный денежный ключ считался настоящей находкой.
    // Направление ошибки безопасное — краснит законный код, не пропускает
    // нарушение, — но цена его высока именно для этого сторожа: он краснеет
    // на **чужом** месте, и разбирающий ищет несуществующее нарушение в
    // файле, где нарушения нет. Правится потому, что дёшево и потому, что
    // задача 9 первой добавляет в `lib/domain/wire/` длинные докстринги.

    test('денежный ключ в строчном комментарии — не находка', () {
      const source = '''
        Map<String, Object?> _encode() => {
          // старая форма, оставлена для истории: 'price': line.price,
          'total': wireMoney(view.total),
        };
        ''';

      expect(
        moneyFieldsNotUsingWireMoney(source),
        isEmpty,
        reason:
            'закомментированный код — не код; сторож обязан читать то, что '
            'компилирует Dart, а не то, что видит в файле глазами',
      );
    });

    test('денежный ключ в блочном комментарии — не находка', () {
      const source = '''
        Map<String, Object?> _encode() => {
          /* было: 'amount': amount.toDouble(), */
          'total': wireMoney(view.total),
        };
        ''';

      expect(moneyFieldsNotUsingWireMoney(source), isEmpty);
    });

    test('денежный ключ внутри строкового литерала — не находка', () {
      // Текст отказа, подсказка, ключ JSON, набранный в строке для лога —
      // всё это не поле кадра, а содержимое строки.
      const source = '''
        String _hint() => "поле 'price': 5 обязано ехать строкой";
        ''';

      expect(moneyFieldsNotUsingWireMoney(source), isEmpty);
    });

    test('настоящая находка ПОСЛЕ комментария всё ещё находится', () {
      // Симметричная проверка: правка обязана научить сторож пропускать
      // комментарий, а не пропускать всё, что за ним. Без неё «починка»
      // могла бы ослепить сторож целиком и осталась бы незамеченной —
      // первый тест выше прошёл бы и на сторожe, который не находит ничего.
      const source = '''
        Map<String, Object?> _encode() => {
          // 'price': line.price,
          'total': view.total,
        };
        ''';

      expect(moneyFieldsNotUsingWireMoney(source), ['total=view.total']);
    });

    test(
      'диверсия: тот же ключ в коде и в комментарии — находка ровно одна',
      () {
        const source = '''
        Map<String, Object?> _encode() => {
          // 'price': line.price,
