      expect(hits, isNotEmpty);
    });

    test('короткое имя по-прежнему не съедает длинное', () {
      // Обратная сторона той же якорной кавычки: `'total'` и
      // `'totalDiscount'` — два разных ключа, и оба обязаны находиться
      // отдельно. Если бы список писался без якоря, порядок перечисления
      // решал бы, какой из них увиден.
      expect(moneyFieldsNotUsingWireMoney(frameWith('total', 'x')), [
