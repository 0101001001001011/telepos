/// Ни одно имя гарнитуры в коде не выдумано.
///
/// # Чем это оплачено
///
/// Живая приёмка 2026-09-19, планшет. Вкладка диагностики принтера показывает
/// чек **текстом тех же байтов**, что ушли в порт, — ради того, чтобы кассир
/// увидел переносы и столбцы до печати. На планшете столбцы разъезжались:
/// разделитель из 48 дефисов выходил короче строки из 48 знаков, то есть
/// предпросмотр врал ровно про то, ради чего он есть.
///
/// Причина: пятнадцать мест просили родовое `'monospace'`. Гарнитуры с таким
/// именем в наборе нет. На кассе его подставляет система, и там всё выглядело
/// правильно; в браузере подставлять некому, и текст рисовался
/// пропорциональным `Roboto`. Дефект жил на одной поверхности из двух и
/// потому не был виден ни набору, ни кассовому экрану.
///
/// # Почему сторож читает pubspec, а не список имён
///
/// Список имён в пробе — второе место, где решается, какие гарнитуры есть у
/// приложения, и он разойдётся с `pubspec.yaml` на первой же правке. Здесь
/// сверяются два источника: имена, названные кодом, и семейства, объявленные
/// сборкой. Разрешительный сторож полон по построению — добавь гарнитуру в
/// pubspec, и она разрешена без правки пробы.
///
/// # Чего эта проба НЕ доказывает
///
/// Что нужный глиф есть в файле гарнитуры: тенге в Roboto когда-то не было, и
/// это ловит `font_coverage_golden_test`. Здесь мерится только то, что
/// названное имя семейства вообще существует в этой сборке.
library;

import 'dart:io';

import 'package:flutter_test/flutter_test.dart';

void main() {
  test('каждое имя гарнитуры в lib/ объявлено в pubspec.yaml', () {
    final pubspec = File('pubspec.yaml').readAsStringSync();
    final declared = RegExp(
      r'^\s*- family:\s*(\S+)',
      multiLine: true,
    ).allMatches(pubspec).map((m) => m.group(1)!).toSet();
    expect(
      declared,
      isNotEmpty,
      reason: 'предпосылка: сборка объявляет хотя бы одну гарнитуру',
    );

    final named = <String, List<String>>{};
    for (final file in Directory('lib').listSync(recursive: true)) {
      if (file is! File || !file.path.endsWith('.dart')) continue;
      final source = file.readAsStringSync();
      for (final m in RegExp(
        r"""fontFamily:\s*'([^']+)'""",
      ).allMatches(source)) {
        final family = m.group(1)!;
        if (declared.contains(family)) continue;
        named.putIfAbsent(family, () => []).add(file.path);
      }
    }

    expect(
      named,
      isEmpty,
      reason:
          'гарнитура, которой нет в наборе, молча подменяется другой: на '
          'кассе её подставит система, в браузере — нет, и один и тот же '
          'экран покажет разное. Имена и места:\n'
          '${named.entries.map((e) => '${e.key}: ${e.value.join(', ')}').join('\n')}',
    );
  });
}
