/// В экранах нет зашитых русских строк.
///
/// # Зачем ещё один сторож про язык
///
/// Их уже двое: экранный обходит 46 маршрутов и смотрит НАРИСОВАННОЕ, а
/// `reports_ui_has_no_russian_literals_test` смотрит исходник, но только
/// модуля отчётов.
///
/// У экранного есть честное слепое пятно, названное в его же докстроке:
/// состояния, куда он не дошёл. Кнопка внутри диалога, плашка после отказа,
/// экран, который открывается только при заведённых данных, — всё это он не
/// видит. 2026-09-22 так нашлись двадцать шесть строк, включая «X-отчёт» и
/// «Чек коррекции» прямо на экране смены, который снимает урок 7.
///
/// Этот сторож читает ИСХОДНИК всего `lib/presentation` и потому не зависит
/// от достижимости.
///
/// # Почему он смотрит ЛЮБОЙ литерал, а не только `Text('…')`
///
/// Первая редакция ловила `Text('…')`. В тот же день выяснилось, чего она не
/// ловит: три ответа X-отчёта на экране смены сначала присваивались
/// переменной и только потом попадали в `Text(msg)`. Сторож молчал, а
/// кассир на английской кассе читал «X-отчёт распечатан».
///
/// Разбор 2026-09-22 дал 88 таких строк: подписи причин списания в отчётах,
/// договоры рассрочки, карточка ремонта, заявка поставщику, модификаторы
/// блюда, режим заказа в истории, семь разделов мастера в отказе
/// «заполните». Все переведены.
///
/// # Что НЕ считается нарушением
///
/// * комментарии и докстроки — они для нас, а не для кассира;
/// * запись в журнал (`talker`, `SetupLogger`, `debugPrint`) — её читает
///   разработчик;
/// * `assert` и `StateError`/`Exception` — тоже разработчик, и по-русски
///   там сказано больше, чем сказалось бы по-английски;
/// * второй довод `WireRefusal` — подпись отказа для журнала; на экран
///   уезжает КОД, и его переводит `ErrorLocalizer`;
/// * поимённые исключения ниже — каждое с доводом.
library;

import 'dart:io';

import 'package:flutter_test/flutter_test.dart';

/// Строки, законно остающиеся русскими, — поимённо и с доводом.
///
/// Не «список на всякий случай»: рядом с каждой сказано, почему её не
/// переводят. Молчаливое исключение превратило бы сторожа в украшение.
const _allowed = <String, String>{
  // Названия казахстанских государственных систем. Их не переводят так же,
  // как не переводят «CO State» в разбивке ставки на американском чеке: это
  // имя органа, а не слово интерфейса.
  'ИС МПТ (ismet.kz / Tañba)': 'имя государственной системы',
  'WebKassa (СНТ)': 'имя государственной системы',

  // Данные, а не надписи: пишутся один раз и потом правятся человеком.
  'Автодобавлено из нормы расхода':
      'примечание к документу в базе; правится в карточке документа',
  'Касса-1':
      'значение по умолчанию у довода виджета; настоящие имена касс '
      'приходят из базы и подставляются вызывающим',

  // Язык называет себя на себе: «ҚАЗ» — это и есть казахский, а не перевод
  // слова «казахский». Переключатель языков показывает их все сразу, и
  // переводить их было бы ошибкой, а не исправлением.
  'ҚАЗ': 'самоназвание языка в переключателе',
  'КЫР': 'самоназвание языка в переключателе',

  // Подпись отказа для журнала: на экран уезжает КОД `error.shift_over_age`,
  // и его переводит `ErrorLocalizer`. Пара «код + подпись» объявлена рядом,
  // а не внутри вызова, поэтому сторож её не относит к журнальным.
  'смена открыта более 24ч — закройте смену':
      'подпись отказа рядом с кодом kShiftOverAgeError; на экран идёт код',
};

/// Начала строк, законно остающихся русскими (имена с подстановкой).
const _allowedPrefixes = <String, String>{
  'Терминал ':
      'имя браузерного терминала по умолчанию: данные, а не надпись. '
      'Переименование — отдельная операция `terminals.rename`',
  'Ингредиентов: ':
      'сводка версии рецепта, уходящая в базу. Запасной путь: словарь берётся '
      'у контекста, а этой веткой экран уже закрыт',
  'себестоимость: ': 'вторая строка той же сводки версии рецепта',
};

/// Файлы, целиком не являющиеся интерфейсом, — поимённо и с доводом.
const _allowedFiles = <String, String>{
  // Готовые команды оболочки Linux для приставки: их читает наладчик в окне
  // терминала, а выполняются они на приставке, которая существует только в
  // Казахстане. Это не надписи, а текст, который уезжает в `sh -c`.
  'lib/presentation/screens/settings/system_terminal_screen.dart':
      'команды оболочки приставки, а не надписи интерфейса',
};

void main() {
  final cyrillic = RegExp(r'[А-Яа-яЁё]');

  /// Любой строковый литерал — одинарный или двойной.
  final anyLiteral = RegExp('\'((?:[^\'\\n]|\\\\.)*)\'|"((?:[^"\\n]|\\\\.)*)"');

  /// Вызовы, чей текст читает разработчик, а не кассир.
  final developerFacing = RegExp(
    r'(talker|logger|_log\b|Talker|SetupLogger|debugPrint'
    r'|\.info\(|\.warning\(|\.error\(|\.debug\(|\.verbose\(|\.handle\('
    r'|\bassert\(|StateError\(|Exception\(|WireRefusal\()',
  );

  test('сторож смотрит не в пустоту: экраны на месте', () {
    final dir = Directory('lib/presentation');
    expect(dir.existsSync(), isTrue);
    final files = dir
        .listSync(recursive: true)
        .whereType<File>()
        .where((f) => f.path.endsWith('.dart'))
        .length;
    expect(
      files,
      greaterThan(50),
      reason: 'экранов почти нет — сторож ищет не там',
    );
  });

  test('ни один литерал не уедет на экран по-русски', () {
    final offenders = <String>[];

    for (final entity in Directory(
      'lib/presentation',
    ).listSync(recursive: true)) {
      if (entity is! File || !entity.path.endsWith('.dart')) continue;
      final path = entity.path.replaceAll(r'\', '/');
      if (_allowedFiles.containsKey(path)) continue;
      final lines = entity.readAsLinesSync();

      for (var i = 0; i < lines.length; i++) {
        final line = lines[i];
        // Комментарии целиком пропускаем: доводы пишутся по-русски
        // намеренно, и это не то, что уедет на экран.
        if (line.trimLeft().startsWith('//')) continue;

        // Вызов мог начаться выше: `talker.warning(` на одной строке, а
        // текст на следующей. Шесть строк назад — с запасом.
        final window = lines.sublist(i - 6 < 0 ? 0 : i - 6, i + 1).join('\n');
        if (developerFacing.hasMatch(window)) continue;

        for (final match in anyLiteral.allMatches(line)) {
          final value = match.group(1) ?? match.group(2) ?? '';
          if (!cyrillic.hasMatch(value)) continue;
          if (_allowed.containsKey(value)) continue;
          if (_allowedPrefixes.keys.any(value.startsWith)) continue;
          offenders.add('$path:${i + 1}: «$value»');
        }
      }
    }

    expect(
      offenders,
      isEmpty,
      reason:
          'эти строки уедут на экран по-русски у человека, выбравшего другой '
          'язык — и обходчик экранов их не увидит, если до этого состояния '
          'не дойдёт. Заведите ключ в `assets/i18n/*.arb` и возьмите слово '
          'из `AppLocalizations`:\n${offenders.join('\n')}',
    );
  });

  test('запасного русского слова нет ни одного', () {
    // Отдельный род того же дефекта: `l10n?.помощь ?? 'Справка'`. Он не
    // «зашитая строка» — словарь спрошен, — но сборка без делегатов покажет
    // русское слово МОЛЧА. Ровно так экран покупателя год печатал
    // по-русски, и вскрылось это, только когда на нём завели первое слово
    // из словаря.
    //
    // Порога здесь нет намеренно: порог — это ratchet, а он разрешает
    // сегодняшнее число навсегда. 2026-09-22 таких мест было восемь, и все
    // сняты: словарь спрашивается через `!`, и сборка без делегатов падает,
    // а не говорит по-русски.
    final fallbacks = <String>[];
    for (final entity in Directory(
      'lib/presentation',
    ).listSync(recursive: true)) {
      if (entity is! File || !entity.path.endsWith('.dart')) continue;
      final path = entity.path.replaceAll(r'\', '/');
      final lines = entity.readAsLinesSync();
      for (var i = 0; i < lines.length; i++) {
        final line = lines[i];
        if (line.trimLeft().startsWith('//')) continue;
        for (final match in anyLiteral.allMatches(line)) {
          final value = match.group(1) ?? match.group(2) ?? '';
          if (!cyrillic.hasMatch(value)) continue;
          if (_allowed.containsKey(value)) continue;
          if (_allowedPrefixes.keys.any(value.startsWith)) continue;
          if (!line.substring(0, match.start).contains('??')) continue;
          fallbacks.add('$path:${i + 1}: «$value»');
        }
      }
    }

    expect(
      fallbacks,
      isEmpty,
      reason:
          'русское слово в запасе у словаря. Спрашивайте словарь через `!`: '
          'сборка без делегатов обязана падать, а не говорить по-русски:'
          '\n${fallbacks.join('\n')}',
    );
  });
}
