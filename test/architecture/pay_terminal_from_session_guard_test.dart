/// Рабочее место берёт **сеанс**, а не тело кадра — задача 16, круг
/// правки 5, ужесточён кругом правки 6 и перенацелен слиянием.
///
/// # Что сменилось в день слияния (2026-09-07)
///
/// Имя источника: `_payTerminal` снят, место берёт `_cartTerminal`. Довод
/// не в имени, а в том, что `_payTerminal` делал **две** работы —
/// отвергал названное телом место и брал его из сеанса, — и первую
/// половину задача 10 к тому времени уже сделала строже и на всю карту
/// продажи сразу (`_refusingTerminalInBody`: имя ищется по написанию и на
/// любой глубине, а не буквой `terminalId`). Пять денежных операций легли
/// в ту же карту, и запрет стал для них **структурным**, а не
/// повторяемым.
///
/// Этот сторож от того не лишний: структурный запрет живёт на карте, а
/// здесь проверяется, что владеющая операция вообще спрашивает имя у
/// сеанса, и что ни она, ни её помощник не читают место из тела иным
/// путём. Сам источник (`_cartTerminal`) из обхода исключён — он читает
/// сеанс, а `terminalId` в нём это имя локальной переменной.
///
/// # Чего не хватало разбиению каталога
///
/// Круг правки 4 развёл каталог оплаты на владеющие рабочим местом
/// операции и невладеющие и потребовал, чтобы каждая новая была отнесена
/// к одной из половин. Это заставляет автора **принять решение** — и
/// именно поэтому операция, не отнесённая никуда, красит сторожа
/// `_partitionCovers` в `test/backend/pay_operations_test.dart`.
///
/// Но **ложное** решение то разбиение не ловило, и это измерено разбором:
/// операция, отнесённая к **невладеющим** и при этом читающая место из
/// тела, проходила все пробы зелёными. Невладеющая половина была чистой
/// декларацией — её не проверяло ничто.
///
/// # Что проверяется здесь
///
/// Не поведение, а **исходник** — тем же приёмом и по той же причине, что
/// `sale_state_owner_guard_test.dart`: поведение невладеющей операции не
/// отличить от поведения владеющей, пока она не соврала, а текст
/// обработчика говорит правду до первого запуска.
///
/// Два утверждения:
///
/// 1. в области оплаты место из тела не читает никто — ни обработчик, ни
///    помощник, которого обработчик зовёт (источник `_cartTerminal` из
///    обхода исключён: он читает сеанс);
/// 2. каждая операция, объявленная владеющей, **зовёт** `_cartTerminal`.
///
/// # Почему проверка пошла за пределы карты (круг правки 6)
///
/// Первая редакция читала **только тела обработчиков внутри карты**, и
/// разбор обошёл её за один заход: обработчик зовёт `_legacyPlace(body)`,
/// а сам помощник объявлен **ниже** карты и читает место из тела —
/// сторож зелёный.
///
/// Это ровно та форма, ради которой переписывался сосед: его докстринг
/// называет «сторож ловит по форме вызова, а не по признаку» **пятым
/// повторением за задачу**. Поэтому здесь сторож спускается на **один
/// уровень**: собирает частных помощников, которых зовут обработчики
/// оплаты, и читает их объявления тоже.
///
/// # Пределы, названные целиком
///
/// - **Глубина ровно один уровень.** Помощник, зовущий второго помощника,
///   который читает тело, не пойман. Названо числом, а не словом «почти»:
///   транзитивный обход текста без разбора Dart врёт в обе стороны, а
///   разбор Dart здесь стоил бы дороже находки. Следующее повторение той
///   же формы — повод унести проверку на разбор, а не углублять текстовый
///   обход.
/// - **Текст, а не Dart.** Имя `_cartTerminal`, собранное из строк, сторож
///   не увидит; `terminalId` в комментарии внутри обработчика — увидит и
///   покраснеет.
/// - **Склейка строк снимается, но только соседних литералов.** Круг
///   правки 6: `body['terminal' 'Id']` проходил мимо. Перед поиском
///   соседние литералы склеиваются ([_glued]); выражение, собранное
///   переменными или `+`, по-прежнему пройдёт.
void main() {
  const source = 'lib/backend/till_operations.dart';

  /// Имена операций, объявленных владеющими рабочим местом.
  ///
  /// Та же пара половин, что в `test/backend/pay_operations_test.dart`.
  /// **Расходиться им не мешает ничто** — `_partitionCovers` этот файл не
  /// читает, и утверждать обратное было бы выдуманным механизмом (круг
  /// правки 6 снял такое утверждение отсюда). Расхождение всё же не
  /// проходит молча: устаревшее имя красит проверку «владеющая операция
  /// потеряла обработчик» ниже, а имя, забытое здесь, — `_partitionCovers`
  /// у соседа.
  const owning = {
    'pay.complete',
    'pay.card',
    'pay.troubles',
    // Возврат добавлен при слиянии. Шесть его операций легли в **ту же**
    // карту, что и денежные, под тот же запрет и с тем же источником места,
    // а сторожа у них не было: их собственный `_refundTerminal` снят вместе
    // с `_payTerminal`. Владеют местом все шесть — черновик возврата лежит
    // на кассе под ключом `terminalId`, и холодный вызов с чужим именем
    // отдавал бы чужой черновик.
    'refund.loadReceipt',
    'refund.startWithoutReceipt',
    'refund.addProduct',
    'refund.setLine',
    'refund.complete',
  };

  /// Исходник со **склеенными** соседними литералами: в Dart
  /// `'terminal' 'Id'` — тот же `'terminalId'`, и сторож обязан видеть их
  /// одинаково.
  String glued() =>
      File(source).readAsStringSync().replaceAll(RegExp(r"'\s*'"), '');

  /// Тела обработчиков оплаты: от `PayOps.<имя>.name:` до следующего
  /// такого же или до закрытия самой карты.
  Map<String, String> payHandlers(String text) {
    final starts = <int, String>{};
    // `PayOps` **и** `RefundOps`: с днём слияния они в одной карте, под
    // одним запретом и с одним источником места. Оставить сторожа на одной
    // половине значило бы, что вторая половина живёт по объявленному
    // правилу, которое никто не проверяет, — ровно та слепота, ради снятия
    // которой этот файл и заведён.
    final pattern = RegExp(r'(Pay|Refund)Ops\.(\w+)\.name:');
    for (final m in pattern.allMatches(text)) {
      final prefix = m.group(1)! == 'Pay' ? 'pay' : 'refund';
      starts[m.start] = '$prefix.${m.group(2)!}';
    }

    // Границы тела — **любой** следующий обработчик, а не только следующий
    // денежный. Найдено слиянием: карта продажи собрала под одной крышей
    // `SaleOps`, `PayOps` и `RefundOps`, `pay.troubles` перестала быть
    // последней записью, и её «тело» дотянулось до закрытия карты, проглотив
    // все шесть обработчиков возврата. Сторож покраснел на слове `terminalId`
    // в **чужом комментарии** — красный цвет без дефекта, ровно та же беда,
    // что и с закрытием карты выше.
    final anyHandler = RegExp(r'\w+Ops\.\w+\.name:');
    final boundaries = [for (final m in anyHandler.allMatches(text)) m.start]
      ..sort();
    expect(
      starts,
      isNotEmpty,
      reason:
          'обработчиков оплаты в $source не нашлось — сторож смотрит '
          'не туда, а не «правило соблюдено»',
    );

    // Конец последнего обработчика — закрытие карты, а не конец файла:
    // иначе в «тело» попало бы всё, что идёт следом, включая определения
    // помощников, и сторож краснел бы на собственном механизме. Ровно это
    // и случилось при слиянии: операции оплаты переехали в
    // `_saleAskHandlers`, а её закрывает `  });` — карту оборачивает
    // `_refusingTerminalInBody`, — не `  };`; «тело» `pay.troubles`
    // проглотило полфайла и выдало четырёх выдуманных нарушителей.
    final offsets = starts.keys.toList()..sort();
    final mapEnd = text.indexOf('\n  });', offsets.last);
    expect(
      mapEnd,
      greaterThan(offsets.last),
      reason: 'карта обработчиков не закрыта — сторож разбирает не то',
    );

    final bodies = <String, String>{};
    for (final from in offsets) {
      final next = boundaries.firstWhere((b) => b > from, orElse: () => mapEnd);
      final to = next < mapEnd ? next : mapEnd;
      bodies[starts[from]!] = _withoutTrailingComment(text.substring(from, to));
    }
    return bodies;
  }

  /// Объявление частного члена [name] — от строки объявления до
  /// одиночной `  }` на том же уровне. `null` — объявления в этом файле
  /// нет (имя пришло извне).
  ///
  /// **Отступ ровно два пробела, и сразу за ним не пробел и не косая
  /// черта** — иначе находится **вызов**, а не объявление, и сторож
  /// краснеет на честном помощнике. Круг правки 6 поймал себя на этом
  /// дважды: сперва принял за тело `_requireInt` его вызов
  /// `_requireInt(body, 'terminalId')`, потом — тот же вызов, перенесённый
  /// на свою строку с отступом восемь (пробелы отступа сходили за имя
  /// типа). Запрет на пробел после отступа отсекает и то и другое, запрет
  /// на косую — упоминание в докстринге.
  String? declarationOf(String text, String name) {
    final decl = RegExp('\\n  (?![ /])[^\\n]*? $name\\(').firstMatch(text);
    if (decl == null) return null;
    final end = text.indexOf('\n  }', decl.start);
    return end < 0
        ? text.substring(decl.start)
        : text.substring(decl.start, end);
  }

  test('в области оплаты и возврата место из тела не читает никто', () {
    final text = glued();
    final handlers = payHandlers(text);
    final offenders = <String>[];

    handlers.forEach((name, body) {
      // Ищется имя **в кавычках**, а не идентификатор. Причина измерена
      // слиянием: обработчики возврата пишут `final terminalId =
      // _cartTerminal(sessionId);` — местная переменная с тем же именем, и
      // прежняя грубая проверка объявляла нарушителями все пять. Чтение
      // места **из кадра** всегда идёт через строковый ключ —
      // `body['terminalId']`, `_requireInt(body, 'terminalId')` — и склейка
      // соседних литералов снята [glued] заранее.
      if (body.contains("'terminalId'")) {
        offenders.add('$name (сам обработчик)');
      }

      // Один уровень вглубь: помощник, которого зовёт обработчик.
      for (final call in RegExp(r'\b(_\w+)\(').allMatches(body)) {
        final helper = call.group(1)!;
        if (helper == '_cartTerminal') continue;
        final declaration = declarationOf(text, helper);
        if (declaration == null) continue;
        if (declaration.contains("'terminalId'")) {
          offenders.add('$name → $helper');
        }
      }
    });

    expect(
      offenders,
      isEmpty,
      reason:
          'имя рабочего места приходит из сеанса (`_cartTerminal`), а кадр, '
          'который его называет, отвергается. Обработчик, читающий тело — '
          'сам или через помощника, — отдаёт чужой чек любому, кто назовёт '
          'номер, и объявление операции «невладеющей» этого не меняет',
    );
  });

  test('каждая владеющая операция берёт место через _cartTerminal', () {
    final handlers = payHandlers(glued());

    // Страховка от вырождения: имена половины обязаны быть в карте, иначе
    // цикл ниже пройдёт по пустому множеству и промолчит.
    expect(
      owning.difference(handlers.keys.toSet()),
      isEmpty,
      reason: 'владеющая операция потеряла обработчик — или переименована',
    );

    for (final name in owning) {
      expect(
        handlers[name],
        contains('_cartTerminal('),
        reason:
            '$name объявлена владеющей рабочим местом, но имени у сеанса '
            'не спрашивает',
      );
    }
  });

  test('склейка соседних литералов сторожу не мешает', () {
    // Страховка от вырождения самого механизма: без [glued] проба на
    // `body['terminal' 'Id']` была бы зелёной, и это измерено разбором.
    expect(
      "body['terminal' 'Id']".replaceAll(RegExp(r"'\s*'"), ''),
      contains('terminalId'),
    );
  });
}

/// Тело обработчика без **чужого** хвоста: пустых строк и комментария,
/// которым начинается следующий обработчик.
///
/// Заведено при слиянии, и не для красоты. Между `pay.troubles` и
/// `refund.loadReceipt` в карте стоит абзац про то, почему возврат больше не
/// берёт место из тела; в нём слово `terminalId` встречается как **цитата**.
/// Без этой обрезки сторож объявлял `pay.troubles` нарушителем за соседский
/// комментарий — красный цвет без дефекта, а он у сторожа дороже пропуска:
/// разбирающий ищет несуществующее и перестаёт верить проверке.
String _withoutTrailingComment(String body) {
  final lines = body.split('\n');
  var end = lines.length;
  while (end > 0) {
    final line = lines[end - 1].trim();
    if (line.isEmpty || line.startsWith('//')) {
      end--;
    } else {
      break;
    }
  }
  return lines.take(end).join('\n');
}
