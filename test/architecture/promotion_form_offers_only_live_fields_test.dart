library;

import 'dart:io';

import 'package:flutter_test/flutter_test.dart';

/// Форма акции не предлагает выбор, который ничего не меняет.
///
/// Шаг 4 задачи 19 плана «полнота продажи» (2026-09-07). Экран акций писал
/// в базу два поля сверх тех, что читает механика скидки:
/// `Promotions.type` и `Promotions.supplierFunded`. Механика
/// (`LocalCartService._applyPromotions`,
/// `lib/data/sale/local_cart_service.dart`) смотрит ровно на
/// `enabled`/`triggerUcode`/`triggerQty`/`rewardUcode`/`rewardQty` — и
/// больше ни на что.
///
/// # Почему снят только `supplierFunded`, а `type` оставлен
///
/// План называл оба поля мёртвыми одинаково. Измерение это не
/// подтвердило, и правится продукт, а не измерение:
///
/// - **`supplierFunded`** мёртв целиком: галочка «акцию оплачивает
///   поставщик» писалась в базу и показывалась ярлыком в списке, и ни одна
///   строка кода нигде её не читала. Владелец, поставивший галочку, решил
///   бы, что расход ляжет на поставщика, — а он не ложится никуда. Показать
///   такой выбор хуже, чем не показать: он не бездействует, он врёт. Снят.
///
/// - **`type` мёртв только наполовину.** Сохранённое значение и правда
///   читает лишь список (значок и подпись «1+1»/«Подарок»). Но в самой
///   форме `_type` — переключатель режима: он задаёт `triggerQty` (2 против
///   1) и открывает выбор товара-подарка. Убрать его значило бы отнять
///   единственный способ завести акцию «купи A → получи B» — не снятие
///   мёртвого поля, а потеря возможности. Оставлен.
///
/// Сторож держит первую половину: пока `supplierFunded` не читает никто,
/// кроме определения таблицы и сгенерированного drift-кода, экран акций не
/// имеет права его предлагать. Появится настоящий читатель (расчёт, отчёт,
/// выгрузка поставщику) — сторож покраснеет и потребует решения заново.
void main() {
  test(
    'supplierFunded не предлагается на экране, пока его никто не читает',
    () {
      final readers = <String>[];
      var scanned = 0;

      for (final entity in Directory('lib').listSync(recursive: true)) {
        if (entity is! File) continue;
        if (!entity.path.endsWith('.dart')) continue;
        final path = entity.path.replaceAll(r'\', '/');

        // Определение колонки и сгенерированный drift-код — не читатели:
        // они описывают хранилище, а не пользуются значением.
        if (path.endsWith('.g.dart')) continue;
        if (path == 'lib/data/database/tables/nomenclature_tables.dart') {
          continue;
        }

        scanned++;
        if (_withoutComments(
          entity.readAsStringSync(),
        ).contains('supplierFunded')) {
          readers.add(path);
        }
      }

      // Сторож, ничего не прочитавший, зелен по недосмотру.
      expect(
        scanned,
        greaterThan(200),
        reason: 'Обход lib/ не состоялся — путь или фильтр сломаны.',
      );

      expect(
        readers,
        isEmpty,
        reason:
            'Поле `supplierFunded` упоминается в продукте. Если появился '
            'настоящий читатель (расчёт, отчёт, выгрузка поставщику) — верни '
            'галочку на экран и перепиши этот сторож под новое положение дел. '
            'Если читателя нет, а упоминание — это снова элемент управления, '
            'то он предлагает владельцу выбор, который никуда не влияет: '
            '$readers',
      );
    },
  );

  test('сторож не покупается на упоминание в комментарии (проверено '
      'подсадкой)', () {
    // Обратный ход к предыдущей проверке. Комментарий, объясняющий, почему
    // поле снято, сам содержит его имя — сторож, ищущий подстроку в сыром
    // исходнике, покраснел бы от собственного объяснения и был бы починен
    // переписыванием комментария, а не кода. Здесь закреплено обратное:
    // код без комментариев — то, что сторож действительно читает.
    const sample = '''
      // supplierFunded снят: его никто не читает.
      /// Докстринг про supplierFunded.
      final x = liveField;
    ''';
    expect(_withoutComments(sample).contains('supplierFunded'), isFalse);
    expect(_withoutComments(sample).contains('liveField'), isTrue);
  });
}

/// Исходник без комментариев: только то, что исполняется.
///
/// Грубо и намеренно: строковые литералы, содержащие `//`, эта функция
/// обрежет вместе с остатком строки. Для поиска имени поля это безопасно —
/// обрезка может дать ложный зелёный, но не ложный красный, а ложный
/// зелёный здесь ловится проверкой «сторож вообще что-то прочитал» и тем,
/// что имя поля в строковом литерале продукта не встречается.
String _withoutComments(String source) {
  final withoutBlocks = source.replaceAll(
    RegExp(r'/\*.*?\*/', dotAll: true),
    ' ',
  );
  return withoutBlocks
      .split('\n')
      .map((line) {
        final at = line.indexOf('//');
        return at < 0 ? line : line.substring(0, at);
      })
      .join('\n');
}
