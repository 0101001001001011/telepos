/// Сторож от возврата (задача 2 — провод перестаёт нести текст исключения),
/// расширенный волной правок фазы 1 (задача 4) и кругом 4 — состоянием
/// экрана (2026-08-27).
///
/// До задачи 2 `till_wire.dart` подставлял пойманное исключение в
/// `ErrorFrame` через `'$error'` — то есть через `Object.toString()`. Для
/// `SqliteException` (`package:sqlite3`) это печатает `causingStatement` и
/// `parametersToStatement` целиком: текстовые параметры не маскируются
/// (маскируется только `Uint8List`), а `Users.password_enc` — текстовый
/// столбец, так что хэш PIN из `UPDATE users SET password_enc = ?`
/// (`AuthService._upgradeStoredPin`) уезжал в кадр отказа, который видит
/// браузер. Задача 2 перевела все шесть мест через `safeErrorText`
/// (`lib/core/errors/safe_error_text.dart`, задача 1).
///
/// **Круг 1 (первая версия этого теста).** Требовал, чтобы интерполяция
/// была **всем** содержимым строкового литерала:
/// `RegExp(r"""['"]\$error['"]""")` — кавычка вплотную к `$error`, кавычка
/// сразу после. Зелёными проходили формы, которыми правило обходится
/// тривиально: `ErrorFrame('handler_failed', 'сбой: $error')` — утечка
/// полная, но перед `$error` есть текст «сбой: », и открывающая кавычка
/// регексу не соседствует; а также `'${error}'` (фигурные скобки — другой
/// текст), `'$err'`/`'$ex'` (другие частые имена переменной исключения) и
/// `error.toString()` без окружающих кавычек вовсе.
///
/// **Круг 2 (эта правка, задача 4).** Ловится интерполяция **в любом месте**
/// литерала — не только как единственное содержимое: `$error`/`${error}`, и
/// то же для `e`/`err`/`ex` — самых частых имён переменной исключения в этом
/// файле и в файлах задачи 3 — плюс `.toString()` на любой из четырёх.
/// Проверка расширена с одного `ErrorFrame(...)` на все роды кадров
/// `till_wire.dart` (`ErrorFrame`, `OkFrame`, `UpdateFrame`, `ProgressFrame`,
/// `DoneFrame` — весь набор конструкторов `WireFrame` из `wire_frame.dart`),
/// и на три файла задачи 3 (`device_check_local.dart`,
/// `first_launch_service.dart`, `global_product_import_service.dart`) — там
/// исключение достигает `OkFrame`/`ProgressFrame` не напрямую из этого
/// файла, а через `DeviceCheckOutcome.unexpectedError(...)` /
/// `onProgress?.call(...)`, и проверяется весь файл целиком, а не вызов
/// определённого имени.
///
/// **Круг 3 (финальная волна закрытия долга безопасности, 2026-08-22,
/// пункт 7).** До этой правки сторож проверял **список из четырёх путей**
/// (`till_wire.dart` плюс три файла задачи 3) — приём на места, а не на
/// сам приём: новый файл, построивший `ErrorFrame`/`OkFrame`/…/
/// `DeviceCheckOutcome.unexpectedError`/`onProgress?.call` с `$e` внутри, в
/// этот список просто не попадал бы и остался бы невидимым. Именно так и
/// нашлось `hardware_settings_screen.dart:1062` (`DeviceCheckOutcome
/// .unexpectedError('$e')`, задача 1 фазы 2 перевела на это исключение
/// `wt_device_check.dart`/`device_check_local.dart`, но не этот вызывающий
/// в другом файле) — красный прогон до правки места, разобранный ниже.
///
/// Правка переводит сторож с фиксированного списка путей на обход **по
/// имени вызова** через весь `lib/`: каждый `.dart`-файл (кроме `.g.dart`)
/// разбирается на вызовы семи целевых имён — пяти конструкторов
/// `WireFrame` и двух каналов передачи текста наружу из задачи 3
/// (`unexpectedError`, `onProgress?.call`) — и каждый найденный вызов, где
/// бы он ни жил, проверяется той же регулярной проверкой на сырую
/// интерполяцию. Новый файл с любым из этих семи имён обнаруживается сам,
/// без правки списка целей. Три файла задачи 3 раньше разбирались **целым
/// файлом построчно** (шире, чем только сами вызовы) — сужение до самих
/// вызовов не теряет покрытия: в этих трёх файлах не было ни одной сырой
/// интерполяции за пределами `unexpectedError`/`onProgress?.call`
/// (проверено чтением при этой правке), а по всему `lib/` вне них
/// построчный обход дал бы лавину ложных срабатываний — `talker.warning`
/// в отладочном логе, не идущем ни на провод, ни во внешний кадр, тоже
/// пишет `'...: $e'` сплошь и рядом, и это не тот же класс дефекта.
///
/// **Честно о пределе — то, чего этот сторож не ловит.** Проверка читает
/// **текст**, не типы и не поток данных:
/// - переименованную переменную — `final problem = e; ErrorFrame(code,
///   '$problem')` пройдёт мимо, потому что «problem» не входит в список
///   частых имён (`error`/`e`/`err`/`ex`), а список конечен по построению;
/// - вызов своей функции — `ErrorFrame(code, myOwnUnsafeFormat(e))` не
///   содержит `$`-интерполяции вовсе, сторожу нечего заметить в тексте
///   самого вызова;
/// - обращение к произвольному полю исключения — `${e.someField}` не ловится
///   нарочно (см. докстрок у `_rawInterpolationPatterns`): ловится голое имя
///   и `.toString()`, но не любое поле, которое могло бы оказаться таким же
///   небезопасным, как `.toString()`, для какого-то будущего типа исключения.
/// Ни то, ни другое не заменяется анализом типов здесь: единственная полная
/// проверка такого случая — код-ревью и то, что `safeErrorText` — теперь
/// единственная функция в проекте, которая имеет право форматировать
/// исключение для внешнего наблюдателя (см. `safe_error_text.dart`).
///
/// **Круг 4 (эта правка, 2026-08-27).** Всё выше стережёт границу провода —
/// `ErrorFrame`/`OkFrame`/… и два канала задачи 3. Но `37fb56e` нашёл ту же
/// сырую интерполяцию по другую сторону: `state.copyWith(error:
/// 'error.load_failed:$e')` — состояние экрана, не кадр. Сегодня это
/// процесс самой кассы, границы не пересекает — но ровно тем же путём, каким
/// провод довозит текст до чужого браузера, состояние экрана довозит его до
/// виджета, а виджет — до пикселя; `login_controller.dart` в том же коммите
/// показал, что чужому браузеру эта строка доезжает напрямую, когда экран
/// вообще работает через провод. 94 таких места в 22 контроллерах
/// `lib/presentation/controllers/**` (измерено там же) были названы в карте
/// отдельным пунктом и не чинились заодно — эта правка их закрывает и ставит
/// сторож, чтобы 95-е само не завелось.
///
/// Механизм расширения — не `_sweepTargets`: `error:` не вызов функции, у
/// которого можно посчитать вложенность скобок от открывающей до закрывающей
/// — это именованный параметр, значение которого лежит в строковом
/// литерале. Извлекается сам литерал (`_errorLiteralPattern`), а офендер
/// определяется той же `_isOffending` — сигнатура утечки (`$e`, `${e}`,
/// `e.toString()` и три других частых имени) одна и та же что на проводе,
/// что в состоянии. Обход — весь `lib/presentation/`, а не только
/// `controllers/`: сторож ловит по слою, а не по списку файлов, где сегодня
/// нашлась проблема — новый экран или виджет с той же ошибкой в любом другом
/// подкаталоге `lib/presentation/` тоже будет пойман.
///
/// Красный прогон до правки (`git stash` на `lib/`, см. коммит с этой
/// правкой): 94 офендера, ровно то число, что и в измерении карты.
import 'dart:io';

import 'package:flutter_test/flutter_test.dart';

/// Целевые вызовы — по имени, не по файлу. Каждый — путь, которым текст
/// исключения может доехать наружу: пять конструкторов `WireFrame`
/// (`till_wire.dart`) и два канала задачи 3, отдающие строку в исход
/// (`DeviceCheckOutcome.unexpectedError`) или в полосу прогресса
/// (`onProgress?.call`). Regex оканчивается на `\(`, чтобы
/// [_callsMatching] мог сразу считать вложенность скобок от места вызова.
///
/// [label] — только для сообщений теста, не участвует в поиске.
const _sweepTargets = <({String label, String regex})>[
  (label: 'ErrorFrame(...)', regex: r'\bErrorFrame\('),
  (label: 'OkFrame(...)', regex: r'\bOkFrame\('),
  (label: 'UpdateFrame(...)', regex: r'\bUpdateFrame\('),
  (label: 'ProgressFrame(...)', regex: r'\bProgressFrame\('),
  (label: 'DoneFrame(...)', regex: r'\bDoneFrame\('),
  (
    label: 'DeviceCheckOutcome.unexpectedError(...)',
    regex: r'\bunexpectedError\(',
  ),
  (label: 'onProgress?.call(...)', regex: r'\bonProgress\??\.call\('),
  // Задача 16, круг правки 2. Отказ очереди печати **уезжает на
  // провод**: `LocalPaymentService` кладёт `PrintSubmitOutcome.message`
  // в `CompletionTrouble.message`, оттуда операция `pay.troubles`
  // несёт его во вкладку браузера и в снек кассиру. **Пять**
  // производителей этого текста интерполировали исключение сырьём —
  // сторож их и нашёл (разбор называл четыре, пятый —
  // `printer_settings_screen.dart`, и именно поэтому цель заведена по
  // имени вызова, а не списком файлов).
  (
    label: 'PrintSubmitOutcome.rejected(...)',
    regex: r'\bPrintSubmitOutcome\.rejected\(',
  ),
];

/// Сырая интерполяция объекта исключения — в любом месте литерала, не только
/// в начале и не только как единственное содержимое:
/// - `$name` (голая форма) — Dart останавливает такую интерполяцию на имени,
///   любое `.field` дальше — уже литеральный текст, а не часть выражения, так
///   что имя ловится независимо от того, что идёт следом;
/// - `${name}` — фигурная форма, но только когда **всё** выражение внутри
///   скобок — само имя, ничего больше;
/// - `name.toString()` — голым выражением или внутри `${...}`.
///
/// Частые имена (`error`, `e`, `err`, `ex`) — ровно те, которыми в этом файле
/// и в файлах задачи 3 названы переменные `catch` и параметры `onError`.
/// `\b` на обоих концах — намеренно: без него `$errors` (список, не
/// исключение) или `${myError}`/`${element}` ловились бы как утечка. Список
/// имён закрыт, поэтому регекс не путает переменную `element` с `e`, а
/// `errCode`/`errors` — с `err`.
///
/// **Намеренно не ловится: `${e.message}`, `${e.code}` и любой другой доступ
/// к полю, кроме `.toString()`.** Это не то же самое, что `$e`/`${e}` —
/// голая интерполяция печатает `Object.toString()` целиком (для
/// `SqliteException` — вместе с параметрами запроса), а обращение к
/// конкретному полю печатает ровно то, что в этом поле лежит и не больше.
/// `device_check_local.dart` делает это осознанно: `on ArgumentError catch
/// (e)` → `'${e.message}'` — `e.message` там всегда текст, который сам же
/// код передал в `ArgumentError(...)` при валидации привязки устройства, а
/// не параметры SQL и не что-либо пользовательское. Первая версия этого
/// регекса ловила и эту форму — красный прогон был ложным срабатыванием,
/// разобранным перед тем, как выключить его нацеленной, а не размытой
/// правкой шаблона. Проверка не защищает от `${x.someOtherField}`, где поле
/// действительно небезопасно, — это предел текстового сторожа, а не то, что
/// он проверяет и молчаливо гарантирует.
final _rawInterpolationPatterns = <RegExp>[
  RegExp(r'\$(error|e|err|ex)\b'),
  RegExp(r'\$\{\s*(error|e|err|ex)\s*\}'),
  RegExp(r'\b(error|e|err|ex)\.toString\(\)'),
];

/// Извлекает текст каждого вызова, совпавшего с [pattern] (обязан
/// оканчиваться на `\(`), целиком — от начала совпадения до соответствующей
/// закрывающей скобки, считая вложенность (часть вызовов в `till_wire.dart`
/// сама многострочная и содержит вложенные скобки).
List<String> _callsMatching(String source, RegExp pattern) {
  final calls = <String>[];
  for (final match in pattern.allMatches(source)) {
    var depth = 1;
    var i = match.end;
    while (i < source.length && depth > 0) {
      if (source[i] == '(') depth++;
      if (source[i] == ')') depth--;
      i++;
    }
    calls.add(source.substring(match.start, i));
  }
  return calls;
}

bool _isOffending(String text) =>
    _rawInterpolationPatterns.any((pattern) => pattern.hasMatch(text));

/// Каждый `.dart`-файл под [dir], кроме сгенерированных (`.g.dart`) — обход
/// по слою (весь `lib/`), а не по списку путей, названных заранее.
List<File> _dartFilesUnder(String dir) {
  return Directory(dir)
      .listSync(recursive: true)
      .whereType<File>()
      .where((f) => f.path.endsWith('.dart') && !f.path.endsWith('.g.dart'))
      .toList();
}

/// Литерал состояния экрана — именованный параметр `error:` со строковым
/// значением в одинарных кавычках (весь стиль `lib/presentation/` — только
/// такие; двойных кавычек у `error:` в дереве нет, проверено при этой
/// правке). Группа `[^']*` — содержимое литерала, ровно то, что попадёт на
/// экран.
/// **Не только `error:`.** Разбор слияния 2026-08-27 нашёл ту же утечку
/// второй формой — позиционным доводом фабрики:
/// `MovementSaveResult.failed('error.save_failed:$e')`. Именованного
/// параметра там нет, и шаблон выше её не видел, хотя текст уезжает на экран
/// ровно так же (через `errorMessage` у вызывающего).
///
/// Поэтому ловится **любой литерал ключа ошибки** — строка, начинающаяся с
/// `'error.`, где бы она ни стояла. Это признак назначения, а не формы
/// вызова: такой литерал по устройству проекта всегда едет в
/// `ErrorLocalizer.localize` и оттуда человеку. Форма вызова меняется от
/// рефакторинга, назначение — нет, и сторож, привязанный к назначению,
/// переживёт то, что сторож, привязанный к форме, пропустил.
final _errorLiteralPattern = RegExp(r"'error\.[^']*'");

void main() {
  final files = _dartFilesUnder('lib');

  test(
    'обход lib/ не пуст (страховка от вырожденного результата листинга)',
    () {
      expect(files.length, greaterThan(100));
    },
  );

  for (final target in _sweepTargets) {
    test('${target.label}: ни один вызов во всём lib/ не несёт сырую '
        'интерполяцию исключения', () {
      final pattern = RegExp(target.regex);
      final offenders = <String>[];
      var callsFound = 0;

      for (final file in files) {
        final source = file.readAsStringSync();
        final calls = _callsMatching(source, pattern);
        callsFound += calls.length;
        for (final call in calls) {
          if (_isOffending(call)) {
            offenders.add(
              '${file.path}: '
              '${call.replaceAll(RegExp(r'\s+'), ' ').trim()}',
            );
          }
        }
      }

      // Страховка от теста, который зелёный только потому, что ничего не
      // нашёл (переименование, рефакторинг, унёсший все вызовы) — та же
      // роль, что у прежнего sanityMarker по одному файлу, теперь по
      // всему обходу разом.
      expect(
        callsFound,
        greaterThan(0),
        reason:
            'ни одного вызова ${target.label} не нашлось во всём lib/ — '
            'сам сторож сломан (переименование? рефакторинг, унёсший все '
            'вызовы?)',
      );

      expect(
        offenders,
        isEmpty,
        reason:
            'наружу едет исключение через toString() — а значит, для '
            'SqliteException, параметры запроса (потенциально хэш PIN) '
            'едут в кадр/исход как есть. Прогони через safeErrorText '
            '(lib/core/errors/safe_error_text.dart). Нашедшиеся места:\n'
            '${offenders.join('\n')}',
      );
    });
  }

  test('error: в состоянии экрана (lib/presentation/**) не несёт сырую '
      'интерполяцию исключения', () {
    final presentationFiles = _dartFilesUnder('lib/presentation');
    final offenders = <String>[];
    var literalsFound = 0;

    for (final file in presentationFiles) {
      final source = file.readAsStringSync();
      for (final match in _errorLiteralPattern.allMatches(source)) {
        literalsFound++;
        final literal = match.group(0)!;
        if (_isOffending(literal)) {
          offenders.add('${file.path}: ${literal.trim()}');
        }
      }
    }

    // Та же страховка, что у сторожа по вызовам: ноль найденных литералов
    // — не «всё почищено», а сломанный обход (переименование `error:`,
    // переезд состояния на другой конструктор).
    expect(
      literalsFound,
      greaterThan(0),
      reason:
          'ни одного литерала error: не нашлось во всём '
          'lib/presentation/ — сам сторож сломан (переименование? '
          'переезд состояния на другой конструктор?)',
    );

    expect(
      offenders,
      isEmpty,
      reason:
          'состояние экрана несёт исключение через toString() — тем же '
          'путём, каким кадр провода нёс хэш PIN до задачи 2. Прогони '
          'через safeErrorText (lib/core/errors/safe_error_text.dart). '
          'Нашедшиеся места:\n'
          '${offenders.join('\n')}',
    );
  });
}
