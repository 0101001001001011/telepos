import 'dart:io';

import 'package:flutter_test/flutter_test.dart';

/// Страж главного инварианта набора иконок: **иконка, попавшая в набор,
/// показывается в продукте**.
///
/// # Почему этот тест важнее всех остальных тестов набора
///
/// Прежний набор `TeleposIcons` — 21 иконка мастера настройки — прожил в
/// репозитории почти месяц и **не использовался ни разу**. У него были:
/// конвейер на 834 строки, шрифт в ассетах, сгенерированный класс констант,
/// тест формы (`telepos_icons_test.dart`), эталонный тест
/// (`icon_font_golden_test.dart`) и сам эталон. Всё зелёное.
///
/// Ни один из этих тестов не спрашивал «а показывают ли её». Они проверяли,
/// что глиф отличается от соседнего и что шрифт грузится, — то есть форму
/// набора, а не его существование в продукте. Набор был удалён 2026-08-27
/// как мёртвый код, выглядящий живым.
///
/// Осиротел он не по недосмотру: иконки рисовались для шагов мастера, а
/// редизайн 2026-08-04 убрал со всех шагов блок с иллюстрацией — по
/// замечанию заказчика «на телеграм не похоже». Место, где они жили, исчезло
/// вместе с плакатом. Набор остался и продолжал проверяться.
///
/// Отсюда правило: **набор рисуется под места, которые существуют**, а
/// проверяется это здесь, а не намерением.
///
/// # Что тест делает, когда набора ещё нет
///
/// Молча проходит — и это не дыра. Набор собирается волнами (спека
/// `2026-08-27-telegram-icon-set-design.md`), и до первой волны файла
/// констант не существует. Тест, падающий на отсутствии того, что ещё не
/// начали, заставил бы отключить себя в тот же день.
const _iconsFile = 'lib/app/theme/telepos_icons.dart';

/// Где искать использование. Весь `lib/`, кроме самого файла констант:
/// объявление — не использование, иначе тест зеленел бы сам от себя.
const _searchRoot = 'lib';

void main() {
  test('каждая иконка набора показывается в продукте хотя бы раз', () {
    final declarations = File(_iconsFile);
    if (!declarations.existsSync()) {
      // Набор ещё не собран — проверять нечего. См. докстринг.
      return;
    }

    final names = RegExp(r'static const IconData (\w+)\s*=')
        .allMatches(declarations.readAsStringSync())
        .map((m) => m.group(1)!)
        .toList();

    expect(
      names,
      isNotEmpty,
      reason:
          'файл набора есть, а констант в нём нет — сломан разбор или '
          'генератор выдал пустой класс',
    );

    final sources = Directory(_searchRoot)
        .listSync(recursive: true)
        .whereType<File>()
        .where((f) => f.path.endsWith('.dart'))
        .where((f) => !f.path.replaceAll(r'\', '/').endsWith(_iconsFile))
        .map((f) => f.readAsStringSync())
        .join('\n');

    final unused = <String>[];
    for (final name in names) {
      if (!RegExp('TeleposIcons\\.$name\\b').hasMatch(sources)) {
        unused.add(name);
      }
    }

    expect(
      unused,
      isEmpty,
      reason:
          'эти иконки набора не показывает ни один экран. Набор, чьи иконки '
          'никто не показывает, — мёртвый код, выглядящий живым: ровно так '
          'прожил месяц прежний набор из 21 иконки, и его пришлось удалить.\n'
          'Либо иконку показать, либо убрать из набора — третьего решения у '
          'этого теста нет.\n\n${unused.join(', ')}',
    );
  });
}
