/// Выпуск сертификата с планшета можно **дойти и нажать** — дыра 1
/// ревизии 2026-09-19.
///
/// # Почему одной пробы провода мало
///
/// `test/backend/certificate_issue_op_test.dart` доказывает, что операция
/// `pay.certificateIssue` работает и что право её охраняет. Она **не
/// доказывает, что кассир может ею воспользоваться**, — и именно эту
/// операцию соседний `qr_setup_reachable_test` называл образцом класса
/// дефекта: «написана и не имеет ни одного вызывающего». Набор при этом был
/// зелёным полтора месяца.
///
/// Здесь по исходникам сверяются три звена цепочки, каждое из которых
/// рвётся молча:
///
/// 1. **точка входа привязывает порт** — без строки экран не найдёт
///    `CertificateIssuer` в контейнере и упадёт резолвом на первом нажатии;
/// 2. **браузерная таблица объявляет маршрут** и ведёт на настоящий экран,
///    а не на заглушку `WtNotPortedScreen`;
/// 3. **экрану назван дом** — вкладка открывается прямо по адресу, стека
///    переходов у неё нет, и `pop()` в ней не делает ничего.
///
/// Четвёртое звено — плитку, с которой на маршрут нажимают, — держит
/// `browser_routes_test` («на каждый объявленный маршрут кто-то ведёт»);
/// здесь она названа поимённо как якорь против слепоты обхода графа
/// импортов, тем же приёмом, что у соседей.
///
/// # Чего эта проба НЕ доказывает
///
/// - **Что выпуск с планшета действительно берёт обязательство.** Это
///   доказывает проба операции; здесь сверяются только звенья
///   достижимости, и ни одно из них не исполняется.
/// - **Что слип напечатается.** Печатает его касса, и с планшета тоже: слип
///   выпуска уходит в очередь **внутри** `LocalCertificateIssuer.issue`,
///   которую и зовёт обработчик `pay.certificateIssue`. До 2026-09-18 здесь
///   стояло обратное утверждение («не напечатается, `CertificateSlipPrinter`
///   в браузере не привязан»), и оно было неверно с первого дня: порт нужен
///   не выпуску, а **повтору**. Повтор с того дня едет своей операцией
///   (`pay.certificateSlip`), и его достижимость мерит
///   `prepayment_refund_reachable_test.dart`.
@Tags(['architecture'])
library;

import 'dart:io';

import 'package:flutter_test/flutter_test.dart';

const _entry = 'lib/web/main_web.dart';
const _table = 'lib/app/router/setup_router.dart';
const _home = 'lib/presentation/screens/terminal/terminal_home_screen.dart';

/// Комментарии не считаются: ссылка в докстринге ничего не привязывает и
/// никуда не ведёт. Ровно на этом сторожа исходника и слепнут.
String _code(String path) {
  final file = File(path);
  if (!file.existsSync()) fail('сторож смотрит в несуществующий файл $path');
  return file
      .readAsLinesSync()
      .where((l) => !l.trimLeft().startsWith('//'))
      .join('\n');
}

void main() {
  test('точка входа браузера привязывает выпуск сертификата', () {
    final source = _code(_entry);
    expect(
      source,
      contains('registerLazySingleton<CertificateIssuer>'),
      reason:
          'Без этой строки экран выпуска в браузере падает резолвом '
          '`GetIt` на первом же нажатии, а операция `pay.certificateIssue` '
          'остаётся ровно тем мёртвым кодом, каким была полтора месяца.',
    );
    expect(
      source,
      contains('WtCertificateIssuer('),
      reason:
          'выпуск обязан быть проводным: `LocalCertificateIssuer` в браузере '
          'не компилируется вовсе (drift, очередь печати), а любая третья '
          'реализация здесь — второй путь к обязательству кассы',
    );
  });

  test('браузерная таблица ведёт на настоящий экран выпуска', () {
    final source = _code(_table);
    expect(
      source,
      contains('path: AppRoutes.certificateIssue'),
      reason:
          'маршрута нет — в браузере это «Page Not Found: GoException» на '
          'плитке, которая стоит на доме терминала',
    );
    // Запись в таблице и **экран** — разные вещи: `/payment` жил в таблице
    // задолго до того, как начал открывать оплату, и вёл на
    // `WtNotPortedScreen`.
    expect(
      source,
      contains('CertificateIssueScreen('),
      reason: 'маршрут ведёт на заглушку, а не на экран выпуска',
    );
    expect(
      source,
      contains('homeRoute: AppRoutes.terminalHome'),
      reason:
          'экрану не назван дом: вкладка, открытая прямо по адресу, стека '
          'переходов не имеет, и кассир остаётся на экране выпуска навсегда',
    );
  });

  test('дом терминала ведёт на выпуск сертификата под тем же ключом', () {
    final source = _code(_home);
    expect(source, contains('context.go(AppRoutes.certificateIssue)'));
    expect(
      source,
      contains('PermissionKeys.opIssueCertificate'),
      reason:
          'плитка обязана стоять под тем же ключом, что маршрут и операция '
          'провода: показ под другим правом означал бы кнопку, которая видна '
          'одному, а работает у другого',
    );
  });
}
