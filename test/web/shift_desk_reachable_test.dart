/// Смену из браузера можно **дойти и закрыть** — решение заказчика
/// 2026-09-18.
///
/// # Почему одной пробы провода мало
///
/// `test/backend/shift_desk_op_test.dart` доказывает, что три операции
/// работают и что деньги ложатся туда же, куда с кассы. Она **не доказывает,
/// что кассир может ими воспользоваться**, — и ровно этот класс дефекта
/// дерево ловило уже четырежды: операции отзыва сеанса были готовы и
/// недостижимы; `pay.certificateIssue` написана и не имеет вызывающего;
/// `WtPaymentService` был верен и не привязан ни одной строкой; приём аванса
/// работал и не имел экрана. Каждый раз набор оставался зелёным.
///
/// # Здесь — ещё и вторая половина того же пробела
///
/// Замерено живьём 2026-09-18: окно просроченной смены в браузере говорило
/// «Закройте смену **на кассе**» и кнопки перехода не имело вовсе. Это было
/// правдой — экрана не было, и `ShiftCloseAtTill` заведена задачей 37 именно
/// затем, чтобы кассир не упирался в заглушку `/shift`. Теперь экран есть, и
/// проба требует, чтобы браузерная таблица объявила `ShiftCloseHere`:
/// оставленный `ShiftCloseAtTill` означал бы рабочий экран, до которого из
/// окна отказа по-прежнему не дойти.
@Tags(['architecture'])
library;

import 'dart:io';

import 'package:flutter_test/flutter_test.dart';

const _entry = 'lib/web/main_web.dart';
const _table = 'lib/app/router/setup_router.dart';
const _home = 'lib/presentation/screens/terminal/terminal_home_screen.dart';
const _screen = 'lib/presentation/screens/terminal/terminal_shift_screen.dart';

/// Комментарии не считаются: ссылка в докстринге ничего не привязывает и
/// никуда не ведёт. Ровно на этом сторожа исходника и слепнут.
String _code(String path) {
  final file = File(path);
  if (!file.existsSync()) fail('сторож смотрит в несуществующий файл $path');
  return file
      .readAsLinesSync()
      .where((l) {
        final t = l.trimLeft();
        return !t.startsWith('//') && !t.startsWith('///');
      })
      .join('\n');
}

void main() {
  test('точка входа браузера привязывает порт смены', () {
    final source = _code(_entry);
    expect(
      source,
      contains('registerLazySingleton<ShiftDeskRepository>'),
      reason:
          'Без этой строки экран смены не найдёт порта и скажет «эта касса '
          'не ведёт смен по проводу», а значок на доме терминала останется '
          'снимком входа — то есть оба пробела останутся ровно там, где их '
          'закрывали. Набор при этом зелен: экранные пробы регистрируют порт '
          'сами.',
    );
    expect(
      source,
      contains('WtShiftDesk('),
      reason:
          'смена обязана быть проводной: `LocalShiftDesk` в браузере не '
          'компилируется вовсе (drift)',
    );
  });

  test('браузерная таблица ведёт на настоящий экран смены', () {
    final source = _code(_table);
    expect(
      source,
      contains('path: AppRoutes.terminalShift'),
      reason:
          'маршрута нет — в браузере это «Page Not Found: GoException» на '
          'кнопке окна просроченной смены',
    );
    // Запись в таблице и **экран** — разные вещи: `/payment` жил в таблице
    // задолго до того, как начал открывать оплату, и вёл на
    // `WtNotPortedScreen`.
    expect(source, contains('TerminalShiftScreen('));
    expect(
      source,
      contains('homeRoute: AppRoutes.terminalHome'),
      reason:
          'экрану не назван дом: вкладка, открытая прямо по адресу, стека '
          'переходов не имеет, и кассир остаётся на экране навсегда',
    );
  });

  test('окно просроченной смены в браузере ведёт на этот экран', () {
    final source = _code(_table);
    expect(
      source,
      contains('ShiftCloseHere('),
      reason:
          'браузерная таблица по-прежнему объявляет `ShiftCloseAtTill` — '
          'окно «Смена открыта более 24 часов» говорит «закройте на кассе» '
          'и кнопки не имеет, при том что рабочий экран смены уже есть. '
          'Именно этот тупик и замерен живьём 2026-09-18.',
    );
    expect(
      source,
      isNot(contains('ShiftCloseAtTill()')),
      reason:
          'в браузерной таблице не должно остаться ни одного '
          '`ShiftCloseAtTill`: экран смены у неё есть',
    );
    expect(
      source,
      contains('context.go(AppRoutes.terminalShift)'),
      reason: 'кнопка окна ведёт не на экран смены браузера',
    );
  });

  test('дом терминала ведёт на смену и знает о просроченной', () {
    final source = _code(_home);
    expect(source, contains('context.go(AppRoutes.terminalShift)'));
    expect(
      source,
      contains('PermissionKeys.navShift'),
      reason:
          'плитка обязана стоять под тем же ключом, что маршрут и три '
          'операции провода',
    );
    // Значок обязан читать **живое** состояние, а не снимок входа: именно
    // снимок и показывал зелёную галочку при просроченной смене.
    //
    // # Круг правки 1: упоминания типа мало, и это измерено диверсией
    //
    // Первая редакция требовала здесь `contains('ShiftDeskRepository')` и
    // `contains('overAge')`. Диверсия — заменить тело `build` на
    // `_fromSnapshot(context)`, то есть вернуть значок к снимку входа, —
    // **прошла зелёной**: и getter порта, и ветка `overAge` остались в
    // файле мёртвым кодом, а сторож смотрел на присутствие слов, а не на
    // то, что их читают.
    //
    // Поэтому требуется **живое звено**: подписка, открытая на доме
    // терминала. Мёртвым кодом её не подделать — `StreamBuilder`, которого
    // никто не строит, в файле не нужен ни для чего.
    expect(
      source,
      contains('StreamBuilder<ShiftDeskView>'),
      reason:
          'дом терминала снова рисует значок смены по снимку, взятому при '
          'входе: он остаётся зелёным часами после закрытия смены и при '
          'переходе суток. Упоминания типа порта в файле для этого мало — '
          'проверено диверсией.',
    );
    expect(
      source,
      contains('.watch()'),
      reason: 'подписка не открывается — значок не узнает об изменении',
    );
    expect(
      source,
      contains('view.overAge'),
      reason:
          'у значка снова два состояния вместо трёх: просроченная смена '
          'неотличима от обычной, и зелёная галочка на ней — прямая ложь. '
          '`view.overAge`, а не голое `overAge`: второе есть и у мёртвой '
          'ветки перечисления.',
    );
  });

  test('экран смены не считает возраста и не считает денег кассы', () {
    final source = _code(_screen);
    // Возраст смены приходит с кассы готовым: предел живёт в `ShiftAgeRule`,
    // которым касса **запирает продажу**. Посчитай вкладка его сама — значок
    // говорил бы одно, а продажа другое.
    for (final forbidden in ['ShiftAgeRule', 'hours: 24', 'Duration(hours']) {
      expect(
        source,
        isNot(contains(forbidden)),
        reason:
            'экран считает возраст смены сам ($forbidden) — второй счёт '
            'возраста разойдётся с тем, которым касса запирает продажу',
      );
    }
    // Единственная арифметика, которая здесь законна, — вычитание для
    // показа расхождения. Сложений выручки, изъятий и остатков быть не
    // должно: их считает касса.
    for (final forbidden in ['cashSales', 'expenseTotal', 'billCounts']) {
      expect(
        source,
        isNot(contains(forbidden)),
        reason:
            'экран считает деньги кассы сам ($forbidden) — у кассы появился '
            'второй бухгалтер',
      );
    }
  });
}
