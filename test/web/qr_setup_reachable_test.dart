/// Настройку QR из браузера можно **дойти и нажать** — решение заказчика
/// 2026-09-18.
///
/// # Почему одной пробы провода мало
///
/// `test/backend/qr_setup_op_test.dart` доказывает, что четыре операции
/// работают и что ключ не возвращается. Она **не доказывает, что владелец
/// может ими воспользоваться**, — и ровно этот класс дефекта дерево ловило
/// уже четырежды: операции отзыва сеанса были готовы и недостижимы;
/// `pay.certificateIssue` написана и не имела ни одного вызывающего
/// (закрыто дырой 1 ревизии 2026-09-19 — `certificate_issue_reachable_test`
/// теперь сторожит те же три звена для неё);
/// `WtPaymentService` был верен и не привязан ни одной строкой; приём аванса
/// работал и не имел экрана в браузере. Каждый раз набор оставался зелёным.
///
/// Здесь по исходникам сверяются три звена цепочки, каждое из которых
/// молчаливо рвётся:
///
/// 1. **точка входа привязывает порт** — без строки экран в браузере не
///    построит форму вовсе и скажет «настройка делается на кассе»;
/// 2. **браузерная таблица объявляет маршрут** и ведёт на настоящий экран, а
///    не на заглушку `WtNotPortedScreen`;
/// 3. **экрану назван дом** — вкладка открывается прямо по адресу, стека
///    переходов у неё нет, и `pop()` в ней не делает ничего.
///
/// Четвёртое звено — плитку, с которой на маршрут нажимают, — держит
/// `browser_routes_test` («на каждый объявленный маршрут кто-то ведёт»), и
/// повторять его здесь значило бы завести второе место, расходящееся с
/// первым молча.
@Tags(['architecture'])
library;

import 'dart:io';

import 'package:flutter_test/flutter_test.dart';

const _entry = 'lib/web/main_web.dart';
const _table = 'lib/app/router/setup_router.dart';
const _home = 'lib/presentation/screens/terminal/terminal_home_screen.dart';

/// Комментарии не считаются: ссылка в докстринге ничего не привязывает и
/// никуда не ведёт. Ровно на этом сторожа исходника и слепнут.
String _code(String path) {
  final file = File(path);
  if (!file.existsSync()) fail('сторож смотрит в несуществующий файл $path');
  return file
      .readAsLinesSync()
      .where((l) => !l.trimLeft().startsWith('//'))
      .join('\n');
}

void main() {
  test('точка входа браузера привязывает порт настройки QR', () {
    final source = _code(_entry);
    expect(
      source,
      contains('registerLazySingleton<QrProviderSetupRepository>'),
      reason:
          'Без этой строки контроллер настройки не найдёт порта в контейнере '
          'и экран скажет «настройка делается на самой кассе» — то есть '
          'пробел останется ровно там, где его закрывали. Набор при этом '
          'зелен: экранные пробы регистрируют порт сами.',
    );
    expect(
      source,
      contains('WtQrProviderSetup('),
      reason:
          'настройка обязана быть проводной: `QrPaymentDesk` в браузере не '
          'компилируется вовсе (drift, HTTP-клиент), а любая третья '
          'реализация здесь — второй путь к ключу провайдера',
    );
  });

  test('браузерная таблица ведёт на настоящий экран настройки QR', () {
    final source = _code(_table);
    expect(
      source,
      contains('path: AppRoutes.qrProviderSettings'),
      reason:
          'маршрута нет — в браузере это «Page Not Found: GoException» на '
          'плитке, которая стоит на доме терминала',
    );
    // Запись в таблице и **экран** — разные вещи: `/payment` жил в таблице
    // задолго до того, как начал открывать оплату, и вёл на
    // `WtNotPortedScreen`. Сторож, смотрящий на наличие записи, был бы зелен
    // на заглушке.
    expect(
      source,
      contains('QrPaymentSetupScreen('),
      reason: 'маршрут ведёт на заглушку, а не на экран настройки',
    );
    expect(
      source,
      contains('homeRoute: AppRoutes.terminalHome'),
      reason:
          'экрану не назван дом: вкладка, открытая прямо по адресу, стека '
          'переходов не имеет, `pop()` в ней не делает ничего, и владелец '
          'остаётся на экране настройки навсегда',
    );
  });

  test('дом терминала ведёт на настройку QR', () {
    // Не подмена `browser_routes_test` («на каждый объявленный маршрут
    // кто-то ведёт»), а якорь против его собственной слепоты: тот сторож
    // обходит граф импортов, и опечатка в обходе сделала бы его зелёным на
    // пустом множестве. Здесь названы файл и переход.
    final source = _code(_home);
    expect(source, contains('context.go(AppRoutes.qrProviderSettings)'));
    expect(
      source,
      contains('PermissionKeys.settingsAccounts'),
      reason:
          'плитка обязана стоять под тем же ключом, что маршрут и четыре '
          'операции провода: показ под другим правом означал бы кнопку, '
          'которая видна одному, а работает у другого',
    );
  });
}
