/// Одноразовые коды, которыми оператор впускает планшет.
///
/// # Что это и чем это не является
///
/// Это **не** приглашение `rk_pki`. Приглашение там впускает машину в
/// удостоверяющий центр установки: оно сжигается выдачей сертификата и стоит
/// ровно столько, сколько стоит право получить сертификат. Здесь право другое
/// и меньшее — один раз скачать **открытый** корневой сертификат, — и
/// смешивать их значило бы, что скачивание корня жжёт приглашение, которым
/// терминалу ещё предстоит записаться.
///
/// # Зачем вообще пускать по коду, если корень открыт
///
/// Корень — публичный сертификат; знание его не даёт ничего, ключа в нём нет.
/// Код закрывает не тайну, а **момент**: корень попадает на устройство ровно
/// тогда, когда человек стоит рядом и осознанно привязывает планшет к этой
/// кассе. Установка корня — это решение доверять, и принимать его должен тот,
/// кто в эту секунду смотрит на кассу, а не браузер, забредший на адрес.
///
/// Записано прямо, чтобы никто не считал эту меру защитой от подмены кассы:
/// от неё она не защищает и защищать не может. Планшет, которому подсунули
/// чужой корень, узнает об этом не здесь.
library;

import 'dart:math';

/// Мятый код и срок, до которого он годен.
class PairingInvite {
  const PairingInvite({required this.code, required this.expiresAt});

  /// То, что оператор читает вслух или показывает кодом.
  final String code;

  final DateTime expiresAt;
}

/// Выдаёт коды и помнит, какие ещё не потрачены.
///
/// В памяти процесса, и это осознанно: код живёт минуты, переживать перезапуск
/// кассы ему незачем, а запись на диск сделала бы из недолговечного пропуска
/// долговечный след.
class PairingInvites {
  PairingInvites({
    this.lifetime = const Duration(minutes: 15),
    Random? random,
    DateTime Function()? clock,
  }) : _random = random ?? Random.secure(),
       _clock = clock ?? DateTime.now;

  final Duration lifetime;
  final Random _random;
  final DateTime Function() _clock;

  /// Алфавит Crockford Base32: 32 знака, каждый несёт ровно 5 бит.
  ///
  /// Ни одной двусмысленной пары: буквы `I`, `L`, `O`, `U` из латиницы
  /// изъяты намеренно (не опечатка) — `I`/`L` неотличимы от цифры `1` на
  /// экране мелким моноширинным шрифтом, `O` неотличима от `0`, а `U`
  /// изъята по тому же соглашению Crockford (чтобы диктуемый вслух код не
  /// складывался в случайное слово). Оставшиеся 10 цифр и 22 буквы дают
  /// точную степень двойки — 32 = 2⁵ — поэтому энтропия кода считается без
  /// остатка: длина × 5 бит, ни одного бита не теряется на округление, как
  /// потерялось бы при делении на 26 или на 36.
  static const _alphabet = '0123456789ABCDEFGHJKMNPQRSTVWXYZ';

  /// Знаков в коде. 10 × 5 бит = 50 бит энтропии — обоснование смотри в
  /// докстринге [mint].
  static const _codeLength = 10;

  /// Через сколько знаков ставить разделитель на экране — только для
  /// чтения; сам код от разделителей не зависит (см. [_normalize]).
  static const _groupSize = 5;

  /// Ключ карты — код в каноническом виде (см. [_normalize]), а не в том,
  /// что вернул [mint]: иначе `redeem`/`revoke` пришлось бы нормализовать
  /// сравнение на каждый вызов, а не один раз на запись.
  final Map<String, DateTime> _outstanding = <String, DateTime>{};

  /// Сколько кодов сейчас ждут предъявления. Наблюдаемая величина: коды,
  /// которые копятся и не тратятся, иначе ничем не видны.
  int get outstanding {
    _forget();
    return _outstanding.length;
  }

  /// Новый код.
  ///
  /// `Random.secure()`, а не `Random()`: угадываемый код — это код, который не
  /// нужен вовсе, и разница между ними невидима глазом. Каждый знак берётся
  /// из [_alphabet] равновероятно (`nextInt(32)` без остатка от деления —
  /// сам алфавит выбран степенью двойки ровно затем, чтобы отбрасывать
  /// нечего было), поэтому 10 знаков дают ровно 2¹⁰×⁵ = 2⁵⁰ равновероятных
  /// кодов — 50 бит энтропии буквально, не оценочно.
  ///
  /// # Почему 50 бит достаточно коду без замка попыток
  ///
  /// PIN кассира — 4 цифры, 10⁴ ≈ 2¹³·³ комбинаций — держится не этим
  /// числом, а замком: после нескольких неверных попыток вход блокируется,
  /// и именно замок делает 13 бит достаточными. У кода привязки замка нет —
  /// `redeem` можно звать сколько угодно раз без штрафа за промах, — поэтому
  /// весь запас обязан быть в самом числе.
  ///
  /// Верхняя граница на то, сколько попыток атакующий успеет сделать за
  /// время жизни кода (15 минут = 900 с): даже щедро — 1000 запросов в
  /// секунду по TLS+QUIC на встроенном железе кассы, что для установки
  /// нового TLS-соединения на каждый запрос уже нереалистично много, —
  /// это 900 000 ≈ 2¹⁹·⁸ попыток за весь срок. Вероятность угадать один из
  /// 2⁵⁰ кодов за 2¹⁹·⁸ попыток — 2¹⁹·⁸⁄2⁵⁰ = 2⁻³⁰·² ≈ 8×10⁻¹⁰, меньше одного
  /// шанса из миллиарда. Даже на два порядка более щедрой оценке скорости
  /// (100 000 зпр/с) вероятность остаётся ниже 10⁻⁶ — на четыре порядка
  /// строже эффективной защиты PIN-замка (типовой замок пускает 5 попыток
  /// до блокировки — 5/10⁴ = 5×10⁻⁴). Код тратится один раз и по счётчику
  /// не размениваем — но это уже запас сверху: сам расчёт исходит из того,
  /// что промах ничего не стоит.
  ///
  /// # Вторая поверхность, тратящая код: `terminals.register` — расчёт выше
  /// её не учитывал
  ///
  /// Разбор финальной волны правок (2026-08-24) назвал то, что расчёт выше
  /// не называет: с задачи 6 плана «знакомство терминала с кассой» [redeem]
  /// зовёт не только `GET /ca.crt?invite=` — его же зовёт обработчик
  /// `terminals.register` (`TillOperations.askHandlers`,
  /// `lib/backend/till_operations.dart`) на **уже открытой** QUIC-сессии.
  /// «1000 запросов в секунду нереалистично много» выше опирался на
  /// стоимость **нового TLS-соединения на каждый запрос** — а у этой
  /// поверхности такой стоимости нет вовсе: сессия уже установлена одним
  /// рукопожатием, дальше каждая попытка — это только кадр на существующем
  /// потоке (или новый поток той же сессии, тоже без нового TLS), и отказ
  /// на неверный код возвращается раньше [_forget]/`_pruneUnusedTerminals`
  /// — до единого обращения к базе (проверка кода в
  /// `TillOperations.askHandlers[terminalRegister.name]` — первая строка
  /// после разбора имени, `redeem(code)` над структурой [_outstanding] в
  /// памяти). Ограничения TLS-рукопожатия здесь нет и в помине — только
  /// стоимость разбора кадра и одного поиска в `Map`, то есть без всякого
  /// искусственного замедления с этой стороны.
  ///
  /// **Вывод выдерживает с запасом даже так, другим счётом.** Возьмём
  /// границу на четыре порядка щедрее исходной «1000/с» — 10 000 000
  /// попыток в секунду (десять миллионов, воспроизвести которые пришлось бы
  /// одному процессу Dart на встроенном железе кассы поверх QUIC/rk_quic —
  /// оценка не измерена и намеренно абсурдно щедра, а не правдоподобна) за
  /// весь 900-секундный срок жизни кода: 9×10⁹ ≈ 2³³·⁰⁷ попыток. Вероятность
  /// угадать — 2³³·⁰⁷⁄2⁵⁰ = 2⁻¹⁶·⁹³ ≈ 1,6×10⁻⁵ — на полтора порядка ниже
  /// типового PIN-замка (5×10⁻⁴) даже на этой заведомо завышенной оценке
  /// скорости. Вывод «50 бит достаточно коду без замка попыток» остаётся в
  /// силе — но именно потому, что запас (50 бит против практических частот
  /// хоть по TLS, хоть внутри открытой сессии) велик, а не потому, что
  /// исходный довод про стоимость TLS-рукопожатия покрывал обе поверхности:
  /// не покрывал.
  PairingInvite mint() {
    _forget();
    final buffer = StringBuffer();
    for (var i = 0; i < _codeLength; i++) {
      if (i > 0 && i % _groupSize == 0) buffer.write('-');
      buffer.write(_alphabet[_random.nextInt(_alphabet.length)]);
    }
    final code = buffer.toString();
    final expiresAt = _clock().add(lifetime);
    // Нормализованный код непуст всегда: свежесгенерированный — не то,
    // что может обнулиться в [_normalize].
    _outstanding[_normalize(code)!] = expiresAt;
    return PairingInvite(code: code, expiresAt: expiresAt);
  }

  /// Тратит код. `true` ровно один раз на каждый выданный и не просроченный.
  ///
  /// Второй вызов с тем же кодом отвечает `false`: пропуск, годный дважды, —
  /// это пропуск, оставшийся у того, кто им уже воспользовался.
  ///
  /// Принимает то же самое в любом регистре, с разделителями-дефисами или
  /// без них — человек набирает код руками, глядя на экран кассы, и форма,
  /// в которой он его наберёт, не обязана совпадать буква в букву с тем, что
  /// показал [mint] (см. [_normalize]).
  bool redeem(String? code) {
    _forget();
    final normalized = _normalize(code);
    if (normalized == null) return false;
    return _outstanding.remove(normalized) != null;
  }

  /// Отменяет один конкретный не потраченный код — не тратит его, а снимает.
  ///
  /// # Чем это отличается от [redeem] при одинаковом теле
  ///
  /// Операция над картой та же самая (убрать запись), но названа отдельно,
  /// потому что событие — другое: [redeem] означает «код предъявили /ca.crt
  /// и он сработал», [revoke] означает «код выдан не был, и мятивший его
  /// экран решил, что он больше не нужен» (правка 2026-08-23, задача «касса
  /// говорит, что набирать»: «Выдать новый код» отзывает прежний, если тот
  /// ещё не предъявлен, — иначе экран показывал бы один код, а годным
  /// оставался другой, ранее выданный тем же щелчком по той же кнопке).
  /// Разница пока не читается ни одним потребителем этого класса, но
  /// разойдись имена местами — лог/счётчик «сколько кодов предъявлено»
  /// однажды понадобится, и тогда [revoke] не должен приплюсовываться к
  /// нему как redeem.
  ///
  /// `false`, если кода уже нет — потрачен, просрочен или отозван раньше:
  /// вызывающему решить, была ли это гонка.
  bool revoke(String? code) {
    _forget();
    final normalized = _normalize(code);
    if (normalized == null) return false;
    return _outstanding.remove(normalized) != null;
  }

  /// Убирает просроченные. Вызывается на каждом действии, чтобы карта не росла
  /// на кассе, которая работает месяцами без перезапуска.
  void _forget() {
    final now = _clock();
    _outstanding.removeWhere((_, expiresAt) => !expiresAt.isAfter(now));
  }

  /// Приводит набранный человеком код к тому же виду, в котором он лежит в
  /// [_outstanding]: регистр роли не играет (`ToUpperCase`), пробелы и
  /// дефисы — только для чтения на экране и при сравнении выбрасываются, а
  /// буквы, которые по вине почерка или экрана могли быть прочитаны вместо
  /// цифры, приводятся к цифре тем же правилом, что определяет сам Crockford
  /// Base32: `O` (буква) → `0` (цифра), `I`/`L` → `1`. Ни `O`, ни `I`, ни `L`
  /// [mint] никогда не кладёт в код сам — так что здесь это не расширение
  /// алфавита, а только приём для той цифры, которую [_alphabet] и так
  /// содержит.
  ///
  /// `null`, если после нормализации нечего сравнивать — тот же смысл, что
  /// был у `code == null || code.isEmpty` до этой правки.
  static String? _normalize(String? raw) {
    if (raw == null) return null;
    final buffer = StringBuffer();
    for (final unit in raw.toUpperCase().codeUnits) {
      final ch = String.fromCharCode(unit);
      switch (ch) {
        case '-':
        case ' ':
        case '_':
          continue;
        case 'O':
          buffer.write('0');
          break;
        case 'I':
        case 'L':
          buffer.write('1');
          break;
        default:
          buffer.write(ch);
      }
    }
    final normalized = buffer.toString();
    return normalized.isEmpty ? null : normalized;
  }
}
