/// Растущая задержка на неверный PIN. Верный PIN она не трогает никогда.
///
/// docs/system-architecture.md, раздел 16 (Информационная безопасность,
/// Инциденты, Обнаружение) требует поднимать тревогу на серию неудачных
/// входов. До 2026-08-20 ограничения не было нигде: PIN из четырёх цифр —
/// это десять тысяч значений, и перебрать их мешала только скорость пальцев.
///
/// # Задача 6 (2026-08-20): ключ — `userId`, не `terminalId`
///
/// Первая версия замка ключевалась `terminalId` — рассуждение было: терминал
/// принадлежит тому, кто за ним стоит. Дыра нашлась в самой посылке:
/// `terminals.register` открыта и вставляет строку без дедупликации, значит
/// `terminalId` — это то, что **выдаёт сама касса по первому требованию**, а
/// не то, чем владеет нападающий. `userId`, наоборот, нападающий не
/// выбирает — он **именует жертву**, и это имя не меняется от попытки к
/// попытке. Замок был переведён на него: пять неудач под одним `userId`
/// запирали кассира на минуту, с любого терминала.
///
/// # Задача 7 (2026-08-21): замок перестаёт быть замком
///
/// Задача 6 сама назвала цену перевода: **имя кассира не секрет** — список
/// кассиров виден на экране входа, — и тот, кто знает только имя, не PIN,
/// мог запирать его на минуту неограниченно долго, с любого терминала. Пять
/// неверных PIN раз в минуту держали жертву запертой навсегда, без единого
/// верного предположения. Для кассы это хуже перебора: запертый кассир не
/// продаёт, и деньги теряются сразу же, а не после того, как кто-то угадает
/// PIN.
///
/// Правка этой задачи убирает самую причину: **замка, отказывающего
/// правильному PIN, больше нет вовсе**. [penalizeFailure] не запирает —
/// он **задерживает** ответ, и чем больше неудач накопилось под этим ключом,
/// тем дольше задержка следующей. Заперт снаружи теперь нельзя никого —
/// можно только сделать подбор дороже для того, кто действительно ошибается
/// PIN-ом.
///
/// # Правка 1 разбора фаз 3/4 закрытия долга (2026-08-21): вызывающий
/// сменил момент, класс — нет
///
/// До этой правки `LocalAuthRepository.login()` звал [penalizeFailure]
/// только **после** того, как PIN уже подтверждённо не подошёл — «верная
/// попытка эту задержку не видит: она проверяется и отвечает немедленно»,
/// говорил докстринг здесь раньше. Разбор нашёл в этом саму дыру: обработчики
/// провода запускаются параллельно (`unawaited`, `till_wire.dart`), и раз
/// быстрый ответ отличал успех от неудачи, нападающий, слизнувший тысячи
/// попыток разом, не ждал ни одной задержки — ждал (и то не он) только тот
/// один ответ, который приходил быстро, то есть верный.
///
/// Теперь `login()` зовёт [penalizeFailure] **до** проверки PIN, на каждую
/// попытку с реальным кандидатом, верную и неверную одинаково — подробности
/// и довод, почему это не запирание, в докстринге `LocalAuthRepository
/// .login`. Класс здесь не менялся ни на строку: он уже считал синхронно —
/// сменился только момент, в который его зовут. (Очередь по ключу, о
/// которой говорил этот абзац изначально, появлялась в классе позже этой же
/// задачи и была снята правкой 1 БЛОКЕРА, 2026-08-22, — см. ниже.)
///
/// # Второй круг задачи 7 (2026-08-21), пункт 1: предел одновременных
/// ожиданий снят
///
/// Первая версия этой правки завела `maxConcurrentPenalties` — предел, сколько
/// попыток касса держит одновременно ждущими свою задержку, — из опасения,
/// что нападающий, открывший много параллельных попыток, займёт кассу их
/// ожиданием. При достижении предела попытка отказывалась ждать вовсе и
/// возвращала `PenaltyOutcome.tooBusy` мгновенно, с нулевой задержкой.
///
/// Опасение оказалось ложным, а лекарство — дырой хуже болезни. Ожидание
/// здесь — это таймер Dart (`Future.delayed`), не поток и не открытое
/// соединение: двадцать, двести, две тысячи отложенных ответов не стоят
/// кассе практически ничего, кроме записи в таблице таймеров рантайма.
/// Настоящая цена, наоборот, была в самом пределе: счётчик `_activePenalties`
/// **общий на всю кассу** и **полностью управляемый нападающим** — он же и
/// решает, сколько параллельных неверных попыток открыть. Открыв двадцать (по
/// любым ключам, не обязательно по жертве) и держа их занятыми долгим сном,
/// он превращал в мгновенный, бесплатный проход **все следующие** попытки,
/// включая попытки по имени настоящей жертвы: единственным ограничителем
/// оставался PBKDF2 (~206 мс на кандидата), то есть ровно то, что было **до
/// всей этой работы**. Механизм, заведённый против отказа в обслуживании,
/// стал калиткой в обход подбора.
///
/// Предел снят целиком, без замены очередью: очередь отодвинула бы то же
/// самое исчерпание памяти на потом, а не устранила бы его, и вдобавок
/// поставила бы в неё вперемешку и настоящих кассиров, и нападающего — нет
/// способа отличить одного от другого на этом этапе, только по счёту неудач,
/// который и так уже учтён. [penalizeFailure] теперь либо ждёт свою полную
/// задержку, либо (для льготных неудач) не ждёт вовсе — третьего пути нет, и
/// `PenaltyOutcome` вместе с ним ушёл: у метода один исход, а не выбор из
/// двух.
///
/// **Единственный настоящий ограниченный ресурс здесь — не таймер, а изолят
/// под выработку PBKDF2** (`LocalAuthRepository._matchAll`, `Isolate.run`):
/// каждая попытка входа — верная или нет — платит за него реальным CPU ещё
/// до того, как дойдёт до этого класса. Ограничитель для него в этом круге
/// правки **сознательно не заведён**: `Isolate.run` спавнил по изоляту на
/// попытку и до всей серии задач про замок, это не регрессия, которую внёс
/// именно этот файл, и не связано с найденной дырой (она была именно в
/// пропуске проверки, а не в цене изолята). Ограничивать его правильно —
/// очередью, а не пропуском, ровно по тому же рассуждению, что и выше, —
/// самостоятельная задача со своей мерой (сколько держать в очереди, как не
/// заставить кассира ждать своей же проверки за спиной у нападающего) и
/// заслуживает отдельного разбора, а не бокового следствия в этом файле.
///
/// ## Величины
///
/// - [graceFailures] = 2 — первые две неудачи не стоят ничего сверх
///   собственной цены проверки (PBKDF2, ~206 мс на кандидата,
///   `pin_credential.dart:292`). Это цена опечатки, не подбора: два подряд
///   неверных PIN — обычное дело у человека, а не сигнал атаки.
/// - [baseDelay] = 1 секунда, [maxDelay] = 30 секунд, рост — удвоением на
///   каждую следующую неудачу (третья неудача — 1 с, четвёртая — 2 с, ...,
///   девятая и далее — потолок в 30 с). Удвоение выбрано, а не линейный
///   рост, потому что цель — сделать **длинную серию** невыносимой, а не
///   растянуть первые несколько неудач: у линейного роста N-я неудача стоит
///   `N × шаг`, и подбор всего пространства всё ещё линеен по времени;
///   у удвоения после десятка неудач ответ уже упирается в потолок, и
///   каждая дальнейшая неудача обходится нападающему ровно в [maxDelay].
///   Для кассира это невидимо: он не подбирает, у него один-два неверных
///   PIN за раз, максимум секунда-другая. Потолок в 30 секунд — то, что
///   держит задержку задержкой, а не замком: без потолка счётчик,
///   растущий без края, стал бы тем же отказом в обслуживании, что и
///   старый замок, только развёрнутым во времени, а не в булевом «заперто».
///
///   Посчитано, не оценено на глаз (`throttle-wall-report.md`): сумма
///   [_delayForCount] по всем c = 0..9999 (льгота — первые три бесплатны,
///   затем 1+2+4+8+16 с на четвёртую–восьмую, дальше потолок в 30 с на
///   каждую из оставшихся 9992) даёт **299791 секунду — 83 часа 16 минут**
///   на полный перебор 10⁴ значений PIN одним **последовательным**
///   нападающим — тем, кто ждёт ответ прежде, чем послать следующую попытку.
///   Это число не изменилось правкой 1 БЛОКЕРА (2026-08-22, см. ниже): для
///   последовательного нападающего оно и не могло — его собственная
///   стратегия (ждать ответа) уже растягивает атаку по времени независимо
///   от того, что делает эта очередь.
///
///   Параллельный нападающий (шлёт много попыток разом, не дожидаясь ответов)
///   — другое число, и оно менялось этой работой дважды в разные стороны;
///   актуальное — в разделе «Правка 1 БЛОКЕРА» ниже.
///
/// # Вход без выбора кассира (walk-up)
///
/// Экран может прислать попытку вовсе без `userId` (набрали PIN, никого не
/// выбрав — касса перебирает всех сама, см. `LocalAuthRepository.login`).
/// Ключевать здесь нечем: заявленной жертвы нет. У walk-up свой общий на
/// кассу счётчик — один на все терминалы и на всех кассиров разом, потому
/// что `terminalId` тут так же подделываем, как и везде, а имени нет вовсе.
/// Тот же принцип «задержка, не замок» действует и здесь: серия неудач без
/// выбора имени просто делает следующую попытку walk-up на этой кассе
/// медленнее, а не отказывает поимённому кассиру. Дорого это не выходит:
/// `walkUpEnabled` выключен по умолчанию (`ThisPos.walkUpEnabled == false`,
/// `local_auth_repository.dart`), так что путь занят только теми точками,
/// что осознанно его включили.
///
/// `terminalId` остаётся вторым ключом, независимым от «кто»: и здесь, как
/// и в задаче 6, задержка берётся как большая из двух — по «кто» (кассир
/// или общий walk-up) и по терминалу, — так что перебор с ротацией
/// `terminalId` (задача 6 показала: `terminals.register` открыта и раздаёт
/// новый `terminalId` бесплатно) по-прежнему упирается в счётчик `userId`,
/// который ротация не трогает.
///
/// # Пункт 3 второго круга задачи 7 (2026-08-21): `_failures` больше не
/// растёт бесконечно
///
/// До этой правки записи из `_failures` удалял только [recordSuccess] —
/// ни срока, ни предела размера не было, и докстринг подавал это как
/// достоинство («часы не нужны»). Но ключ `t:<id>` заводится бесплатно (см.
/// задачу 6: `terminals.register` открыта), а касса «работает месяцами без
/// перезапуска» — мелко по байтам одной записи, но безгранично по росту
/// карты.
///
/// Приём — тот же, что у `SessionRegistry._forget()`
/// (`session_registry.dart`): ленивая уборка на каждом обращении к
/// [penalizeFailure], без будильника и без отдельного таймера. Запись,
/// по которой дольше [staleAfter] не было неудач, стирается при следующем
/// вызове (любом, не обязательно по тому же ключу) — см. [_forget].
///
/// # Правка 1 разбора (2026-08-21): очередь по ключу — снята правкой 1
/// БЛОКЕРА, см. следующий раздел
///
/// Этот раздел был здесь и описывал `_queueTail` — карту хвостов очереди,
/// к которой пристёгивалась каждая новая неудача того же ключа, так что N
/// неудач, отправленных разом, стоили ровно то же, что и N отправленных
/// одна за другой. Измеренная тогда цель («199 мс параллельно против 8466 мс
/// последовательно на 200 неудач — 223×, параллельный подбор почти
/// бесплатен») была решена честно и подтверждена прогоном. Но у решения
/// была цена, которую тот прогон не проверял: очередь суммирует задержки
/// **чужих** неудач наравне со своими, а сама она ключуется тем же `userId`,
/// каким может назваться и честный кассир. Раздел ниже — то, что это значило
/// на практике, и почему `_queueTail` больше нет.
///
/// # Правка 1 БЛОКЕРА закрытия долга (2026-08-22): очередь была самой дырой
///
/// ## Что нашёл разбор
///
/// Очередь `_queueTail` не различала, чья неудача в ней стоит. Честная
/// попытка кассира с верным PIN считается `penalizeFailure` тем же ходом,
/// что и неудача (докстринг `LocalAuthRepository.login`, «замок ждёт до
/// проверки»), и её ожидание вставало в тот же хвост, что и ожидания уже
/// накопленных чужих неудач по тому же `userId`. Раз очередь суммирует, а не
/// берёт максимум, стена честной попытки росла вместе с числом чужих
/// неудач — **без потолка**: измерено (`throttle-cap-report.md`,
/// `fake_async` на настоящих величинах прода) — при 200 чужих неудачах по
/// ключу жертвы честная попытка после них ждала 1 ч 36 мин; при 1000 — 8 ч
/// 16 мин; при 10⁴ — 83 часа. Нападающему для этого не был нужен PIN и тем
/// более пароль — только ~200 кадров `auth.login`, посланных не дожидаясь
/// ответов, по имени, которое видно на экране входа (задача 7 уже называла
/// эту цену для замка, отказывающего в доступе; очередь воспроизвела ту же
/// цену другим механизмом).
///
/// Хуже: `terminals.selfEnsure` — `OpenAccess`. Неаутентифицированный, кто
/// дотянулся до кассы по QUIC, открывает сессию, зовёт его — и его
/// `session → terminal` становится терминалом **самой кассы** (`isSelf`,
/// `TillOperations._sessionTerminals`). Каждый его неверный `auth.login`
/// растит тот же ключ `t:<self>`, по которому платит и честный кассир за
/// десктопной кассой — `LocalAuthRepository` в процессе один. То есть
/// неаутентифицированное устройство в сети магазина запирало вход всем.
///
/// ## Решение: очередь снята, throughput ограничен иначе
///
/// **Запертая касса не продаёт, и деньги теряются сразу и наверняка.**
/// Перебор требует доступа в сеть магазина и оставляет следы (журнал
/// событий безопасности — фаза 8, не эта работа). Поэтому размен решён в
/// пользу доступности:
///
/// 1. **`_queueTail` снята целиком.** [penalizeFailure] снова ждёт свой
///    личный, независимый таймер (см. докстринг там) — ни один вызов не
///    ждёт, пока доиграют чужие. Задержка любой попытки ограничена сверху
///    [maxDelay] (30 секунд) — **не часами**, и не зависит от того, сколько
///    чужих неудач по тому же ключу накопилось раньше: `_delayForCount`
///    капает и растущий счёт, и, тем самым, саму задержку одной попытки.
///    Честный кассир после любой чужой серии ждёт не дольше 30 секунд —
///    измерено тем же прогоном, что и абзац выше. **Это верно только про
///    [LoginThrottle] саму по себе**, не про вход целиком — правка А
///    БЛОКЕРА закрытия долга (2026-08-22) нашла, что докстринг этого класса
///    именно так и читался в отчёте (`throttle-cap-report.md`), а на деле
///    30 секунд — это стена ОДНОЙ подсистемы: `LocalAuthRepository.login`
///    зовёт [penalizeFailure] и только потом `_matchAll`, и вторая ждёт
///    свою собственную очередь — `Pbkdf2Gate`, пункт 3 ниже. Настоящее
///    ожидание входа — сумма обеих стен, не 30 секунд.
/// 2. **Постоянный пол времени ответа остаётся.** [penalizeFailure] всё ещё
///    зовётся до проверки PIN, на каждую попытку с реальным кандидатом,
///    верную и неверную одинаково (`LocalAuthRepository.login`) — оракул
///    «быстрый ответ = верный PIN» не возвращается: у верной и у неверной
///    попытки с одним и тем же накопленным счётом задержка идентична, а
///    сама проверка (`PinCredential._equalInConstantTime`,
///    `pin_credential.dart`) — постоянного времени независимо от исхода.
/// 3. **Throughput ограничен очередью на выработку PBKDF2, а не цепной
///    задержкой.** Снятие `_queueTail` возвращает то, что она была призвана
///    закрыть, — параллельный нападающий больше не платит суммой задержек.
///    Но он платит другим настоящим ограничителем: `LocalAuthRepository
///    ._matchAll` (PBKDF2, ~206 мс на кандидата) теперь идёт через
///    `Pbkdf2Gate` (`lib/data/auth/pbkdf2_gate.dart`) — предел одновременных
///    проверок в изоляте. При достижении предела следующая попытка **ждёт
///    свою очередь**, не отказывает и не проскакивает мимо — тот же принцип,
///    что уже дважды нарушали в этой самой работе (`maxConcurrentPenalties`
///    выше в этом файле).
///
///    До правки А БЛОКЕРА (2026-08-22) очередь `Pbkdf2Gate` была ОДНОЙ общей
///    FIFO на все попытки разом — залп нападающего в 10⁴ значений вставал в
///    ту же очередь, что и попытка честного кассира, и то число, которое
///    `throttle-cap-report.md` называл ценой нападающему (~17 минут), было
///    на самом деле ценой, посчитанной с ДВУХ сторон одной очереди: те же
///    ~17 минут ждала бы и честная попытка. Правка А сделала очередь
///    круговой по ключу справедливости — QUIC-сессии (`AuthAttempt
///    .sessionKey`), не `userId`: нападающий выбирает `userId` жертвы
///    свободно, а сессий у него ровно столько, сколько он смог завести
///    (потолок регистрации терминалов — 200). Честная попытка, стоящая на
///    отдельной сессии, получает слот раз в N чужих СЕССИЙ, а не раз в N
///    его ПОПЫТОК — измерено (`pbkdf2_gate_fairness_bench_test.dart`,
///    залп 10⁴ на 1/10/200 сессий, худший случай — очередь нападающего уже
///    выстроена до прихода честной попытки): 412 мс / 1442 мс / 21012 мс —
///    на порядки меньше прежних ~17 минут при ЛЮБОМ раскладе сессий.
///    Точные числа и то, чем ограничен полный перебор нападающему, —
///    `fairqueue-and-perms-report.md`.
///
/// Это **не останавливает** перебор четырёхзначного PIN полностью — граница
/// названа явно в спеке (`docs/internal/superpowers/specs/2026-08-21-security-debt
/// -closure-design.md`, «Границы»), не спрятана. Настоящее лечение —
/// журнал событий безопасности с тревогой (фаза 8) и длина PIN, не эта
/// правка. **Полного потолка ожидания честного кассира тоже нет**: он растёт
/// с числом РАЗЛИЧНЫХ QUIC-сессий, которые успел завести нападающий — то
/// есть ограничен потолком регистрации терминалов (200) и тем, сколько из
/// них ленивая уборка (`TillOperations._pruneUnusedTerminals`) успела
/// собрать, а не какой-либо константой в этом классе или в `Pbkdf2Gate`.
library;

import 'package:meta/meta.dart' show visibleForTesting;
import 'package:telepos/backend/failure_ledger.dart';

class LoginThrottle {
  LoginThrottle({
    this.graceFailures = 2,
    this.baseDelay = const Duration(seconds: 1),
    this.maxDelay = const Duration(seconds: 30),
    this.staleAfter = const Duration(hours: 1),
    Future<void> Function(Duration)? sleep,
    DateTime Function()? clock,
  }) : _sleep = sleep ?? Future.delayed,
       _ledger = FailureLedger(staleAfter: staleAfter, clock: clock);

  final int graceFailures;
  final Duration baseDelay;
  final Duration maxDelay;

  /// Сколько запись о неудачах живёт без новых неудач по этому ключу,
  /// прежде чем [_forget] сотрёт её. Не про безопасность: час бездействия
  /// ничего не отбирает у настоящего нападающего — тот, кто ждал час, ждал
  /// дольше [maxDelay] в любом случае, — а про то же самое, что решает
  /// `SessionRegistry._forget()`: без уборки карта росла бы без предела.
  final Duration staleAfter;
  final Future<void> Function(Duration) _sleep;

  /// Счёт неудач по ключу. Один счёт на все три вида ключей, различённых
  /// префиксом строки: `t:` — терминал, `u:` — кассир, `w` — общий счётчик
  /// walk-up. Нет `lockedAt` и нет часов истечения задержки вовсе — задержка
  /// не рассасывается сама по себе, только [recordSuccess] сбрасывает счёт
  /// целиком. Время последней неудачи в счёте — не про задержку, а про то,
  /// когда запись можно забыть (см. [staleAfter], [_forget]).
  ///
  /// С 2026-09-13 две карты (`_failures`/`_touchedAt`) и уборка вынесены в
  /// [FailureLedger]: тот же счёт ведёт `CertificateThrottle`, и третья копия
  /// этих строк была бы параллельной реализацией одного и того же. Поведение
  /// класса не менялось ни в одной ветке.
  final FailureLedger _ledger;

  static const String _walkUpKey = 'w';
  static String _terminalKey(int terminalId) => 't:$terminalId';
  static String _userKey(int userId) => 'u:$userId';

  /// Ключ "кто" для этой попытки: конкретный кассир, если он назван, иначе
  /// общий walk-up-счётчик кассы.
  static String _whoKey(int? userId) =>
      userId == null ? _walkUpKey : _userKey(userId);

  /// Сколько стоила бы следующая неудачная попытка по этому ключу, будь
  /// она единственной. Чистая функция без побочных эффектов — ничего не
  /// меняет и не ждёт.
  ///
  /// Правка 2 разбора (2026-08-21): в `lib/` эту функцию не зовёт ни одна
  /// строка рабочего кода — единственный потребитель тест, отсюда и
  /// `@visibleForTesting`. Прежний докстринг называл её «безопасной для
  /// показа на экране» — неправда, которую никто не проверял: ни один
  /// экран её не показывает, и обещание было придумано, а не установлено
  /// по коду.
  ///
  /// С правки 1 БЛОКЕРА (2026-08-22, докстринг класса) это и есть настоящая
  /// цена следующей попытки, не только гипотетическая: очереди `_queueTail`,
  /// из-за которой этот абзац раньше предупреждал о занижении, в классе
  /// больше нет — [penalizeFailure] ждёт ровно тот же [_delayForCount] от
  /// счёта в [_ledger], который здесь и вычислен, ничего сверх.
  ///
  /// Большая из задержек по «кто» (кассир или walk-up) и по терминалу —
  /// тот же принцип, что был у `retryAfter` в задаче 6: нападающий, плохой
  /// по любой из двух осей, платит за худшую из них.
  @visibleForTesting
  Duration delayFor({required int terminalId, int? userId}) {
    final byWho = _delayForCount(_ledger.countOf(_whoKey(userId)));
    final byTerminal = _delayForCount(
      _ledger.countOf(_terminalKey(terminalId)),
    );
    return byWho > byTerminal ? byWho : byTerminal;
  }

  Duration _delayForCount(int failures) {
    if (failures <= graceFailures) return Duration.zero;
    var delay = baseDelay;
    var doublings = failures - graceFailures - 1;
    while (doublings > 0 && delay < maxDelay) {
      delay *= 2;
      doublings--;
    }
    return delay > maxDelay ? maxDelay : delay;
  }

  /// Считает неудачу по обоим ключам (кассир-или-walk-up, терминал) и
  /// выжидает задержку, положенную за неудачи, накопленные **до** этой —
  /// эта попытка платит за прошлые, не за саму себя.
  ///
  /// Счёт растёт **синхронно, до** `await` ниже, а не после него — пункт 2
  /// второго круга задачи 7 (2026-08-21). До этой правки `delayFor`
  /// читался до `await _sleep`, а `_failures[...]++` выполнялся после: два
  /// параллельных вызова по одному ключу оба читали один и тот же
  /// доинкрементный счёт, оба получали одну и ту же задержку и лишь потом,
  /// вперемешку, оба её накручивали — параллельный нападающий платил не
  /// больше последовательного, хотя докстринг обещал «каждая дальнейшая
  /// неудача обходится ровно в [maxDelay]» именно для растущей серии. Dart
  /// однопоточен: синхронная часть одного вызова [penalizeFailure] всегда
  /// целиком отрабатывает раньше синхронной части следующего, так что
  /// увеличенный здесь счёт уже виден следующему вызову, даже если он
  /// начался до того, как этот успел дождаться своего `_sleep`.
  ///
  /// Не блокирует изолят интерфейса: `await` здесь просто отпускает event
  /// loop до истечения таймера, ровно как и остальной путь входа
  /// (`_matchAll` уже уходит в отдельный isolate, `local_auth_repository.dart`).
  /// Другие попытки — в том числе верный PIN за соседним терминалом —
  /// продолжают обрабатываться, пока эта ждёт.
  ///
  /// Предела на число одновременно ожидающих попыток нет (см. докстринг
  /// класса, «Второй круг задачи 7, пункт 1») — ждут все, сколько бы их ни
  /// было одновременно, и ждут **независимо**: правка 1 БЛОКЕРА (2026-08-22,
  /// докстринг класса) сняла очередь по ключу (была здесь — `_queueTail`).
  /// Задержка этого вызова — только [_delayForCount] от счёта, накопленного
  /// до него, и ничего сверх: она не ждёт, пока доиграют чужие, ещё не
  /// завершившиеся ожидания того же ключа. Потолок — [maxDelay], один и тот
  /// же для всех: ни у этой попытки, ни у ста параллельных по тому же ключу
  /// ожидание не превышает его, сколько бы чужих неудач ни накопилось
  /// раньше.
  Future<void> penalizeFailure({required int terminalId, int? userId}) async {
    _forget();

    final whoKey = _whoKey(userId);
    final terminalKey = _terminalKey(terminalId);
    final byWho = _ledger.countOf(whoKey);
    final byTerminal = _ledger.countOf(terminalKey);

    final now = _ledger.now();
    _ledger.add(whoKey, now);
    _ledger.add(terminalKey, now);

    final delayByWho = _delayForCount(byWho);
    final delayByTerminal = _delayForCount(byTerminal);
    final delay = delayByWho > delayByTerminal ? delayByWho : delayByTerminal;
    if (delay == Duration.zero) return;

    await _sleep(delay);
  }

  /// Сбрасывает оба счётчика этой попытки. Полный сброс, не декремент — см.
  /// тест «успешный вход полностью сбрасывает счёт».
  void recordSuccess({required int terminalId, int? userId}) {
    _ledger.clear(_whoKey(userId));
    _ledger.clear(_terminalKey(terminalId));
  }

  /// Убирает записи, по которым дольше [staleAfter] не было неудач —
  /// приём `SessionRegistry._forget()` (`session_registry.dart`): ленивая
  /// уборка на каждом обращении к [penalizeFailure], а не будильник. Не
  /// зовётся из [delayFor]: та документирована как чистая функция без
  /// побочных эффектов, и просроченная, но ещё не убранная запись из неё
  /// видна как есть — то же поведение, каким было бы её отсутствие,
  /// разница только в том, когда карта физически освободится.
  void _forget() => _ledger.forgetStale();
}
