/// Признак «эта касса на самом деле слушает сеть» — наружу из [ApiServer],
/// который сознательно не живёт в `GetIt`.
///
/// # Почему не сам `ApiServer` в `GetIt`
///
/// `ApiServer` собирается один раз в `lib/main.dart`, с настоящими сокетами и
/// настоящим TLS, и его жизненный цикл (`start()`/`stop()`, повторный подъём
/// при смене листа, потеря сокетов при перезапуске) целиком — забота этого
/// файла. Заводить его синглтоном `GetIt` означало бы либо строить его
/// заново на каждое обращение (второй сервер, второй порт), либо прятать
/// вопрос «а поднят ли он вообще сейчас» за самим объектом — а экрану
/// нужен ровно один бит из всего этого объекта, а не сам объект.
///
/// # Что здесь и почему этого мало, но достаточно
///
/// Пункт 6 волны правок «касса говорит, что набирать» (2026-08-23): гейт
/// «не выдавать код при выключенном обслуживании терминалов»
/// (`TerminalPairingScreen`) раньше спрашивал `TerminalServiceChoice` —
/// **настройку**, а не сервер. Между «оператор включил обслуживание» и
/// «касса перезапущена» настройка уже читается как `true`
/// (`TerminalServiceSettingsScreen` сама предупреждает об этом:
/// `terminalServiceRestartNote`), а `ApiServer.scope` этого запуска —
/// всё ещё [ListenScope.loopback]: сервер поднят, но снаружи магазина его не
/// видно. Экран, спрашивающий настройку, в этом окне бодро выдал бы код по
/// адресу, на котором никто не ответит, — ровно то состояние, ради которого
/// гейт и заводился.
///
/// Поэтому источник истины — не настройка и не факт, что какой-то сокет
/// открыт (петля тоже сокет), а то, что сервер поднялся **с областью
/// [ListenScope.everywhere]**: только тогда адрес, который покажет экран,
/// отвечает устройству за пределами этой машины. `lib/main.dart` пишет сюда
/// после каждого исхода `server.start()`, этим же значением, каким сам
/// [ApiServer] сообщает о себе (`started`/`server.scope`) — не пересчитывая
/// условие заново.
class ApiServerReachability {
  /// Адрес, который стоит показывать человеку, или `null`, если сервер не
  /// поднят с областью [ListenScope.everywhere] прямо сейчас.
  ///
  /// То же значение, что вернул `ApiServer.start()` при успехе
  /// (`ApiServer.url` дальше не меняется, пока сервер не перезапущен) —
  /// экран не пересобирает адрес сам из имени хоста и порта по умолчанию.
  ///
  /// Единственное поле здесь — задним числом, пункт 5 финальной волны правок
  /// (2026-08-24). До неё рядом жил `_listening`/`listening` — тот же бит,
  /// что и `url != null`, вычисленный отдельным полем, а не выведенный:
  /// `markUnreachable()` всегда обнулял оба разом, `markListening()` всегда
  /// выставлял оба разом, и ни строки в `lib/`, ни в тестах не читало
  /// `listening` — единственный вызывающий, `TerminalPairingScreen`, берёт
  /// только `url`, и это не пробел, а точное соответствие докстрингу
  /// [markUnreachable] тремя строками ниже: «не поднялся вовсе» и «поднялся
  /// только на петле» для экрана привязки неотличимы, значит и второму биту,
  /// который различал бы их, там взяться неоткуда. Комментарий у
  /// `service_locator.dart` («экран привязки читает `listening`/`url`
  /// отсюда») был неточным с самого своего дня — читает только `url` — и
  /// исправлен вместе с этой правкой, а не оставлен как задел на будущего
  /// читателя, которого голый комментарий не заводит.
  String? _url;

  /// `https://<host>:<port>` действующего слушателя, или `null`.
  String? get url => _url;

  /// Пишет `lib/main.dart` сразу после успешного `ApiServer.start()` с
  /// областью [ListenScope.everywhere]. `url` — то, что вернул `start()`.
  void markListening(String url) {
    _url = url;
  }

  /// Пишет `lib/main.dart`, когда сервер не поднялся вовсе или поднялся
  /// только на петле ([ListenScope.loopback]) — оба состояния для экрана
  /// привязки неотличимы: адреса показать некому.
  void markUnreachable() {
    _url = null;
  }
}
