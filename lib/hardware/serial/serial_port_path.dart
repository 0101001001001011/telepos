import 'dart:io';

/// Путь, которым открывается последовательный прибор.
///
/// # Зачем это отдельная функция
///
/// На Windows имя `COM10` и выше открывается **только** через пространство
/// устройств: `\\.\COM10`. Поэтому касса дописывала префикс всегда — и это
/// было верно ровно до того дня, когда портом захотели назвать путь файла.
///
/// **Измерено 2026-09-19** (`docs/internal/superpowers/plans/2026-09-19-builtin-emulators.md`):
///
/// | Путь | Итог |
/// | --- | --- |
/// | `C:\…\scale.txt` как есть | открылся, 17 байт прочитано |
/// | `\\.\C:\…\scale.txt` | отказ, errno 53 «The network path was not found» |
///
/// То есть префикс превращает обычный путь в сетевой, и подставить прибору
/// файл было нельзя вовсе. Здесь префикс ставится только там, где он нужен, —
/// у имён вида `COMn`/`LPTn`.
///
/// # Почему путь файла вообще разрешён
///
/// Решение заказчика 2026-09-19: встроенный эмулятор не должен требовать
/// установки стороннего виртуального COM-порта («у нас всё в комплексе»). Файл
/// — самая дальняя точка подстановки, до какой можно дотянуться без драйвера
/// ОС: подставляется **адрес**, а не класс драйвера, и касса читает прибор
/// своим `ScalesService`, своим разбором протокола, своим опросом.
///
/// **Чего это НЕ даёт.** Файл — не поток: у него есть длина и смещение, а у
/// порта нет ни того, ни другого. Эмуляция файлом поэтому слабее эмуляции
/// сокетом (ESC/POS), и проба, идущая через файл, не доказывает поведения на
/// настоящем COM — в первую очередь про обрыв связи и про чтение вперёд
/// записи. Это сказано на самих пробах, чтобы зелёный цвет не обещал лишнего.
String serialPortPath(String port) {
  if (!Platform.isWindows) return port;
  if (port.startsWith(r'\\')) return port; // уже путь устройства или сетевой
  return _looksLikeDeviceName(port) ? '\\\\.\\$port' : port;
}

/// Открывает последовательный прибор — и отказывает, если его нет.
///
/// # Почему путь файла обязан существовать заранее
///
/// `FileMode.append` создаёт файл, которого нет. Для имени `COM7` это
/// безобидно (устройство не создашь), а для пути — беда: опечатка в настройках
/// перестала бы быть отказом и стала бы **молчащим прибором**. Касса
/// открыла бы пустой файл, ничего из него не прочитала и сказала бы «весы
/// молчат» вместо «порт не открылся» — то есть увела бы наладчика искать
/// обрыв провода вместо опечатки.
///
/// Измерено в тот же час: проба, открывавшая порт «нет такого порта»,
/// перестала получать отказ и **создала файл с таким именем** в корне
/// репозитория.
Future<RandomAccessFile> openSerialPort(
  String port, {
  required FileMode mode,
}) async {
  final path = serialPortPath(port);
  if (!_looksLikeDeviceName(port) && !await File(path).exists()) {
    throw PathNotFoundException(
      path,
      const OSError('порт не существует'),
      'Путь порта должен существовать заранее: файл создаёт эмулятор, а не '
      'касса. Проверьте написание, или это имя COM-порта с опечаткой',
    );
  }
  return File(path).open(mode: mode);
}

/// `COM3`, `COM10`, `LPT1` — имена устройств Windows, и только они.
///
/// Регистр не важен: в настройках пишут и `com3`, и `COM3`, а Windows их не
/// различает.
bool _looksLikeDeviceName(String port) =>
    RegExp(r'^(COM|LPT)\d+$', caseSensitive: false).hasMatch(port);
