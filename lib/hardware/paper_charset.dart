final Map<int, int> _cp866Inverse = _inverseOf(_cp866High);
final Map<int, int> _cp1251Inverse = _inverseOf(_cp1251High);

Map<int, int> _inverseOf(List<int> high) {
  final map = <int, int>{};
  for (var i = 0; i < high.length; i++) {
    if (high[i] >= 0) map[high[i]] = 0x80 + i;
  }
  return map;
}

/// Знак, которым принтер печатает то, чего в странице нет, — вопрос.
const int questionMark = 0x3F;

/// Замены, которые делаются **всегда**, даже если знак в странице есть.
///
/// Это не «кодировка», а починка невидимых знаков, которые на ленте выглядят
/// мусором:
///
/// * `U+00A0` (неразрывный пробел) в CP866 лежит на `0xFF`, а в CP1251 — на
///   `0xA0`. Обе позиции многие термопринтеры рисуют **заливкой**, а не
///   пробелом: страницу они знают лишь в той части, где есть буквы. Пробел —
///   это то, что знак значит, и он гарантированно рисуется пробелом;
/// * узкий и тонкий пробелы — то же самое, только их нет ни в одной из двух
///   страниц;
/// * мягкий перенос `U+00AD` и пробел нулевой ширины `U+200B` **не значат
///   ничего видимого**: они должны исчезнуть, а не занять колонку. Мягкий
///   перенос в CP1251 лежит на `0xAD` и напечатался бы дефисом посреди слова.
const Map<int, String> alwaysReplaced = <int, String>{
  0x00A0: ' ', // неразрывный пробел
  0x2007: ' ', // цифровой пробел
  0x2009: ' ', // тонкий пробел
  0x202F: ' ', // узкий неразрывный пробел
  0x00AD: '', // мягкий перенос
  0x200B: '', // пробел нулевой ширины
  0xFEFF: '', // BOM, приезжает вместе с вставленным из буфера текстом
};

/// Замены для знаков, которых в выбранной странице нет.
///
/// Применяются **только** когда страница знак не берёт: `і` доживает до
/// этикетки CP1251 (`0xB3`) и вырождается в `и` на чеке CP866. Проверка идёт
/// по таблице, а не по списку языков, — поэтому правило одно на обе страницы.
///
/// ## Казахские буквы: что здесь решено и почему
///
/// **Ни одна кодовая страница ESC/POS не содержит ә, ғ, қ, ң, ө, ұ, ү, һ.**
/// Это измерено, а не предположено: страницы `ESC t n`, которые понимает
/// чековый принтер, — это набор DOS/Windows-страниц (PC437, PC850, PC866,
/// WPC1251, …), и казахский алфавит не покрывает ни одна. `KZ-1048`
/// (СТ РК 1048-2002) существует как национальный стандарт, но кодовой
/// страницы принтера под него нет. Значит выбор был между тремя ответами,
/// и вот почему выбран третий:
///
/// 1. **Другая страница `ESC t n`** — отпадает: такой страницы нет. Объявить
///    её значило бы записать в код обещание, которого железо не выполнит.
/// 2. **Отказ печатать** — отпадает: на чек казахские буквы попадают из
///    названия товара, имени и адреса продавца и текста шаблона, то есть из
///    справочников магазина. Отказ означал бы кассу, которая не печатает чек
///    за товар с казахским названием, — это хуже, чем печатать его с русской
///    буквой.
/// 3. **Однобуквенная замена на русскую основу** — выбрано. Каждая замена
///    — один знак в один знак, поэтому разметка колонок (она считается по
///    `String.length` **до** кодирования) не съезжает.
///
/// **Это ухудшение, а не соответствие, и оно названо вслух.** `Сүт` на ленте
/// выйдет `Сут`. Заказчику это видно **до печати**: предпросмотр чека и
/// шаблона собирается из тех же байтов и той же таблицей, поэтому в поле
/// шапки шаблона видно ровно то, что напечатается. Другого предупреждения
/// нет и не задумано — экран, показывающий правду, и есть предупреждение.
///
/// **Фискальный документ этим не затронут.** В ОФД чек уезжает по HTTP в
/// UTF-8 (`webkassa_provider.dart`), и казахские буквы доезжают целыми.
/// Вырождается только бумажная копия покупателя.
///
/// ## Знак тенге
///
/// `₸` (U+20B8) нет ни в CP866, ни в CP1251. Заменяется на **`тг`** —
/// сокращение, которым тенге подписан в казахстанской рознице. Второй,
/// удалённый теперь кодировщик подставлял сюда латинскую `T`: это выдуманное
/// соответствие, которое выглядит правдой, и оно хуже вопроса. `тг` длиннее
/// исходного знака на один символ — поэтому замены идут **до** разметки
/// строки, а не внутри кодирования (см. [paperText]).
const Map<int, String> unsupportedReplacements = <int, String>{
  // ── Казахские буквы: русская основа.
  0x04D8: 'А', 0x04D9: 'а', // Ә ә
  0x0492: 'Г', 0x0493: 'г', // Ғ ғ
  0x049A: 'К', 0x049B: 'к', // Қ қ
  0x04A2: 'Н', 0x04A3: 'н', // Ң ң
  0x04E8: 'О', 0x04E9: 'о', // Ө ө
  0x04B0: 'У', 0x04B1: 'у', // Ұ ұ
  0x04AE: 'У', 0x04AF: 'у', // Ү ү
  0x04BA: 'Х', 0x04BB: 'х', // Һ һ
  0x0406: 'И', 0x0456: 'и', // І і — в CP1251 есть, сюда не дойдут
  // ── Деньги.
  0x20B8: 'тг', // ₸
  0x20BD: 'руб', // ₽
  0x20B4: 'грн', // ₴
  0x20AC: 'EUR', // € — в CP1251 есть (0x88), сюда дойдёт только с CP866
  0x00A3: 'GBP', // £
  0x00A5: 'JPY', // ¥
  // ── Кавычки и тире: то, что приезжает из текстового редактора вместе с
  //    вставленным шаблоном. Без замены целая шапка выходила вопросами.
  0x00AB: '"', 0x00BB: '"', // « »
  0x201C: '"', 0x201D: '"', 0x201E: '"', 0x201F: '"',
  0x2018: "'", 0x2019: "'", 0x201A: ',', 0x201B: "'",
  0x2013: '-', 0x2014: '-', 0x2015: '-', 0x2011: '-', 0x2212: '-',
  0x2026: '...',
  0x2022: '*', // •
  0x00D7: 'x', // × — «2 × 250»
  0x00A9: '(C)', 0x00AE: '(R)', 0x2122: '(TM)',
};

/// Можно ли положить [rune] в страницу [charset] одним байтом.
bool isEncodable(int rune, PaperCharset charset) {
  if (rune < 0x80) return true;
  return switch (charset) {
    PaperCharset.cp866 => _cp866Inverse.containsKey(rune),
    PaperCharset.windows1251 => _cp1251Inverse.containsKey(rune),
  };
}

/// Текст, готовый к разметке и кодированию в [charset].
///
/// **Вызывается до того, как строка измерена.** Ширина колонок чека считается
/// по `String.length` (`ReceiptBuilder.addRow`, `_truncate`, перенос по
/// словам), а замена может быть длиннее одного знака (`₸` → `тг`). Замена
/// внутри кодировщика сдвинула бы строку вправо ровно на столько, на сколько
/// разошлись длины, и колонка суммы перестала бы сходиться — молча, потому
/// что кодировщик стоит после разметки.
///
/// Что остаётся вопросом после этого вызова — то, для чего замены **не
/// придумано**, и это намеренно: см. [unsupportedReplacements].
String paperText(String source, PaperCharset charset) {
  final out = StringBuffer();
  for (final rune in source.runes) {
    final forced = alwaysReplaced[rune];
    if (forced != null) {
      out.write(forced);
      continue;
    }
    if (isEncodable(rune, charset)) {
      out.writeCharCode(rune);
      continue;
    }
    final replacement = unsupportedReplacements[rune];
    if (replacement != null) {
      out.write(replacement);
      continue;
    }
    out.writeCharCode(questionMark);
  }
  return out.toString();
}

/// Знаки [source], которые в [charset] не лягут **и** замены не имеют.
///
/// Для диагностики и проб: «что на этой ленте выйдет вопросом». Пустой набор
/// — не обещание, что бумага читаема (замены — тоже потеря), а обещание, что
/// вопросов не будет.
Set<int> unrepresentableRunes(String source, PaperCharset charset) {
  final out = <int>{};
  for (final rune in source.runes) {
    if (alwaysReplaced.containsKey(rune)) continue;
    if (isEncodable(rune, charset)) continue;
    if (unsupportedReplacements.containsKey(rune)) continue;
    out.add(rune);
  }
  return out;
}

/// Байты [text] в странице [charset].
///
/// Замены [paperText] делаются здесь же, чтобы ни один вызывающий не мог
/// кодировать «сырой» текст. Тем, кто размечает колонки, нужен [paperText]
/// **раньше** — после него этот вызов уже ничего не меняет (замены
/// идемпотентны: их результат в странице лежит).
Uint8List encodePaper(String text, PaperCharset charset) {
  final prepared = paperText(text, charset);
  final inverse = switch (charset) {
    PaperCharset.cp866 => _cp866Inverse,
    PaperCharset.windows1251 => _cp1251Inverse,
  };
  final bytes = <int>[];
  for (final rune in prepared.runes) {
    if (rune < 0x80) {
      bytes.add(rune);
      continue;
    }
    bytes.add(inverse[rune] ?? questionMark);
  }
  return Uint8List.fromList(bytes);
}

/// Один байт [charset] → знак Unicode.
///
/// Обратная сторона той же таблицы. Ею читают бумагу предпросмотр
/// (`escpos_text_preview.dart`) и эмулятор принтера (`emulators/escpos`), —
/// поэтому «что видит кассир» и «что получил принтер» не могут разойтись
/// из-за разных таблиц.
String decodePaperByte(int byte, PaperCharset charset) {
  final b = byte & 0xFF;
  if (b < 0x80) return String.fromCharCode(b);
  final high = switch (charset) {
    PaperCharset.cp866 => _cp866High,
    PaperCharset.windows1251 => _cp1251High,
  };
  final rune = high[b - 0x80];
  if (rune < 0) return '?';
  return String.fromCharCode(rune);
}

/// Байты [bytes] страницы [charset] — текстом.
String decodePaper(Iterable<int> bytes, PaperCharset charset) {
  final out = StringBuffer();
  for (final b in bytes) {
    out.write(decodePaperByte(b, charset));
  }
  return out.toString();
}
