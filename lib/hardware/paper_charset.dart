/// Одна таблица знаков на всю бумагу: CP866 для чека, Windows-1251 для
/// этикетки EPL.
///
/// ## Зачем это отдельный файл
///
/// До этой правки таблиц CP866 в дереве было **пять**, и они расходились между
/// собой (измерено 2026-09-19):
///
/// * `hardware/printer/receipt_builder.dart` — кодировщик боевого чека, `₸`
///   давал `'?'`;
/// * `hardware/printer/receipt/receipt_builder.dart` (`Cp866Encoder`) — второй
///   кодировщик, `₸` давал `'T'`, а `₽` — `'P'`;
/// * `hardware/printer/escpos_text_preview.dart` — **декодировщик**
///   предпросмотра;
/// * `emulators/escpos/render.dart` — декодировщик эмулятора, читавший `0xFC`
///   как `·`, хотя продукт кладёт туда `№`;
/// * `hardware/display/led_display_extended.dart` — кодировщик табло.
///
/// Расхождение кодировщика с декодировщиком опаснее, чем каждый из них по
/// отдельности: предпросмотр и эмулятор — это **пробы**, и покуда они читают
/// байты по своей таблице, проба зеленеет на бумаге, которой никто не видел.
/// `0xFC` — пример: чек печатал `№`, а проба через эмулятор читала `·`, и
/// утверждение «на бумаге номер чека» было недоказуемо.
///
/// Здесь одна таблица, полная (все 128 позиций старшей половины), и **обе**
/// стороны — кодирование и декодирование — выводятся из неё.
///
/// ## Чего это НЕ доказывает
///
/// Таблица описывает, какие байты уходят в принтер, и ничего не говорит о том,
/// **что принтер нарисует**. Кодовую страницу выбирает `ESC t 17`
/// (`EscPosCommands.init`); принтер, который её не поддерживает или
/// переключён кнопкой, нарисует свою. Ни одного замера на настоящем XPrinter
/// у проекта нет — см. п. 15 «РЕВИЗИЯ 2026-09-19». Проверено здесь ровно одно:
/// поток байтов и то, как его читают предпросмотр и эмулятор, — это одно и то
/// же.
library;

import 'dart:typed_data';

/// Кодовая страница бумаги.
enum PaperCharset {
  /// CP866 (ESC/POS `ESC t 17`) — чек.
  cp866,

  /// Windows-1251 (EPL `I8,C,001`) — этикетка.
  windows1251,
}

