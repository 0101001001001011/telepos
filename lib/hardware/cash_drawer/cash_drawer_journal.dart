import 'dart:async';

/// Одна попытка открыть денежный ящик.
///
/// # Почему «команда принята», а не «ящик открыт»
///
/// Касса не знает, открылся ли ящик. Соленоид обратной связи не даёт: на
/// обоих путях — и `ESC p` через принтер, и запись в последовательный порт —
/// успехом считается «байты ушли и порт не отказал». [accepted] названо так
/// намеренно, чтобы это не приходилось выяснять по исходникам.
///
/// `CashDrawerService.isOpen` этого различия не делает и возвращает `true`
/// сразу после отправки. Здесь оно сделано: диагностика существует ровно
/// затем, чтобы наладчик видел настоящую границу знания кассы, а не
/// правдоподобную картинку.
class CashDrawerKick {
  const CashDrawerKick({
    required this.at,
    required this.path,
    required this.accepted,
    this.note,
  });

  final DateTime at;

  /// Каким путём шла команда.
  final CashDrawerPath path;

  /// Приняли ли байты к отправке без отказа.
  final bool accepted;

  /// Причина отказа или пояснение к запасному пути.
  final String? note;
}

enum CashDrawerPath {
  /// Отдельный ящик на последовательном порту — пробуется первым.
  serialPort,

  /// `ESC p` через чековый принтер. Единственный путь там, где ящик воткнут
  /// в принтер, и запасной там, где есть свой порт.
  viaPrinter,
}

/// Память об импульсах ящика — то, чего у кассы не было вовсе.
///
/// # Почему в памяти, а не в базе
///
/// Вопрос, на который отвечает эта запись, — «работает ли ящик **сейчас**»:
/// её читает наладчик при запуске и кассир, у которого ящик не открылся
/// минуту назад. Для него хватает последних попыток текущего запуска.
///
/// Вопрос «кто и когда открывал ящик за смену» — **другой**, и отвечать на
/// него этой записью нельзя: это учётный вопрос, у него свой журнал кассовых
/// операций, своё право и своё хранение. Завести здесь таблицу значило бы
/// выдать диагностику за учёт — и первый же спор о недостаче пошёл бы по
/// записи, которая теряется при перезапуске и ничего не доказывает.
///
/// Предел [limit] — не экономия, а то же самое: список, растущий без границы,
/// перестаёт быть ответом на «что было только что».
class CashDrawerJournal {
  CashDrawerJournal({this.limit = 50});

  final int limit;
  final List<CashDrawerKick> _kicks = [];
  final StreamController<List<CashDrawerKick>> _changes =
      StreamController<List<CashDrawerKick>>.broadcast();

  /// Последние попытки, новые первыми.
  List<CashDrawerKick> recent() => List.unmodifiable(_kicks.reversed);

  /// Поток для экрана диагностики: первым событием — то, что уже есть, иначе
  /// экран, открытый после импульса, показал бы пустоту.
  Stream<List<CashDrawerKick>> watch() async* {
    yield recent();
    yield* _changes.stream;
  }

  void record(CashDrawerKick kick) {
    _kicks.add(kick);
    if (_kicks.length > limit) _kicks.removeRange(0, _kicks.length - limit);
    if (!_changes.isClosed) _changes.add(recent());
  }

  Future<void> dispose() => _changes.close();
}
