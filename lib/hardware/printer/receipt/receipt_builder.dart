import 'dart:typed_data';

/// Общий вид собирателя документа: байты наружу.
///
/// ## Что отсюда убрано и почему
///
/// **`Cp866Encoder`** — второй кодировщик CP866 в дереве. Он расходился с
/// боевым: `₸` давал латинскую `'T'`, `₽` — `'P'`. Выдуманное соответствие
/// выглядит правдой и потому хуже знака вопроса. Таблица знаков теперь одна —
/// `hardware/paper_charset.dart`, и обе стороны, кодирование и декодирование,
/// выводятся из неё.
///
/// **`EscPosCommands`** — вторая копия набора команд. Байты пересекающихся
/// двенадцати констант совпадали с копией в `printer_manager.dart`
/// (сверено поимённо 2026-09-19), но копия была беднее: без `ESC i`, без
/// импульса ящика, без QR, — и её `cutPaper` уже начал расходиться по смыслу с
/// соседом. Остался один набор, в `printer_manager.dart`, где у каждой спорной
/// константы написано, чем она является на самом деле.
abstract class ReceiptBuilder {
  Uint8List build();

  String toDebugString();
}

