import 'package:decimal/decimal.dart';

abstract class ShiftService {
  Future<void> onOpenShift(int userId, {Decimal? openingCash});

  /// Закрыть смену кассы: числа, уточнённое время открытия, Z-отчёт.
  ///
  /// # Z-отчёт не обгоняет документы своей смены
  ///
  /// Дыра, найденная ревизией 2026-09-19: Z уходил оператору сразу, не
  /// оглядываясь на очередь фискализации, и документы смены, которые в этот
  /// момент досылал `FiscalReplayScheduler`, приходили к оператору **после**
  /// отчёта — то есть попадали в следующую смену оператора. Отчёт оператора
  /// расходился с кассой, и расходился молча.
  ///
  /// Поэтому закрытие: (1) ждёт один проход повтора, (2) отправляет Z только
  /// если после прохода очередь пуста, (3) закрывает смену кассы в любом
  /// случае. Разбор всех трёх решений — в докстрингах
  /// `ShiftServiceImpl.onCloseShift` и `ShiftServiceImpl.fiscalCloseShift`.
  Future<void> onCloseShift(Decimal cashInPos);

  Future<dynamic> getOpenedShift();

  Future<bool> isShiftOverAge({Duration maxAge = const Duration(hours: 24)});

  /// Сколько чеков закрываемой смены остались **без фискального
  /// документа**, и какие именно — задача 11.
  ///
  /// # Смену закрыть можно, но не молча
  ///
  /// Запрещать закрытие было бы хуже беды: кассир не может уйти домой,
  /// пока кто-то не починит оператора, а деньги уже взяты и товар отдан.
  /// Но и промолчать нельзя: до этой задачи чеки без документа не
  /// показывались нигде, и смена закрывалась так, будто их нет. Поэтому
  /// закрытие **называет число и номера** — в журнале и в подтверждении
  /// на экране.
  ///
  /// Считается по очереди фискализации (строки со статусом `failed`), а
  /// не по `Sales`: колонка исхода в продажах появляется только задачей
  /// 14. Списанные рукой человека не считаются — они уже разобраны.
  ///
  /// Пустой ответ, если очередь кассе не собрана: молчать здесь честнее,
  /// чем утверждать «ноль».
  Future<UnfiscalizedAtClose> unfiscalizedAtClose();

  /// Догасить Z-отчёт, задержанный прошлым закрытием смены.
  ///
  /// Зовётся **открытием смены** и только им — это единственный момент,
  /// когда у оператора ещё нет ни одного документа нового дня, а значит
  /// Z закроет ровно вчерашнюю смену. Разбор трёх рассмотренных дверей и
  /// того, почему круг повтора здесь не годится, — в докстринге
  /// `ShiftServiceImpl.settleOwedZReport`.
  ///
  /// Вход открыт и снаружи намеренно: по нему делается кнопка «дослать
  /// отчёт» на экране диагностики. Кнопка — **второй** вход, а не первый:
  /// беда была в том, что задержку никто не замечает.
  Future<void> settleOwedZReport();

  /// Висящий долг по Z-отчёту, если он есть. `null` — долга нет **или**
  /// прочитать его не удалось (причина — в журнале): выдуманного «нет»
  /// здесь не бывает, но и отличить эти два случая снаружи нечем, и это
  /// названо.
  Future<OwedZReport?> owedZReport();
}

/// Z-отчёт, который касса задолжала оператору.
///
/// Он не «не отправлен» — он **записан как долг** и будет отправлен при
/// первой законной возможности. Разбор — `FiscalOwedReports`.
class OwedZReport {
  const OwedZReport({
    required this.shiftId,
    required this.owedAt,
    required this.documentsWaiting,
    required this.attempts,
    this.lastError,
  });

  /// Смена кассы, чьё закрытие отчёт не отправило.
  final int shiftId;

  final DateTime owedAt;

  /// Сколько документов не доехало **в тот момент**. Число историческое:
  /// сегодняшнее состояние очереди спрашивается у очереди.
  final int documentsWaiting;

  final int attempts;

  /// Почему не удалась последняя попытка — названной причиной.
  final String? lastError;
}

/// Что осталось нефискализованным к моменту закрытия смены.
///
/// Два разных состояния, и путать их нельзя:
///
/// * [count] — чеки, которым документа **не будет сам собой**: оператор
///   отказал нетранзиентно или чек пережил автономное окно. Их лечит
///   человек на экране нефискализованных чеков.
/// * [onTheWay] — чеки, которые **ещё уедут**: строки очереди со статусом
///   `pending`. Беды в них пока нет, но Z-отчёт, ушедший раньше них,
///   разойдётся с кассой (разбор — `ShiftService.onCloseShift`), и потому
///   кассир видит их число **до** нажатия «Закрыть».
class UnfiscalizedAtClose {
  const UnfiscalizedAtClose({
    required this.count,
    required this.receiptNumbers,
    this.onTheWay = 0,
    this.onTheWayReceipts = const [],
  });

  static const empty = UnfiscalizedAtClose(count: 0, receiptNumbers: []);

  final int count;

  /// Номера чеков — по ним человек находит продажу. Может быть короче
  /// [count]: у строк старого вида номер в записке, а не в документе, и
  /// прочитаться он может не всегда.
  final List<int> receiptNumbers;

  /// Сколько документов смены **ещё не у оператора** (очередь, `pending`).
  final int onTheWay;

  /// Номера этих чеков — той же меры точности, что и [receiptNumbers].
  final List<int> onTheWayReceipts;

  /// Ни беды, ни ожидания: закрытие молчит только здесь.
  bool get isEmpty => count == 0 && onTheWay == 0;

  /// Есть чеки, которым документа не будет сам собой.
  bool get hasFailed => count > 0;
}
