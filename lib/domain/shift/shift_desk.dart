/// Смену можно закрыть **не подходя к кассе** — решение заказчика 2026-09-18,
/// дословно: «это не граница, а пробел — в браузере должно работать то же,
/// что в приложении».
///
/// # Что было измерено живьём 2026-09-18
///
/// Смена старше суток запирает продажу окном: «Смена открыта более 24 часов.
/// Продажа заблокирована. **Закройте смену на кассе** и откройте новую».
/// Кнопки перехода в этом окне у браузера нет вовсе — и правильно, что не
/// было: `ShiftCloseAtTill` заведена задачей 37 именно затем, чтобы кассир не
/// упирался в заглушку `/shift`. Но путь от этого не появился: с планшета
/// смену закрыть было нечем, и окно честно называло стену стеной.
///
/// Вторая половина того же пробела — **дом браузерного терминала показывал
/// «Смена открыта» зелёным значком и при просроченной смене**. Состояние
/// смены приезжало один раз, в `AuthSession` при входе (`SessionRegistry
/// .mint`, `shiftOpen`), и с тех пор не менялось ничем: ни одной операции
/// провода про смену в каталоге не было. Кассир узнавал о беде, только
/// упершись в продажу.
///
/// # Что вкладка вправе задать при закрытии, а что обязана посчитать касса
///
/// Это главный вопрос всего файла, и ответ у него **один довод**, а не вкус.
///
/// Вкладка задаёт ровно одно число — [ShiftDeskRepository.close] с
/// `counted`: **сколько денег человек насчитал в ящике**. Больше ничего.
///
/// Почему именно его — и только его:
///
/// * это **физический замер**, а не запись. Его не выводит никакая
///   арифметика над журналом кассы: в ящике лежит то, что лежит, и узнать
///   это можно только пересчитав. Никто, кроме человека у ящика, этого числа
///   не знает — и потому оно обязано прийти оттуда, где стоит человек.
/// * всё остальное — **арифметика над собственным журналом кассы**: сколько
///   было на начало смены, сколько пришло наличными, сколько ушло изъятиями,
///   сколько должно быть, расхождение, время закрытия, уточнённое время
///   открытия, Z-отчёт, список нефискализованных чеков. Посчитай хоть одно
///   из этого вкладка — у кассы появился бы **второй бухгалтер**, и разошлись
///   бы они на первой же правке.
/// * и есть довод жёстче: кадр можно собрать **мимо экрана**. Вкладка,
///   которой позволено назвать «системный итог», закрывала бы смену на
///   числе, которого никто не считал, — и расхождение вышло бы нулевым по
///   построению. Ровно то, ради чего расхождение и считают.
///
/// Отсюда `counted` — **`Decimal?`, и `null` значит «никто не считал»**, а не
/// «ноль». Это не удобство записи: ноль в ящике — законный и очень
/// осмысленный результат пересчёта («ящик пуст»), и подменить им «не
/// считали» значило бы записать недостачу на всю выручку смены. Когда
/// `counted == null`, касса берёт **свой** системный итог — тем же
/// правилом, каким это делал кассовый экран (`hasCounted ? enteredTotal :
/// systemTotal`), — и расхождения не пишет вовсе: сравнивать не с чем.
///
/// # Единицы времени: секунды, не миллисекунды
///
/// `Shifts.openTime`/`closeTime` — `IntColumn` в **секундах**
/// (`DateTime.now().millisecondsSinceEpoch ~/ 1000` на записи, `* 1000` на
/// показе). [ShiftDeskView.openedAtSeconds] несёт ту же единицу и назван так,
/// чтобы ошибиться было труднее: ошибка в единицах уже стоила получаса
/// разбора, а при трёхзначном множителе просроченная смена выглядела бы
/// свежей, и наоборот.
library;

import 'package:decimal/decimal.dart';

/// Состояние смены глазами браузерного терминала.
class ShiftDeskView {
  const ShiftDeskView({
    required this.open,
    required this.overAge,
    this.openedAtSeconds,
    this.cashierName,
    required this.openingCash,
    required this.systemTotal,
    required this.expectedCash,
    required this.unfinishedSales,
    required this.unfiscalizedCount,
    required this.unfiscalizedReceipts,
  });

  /// Смена, у которой на кассе нет ничего: ни открытой смены, ни чисел.
  static final closed = ShiftDeskView(
    open: false,
    overAge: false,
    openingCash: Decimal.zero,
    systemTotal: Decimal.zero,
    expectedCash: Decimal.zero,
    unfinishedSales: 0,
    unfiscalizedCount: 0,
    unfiscalizedReceipts: const [],
  );

  /// На кассе есть открытая смена.
  final bool open;

  /// Смена открыта дольше предела (`ShiftAgeRule.limit`, сутки, сравнение
  /// `>=`) — то есть продажа уже заперта.
  ///
  /// Считает **касса**, своим же правилом, которым запирает продажу. Вкладка
  /// не вычитает времён и не знает предела: два места, считающие возраст
  /// смены, разошлись бы, и значок говорил бы одно, а продажа — другое.
  final bool overAge;

  /// Когда смена открыта — **в секундах** эпохи (докстринг файла).
  final int? openedAtSeconds;

  final String? cashierName;

  /// Сколько было в ящике на открытие смены.
  final Decimal openingCash;

  /// Сколько, по журналу кассы, в ящике сейчас (остаток счёта кассы).
  ///
  /// Это **не** «сколько должно быть» ([expectedCash]) — числа считаются
  /// по-разному и расходятся ровно там, где мимо смены прошла денежная
  /// запись. Оба показываются кассиру; ни одно из них вкладка не считает.
  final Decimal systemTotal;

  /// Сколько должно быть по смене: начало + наличная выручка − наличные
  /// возвраты − изъятия и дивиденды.
  final Decimal expectedCash;

  /// Незаконченные чеки смены — начатые и отложенные. Не запрет, а
  /// предупреждение: закрытие их приберёт.
  final int unfinishedSales;

  /// Сколько чеков смены остались без фискального документа.
  ///
  /// Смену закрыть можно, но не молча — разбор в докстринге
  /// `ShiftService.unfiscalizedAtClose`: запрещать хуже беды (кассир не
  /// может уйти домой, пока чинят оператора, а деньги взяты и товар отдан),
  /// но и промолчать нельзя.
  final int unfiscalizedCount;

  /// Номера этих чеков — по ним человек находит продажу. Может быть короче
  /// [unfiscalizedCount].
  final List<int> unfiscalizedReceipts;
}

/// Смена с браузерного терминала: состояние, закрытие, открытие.
///
/// Две реализации: `LocalShiftDesk` на кассе и `WtShiftDesk` в браузере.
abstract interface class ShiftDeskRepository {
  /// Состояние смены **сейчас и при каждом изменении**.
  ///
  /// Подписка, а не вопрос, и это ровно та половина работы, которую просил
  /// заказчик: значок «Смена открыта» на доме терминала был снимком, взятым
  /// при входе, и оставался зелёным часами после того, как смену закрыли или
  /// она перевалила за сутки. Вопрос чинил бы это только в момент, когда
  /// экран строится; вкладку же держат открытой всю смену.
  Stream<ShiftDeskView> watch();

  /// Закрыть смену. [counted] — сколько **насчитал человек** в ящике;
  /// `null` — не считал, и тогда касса берёт свой системный итог.
  ///
  /// Разбор, почему это единственное, что вкладка вправе задать, — в
  /// докстринге файла.
  Future<void> close({Decimal? counted});

  /// Открыть смену. [openingCash] — сколько человек положил в ящик на
  /// начало; `null` — ноль.
  ///
  /// **Кассира называет касса, а не вкладка** (И162, и тот же приём, каким
  /// оплата берёт рабочее место из сеанса): смену открывает тот, чьим
  /// сеансом пришла заявка. Приди `userId` в теле кадра, любой кассир мог бы
  /// открыть смену на чужое имя — а именем смены подписан Z-отчёт и вся её
  /// выручка.
  Future<void> open({Decimal? openingCash});
}

/// На кассе нет открытой смены — закрывать нечего.
///
/// Отдельный код, а не молчаливый успех: кассовая служба
/// (`ShiftServiceImpl.onCloseShift`) при отсутствии смены пишет
/// предупреждение в журнал и **возвращается как ни в чём не бывало**. На
/// кассе это видно — экран смены перерисовывается и показывает «закрыта»; по
/// проводу вкладка получила бы «готово» и ушла бы, считая, что закрыла
/// смену, которой не было. Разница важна на просроченной смене: кассир
/// решил бы, что теперь можно продавать.
const shiftNotOpenCode = 'shift_desk_not_open';

/// На кассе уже есть открытая смена — вторую открывать нечем.
///
/// `ShiftDao.findOpenedShift` читает `getSingleOrNull()`: две открытые смены
/// на одной кассе — не состояние, а падение. Запрет держится здесь, до
/// записи.
const shiftAlreadyOpenCode = 'shift_desk_already_open';

/// Заявке на открытие смены нечем назвать кассира.
///
/// Кассир берётся **из сеанса**, никогда из тела кадра (И162): именем смены
/// подписан Z-отчёт и вся её выручка, и вкладка, называющая кассира сама,
/// открывала бы смену на чужое имя. Сеанса нет — открывать не на кого, и это
/// отказ, а не смена на кассира `0`.
const shiftActorUnknownCode = 'shift_desk_actor_unknown';

