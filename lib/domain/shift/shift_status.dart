/// Что известно о смене — задача 47 плана «Продажа с браузерного терминала».
///
/// # Почему три состояния, а не `bool`
///
/// Признак смены жил `bool`-ом от провода до значка: `AuthSession.shiftOpen`,
/// `json['shiftOpen'] == true` в разборе кадра, `isShiftOpened = false`
/// умолчанием в `LoginState` и `AppState`. «Измерено: закрыта» и «никто не
/// спрашивал» были одним значением, и оба красились «Смена закрыта»: до входа,
/// после выхода, на кадре от кассы, которая признака не прислала. Читатель при
/// этом не косметический — `LoginNotifier.getPostLoginRoute` решает по нему,
/// куда вести кассира.
///
/// [unknown] — не ошибка и не отказ: это честное «не знаю». Касса сама его не
/// пишет никогда: она смену измеряет и отвечает [open] или [closed].
enum ShiftStatus {
  /// Касса измерила: смена открыта.
  open,

  /// Касса измерила: открытой смены нет.
  closed,

  /// Не спрашивали или ответ не прочитан.
  unknown,
}
