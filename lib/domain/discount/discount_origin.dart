/// Откуда взялась скидка строки.
///
/// # Зачем это вообще нужно
///
/// Сегодня скидка **выводится**: `priceBefore − price`. Разность не помнит,
/// откуда она взялась, и подарок акции в проданном чеке неотличим от того,
/// что кассир уступил рукой. Значит нельзя ни спросить «сколько мы отдали
/// акциями за месяц», ни ответить «кто разрешил эту скидку» — а второй
/// вопрос задаёт владелец, и задаёт он его про деньги.
///
/// # Значения лежат на диске
///
/// Числа попадают в `sale_discounts.origin` и едут между кассами. Их менять
/// нельзя; добавлять новые — только в конец.
abstract final class DiscountOrigin {
  /// Кассир уступил рукой: процентом, суммой или правкой цены.
  static const int manual = 0;

  /// Подарок акции (`Promotions`) — «2+1» и подобное.
  static const int promotion = 1;

  /// Правило скидочной программы. **Точка расширения, писателя пока нет.**
  ///
  /// Объявлено сейчас нарочно: когда справочник правил появится, он добавит
  /// свою таблицу, источник в `capFor` и писателя со своим `sourceId` — а
  /// схема, контракт, аудит, отчёты и фискальный путь **не поменяются ни
  /// строкой**. Номер, выбранный задним числом, стоил бы миграции.
  static const int rule = 2;

  /// Программа лояльности покупателя.
  static const int loyalty = 3;

  static const List<int> values = <int>[manual, promotion, rule, loyalty];

  /// Словами — для отчёта и для экрана. Неизвестное число не выдумывается
  /// в «ручную»: происхождение, которого читатель не знает, обязано быть
  /// видно как незнакомое, иначе чужая запись тихо запишется в кассира.
  static String nameOf(int origin) => switch (origin) {
    manual => 'скидка кассира',
    promotion => 'подарок акции',
    rule => 'скидочное правило',
    loyalty => 'программа лояльности',
    _ => 'происхождение #$origin',
  };
}
