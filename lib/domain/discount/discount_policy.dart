import 'package:decimal/decimal.dart';
import 'package:meta/meta.dart';

/// Полномочия того, кто просит скидку, — **обязательный довод** команд
/// корзины, назначающих или уменьшающих цену.
///
/// # Довод, а не поиск службы внутри реализации
///
/// Реализация могла бы спросить права сама — резолвом из контейнера или
/// чтением «текущего сеанса». Разница не в стиле, а в том, что забывается:
/// поиск внутри обходится **новым путём вызова**, и новый путь появится
/// (браузерная реализация контракта появилась ровно так). Требование,
/// объявленное доводом, забыть нельзя: команда без него не компилируется, и
/// это свойство сборки, а не дисциплины.
///
/// Тем же приёмом задача 3 этого плана закрыла фискальный порт: **тип, а не
/// сторож**.
///
/// # Что здесь есть и чего нет
///
/// [roleIndex] и [permissions] — ровно то, что читает касса.
///
/// [userId] появился в задаче 13 вместе с таблицей аудита и **вместе с её
/// читателем**: до неё он был бы полем без читателя, а такое поле в этом
/// дереве уже четырежды оказывалось мёртвым кодом, выглядящим живым.
/// Имени по-прежнему нет — отчёт берёт его из `Users` по идентификатору, и
/// вторая копия имени разъехалась бы с первой при переименовании.
///
/// # Кто его строит — и кто **не** строит
///
/// - касса (десктоп): `SaleNotifier` из `AppState` вошедшего;
/// - провод: `TillOperations` из `AuthSession`, выписанного кассой, —
///   **никогда из тела кадра**. Тем же правилом, что и `terminalId`
///   (докстринг `CartService`): полномочия, названные клиентом, полномочиями
///   не являются. Браузерная реализация контракта (`WtCartService`) этот
///   довод по проводу **не отправляет** вовсе — отправлять его значило бы
///   предлагать кассе поверить вкладке.
@immutable
final class DiscountAuthority {
  const DiscountAuthority({
    required this.roleIndex,
    required this.permissions,
    this.userId,
  });

  /// Полномочий нет: роль неизвестна, прав ноль.
  ///
  /// Не «удобное умолчание», а честный ответ фронта, у которого сеанса нет:
  /// такой довод получает отказ по праву на первом же шаге. Умолчанием
  /// довода он не является намеренно — довод обязателен, и написать
  /// `by: DiscountAuthority.none` можно только сознательно.
  static const none = DiscountAuthority(roleIndex: -1, permissions: {});

  /// `UserRole.index` вошедшего — ключ, по которому ищется его предел.
  /// Отрицательное значение означает «роль неизвестна» и попадает на строку
  /// умолчания.
  final int roleIndex;

  /// Кто просит — для аудита скидки (`DiscountAuditEntries.userId`).
  ///
  /// `null` означает «сеанса не было», и такая попытка **тоже** пишется:
  /// вкладка без входа доходит до кассы и получает отказ по праву, а
  /// записать этот отказ нужнее, чем прочие.
  final int? userId;

  /// Действующие права сеанса — уже пересечённые с правами режима терминала
  /// там, где сеанс выписывала касса (`AuthSession.permissions`).
  final Set<String> permissions;
}

/// Сколько скидки разрешено этой роли.
@immutable
final class DiscountCap {
  const DiscountCap({
    required this.maxPercent,
    required this.approvalAbove,
    required this.source,
  });

  /// Потолок ручной скидки в процентах от стоимости строки.
  ///
  /// Сто означает «сколько угодно» — объявленным значением, а не отсутствием
  /// значения (I165).
  final Decimal maxPercent;

  /// Выше этого процента требуется подтверждение старшего; `null` — не
  /// требуется вовсе.
  final Decimal? approvalAbove;

  /// Откуда взят предел — **словами, для кассира**: «предел роли Кассир» или
  /// «предел кассы по умолчанию».
  ///
  /// Не для журнала и не для отладки: отказ, не назвавший, чей это предел,
  /// отправляет кассира спрашивать «а кто мне это запретил» — и человек с
  /// правом изменить предел роли будет искать его в настройках кассы.
  final String source;
}

/// Читатель пределов скидки.
///
/// Контракт в домене при единственной реализации — не церемония: пробы
/// корзины поднимают предел настоящей таблицей, а экран настроек пишет в неё
/// же; разводить их через интерфейс нужно затем, чтобы `LocalCartService` не
/// научился читать `DiscountLimits` сам и не размазал правило разрешения
/// (роль → умолчание) по второму месту.
abstract interface class DiscountPolicy {
  /// Предел для роли [roleIndex] (`UserRole.index`, отрицательное — «роль
  /// неизвестна»).
  Future<DiscountCap> capFor(int roleIndex);
}
