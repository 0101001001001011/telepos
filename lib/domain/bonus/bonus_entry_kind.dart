/// Род движения бонусного счёта — **и знак движения вместе с ним**.
///
/// # Почему знак живёт в роде, а не в сумме
///
/// Отрицательная сумма в денежной таблице читается двояко: «минус сто» это
/// и списание ста, и сторно начисления ста, и возврат списанных ста —
/// движения с разным смыслом и разной судьбой в отчёте. Хуже другое: любая
/// выборка `SUM(amount)`, написанная без разбора рода, дала бы **число,
/// похожее на правду**. Такое число невозможно опознать глазами, и именно
/// поэтому [BonusEntries.amount] всегда неотрицательна, а направление
/// называет [BonusEntryKind].
///
/// # Значения лежат на диске
///
/// Числа — часть данных в `bonus_entries.kind` и едут между кассами при
/// сведении. Их менять нельзя; добавлять новые — можно только в конец.
abstract final class BonusEntryKind {
  /// Начислено за покупку. **Плюс.**
  static const int accrual = 0;

  /// Списано в оплату чека. **Минус.**
  static const int redemption = 1;

  /// Сторно начисления при возврате: товара нет — начислять было не за что.
  /// **Минус.**
  static const int accrualReversal = 2;

  /// Возврат списанного при возврате чека: покупатель забрал свои бонусы
  /// обратно. **Плюс.**
  static const int redemptionReturn = 3;

  /// Перерасход, обнаруженный при сведении касс. **Минус.**
  ///
  /// Две кассы, торгующие оффлайн, могут списать один остаток дважды: обе
  /// видели его целым. Журнал это **не предотвращает** — он делает это
  /// видимым. Запись рода [overspend] с причиной ставится тогда, когда
  /// сведённый журнал уводит остаток ниже нуля, и попадает в отчёт.
  /// Сегодня расхождение и тихое, и неограниченное.
  static const int overspend = 4;

  /// Стартовый остаток, положенный миграцией v40. **Плюс.**
  ///
  /// Историю движений из чеков **не восстанавливаем**: её там нет. Честное
  /// «до v40 один стартовый остаток» лучше выдуманной истории, которая
  /// выглядела бы как настоящая и разошлась бы с чеками у первого, кто
  /// стал бы сверять.
  static const int opening = 5;

  /// Стартовый **долг** — та же миграция, когда остаток счёта отрицателен.
  /// **Минус.**
  ///
  /// У бонусного счёта отрицательного остатка быть не должно, но в базах,
  /// прошедших через дефект возврата (`AccountPosting`, задача 10), он
  /// есть. Записать его нулём значило бы подарить покупателю чужие деньги
  /// и сделать первую же сверку ложью.
  static const int openingDeficit = 6;

  /// Все объявленные рода — чтобы сторож мог перебрать их все, а не пару
  /// для примера.
  static const List<int> values = <int>[
    accrual,
    redemption,
    accrualReversal,
    redemptionReturn,
    overspend,
    opening,
    openingDeficit,
  ];

  /// `+1` — движение поднимает остаток, `−1` — опускает.
  ///
  /// Неизвестный род — `ArgumentError`, а не ноль. Ноль означал бы «эта
  /// запись ни на что не влияет», и запись из будущей версии, приехавшая
  /// со свежей кассы, тихо выпала бы из баланса: сверка показала бы
  /// расхождение, а причину искали бы в чеках.
  static int signOf(int kind) => switch (kind) {
    accrual || redemptionReturn || opening => 1,
    redemption || accrualReversal || overspend || openingDeficit => -1,
    _ => throw ArgumentError.value(
      kind,
      'kind',
      'неизвестный род движения бонусного счёта: баланс по нему не считается',
    ),
  };
}
