import 'package:telepos/domain/usecases/sale/sale_initiation_result.dart';

abstract class SaleInitiationUseCase {
  /// Начинает или продолжает чек **на рабочем месте `terminalId`**.
  ///
  /// Задача 5: до неё терминал вычислял себя сам (`terminals.self()`) —
  /// работало, пока единственный вызывающий был кассой. `terminalId` —
  /// довод, а не умолчание, потому что вызывающих теперь два рода: касса
  /// (сама вычисляет свой `terminals.self()` и передаёт его) и браузерный
  /// терминал (задачи 10, 12; его id — из сессии провода, не из локальной
  /// базы кассы). Без явного довода второй получил бы терминал первого.
  ///
  /// **Кассира здесь нет, и это не забывчивость.** Чек пишется на владельца
  /// открытой смены (`shift.userId`): одно рабочее место — своя ККМ и своя
  /// смена (решение заказчика 2026-09-15), и выручка чека — выручка этой
  /// смены. Прежний довод `int? userId` не передавал ни один вызывающий и
  /// в запись не попадал — снят приёмкой 2026-09-17, чтобы следующий
  /// читатель не принял его за «кто пробил чек».
  Future<SaleInitiationResult> initiate({
    required int terminalId,
    bool isWholesale = false,
  });
}
