import 'package:decimal/decimal.dart';

import 'package:telepos/domain/payment/credit_contract.dart';

import 'package:telepos/domain/sale/receipt_line.dart';

abstract class SaleUseCase {
  /// Записать продажу: **строки чека**, состояние, платежи, остатки,
  /// балансы, ЭСФ.
  ///
  /// **Фискального документа здесь больше нет — задача 16.** Он жил тут с
  /// `try`/`catch`, писал `Talker.warning` на отказ оператора и не
  /// сообщал вызывающему ничего: кассир видел успех, терминал не видел
  /// ничего. Фискализация переехала к двум другим действиям завершения
  /// оплаты — печати и денежному ящику — в `LocalPaymentService.complete`,
  /// где её исход становится значением (`SaleOutcome.fiscal`).
  ///
  /// **Единственный вызывающий — `PaymentService.complete`.** Второй,
  /// `SaleNotifier.completeSale`, удалён задачей 9: у него самого
  /// вызывающих в `lib/` было ноль, а держать второй путь к деньгам —
  /// значит держать путь, на котором чек записан, но не фискализован и не
  /// напечатан.
  ///
  /// Признак `Sales.isOfd` метод по-прежнему выводит и пишет сам — его
  /// читает ЭСФ.
  ///
  /// # [lines] — формат завершённого чека, задача 9
  ///
  /// То, что посчитал `SaleCheckoutService.prepare`: цена единицы с
  /// вложенной **акционной** скидкой и округлённая до денежных трёх
  /// знаков (I159). Записывается **внутри той же транзакции**, что и
  /// всё остальное, и это не перестановка ради опрятности.
  ///
  /// До задачи 9 записывал отдельный `SaleCheckoutService.finalize`
  /// **после** этого метода — и он был мёртв: звал его только
  /// `SaleNotifier.completeSale`, у которого вызывающих ноль. Значит
  /// акции, которые в базе не хранятся вовсе (докстринг
  /// `LocalCartService`), не доезжали до проданного чека **никогда**, а
  /// цена единицы навсегда оставалась масштаба 10.
  ///
  /// Внутри транзакции, а не после неё, потому что «после» — это окно,
  /// в котором чек уже продан, а цены ещё корзинные. Здесь такого окна
  /// нет по построению: нарушение любого ключа откатывает и деньги, и
  /// формат разом.
  ///
  /// Строки переписываются **на месте**, по `SaleProducts.id`: с задачи 7
  /// они лежат в базе с первой команды корзины, и «удалить и вставить»
  /// потеряло бы марки, модификаторы и доли гостей — все они привязаны к
  /// номеру строки, а не к товару.
  ///
  /// Пустой список — законное значение: чек без строк до этого метода не
  /// доходит (`prepare` отвечает отказом `receipt_empty`), но требовать
  /// непустоты здесь значило бы завести вторую проверку того же.
  Future<void> perform({
    required int receiptNo,
    required int posId,
    required Decimal amount,
    required List<ReceiptLine> lines,
    required List<PaymentEntry> payments,
    required Decimal change,
    required bool selectiveOfd,
    String? customerBin,
    int? agentLocalId,
    int? agentServerId,
    List<CustomFieldEntry>? customFields,
    WithdrawalEntry? withdrawal,

    /// Договор рассрочки, который обязан родиться **той же транзакцией**,
    /// что и чек, — задача 24.
    ///
    /// Довод, почему доводом, а не отдельным вызовом рядом: договор,
    /// заведённый до продажи, переживает её падение и вешает на
    /// покупателя долг за товар, которого он не получил; заведённый после
    /// — не переживает своего падения и оставляет чек, оплаченный
    /// рассрочкой без договора. Второе хуже: чек при этом **сходится по
    /// строкам**, и заметить пропажу нечем.
    ///
    /// Тот же приём и то же место, что у гашения сертификата.
    CreditContractDraft? credit,
  });

  /// Вернуть остаток товара, списанный [perform].
  ///
  /// **Жив в договоре, мёртв в деле — замер, а не догадка (задача 14,
  /// круг правки 2).** `git grep reverseSaleStock -- lib/` даёт четыре
  /// вхождения: это объявление, реализация и два **комментария** в
  /// `local_payment_service.dart`. Вызывающих в продукте — **ноль**.
  ///
  /// Так вышло за две правки. Первая: путь оплаты звал его перед каждой
  /// подготовкой чека — наследство времён, когда корзина жила в памяти
  /// экрана; с задачи 7 строки лежат в базе с первой команды, и вызов
  /// стал прибавлять остаток товару, у которого его никто не отнимал, и
  /// заодно отменял собой запрет продажи сверх остатка. Снят. Вторая:
  /// отмена уже проведённой оплаты, единственный законный читатель, убрана
  /// целиком (докстринг `payAlreadyTakenCode`).
  ///
  /// Метод **не удалён** намеренно: возврат остатка — то, без чего отмена
  /// не может существовать, и будущая спека отмены (со своим экраном,
  /// подтверждением и возвратом склада WMS, серийных номеров и
  /// ингредиентов, которых этот метод не трогает) начнётся с него.
  /// Названо здесь, чтобы «есть в интерфейсе» не читалось как «работает».
  Future<void> reverseSaleStock({required int receiptNo, required int posId});
}

class PaymentEntry {
  const PaymentEntry({
    required this.payeeAccountId,
    required this.amount,
    required this.kindId,
    this.customerLocalId,
    this.approvalCode,
    this.cardMask,
    this.terminalTransactionId,
    this.reference,
    this.providerCode,
  });

  final int payeeAccountId;

  final Decimal amount;

  /// Вид оплаты — строка `PaymentKinds` (задача 14, v41).
  ///
  /// **Обязательный довод, а не необязательный.** До v41 колонки вида не
  /// было вовсе, и вид выводился из рода счёта-получателя в десяти
  /// местах; сделать его необязательным здесь значило бы оставить
  /// одиннадцатое — «а если не назвали, вывести». Тот, кто пишет строку
  /// оплаты, знает, чем платят: это его единственная работа.
  final int kindId;

  final int? customerLocalId;

  final String? approvalCode;

  final String? cardMask;

  final String? terminalTransactionId;

  /// Документ-основание: номер сертификата, номер предоплаты, договор.
  final String? reference;

  /// Код внешнего провайдера у видов, которые с ним разговаривают.
  final String? providerCode;
}

class CustomFieldEntry {
  const CustomFieldEntry({
    required this.customFieldId,
    required this.customFieldItemId,
  });

  final int customFieldId;

  final int customFieldItemId;
}

class WithdrawalEntry {
  const WithdrawalEntry({required this.agentAccountId, required this.amount});

  final int agentAccountId;

  final Decimal amount;
}
