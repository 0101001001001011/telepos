  static const unchanged = SaleFiscalization(FiscalState.unchanged);
  static const operatorAbsent = SaleFiscalization(FiscalState.operatorAbsent);
  static const fiscalModuleAbsent = SaleFiscalization(
    FiscalState.fiscalModuleAbsent,
