/// Что терминал просит сделать с деньгами.
///
/// **Ни одно поле здесь не является правдой о деньгах** — это заявка, а
/// правду выводит касса из своей базы. [claimedChange] назван так нарочно:
/// «сдача, которую посчитал терминал», а не «сдача».
@immutable
class PaymentRequest {
  PaymentRequest({
    required this.type,
    Decimal? cashReceived,
    Decimal? cardAmount,
    Decimal? bonusUsed,
    Decimal? prepaymentUsed,
    this.prepaymentReference,
    this.claimedChange,
    this.accountId,
    this.customerId,
    this.customerBin,
    this.approvalCode,
    this.cardMask,
    this.transactionId,
    this.qrIntentKey,
    this.certificates = const <CertificateTender>[],
    this.installmentTermMonths,
    this.installmentScheme,
  }) : cashReceived = cashReceived ?? Decimal.zero,
       cardAmount = cardAmount ?? Decimal.zero,
       bonusUsed = bonusUsed ?? Decimal.zero,
       prepaymentUsed = prepaymentUsed ?? Decimal.zero;

  final PaymentType type;

  /// Сколько наличных дал покупатель.
  final Decimal cashReceived;

  /// Сколько из суммы чека уходит картой (смешанная оплата).
  final Decimal cardAmount;

  /// Сколько бонуса просят засчитать. Потолок ставит касса.
  final Decimal bonusUsed;

  /// Сколько **аванса** просят засчитать. Потолок ставит касса.
  ///
  /// # Почему поле, а не член [PaymentType]
  ///
  /// Зачёт аванса не исключает ни наличных, ни карты, ни долга: аванс
  /// покрывает часть чека, остальное платится чем угодно. Ровно та же
  /// форма, что у [bonusUsed], и по той же причине — оба они
  /// `PaymentSettlement.offset`, то есть уменьшают сумму к оплате, а не
  /// заменяют собой способ её внести. Членом перечисления это выразить
  /// нельзя: пришлось бы завести `prepaymentAndCash`,
  /// `prepaymentAndCard`, `prepaymentAndMixed` — и по одному на каждый
  /// следующий вид зачёта.
  ///
  /// Потолков три, и все три ставит касса, а не заявка терминала:
  /// остаток аванса на счёте покупателя, сумма чека и остаток после
  /// бонуса.
  final Decimal prepaymentUsed;

  /// Документ-основание аванса — уезжает в `Payments.reference`.
  ///
  /// Своей таблицы у аванса нет (спека, ярус 6), и это единственное
  /// место, где чек называет, **по какому документу** зачтены деньги.
  final String? prepaymentReference;

  /// Сдача, посчитанная терминалом.
  ///
  /// Кассой **не используется как число** ни в одной ветке. Едет затем,
  /// чтобы касса заметила расхождение со своим расчётом и записала его:
  /// расхождение значит либо ошибку в экране, либо чужой клиент, и обе
  /// беды обязаны оставить след, а не пройти молча.
  final Decimal? claimedChange;

  /// Счёт, выбранный кассиром для безналичной части. `null` — касса
  /// выберет сама (первый видимый банковский счёт).
  ///
  /// **Касса проверяет его против собственного списка** ([accounts]):
  /// названный счёт обязан быть в нём и быть банковским. Круг правки 1
  /// нашёл, что без проверки это была вторая дыра того же класса, что и
  /// сдача: браузер диктовал, **куда лягут деньги**, — пробы увели выручку
  /// на расчётный счёт агента и уменьшили оплатой картой бонусный баланс
  /// покупателя. Отказ — [payAccountNotAllowedCode].
  final int? accountId;

  /// Покупатель: клиент лояльности либо должник при [PaymentType.debt].
  final int? customerId;

  /// ИИН/БИН покупателя для чека.
  final String? customerBin;

  final String? approvalCode;
  final String? cardMask;
  final String? transactionId;

  /// Ключ намерения QR/СБП, деньги которого идут в этот чек — задача 22.
  ///
  /// # Едет **ключ**, а не сумма, и это то же правило, что у сдачи
  ///
  /// Ни одно поле этого класса не является правдой о деньгах, и здесь это
  /// особенно дорого: сумма QR **уже подтверждена провайдером** и лежит в
  /// `payment_intents` кассы. Терминал называет, **какое** намерение
  /// закрывать; сколько в нём денег, касса читает у себя.
  ///
  /// Приехавшая сумма была бы третьей дырой того же класса, что сдача и
  /// счёт-получатель: браузер диктовал бы, сколько покупатель заплатил
  /// телефоном, и чек сошёлся бы на выдуманном числе.
  final String? qrIntentKey;

  /// Подарочные сертификаты, поданные к этому чеку — задача 21.
  ///
  /// # Почему список, а не одна бумажка
  ///
  /// Покупателю дарят сертификаты по одному, а тратит он их сразу: два по
  /// тысяче за чек на две тысячи — обычный день, а не край. Одно поле
  /// заставило бы кассира пробивать два чека, и это не ограничение
  /// продукта, а ограничение поля.
  ///
  /// **Цена списка названа: он делает возможным предъявить одну бумажку
  /// дважды** — и именно поэтому касса отвечает на это `certificate_duplicate`
  /// до раскладки. Две строки по 300 с сертификата на 500 порознь проходят
  /// проверку остатка (500 ≥ 300 обе), а вместе требуют 600.
  ///
  /// Сколько каждый покроет, решает **касса**, а не терминал: у сертификата
  /// сдачи нет (`givesChange = false`), поэтому берётся
  /// `min(остаток, сколько осталось доплатить)` — разбор решения в
  /// докстринге `CertificateApplication`.
  final List<CertificateTender> certificates;

  /// Срок рассрочки в месяцах — задача 24.
  ///
  /// Читается **только** при [PaymentType.installment]; на остальных
  /// путях игнорируется молча, как `cardAmount` на чистой наличной
  /// оплате.
  ///
  /// Проверяет его касса по своему списку
  /// (`InstallmentScheduler.allowedTerms`), а не экран: срок в тысячу
  /// месяцев — это тысяча строк в базе на один чек и опечатка, которую
  /// спрятанный выпадающий список не остановит (I162).
  final int? installmentTermMonths;

  /// Код схемы графика (`InstallmentScheme.code`).
  ///
  /// Строка, а не член перечисления, ровно по той же причине, по какой
  /// строкой едет вид оплаты: разбирает её касса
  /// (`InstallmentScheme.byCode`), и незнакомое значение — отказ, а не
  /// подставленная схема. Подставленная уехала бы в **печатный договор**
  /// как подписанная.
  final String? installmentScheme;

  /// # Чего здесь НЕТ: суммы надбавки, и это ответ, а не пропуск
  ///
  /// Соблазн дать терминалу назвать надбавку по рассрочке велик — так
  /// работает розничная «0-0-12». И он неверен по измеримой причине:
  /// надбавка, не входящая в сумму чека, — это деньги, полученные кассой
  /// **без единого фискального документа**. Оператор пересчитывает
  /// `Σ line == Σ payments` с нулевым допуском и про надбавку не знает
  /// ничего; на чеке 10 000 с надбавкой 1 500 покупатель заплатил бы
  /// 11 500, а документ был бы на 10 000.
  ///
  /// Надбавка розничной рассрочки живёт **в цене товара**, где она уже
  /// фискализована. Касса продаёт по цене чека, и договор заводится с
  /// нулевой надбавкой. Представить договор с надбавкой график умеет
  /// (`InstallmentScheduler.build(feeTotal:)`) — это нужно тому, кто
  /// принесёт подписанный договор из банковского модуля.
}

/// Одна бумажка, поданная к чеку: номер и, если он есть, ПИН.
///
/// Отдельный тип, а не два параллельных списка строк: списки номеров и
/// ПИНов разъезжаются по длине молча, и разъехавшись отдают ПИН одного
/// сертификата другому — то есть отказывают в оплате там, где всё верно.
@immutable
class CertificateTender {
