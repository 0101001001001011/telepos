}

/// Чем кончилась оплата.
@immutable
class SaleOutcome {
  const SaleOutcome({
    required this.receiptNo,
    required this.posId,
    required this.amount,
    required this.change,
    required this.paid,
    required this.debt,
    this.repeat = false,
    this.fiscal = SaleFiscalization.notRequired,
  });

  final int receiptNo;
  final int posId;

  /// Сумма чека — та, которую вывела касса из строк своей базы.
  final Decimal amount;

  /// Сдача, посчитанная **кассой**.
  final Decimal change;

  /// Сумма записанных платежей (наличные + карта + бонус).
  final Decimal paid;

  /// Остаток, ушедший на баланс покупателя. Ноль везде, кроме
  /// [PaymentType.debt].
  final Decimal debt;

  /// Это был повтор: касса вернула прежний итог и **ничего не сделала
  /// заново**.
  final bool repeat;

  /// Чем кончилась фискализация — задача 16.
  ///
  /// # Решение о деньгах при отказе фискализации, принятое, а не
  /// доставшееся по умолчанию
  ///
  /// **Деньги остаются взятыми.** [FiscalState.failed] значит «продажа
  /// записана, чек не фискален», а не «оплата не прошла».
  ///
  /// Доводы, по порядку веса:
  ///
  /// 1. **Откатывать нечего и нечем.** Транзакция продажи — остаток
  ///    товара, склад WMS, серийные номера, ингредиенты, строки
  ///    `Payments`, балансы счетов — закрыта до того, как фискализация
  ///    началась. Обратного хода в дереве нет:
  ///    `SaleUseCase.reverseSaleStock` возвращает только остаток карточки
  ///    (не WMS, не серийники, не ингредиенты) и не имеет ни одного
  ///    вызывающего. «Откат» был бы враньём в докстринге.
  /// 2. **Отказать хуже, чем не отказать.** Деньги уже в ящике, товар
  ///    отдан. Сказать кассиру «оплата не прошла» значит подтолкнуть его
  ///    взять их второй раз.
  /// 3. **Взять деньги и не отдать чек — уже случившееся, а не выбор.**
  ///    Отказ пришёл после того, как продажа записана; вопрос не «брать
  ///    ли деньги», а «что сказать». Оставить оплату и назвать беду —
  ///    единственный ответ, который не добавляет к нефискальному чеку
  ///    ещё и потерянные деньги.
  ///
  /// # Довод, который стоял здесь и оказался ложным (круг правки 1)
  ///
  /// Первая редакция этого докстринга утверждала третьим доводом, что
  /// «лечение у этой беды уже есть» — очередь фискализации и служба
  /// разбора нефискализованных операций. **Это неправда, и неправда ровно
  /// в том случае, ради которого довод писался.** Измерено чтением, а не
  /// памятью:
  ///
  /// - `OfflineQueueingProvider._guard` кладёт в очередь при
  ///   недостижимости, при броске и при транзиентном коде, а
  ///   `_isTransient` истинен **только** для `network` и `tokenExpired`.
  ///   Все три пути возвращают `FiscalResult.queued()`, то есть
  ///   `success: true`. Значит [FiscalState.failed] ставится только при
  ///   `success: false` с нетранзиентным кодом — **в точности дополнение
  ///   к «очередь подберёт»**;
  /// - `FiscalServiceImpl._persistReceipt` начинается с
  ///   `if (!result.success || !result.hasFiscalSign) return;` — в
