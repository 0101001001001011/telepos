/// Оплата чека как контракт — задача 14 плана «Продажа с браузерного
/// терминала», фаза 5.
///
/// Чистый Dart: ни Flutter, ни drift. Реализаций две — кассовая
/// (`LocalPaymentService`) и браузерная поверх провода
/// (`WtPaymentService`); экран оплаты один и тот же.
///
/// # Почему здесь шесть методов, а не двадцать
///
/// У `PaymentNotifier` двадцать операций. По проводу едут шесть, и правило
/// отбора одно: **едет то, что меняет правду о деньгах или трогает
/// железо** (I163). Цифровая клавиатура, активное поле, «без сдачи»,
/// раскладка номиналов, выбор активного ввода — состояние экрана: они не
/// пишут в базу, не двигают остаток и не разговаривают с эквайрингом.
/// Отправлять их по проводу значило бы платить кругом сети за нажатие
/// цифры.
///
/// # Главное правило: сдачу считает касса
///
/// [SaleOutcome.change] приходит **от кассы**, и она считает его сама, из
/// суммы чека, которую сама же и вывела из строк в своей базе. Терминал
/// — это вкладка браузера, её содержимое нам не принадлежит:
/// [PaymentRequest.claimedChange] существует не затем, чтобы касса им
/// пользовалась, а затем, чтобы она **заметила расхождение** и записала
/// его в журнал. Ни одна ветка кассовой реализации не читает это поле как
/// число.
///
/// Та же причина и у [reserveBonus], и у потолка в [chargeCard]: сумма
/// списываемого бонуса и сумма, уходящая в эквайринг, — деньги, и
/// последнее слово о них за кассой.
///
/// # Права
///
/// Проверяет их **касса, до вызова обработчика** (I44, I162), сторож
/// провода — не эта реализация и не спрятанная кнопка:
///
/// - `pay.accounts`, `pay.loyalty`, `pay.bonus`, `pay.card` —
///   `PermissionKeys.navSale`;
/// - `pay.complete` — `navSale`, а сверх него, **по телу запроса**:
///   `op.sellDebt` для [PaymentType.debt]. Этот ключ до задачи 14 не
///   читала ни одна строка `lib/` (докстринг `PermissionKeys`, «эти
///   восемь не сняты»); здесь у него появляется первый настоящий
///   читатель.
///
/// **`op.cancelPayment` читателя не получил и остаётся плацебо** — как
/// `op.cashInOut`. Круг правки 1 убрал отмену уже проведённой оплаты
/// целиком: у неё не было ни одного производителя в `lib/` (ни экрана,
/// ни кнопки, ни подтверждения), она была достижима только рукописным
/// кадром, и приносила с собой дыру в проверке прав, невозвращаемые
/// склад WMS/серийники/ингредиенты, двойное списание при переоплате и
/// отсутствие проверки владельца и срока смены. Отмена — отдельная
/// работа со своей спекой, а не флаг в кадре.
///
/// # Отказ — значение, исключение — транспорт
///
/// Как и у `CartService`: методы бросают `WireRefusal`, а наружу, на
/// провод, он уезжает **значением** — кадром отказа с кодом и текстом
/// (I144). Коды перечислены константами ниже, чтобы терминал отличал
/// причину по коду, а не по подстроке в тексте. Коды `cart_stale` и
/// `cart_wrong_receipt` намеренно **те же самые**, что у корзины: беда та
/// же (снимок терминала устарел), лечение то же (перечитать корзину и
/// повторить), и заводить им вторые имена значило бы заставить терминал
/// знать два способа сказать одно и то же.
abstract interface class PaymentService {
  /// Счета, на которые касса умеет принять деньги.
  ///
  /// Порядок значим: счета кассы (`AccountType.pos`) идут первыми — это
  /// умолчание для наличных, и [PaymentAccount.isDefault] помечает их.
  Future<List<PaymentAccount>> accounts();

  /// Торгует ли **эта касса** в долг — тумблер мастера настройки
  /// «Разрешить продажу в кредит» (`ThisPosEntries.sellInDebt`).
  ///
  /// # Это не право и не разрешение рабочего места
  ///
  /// Три разных ответа, и путать их дорого: право `op.sellDebt` — про
  /// человека (сторож провода), `Terminal.allowedPaymentTypes` — про
  /// рабочее место (`_requireAllowedTypes`), а это — про кассу. Экран
  /// оплаты спрашивает все три и показывает кнопку «В долг» только
  /// тогда, когда сошлись все.
  ///
  /// # Зачем экрану вообще спрашивать
  ///
  /// Затем же, зачем он спрашивает набор видов рабочего места (задача 15):
  /// чтобы кассир не выбирал покупателя и не набирал сумму ради отказа
  /// последним нажатием. Ответ — **удобство**; запрет держит касса и
  /// отвечает [payDebtNotSoldHereCode] любому кадру, в том числе
  /// собранному мимо экрана.
  ///
  /// **Отказа не бросает и умалчивает в безопасную сторону:** касса без
  /// строки настроек (мастер не пройден) отвечает `false` — «в долг не
  /// торгуют», а не «торгуют».
  Future<bool> sellsInDebt();

  /// Клиент программы лояльности по номеру телефона.
  ///
  /// `null` — такого нет; это не отказ, а обычный ответ: кассир набирает
  /// номер по цифре, и «пока не нашли» — нормальное состояние поиска.
  Future<LoyaltyCustomer?> findLoyalty(String phone);

  /// Сколько бонуса клиента [customerId] касса **согласна** засчитать,
  /// если у неё просят [amount].
  ///
  /// Ничего не удерживает и не списывает — списание происходит в
  /// [complete], одной транзакцией с самой продажей. Имя «reserve» взято
  /// из брифа задачи; по существу это вопрос «сколько из этого настоящее»,
  /// и ответ считает касса, а не браузер.
  ///
  /// **Предел, названный честно:** здесь потолок один — остаток бонусного
  /// счёта. Второй потолок — сумма чека — тут недостижим: у метода нет ни
  /// рабочего места, ни номера чека, значит и суммы. Его накладывает
  /// [complete], где сумма чека уже посчитана кассой, и именно там он
  /// имеет силу; ответ этого метода — предварительный, экран показывает
  /// его человеку, но деньгами он не становится.
  Future<Decimal> reserveBonus(int customerId, Decimal amount);

  /// Сколько аванса внесено покупателем [customerId] — **вход в зачёт
  /// аванса** (задача 23 написала механику, этот метод — вход в неё).
  ///
  /// # Зачем экрану этот вопрос
  ///
  /// Кассир решает, сколько зачесть, и решать вслепую он не может: аванс
  /// живёт кредитовым сальдо на расчётном счёте покупателя
  /// (`Agents.mainAccountId`), а у вкладки браузера базы нет. До этого
  /// метода остатка не отдавала ни одна операция, и зачёт аванса был
  /// написан целиком и недостижим ни с одного экрана.
  ///
  /// # Что отвечает
  ///
  /// **Положительную часть** сальдо. Минус на том же счёте — долг
  /// покупателя, а не аванс, и показать кассиру «аванс −300» значило бы
  /// предложить зачесть долг. Ноль — внесённого нет.
  ///
  /// Отказы значением (I144): [payKindInactiveCode] — вид «аванс» выключен
  /// в справочнике кассы (виды 5–8 заводятся выключенными);
  /// [payCustomerUnknownCode]; [payPrepaymentAccountMissingCode].
  ///
  /// **Ответ — предпросмотр, а не резерв.** Потолок и условная запись
  /// остаются в [complete] (`AccountDao.claimCredit`): второй чек того же
  /// покупателя между этим вопросом и оплатой не получит те же деньги.
  Future<Decimal> prepaymentBalance(int customerId);

  /// Что касса знает о подарочном сертификате [number] — **вход в гашение
  /// сертификата** (задача 21 написала гашение, этот метод — вход в него).
  ///
  /// Кассир видит остаток бумажки **до** гашения и решает, подавать ли
  /// её. Отказы — те же, которыми ответило бы гашение, и **в том же
  /// порядке**: вид выключен ([payKindInactiveCode]), нет такого
  /// (`certificate_unknown`), ПИН не подошёл (`certificate_pin_wrong` —
  /// **до** разговора об остатке и сроке), срок вышел, остатка нет, нет
  /// счёта обязательства.
  ///
  /// Не чистое чтение: истёкший сертификат получает отметку `expired`
  /// (докстринг `CertificateStatus.expired`). `pinHash` в ответе браузеру
  /// не едет (`certificateToWireJson`).
  Future<GiftCertificate> findCertificate(String number, {String? pin});

  /// Можно ли на этой кассе показать код QR — **до** первого «Показать QR».
  ///
  /// `null` — можно: вид оплаты QR включён и провайдер заведён. Иначе — код
  /// той беды, которой ответил бы [startQr]: [payKindInactiveCode],
  /// [payKindUnknownCode] или `qr_not_configured`. Порядок проверок тот же.
  ///
  /// # Зачем (пункт 9 C, 2026-09-15)
  ///
  /// Панель QR узнавала «не настроено» только на первом нажатии: кассир
  /// набирал сумму и получал отказ. Ответ — **удобство**, как у
  /// [sellsInDebt]: запрет держит [startQr], отвечающий тем же кодом любому
  /// кадру. Отказом не бросает: беда настройки — ответ, а не исключение.
  Future<String?> qrUnavailableReason();

  // ── оплата по QR/СБП: вход ──────────────────────────────────────────────
  //
  // Три метода, а не один с режимом, и довод не в красоте: у трёх разные
  // ответы на вопрос «что будет при повторе». [startQr] идемпотентен по
  // ключу попытки; [pollQr] — чистый вопрос с одним кругом сети; [cancelQr]
  // необратим. Режим в теле сделал бы право и повтор зависящими от поля
  // кадра — ровно то, что у `pay.complete` названо единственным таким
  // случаем в дереве и оправдано одной и той же работой над одним чеком.
  //
  // Все три берут рабочее место доводом (на проводе — из сеанса) и
  // отдают [QrTender] — без адреса провайдера, без его ключа и без его
  // имени (докстринг `QrProviderSettings`).

  /// Показать покупателю код на [amount] по открытому чеку рабочего места.
  ///
  /// [meta] `.key` — **ключ попытки**, а не чека: после отмены новый код
  /// заводится новой попыткой, а повтор той же попытки (ответ не дошёл)
  /// возвращает прежнее намерение, а не второе. Сумма входит в ключ
  /// намерения — тем же приёмом, что у памяти проведения карты.
  ///
  /// Отказы значением: [payKindInactiveCode]; `qr_not_configured` —
  /// провайдера на кассе нет; [payReceiptNotFoundCode];
  /// [payInsufficientCode]; [payAmountExceedsReceiptCode];
  /// [payQrIntentLiveCode] — на чеке уже ждёт другой код.
  ///
  /// Отказ **провайдера** — не исключение, а [QrTender.refusalCode]:
  /// транзиентный оставляет ожидание живым (касса повторит), прочие
  /// закрывают попытку фазой `failed`.
  Future<QrTender> startQr(
    int terminalId,
    Decimal amount,
    CartCommandMeta meta,
  );

  /// Один круг ожидания по намерению [intentKey] **этого рабочего места**.
  ///
  /// Сдаётся касса сама: терпение — её настройка, и круг, пришедший
  /// после срока, отменяет код у провайдера (фаза `patienceSpent`).
  /// Вкладка ждать дольше не может ничем.
  ///
  /// Чужое намерение — [payQrIntentUnknownCode], как несуществующее:
  /// ключи попыток не секрет, а отказ «это не ваше» подтвердил бы, что
  /// такое есть.
  Future<QrTender> pollQr(int terminalId, String intentKey);

  /// Кассир прервал ожидание.
  ///
  /// **Ответ читается**: провайдер мог ответить «уже оплачено», и тогда
  /// фаза — `paidAfterGiveUp`, а деньги идут в открытый чек. Не
  /// дозвонились — `cancelUnconfirmed`: деньги ещё могут прийти, и чек
  /// закрывать нельзя.
  Future<QrTender> cancelQr(int terminalId, String intentKey);

  /// Провести [amount] через платёжный терминал, привязанный к рабочему
  /// месту [terminalId].
  ///
  /// Единственная операция контракта, трогающая железо. Привязка берётся
  /// **терминала-вызывающего**, а не кассы: у браузерного рабочего места
  /// свой эквайринг, и до этой задачи `PaymentNotifier` спрашивал
  /// привязку через `TerminalRepository.self()` — то есть всегда
  /// оборудование самой кассы.
  ///
  /// [meta] — ключ повтора: тот же ключ не проводит карту дважды.
  Future<CardCharge> chargeCard(
    int terminalId,
    Decimal amount,
    CartCommandMeta meta,
  );

  /// Завершить оплату чека [CartCommandMeta.receiptNo].
  ///
  /// Повтор с тем же [CartCommandMeta.key] безопасен и обязателен к
  /// поддержке: кассир повторяет оплату, когда бросила фискализация или
  /// принтер, а вкладка — когда не дождалась ответа. Повтор возвращает
  /// тот же итог и **не берёт деньги второй раз**
  /// ([SaleOutcome.repeat] — `true`).
  Future<SaleOutcome> complete(
    int terminalId,
    PaymentRequest request,
    CartCommandMeta meta,
  );

  /// Чем кончились **отправленные** действия железа чека [receiptNo] —
  /// задача 16, круг правки 1.
  ///
  /// Печать и денежный ящик уходят `unawaited` (правило «оплата не ждёт
  /// железа»), поэтому в [SaleOutcome] их исход попасть не может: к
  /// моменту ответа кассиру они ещё идут. Но и пропасть он не имеет
  /// права: до задачи 16 экран показывал оранжевое «Ошибка печати» и при
  /// отказе очереди, и при исключении, а задача этот сигнал сняла вместе
  /// с печатью. Метод его возвращает.
  ///
  /// **Ждать этого можно только после того, как кассиру сказано об успехе
  /// оплаты.** Вызов до того вернул бы правило «не ждёт железа» обратно
  /// тем же ожиданием под другим именем.
  ///
  /// **Чтение разрушающее и по владельцу** (круг правки 2). Запись
  /// отдаётся один раз и снимается — второй спрос того же чека вернёт
  /// пустой список; и отдаётся она только **тому рабочему месту, которое
  /// этот чек оплачивало**. Без владения любой сеанс с `nav.sale` мог бы
  /// не просто прочитать чужую беду, а **съесть** её — номера чеков
  /// последовательны по кассе, перебрать их ничего не стоит, — и
  /// настоящий владелец не увидел бы ничего.
  ///
  /// Владение проверяется **не по `Sales.terminalId`**: `perform`
  /// обнуляет его на оплаченном чеке (владелец бывает только у чека в
  /// работе). Касса помнит владельца рядом с самой записью о беде.
  ///
  /// Пустой список — «ничего не сломалось», «спросил не тот» **или**
  /// «касса уже не помнит»: без читателя запись вытесняется следующими
  /// чеками. Это не хранилище исходов, а сигнал одному вызывающему;
  /// долговечное место для того, что не напечаталось, — сама очередь
  /// печати, у неё свой экран с повтором
  /// (`printer_settings_screen.dart`).
  Future<List<CompletionTrouble>> hardwareTroubles(
    int terminalId,
    int receiptNo,
  );
}

/// Что именно не получилось после того, как деньги записаны.
enum CompletionTroubleKind {
  /// Чек не принят в очередь печати (или сборка/отправка бросила).
  ///
  /// Задание, **принятое** очередью и не напечатавшееся потом, сюда не
  /// попадает: оно живёт в очереди, видно на её экране и повторяется
  /// оттуда. Здесь — только то, чего в очереди не оказалось вовсе.
  print,

  /// Денежный ящик не открылся.
  drawer,
}

/// Беда железа, случившаяся после оплаты.
@immutable
class CompletionTrouble {
  const CompletionTrouble({
    required this.kind,
    required this.receiptNo,
    required this.message,
  });

  final CompletionTroubleKind kind;
  final int receiptNo;

  /// Причина словами. Текста исключения не содержит (I144).
  final String message;

  @override
  bool operator ==(Object other) =>
      other is CompletionTrouble &&
      other.kind == kind &&
      other.receiptNo == receiptNo &&
      other.message == message;

  @override
  int get hashCode => Object.hash(kind, receiptNo, message);
}

/// Вид оплаты.
///
/// [debt] заведён этой задачей и не выдуман: механизм продажи в долг в
/// дереве уже есть — `SaleUseCaseImpl.perform` списывает разницу между
/// суммой чека и суммой платежей на баланс агента
/// (`_updateAgentBalance(agentLocalId, -debitAmount)`). Не было **входа** в
/// этот механизм: ни экрана, ни вида оплаты, ни права. Право есть с самого
/// начала (`PermissionKeys.opSellDebt`) и до этой задачи не читалось.
///
/// Задача 15 («виды оплаты как свойство терминала») берёт это перечисление
/// в `Terminal.allowedPaymentTypes` — поэтому оно живёт в домене, а не в
/// контроллере, где было до этой задачи.
enum PaymentType {
  cash,
  card,
  mixed,

  /// Продажа в долг: платежи покрывают меньше суммы чека, остаток ложится
  /// на баланс покупателя. Требует `op.sellDebt` и названного покупателя.
  debt,

  /// Продажа в рассрочку — задача 24.
  ///
  /// # Почему член перечисления, а не поле, как у аванса и сертификата
  ///
  /// Потому что рассрочка — **остаток чека**, а не зачёт. Аванс,
  /// сертификат, бонус и QR уменьшают сумму к доплате и потому
  /// сочетаются друг с другом сколько угодно; рассрочка **заменяет
  /// собой** способ внести остаток — ровно как долг. Двух остатков у
  /// одного чека быть не может, и в этом же ответ на вопрос «что мешает
  /// выдать две рассрочки на один чек»: вид оплаты у заявки один, а
  /// значит и договор один. Второй заслон — уникальный ключ
  /// `{receiptNo, posId}` таблицы `credit_contracts`.
  ///
  /// **Дописан в конец `values`, и это не вкусовщина.** Порядок членов
  /// уезжает на диск (`Terminals.allowedPaymentTypes`, `paymentTypeNames`)
  /// и на провод; вставка в середину переназначила бы уже разрешённые
  /// рабочим местам виды (предупреждение записано в
  /// `terminal_tables.dart:52`).
  ///
  /// Требует `op.sellDebt` (то же право, что долг: вопрос один — «кому
  /// можно отдать товар за запись»), названного покупателя, включённого
  /// тумблера кассы `sellInDebt` и **отсутствия просрочки** у покупателя.
  installment;

  /// Имя на проводе. Совпадает с [name] — метод существует затем, чтобы
  /// разбор и сборка кадра пользовались одной парой, а не двумя списками.
  static PaymentType? byWireName(String? value) {
    for (final type in values) {
      if (type.name == value) return type;
    }
    return null;
  }
}

