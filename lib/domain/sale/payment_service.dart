  final FiscalState state;

  /// Фискальный признак — только при [FiscalState.done].
  final String? sign;

  /// Причина, названная словами. Не содержит текста исключения (I144).
  final String? message;

  bool get isFailed => state == FiscalState.failed;

  /// Касса собрана без узла фискализации. Не настройка — сборка.
  ///
  /// Читает `payment_screen.dart`, чтобы показать красную полосу. Соседей
  /// «isOperatorAbsent» и «hasNoDocument» здесь **нет намеренно**: задача
  /// 5 завела их за компанию, и проход `anti-gaps` показал, что у первого
  /// нет ни одного вызывающего во всём дереве, а у второго — только
  /// утверждение в пробе, дублирующее сравнение строкой выше. Симметрия
  /// — не причина заводить член; спрашивающий — причина. Понадобится
  /// «оператора нет» продукту — заведётся тогда, вместе со своим
  /// читателем.
