  final String number;

  /// ПИН, набранный кассиром. `null` — у сертификата ПИНа нет.
  ///
  /// В журнал не пишется ни одной веткой: `LocalPaymentService` логирует
  /// номер, но не ПИН. Тот же довод, что у хэша вместо текста.
  final String? pin;

  @override
  bool operator ==(Object other) =>
      other is CertificateTender && other.number == number && other.pin == pin;

  @override
  int get hashCode => Object.hash(number, pin);

  @override
  String toString() => 'CertificateTender($number)';
}

/// Чем кончилась фискализация чека — задача 16.
///
/// Заведено затем, чтобы отказ фискального оператора перестал быть
/// **молчаливым**: до задачи 16 он ловился внутри `SaleUseCaseImpl.perform`
/// и уходил в `Talker.warning`, а кассир и терминал не узнавали о нём
/// ничего.
///
/// Порядок членов **не является** их номером в базе. Колонка
/// `Sales.fiscalState` хранит `FiscalStateCodes.of(...)` — стабильное
/// число, объявленное в `lib/domain/fiscal/fiscal_state_codes.dart`
/// отдельно от порядка. Провод (`pay_ops.dart`) сверяет по имени члена.
/// `index` не хранит и не сравнивает никто: это закреплено сторожем в
/// `test/domain/fiscal/fiscal_state_codes_test.dart`.
enum FiscalState {
  /// **Политика чека** вывела «не в этот раз»: оператор у кассы есть и
  /// включён, а `ThisPos.ofdSyncType` для этого чека документа не требует
  /// (выборочная фискализация, только безналичные и т. п.).
  ///
  /// Это утверждение о **чеке**, а не о кассе. Два других «не нужен» —
  /// [operatorAbsent] и [fiscalModuleAbsent] — говорят про кассу, и лечатся
  /// они разным: одно настройкой, другое сборкой. До задачи 5 все три
  /// приезжали сюда одним значением, и докстринг это прямо признавал.
  notRequired,

  /// **Оператора у кассы нет** — `FiscalSettings.operatorType == none`,
  /// то есть фискальный оператор не настроен или выключен.
  ///
  /// Это настройка, а не поломка: касса торгует, чеки печатаются,
  /// фискальных документов нет. Показывается **строкой в подвале чека**
  /// («Фискальный оператор не настроен», `noFiscalDocumentReason`), а на
  /// экране оплаты — **ничем**: окно на каждой продаже отучаются замечать
  /// за день, и тогда оно перестаёт работать и для настоящих бед.
  operatorAbsent,

  /// **Узла фискализации нет в собранной кассе** — `FiscalService` не
  /// собран вовсе (`_fiscal == null`).
  ///
  /// Это сломанная сборка, а не настройка: настройками такое не лечится и
  /// кассиром не исправляется. Красная полоса и `error` в журнал **каждый
  /// раз**, а не однажды.
  fiscalModuleAbsent,

  /// Оператор ответил и выдал фискальный признак.
  done,

  /// Оператор недоступен, чек **встал в очередь** фискализации и уедет
  /// сам. Не отказ.
  queued,

  /// Фискализовать не удалось: **деньги взяты, чек не фискален**. Решение
  /// задачи 16 — см. докстринг [SaleOutcome.fiscal].
  failed,

  /// Повтор команды: касса ничего не делала заново, и придумывать
  /// состояние ей не из чего.
  unchanged,
}

/// Исход фискализации одного чека.
