/// Предлагать ли кассиру «В долг» — и если нет, то почему именно.
///
/// # Три разных ответа, которые нельзя складывать в один булев
///
/// Продажа в долг загорожена **тремя** независимыми вещами, и каждая
/// живёт в своём месте:
///
/// 1. **Касса** — тумблер мастера настройки «Разрешить продажу в кредит»
///    (`ThisPosEntries.sellInDebt`). Свойство торговой точки: «здесь
///    вообще не торгуют в кредит».
/// 2. **Человек** — право `op.sellDebt`. Оно переносится с ролью из
///    магазина в магазин и ничего не говорит о самой точке.
/// 3. **Ответ кассы ещё не приехал.** Третье состояние, а не второе:
///    «не знаем» и «нельзя» — разные вещи, и кассиру они говорятся
///    разными словами.
///
/// Свести первые два в один булев значило бы объявить их одним и тем же:
/// администратор с правом по должности продавал бы в кредит там, где
/// кредита нет, а включённый на кассе кредит выдавал бы право тому, кому
/// его не давали. Обе подмены — деньги.
///
/// # Почему рабочего места здесь нет
///
/// Долг **не сторожится** набором `Terminal.allowedPaymentTypes`:
/// `tenderPaymentTypes` не содержит `debt` намеренно, и
/// `paymentTypeOfferable` отвечает про него `true` всегда (разбор —
/// `lib/domain/terminal/terminal.dart`, задача 15). Завести здесь
/// четвёртое условие по набору значило бы соврать в другую сторону —
/// показать на экране запрет, которого у кассы нет.
///
/// # Это удобство, а не защита
///
/// Ни одна ветка ниже ничего не запрещает. Запрет держит касса:
/// `LocalPaymentService._requireDebtSoldHere` отвечает
/// `debt_not_sold_here`, а право `op.sellDebt` проверяет сторож провода
/// до вызова обработчика (I44, I162). Кадру, собранному мимо этого
/// экрана, отвечают тем же самым.
library;

/// Что экран говорит кассиру про кнопку «В долг».
enum DebtOffer {
  /// Сошлось всё: касса торгует в кредит, право у кассира есть.
  available,

  /// Тумблер кассы выключен — здесь в кредит не торгуют вовсе.
  notSoldHere,

  /// Касса торгует в кредит, но у этого кассира нет `op.sellDebt`.
  notPermitted,

  /// Касса ещё не ответила, торгует ли она в кредит.
  ///
  /// Отдельное состояние, а не «нельзя»: неотвеченный вопрос — это не
  /// запрет, и говорить кассиру «здесь не торгуют в кредит», когда мы
  /// этого не знаем, значит соврать. Кнопка при этом всё равно гаснет —
  /// пускать в оплату по незнанию нельзя, — но причина называется своя.
  unknown,
}

/// Предложение долга: [sellInDebt] — тумблер кассы (`null` — ответа ещё
/// нет), [permitted] — право `op.sellDebt` у кассира.
///
/// **Порядок ветвей значим.** Место отвечает раньше человека: на кассе,
/// где кредита нет, «у вас нет права» — неправда, и кассир пошёл бы
/// добиваться права, которое ничего не изменит.
DebtOffer debtOfferOf({required bool? sellInDebt, required bool permitted}) {
  if (sellInDebt == null) return DebtOffer.unknown;
  if (!sellInDebt) return DebtOffer.notSoldHere;
  if (!permitted) return DebtOffer.notPermitted;
  return DebtOffer.available;
}
