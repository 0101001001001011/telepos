  /// Переключает чек между розницей и оптом.
  ///
  /// # Что делает и чего не делает
  ///
  /// **Режим действует на строки, добавленные после него.** Уже набранные
  /// строки командой не переоцениваются — это политика, а не упущение:
  /// переоценка задним числом изменила бы деньги в строках, которые
  /// кассир уже видел и, возможно, назвал покупателю. Хочет пересчитать —
  /// правит цену строки (`updatePrice`) или набирает её заново.
  ///
  /// **Пересканировать товар после переключения — работает.** Новые
  /// единицы ложатся **отдельной строкой** по цене нового режима, а не
  /// подмешиваются в старую (кассовая реализация: слияние только в строку
  /// с той же ценой). До круга правки 5 они молча уходили в старую строку
  /// по старой цене, и товар, уже лежащий в корзине, оптовую цену не
  /// получал никогда.
  ///
  /// **Задача 8 уточнила, какая цена считается «той же»: видимая.** Ключ
  /// слияния — цена, какой её показывает снимок (после округлений чека), а
  /// не сырое число в базе: при включённом округлении две строки могли
  /// выглядеть одинаково и не сливаться никогда, а объяснить это кассиру
  /// было нечем. Тем же кругом слияние перестало трогать строки с ручной
  /// скидкой и с маркой — подробности в `LocalCartService._mergeTarget`.
  ///
  /// Значит в чеке могут одновременно лежать строки обоих режимов. Снимок
  /// этого **не помечает**: у `CartView` нет признака «в чеке смесь цен»,
  /// и экран показывает только текущий режим чека. Кассир различает
  /// строки по их ценам — не идеально, но честно; отдельный признак это
  /// поле в снимке и работа для экрана, за границей этой задачи.
  ///
  /// # Пределы, которые надо знать до того, как это включат
  ///
  /// **Нулевая оптовая цена считается НЕзаданной — закрыто кругом правки 1
  /// задачи 10.** Здесь стояло обратное, и стояло пределом: опт применялся
  /// по признаку «оптовая цена задана», а не «задана и осмысленна», а ноль
  /// попадает в `ProductPrices.wholesalePrice` штатными путями — импорт
  /// каталога с нулевой закупочной ценой, заведение товара с пустой
  /// минимальной ценой, правка цен существующего товара. Предел был записан
  /// и оставлен открытым на том основании, что опт недостижим; задача 10
  /// написала обработчик, и он стал достижим.
  ///
  /// Цена предела измерена до конца, и она не кончалась корзиной: строка с
  /// ценой 0 → подготовка чека отдаёт сумму 0 без отказа → фискальный
  /// провайдер пишет цену без единой проверки на ноль (проверка есть только
  /// у скидки и наценки). Чек на ноль уезжал бы в ОФД как обычный.
  ///
  /// Решение о данных принято здесь и одно: **ноль трактуется как
  /// отсутствие** (`LocalCartService._addOrMerge`), то есть берётся
  /// розничная цена. Не отказ: «у товара нет оптовой цены» — обычное
  /// состояние каталога, а не ошибка команды, и отказ остановил бы весь
  /// оптовый чек из-за одной позиции.
  ///
  /// **На кассе опта сегодня нет вовсе.** `sale_controller.toggleMode`
  /// меняет режим в состоянии экрана, но путь завершения продажи цену по
  /// нему не выбирает, а единственный юзкейс, который выбирал
  /// (`SaleProductCreationUseCase`), не имеет вызывающих. То есть после
  /// этой задачи опт работает **с браузерного терминала и не работает на
  /// кассе** — расхождение двух фронтов, которое закрывает задача 8,
  /// переводя экран кассы на этот контракт.
  ///
  /// # Право кассира и настройка кассы — так же «и», как у [updatePrice]
  /// (ревизия второго фронта 2026-09-19)
  ///
  /// - **`op.editPrice`** — право кассира, из [by], проверяется первым,
  ///   отказ [cartForbiddenCode];
  /// - **`ThisPosEntries.editPrice`** — настройка кассы, проверяется второй,
  ///   отказ [cartDeniedPolicyCode].
  ///
  /// До ревизии здесь стояло только право, и в докстринге [updatePrice] это
  /// было записано открытой дверью: владелец, выключивший «Правку цены»,
  /// закрывал ручную цену строки и **не** закрывал оптовый прейскурант,
  /// хотя это тот же самый «продать дешевле розничной», только списком. Обе
  /// величины и порядок разобраны в докстринге [updatePrice], здесь тот же
  /// порядок и те же коды — два ответа на один вопрос разошлись бы при
  /// первой же правке.
  ///
  /// **Настройка спрашивается только при включении опта.** Возврат в
  /// розницу (`value == false`) не закрыт ничем, кроме права: иначе чек,
  /// ставший оптовым до щелчка тумблером, оказался бы заперт в опте
  /// навсегда. Разбор — в докстринге
  /// `LocalCartService._requirePriceEditingEnabled`.
  ///
  /// **Тем же ходом закрыт второй вход** — `start(wholesale: true)`, каким
  /// экран продажи начинает чек, если режим остался оптовым с прошлого.
