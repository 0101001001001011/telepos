/// Корзина чека как контракт — задача 7 плана «Продажа с браузерного
/// терминала», шаг 2 спеки.
///
/// Чистый Dart: ни Flutter, ни drift. Реализаций две — кассовая
/// (`LocalCartService`, эта же задача) и браузерная поверх провода
/// (задача 12); экран продажи один и тот же, под ним меняется только
/// реализация (шаг 5 спеки).
///
/// # Три правила, общие для каждой изменяющей команды
///
/// 1. **Владелец.** Каждая команда несёт `terminalId` и работает только с
///    чеком в работе **этого** рабочего места (`SaleDao.findInProgress`).
///    Чужой чек командой не достать — не потому, что кнопка спрятана, а
///    потому, что запрос его не находит.
///
///    **Требование безопасности к тому, кто вызывает контракт с провода
///    (задачи 10 и 12).** `terminalId` — обычный довод метода, и сам
///    контракт проверить его происхождение не может. Тот, кто разбирает
///    кадр провода, **обязан** брать имя рабочего места из **сеанса**, а
///    не из тела кадра, и обязан отвергать кадр, в котором оно названо.
///    Иначе «назови чужое место — получи его корзину» становится рабочим
///    приёмом: подписка отдаст чужие строки, а команда их изменит.
///
///    **Отвергать, а не игнорировать — решение заказчика (круг правки 5),
///    и оно перекрывает бриф задачи 10 в этой части.** Бриф говорит
///    «поле тела игнорируется»; здесь требуется отказ. Кадр с названным
///    именем рабочего места — это либо ошибка клиента, либо попытка;
///    молчаливое игнорирование прячет обе, и первая всплывёт как
///    необъяснимое «команды уходят не туда», а вторая не всплывёт вовсе.
///    Проверить это должен сторож задачи 10: сам контракт не может —
///    `terminalId` доходит до него уже значением.
///    Круг правки 3 снял единственное, что этому мешало непреднамеренно
///    (строгую сверку номера чека у `start` с холода), — и проба разбора
///    в круге 4 показала, что чужая корзина отдаётся вызовом с чужим
///    именем места. Сегодня дефекта в продукте нет: корзина на провод не
///    выведена. Требование записано **до** того, как её выведут, а не
///    после.
/// 2. **Опознание чека и версия.** [CartCommandMeta.receiptNo] говорит,
///    **какой** чек терминал видел; [CartCommandMeta.baseVersion] —
///    **каким** он его видел. Разошёлся номер — отказ
///    [cartWrongReceiptCode]; тот же номер, но разошлась версия — отказ
///    [cartStaleCode]. Беды разные, и коды разные: первая значит «команда
///    адресована чеку, которого у меня уже нет», вторая — «чек тот, но он
///    уехал вперёд». Одной версии не хватает по построению — она считает
///    изменения **текущего** чека и у каждого нового начинается с нуля,
///    так что у разных чеков версии совпадают постоянно (проба круга
///    правки 2 — см. докстринг [CartCommandMeta]).
/// 3. **Ключ повтора.** [CartCommandMeta.key] помнится кассой в той же
///    транзакции, что и само изменение. Повтор с тем же ключом возвращает
///    тот же снимок и корзину второй раз не меняет — терминал имеет право
///    повторить запрос, не дождавшись ответа (обрыв провода, перезагрузка
///    вкладки), и обязан от этого не получить второй товар в чеке.
///
/// Порядок проверок именно такой: **сначала ключ, потом номер чека, потом
/// версия**. Повтор приходит с той же (уже устаревшей после первого
/// применения) версией — проверь версию раньше ключа, и любой честный
/// повтор получал бы [cartStaleCode] вместо ответа, то есть защита от
/// повтора не работала бы вовсе. Номер раньше версии потому, что при
/// разошедшемся номере сравнивать версии бессмысленно: это счётчики двух
/// разных чеков.
///
/// **Честный предел защиты от повтора: слот, а не журнал.** Касса помнит
/// **одну** последнюю команду чека (`Sales.lastCommandKey`, одна колонка).
/// Значит правило 3 выполняется ровно для последней применённой команды, и
/// перебить её может кто угодно, а не только сам терминал:
///
/// - терминал нарушил «одну команду в полёте» (I161) и шлёт вторую, не
///   дождавшись первой, — повтор первой уже не опознаётся;
/// - чек отложен и **поднят соседом** — подъём пишет свой ключ в тот же
///   слот, и честный повтор `defer` получает отказ **не по вине того, кто
///   его послал**;
/// - любая будущая команда, которая тронет этот слот, сделает то же самое.
///
/// Во всех случаях отказ безопасен — корзина не меняется, — но буква
/// правила 3 нарушена. Журнал ключей на чек это закрыл бы; он не заведён
/// осознанно (хранить в нём было бы нечего сверх одной строки при
/// соблюдённом I161), и цена решения записана здесь, а не обнаруживается.

/// **Честный предел кодов отказа: один код — не один производитель.**
/// [cartNotStartedCode] сегодня бросают три разных места кассовой
/// реализации, и одно из них — проигравший гонку за откладывание (сосед
/// отложил чек первым). Терминал по коду не отличит «чека не было вовсе»
/// от «чек только что увели». Список производителей любого кода получают
/// **поиском по коду**, а не по памяти: три круга правки подряд предел
/// оказывался шире, чем описан, ровно потому, что описывался от того
/// случая, который его породил.
///
/// # Отказ — значение, исключение — транспорт
///
/// Команды бросают [WireRefusal] (см. `lib/domain/wire/wire_refusal.dart`).
/// Наружу, на провод, он уезжает **значением** — кадром отказа с кодом и
/// текстом (I144): `till_wire.dart` ловит [WireRefusal] раньше общего
/// `on Object` и не подставляет в кадр текст произвольного исключения.
/// Коды перечислены константами ниже, чтобы терминал отличал причину по
/// коду, а не по подстроке в тексте.
abstract interface class CartService {
  /// Корзина этого рабочего места сейчас и при каждом её изменении.
  ///
  /// Первое значение приходит сразу; пустая корзина — это снимок с
  /// пустым списком строк и `receiptNo == null`, а не отсутствие
  /// значения (иначе экран ждал бы первого чека вечным индикатором).
  Stream<CartView> watch(int terminalId);

  /// Общий пул отложенных чеков этой кассы — всем рабочим местам
  /// одинаково (решение 3 спеки, шаг 8).
  ///
  /// # Довод [by] обязателен — задача 10 ревизии 2026-09-19
  ///
  /// Право `op.deferSale` закрывает эту подписку **с обеих сторон**: пул
  /// отдаёт номера, суммы, число строк и **имя кассира**, отложившего каждый
  /// чек ([DeferredCart.userName]). Писать и читать здесь одна возможность, и
  /// ключ у них один — разбор в докстринге `SaleOps.deferredList`.
  ///
  /// До этой задачи право стояло только у сторожа провода. На самой кассе
  /// подписка звалась без довода вовсе (`deferredCartsProvider` →
  /// `GetIt.I<CartService>().watchDeferred()`), то есть кассир без
  /// `op.deferSale`, сидящий **за кассой**, видел чужой пул целиком —
  /// касса была слабее планшета. Тот же приём, которым задача 28 закрыла
  /// [defer] и [loadDeferred]: требование, объявленное доводом, забыть
  /// нельзя по сборке.
  ///
  /// Отказ — [cartForbiddenCode], и приходит он **подписке**: поток
  /// отказывает вместо того, чтобы отдать первое значение. Молчащая
  /// подписка была бы неотличима от пустого пула.
  Stream<List<DeferredCart>> watchDeferred({required DiscountAuthority by});

  /// Поиск товара по имени или штрихкоду.
  /// Поиск товара по имени или штрихкоду.
  ///
  /// **Предел контракта: поиск не знает про опт.** У него нет ни
  /// рабочего места, ни чека — значит и признака режима, — поэтому цена в
  /// [ProductSearchResult] всегда розничная. В оптовом чеке кассир увидит
  /// в списке поиска одну цену, а в строке чека другую. Довод сюда не
  /// добавлен намеренно: это изменило бы подпись, на которую уже опираются
  /// задачи 8, 10 и 12, ради поля, которое экран может взять из снимка
  /// корзины. Названо, чтобы следующий не принял расхождение за дефект
  /// реализации.
  Future<List<ProductSearchResult>> search(String query);

  /// Начать чек — или продолжить уже начатый этим рабочим местом.
  ///
  /// **Единственная команда, которой разрешено звать себя «с холода».**
  /// `meta.receiptNo == null` здесь значит «я не знаю, что у меня в
  /// работе», и касса отвечает тем, что есть: продолжает начатый чек или
  /// заводит новый. Названный номер, наоборот, сверяется строго, как у
  /// всех прочих команд, — вместе с версией.
  ///
  /// **Довод `wholesale` действует только при заведении нового чека.** На
  /// возобновлении он игнорируется: возобновление не пишет в чек ничего
  /// (иначе повторный вход на экран молча менял бы режим уже начатого
  /// чека — измеренный дефект круга правки 4). Менять режим — [setWholesale].
  ///
  /// Правило заведено кругом правки 3 и именно правилом, а не поблажкой:
  /// вторая вкладка того же терминала и вкладка, переподключившаяся до
  /// первого кадра подписки, зовут `start` первым делом и номера не
  /// знают. Безопасно это **по построению** — `start` не меняет в чеке ни
  /// одной колонки, кроме ключа повтора (кассовая реализация: путь
  /// возобновления не пишет вниз ничего, см. `LocalCartService.start`), —
  /// и потому не распространяется ни на одну другую команду.
  ///
  /// # `wholesale: true` — второй вход в опт, и он закрыт настройкой кассы
  /// (ревизия второго фронта 2026-09-19)
  ///
  /// Новый чек с оптом заводится только на кассе, где `ThisPosEntries
  /// .editPrice` включена; иначе — [cartDeniedPolicyCode], тот же отказ,
  /// что у [setWholesale]. Без этого владелец, выключивший «Правку цены»
  /// при открытом оптовом чеке, получал следующий чек снова оптовым: экран
  /// продажи передаёт сюда свой режим, а режим переживает завершённый чек.
  ///
  /// **На возобновлении не спрашивается**: возобновление [wholesale] не
  /// читает вовсе, и отказ на нём запер бы уже начатый чек.
  ///
  /// **Правом опт здесь НЕ закрыт** — довода [DiscountAuthority] у этой
  /// команды нет ни на одном фронте. На проводе входа нет вовсе
  /// (`sale.start` с оптом отказывает `TillOperations`), на кассе он
  /// остаётся; названо, чтобы следующий не читал «опт закрыт» шире, чем
  /// написано.
  Future<CartView> start({
    required int terminalId,
    required bool wholesale,
    required CartCommandMeta meta,
  });

  Future<CartView> addByBarcode(
    int terminalId,
    String barcode,
    CartCommandMeta meta,
  );

  Future<CartView> addProduct(
    int terminalId,
    int productId,
    Decimal quantity,
    CartCommandMeta meta,
  );

  Future<CartView> setQuantity(
    int terminalId,
    String lineId,
    Decimal quantity,
    CartCommandMeta meta,
  );

  Future<CartView> increment(
    int terminalId,
    String lineId,
    CartCommandMeta meta,
  );

  Future<CartView> decrement(
    int terminalId,
    String lineId,
    CartCommandMeta meta,
  );

  /// Скидка строке процентом.
  ///
  /// **Довод [by] обязателен и назван — задача 12 плана «Полнота продажи».**
  /// До неё предела скидки не было никакого: единственным потолком была
  /// арифметика «скидка не больше стоимости строки», то есть **строка
  /// бесплатно была законной операцией**, а право `op.sellDiscount`
  /// проверялось только сторожем провода — на кассе его не проверял никто,
  /// и защитой служила спрятанная кнопка. Полномочия приходят **доводом**, а
  /// не ищутся внутри реализации: требование, объявленное доводом, забыть
  /// нельзя — команда без него не компилируется, тогда как поиск внутри
  /// обходится новым путём вызова, и новый путь появится (докстринг
  /// [DiscountAuthority]).
  ///
  /// Отказы по порядку от дешёвого к дорогому: [cartForbiddenCode] (нет
  /// права), [cartDeniedPolicyCode] (тумблер кассы), [cartDeniedLimitCode]
  /// (предел роли), [cartApprovalRequiredCode] (нужно подтверждение
  /// старшего), [cartInvalidAmountCode] (значение вне допустимого).
  Future<CartView> setDiscountPercent(
    int terminalId,
    String lineId,
    Decimal percent,
    CartCommandMeta meta, {
    required DiscountAuthority by,
  });

  /// Скидка строке суммой — тот же предел и те же отказы, что у
  /// [setDiscountPercent].
  ///
  /// Предел объявлен процентом, а сумма — деньгами, и сравнение идёт
  /// **умножением** стоимости строки на процент, а не делением суммы на
  /// стоимость: делением деньги ушли бы в период (33 % от 100), и предел
  /// начал бы врать на копейку в обе стороны.
  Future<CartView> setDiscountAmount(
    int terminalId,
    String lineId,
    Decimal amount,
    CartCommandMeta meta, {
    required DiscountAuthority by,
  });

  /// Ставит строке [lineId] цену единицы [price].
  ///
  /// **Строка может исчезнуть из снимка — и это не ошибка.** Если после
  /// правки в чеке нашлась более ранняя строка того же товара с той же
  /// видимой ценой, без ручной скидки и без марки, обе становятся одной:
  /// выживает **ранняя**, количества складываются. Иначе кассир, вернувший
  /// цену обратно к цене соседней строки, навсегда оставался с двумя
  /// одинаковыми рядами в чеке и без способа их свести (задача 8, находка
  /// 2). Экран обязан пережить пропажу выбранной строки — снять выбор, а
  /// не показывать пустоту.
  ///
  /// # Понижающая ветка — это скидка другим входом (задача 12)
  ///
  /// Предел скидки, который меряет только `setDiscount*`, — театр:
  /// `updatePrice(0)` на товар за 500 отдаёт строку бесплатно, не тронув ни
  /// одной колонки скидки. Поэтому [by] обязателен и здесь, а понижение
  /// цены **ниже каталожной** меряется тем же пределом роли.
  ///
  /// Отсчёт идёт от **каталожной** цены, а не от нынешней цены строки. Иначе
  /// предел режется ломтями: два понижения по 10 % от предыдущей цены — это
  /// 19 % от каталожной, и каждое по отдельности проходит.
  ///
  /// Повышение цены пределом скидки не меряется вовсе: это не уступка.
  ///
  /// # Право кассира и настройка кассы — две разные величины (задача 9
  /// ревизии 2026-09-19)
  ///
  /// Их легко перепутать, потому что обе называются `editPrice`, и путаница
  /// стоила дыры: настройку читал **только экран кассы**
  /// (`sale_screen._showEditDialog`, `!policy.editPrice`), а команда — ни на
  /// кассе, ни на проводе. С планшета цену правили вопреки настройке
  /// «Политика продаж», выставленной на кассе, и настройка выглядела
  /// работающей.
  ///
  /// - **`op.editPrice`** — право **кассира**: кому можно. Живёт в [by],
  ///   проверяется первым, отказ [cartForbiddenCode].
  /// - **`ThisPosEntries.editPrice`** — настройка **кассы**: можно ли здесь
  ///   вообще. Не зависит ни от кассира, ни от роли, запрещает всем сразу.
  ///   Проверяется второй, отказ [cartDeniedPolicyCode].
  ///
  /// **Складываются они «и», а не «или»**: править цену может тот, у кого
  /// есть право, **на кассе, где это разрешено**. Порядок выбран не
  /// произвольно, а тем же правилом, что у скидки ([setDiscountPercent]):
  /// сначала «кому», потом «где», потом «сколько», — иначе кассир без права
  /// на кассе с выключенной настройкой узнавал бы про настройку, а про своё
  /// право не узнал бы никогда, и владелец, включивший настройку, получил бы
  /// вторую жалобу на ровном месте.
  ///
  /// **Чего это НЕ доказывает.** Что закрыты все пути изменить деньги
  /// строки. Опт закрыт той же настройкой — ревизией второго фронта
  /// 2026-09-19, и это правка **против** того, что было написано здесь
  /// раньше («[setWholesale] этой настройкой не закрыт»): оптовый
  /// прейскурант и есть «цена ниже розничной», и оставлять его открытым
  /// значило выдавать настройку за запрет, которым она не была. Акции же
  /// считаются при сборке снимка и через команду не проходят вовсе — их эта
  /// настройка по-прежнему не касается.
  Future<CartView> updatePrice(
    int terminalId,
    String lineId,
    Decimal price,
    CartCommandMeta meta, {
    required DiscountAuthority by,
  });

  Future<CartView> setMark(
    int terminalId,
    String lineId,
    String mark,
    CartCommandMeta meta,
  );

  Future<CartView> removeLine(
    int terminalId,
    String lineId,
    CartCommandMeta meta,
  );

  Future<CartView> clear(int terminalId, CartCommandMeta meta);

  /// Отложить чек: он уходит в общий пул кассы и перестаёт принадлежать
  /// рабочему месту. Возвращает **пустую** корзину — у рабочего места
  /// после откладывания чека в работе нет; следующий начинается [start].
  ///
  /// **Довод [by] обязателен — задача 28.** Право `op.deferSale` проверяет
  /// **корзина**, а не сторож провода: экран кассы зовёт этот контракт
  /// напрямую, и до задачи владелец, снявший кассиру «Отложенную продажу»,
  /// запрещал это браузеру и ничего — самой кассе. Тот же приём, что у
  /// скидки: требование доводом забыть нельзя по сборке. Отказ —
  /// [cartForbiddenCode].
  Future<CartView> defer(
    int terminalId,
    CartCommandMeta meta, {
    required DiscountAuthority by,
  });

  /// Поднять отложенный чек [receiptNo] себе.
  ///
