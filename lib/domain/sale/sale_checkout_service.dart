/// Итог подготовки чека к оплате: сумма и строки — или названная причина
/// отказа.
///
/// Пара «значение или причина», а не бросок: отказ здесь — обычный
/// сценарий (маркируемый товар без марки, товара не хватает на складе,
/// сумма выше потолка), и он приходит **значением** (I144), потому что
/// каждый из этих случаев кассир должен увидеть словами.
@immutable
class CheckoutPreparation {
  const CheckoutPreparation.ready({
    required this.receiptNo,
    required this.posId,
    required Decimal this.amount,
    required this.lines,
  }) : refusal = null;

  const CheckoutPreparation.refused(WireRefusal this.refusal)
    : receiptNo = 0,
      posId = 0,
      amount = null,
      lines = const [];

  final int receiptNo;

  final int posId;

  /// Сумма чека к оплате — `Decimal` P18,S3 (I159).
  final Decimal? amount;

  /// Строки в формате завершённого чека — довод `SaleUseCase.perform`,
  /// который их и записывает. Пусты у отказа.
  final List<ReceiptLine> lines;

  final WireRefusal? refusal;
}

/// Подготовка чека к оплате — задача 8 плана «Продажа с браузерного
/// терминала».
///
/// # Зачем контракт, если завершение продажи — задача 11
///
/// Задача 8 переводит экран продажи на `CartService`, и вместе с этим
/// экран теряет право разговаривать с базой (сторож
/// `test/architecture/sale_layering_test.dart`). Завершение продажи в
/// контроллере читало базу семью вызовами: настройки кассы, маркируемость
/// каждого товара, остатки, перезапись строк чека, сумма. Оставить их —
/// значит не сделать задачу 8; переписать всё завершение — значит сделать
/// задачу 11. Здесь — ровно та часть, которую задача 8 обязана унести.
///
/// # Два шага, а не один: корзина остаётся корзиной до успеха оплаты
///
/// **Решение круга правки 1 (C2, C3).** Первая версия считала и **сразу
/// записывала** формат завершённого чека в те же колонки, из которых
/// корзина читает цену и скидку. Это давало три беды разом, и все денежные:
///
/// 1. **Неидемпотентность.** Запись делила итог строки на количество с
///    денежными тремя знаками, а корзина читала результат обратно как
///    ручную скидку — и получала скидку **больше** назначенной. Замер
///    разбора: ручная скидка 10 на трёх штуках по 100 давала 290 → 289.998
///    → 289.998. Ровно та ловушка, которую задача 7 уже решила десятью
///    знаками для самой корзины (докстринг `LocalCartService`); перенос из
///    контроллера принёс три знака, но у контроллера **обратного чтения не
///    было**, а здесь оно появилось.
/// 2. **Подарок акции превращался в ручную скидку.** Запечённая в цену
///    акционная скидка неотличима от назначенной кассиром: строка
///    переставала сливаться, выпадала из расчёта акций и переживала смену
///    количества застывшей суммой — то есть находка 3 задачи 8
///    воспроизводилась **через оплату**.
/// 3. **Деньги в корзине менялись без версии** — нарушение правила, на
///    котором стоит весь протокол команд задачи 7: браузерный терминал об
///    изменении не узнавал бы вовсе.
///
/// Путь достижим и не редок: завершение продажи бросает (фискализация,
/// принтер, база) — и кассир повторяет оплату по **испорченной** корзине.
///
/// Поэтому шагов два:
///
/// - [prepare] **проверяет и считает**, и в строки корзины не пишет
///   ничего. Единственная его запись — снятие платежей прежней попытки, и
///   это не состояние корзины, а мусор несостоявшейся оплаты, который
///   иначе удвоился бы (`SaleUseCase.perform` платежи вставляет).
/// - **записывает** посчитанное `SaleUseCase.perform` — внутри своей
///   транзакции, тем же оборотом, которым чек перестаёт быть корзиной.
///
/// **Чем это лучше второго выхода — «писать, но с подъёмом версии и своим
/// ключом команды».** Подъём версии честно рассказал бы браузеру об
/// изменении, но само изменение осталось бы неверным: кассир, у которого
/// оплата не прошла, вернулся бы в корзину, где акция превратилась в ручную
/// скидку, а строки перестали сливаться. Версия сообщает о порче, а не
/// отменяет её.
///
/// # Задача 9: запись переехала внутрь транзакции продажи
///
/// До задачи 9 второй шаг был **отдельным методом этого контракта**
/// (`finalize`), и стоял он после `SaleUseCase.perform`. Между успехом
/// продажи и записью оставалось окно: смерть кассы в нём оставляла
/// проданному чеку цены корзины — без вложенной акционной скидки и без
/// округлений. Окно было названо честно и оставлено на будущую задачу.
///
/// Задача 9 нашла, что окно было не пределом, а **постоянным
/// состоянием**: `finalize` звал только `SaleNotifier.completeSale`, у
/// которого вызывающих ноль, а путь оплаты
/// (`PaymentService.complete` → [prepare] → `SaleUseCase.perform`) его не
/// трогал вовсе. То есть подарок акции не доезжал до завершённого чека
/// **никогда**, а цена единицы навсегда оставалась масштаба 10.
///
/// Запись перенесена в транзакцию `perform` — туда, где уже переводится
/// состояние чека, пишутся платежи и снимаются остатки. Окна больше нет
/// по построению: либо чек продан и переписан, либо ни то, ни другое.
/// **Не в [prepare]** — тот стоит до «занятия чека» и до денег и
/// повторяется на каждой попытке, и строки, положенные там, портили бы
/// корзину при каждом отказе оплаты.
///
/// # Задача 44: экрану этот контракт больше не нужен
///
/// Здесь жили настройки правки строки (`policy`), и экран продажи просил
/// контракт ради одного этого метода — а браузер, у которого реализации нет
/// и быть не должно (`prepare` снимает платежи и живёт внутри оплаты),
/// прятал из-за него кнопку «Редактировать». Настройки уехали в
/// `SaleEditTermsReader` вместе с пределом скидки; здесь осталось то, что
/// зовёт одна `LocalPaymentService` на кассе.
abstract interface class SaleCheckoutService {
  /// Умолчание «выборочная отправка в ОФД» для этой кассы.
  Future<bool> selectiveOfdDefault();

  /// Проверяет чек и считает, чем он станет после оплаты.
  ///
  /// **В строки корзины не пишет** (см. докстринг контракта). Снимает
  /// платежи прежней попытки — это не корзина, а мусор несостоявшейся
  /// оплаты.
  ///
  /// Коды отказа: [checkoutEmptyCode], [checkoutMarkRequiredCode],
  /// [checkoutInsufficientStockCode], [checkoutBigAmountCode]. В сообщении
  /// отказа с именем товара едет **имя товара** — экран показывает его
  /// человеку.
  ///
  /// Повторный вызов даёт тот же ответ: считать не с чего иначе — корзина
  /// не тронута.
  Future<CheckoutPreparation> prepare({
    required int receiptNo,
    required int posId,
  });
}

/// В чеке нет ни одной строки.
const checkoutEmptyCode = 'receipt_empty';

/// В чеке есть маркируемый товар без кода маркировки. Сообщение отказа —
/// имя товара.
const checkoutMarkRequiredCode = 'mark_required';

/// Товара в чеке больше, чем на остатке, и касса настроена это запрещать
/// (`ThisPosEntries.blockOversell`). Сообщение отказа — имя товара.
const checkoutInsufficientStockCode = 'insufficient_stock';

/// Сумма чека выше потолка, и касса настроена это запрещать
/// (`ThisPosEntries.allowBigAmount`).
const checkoutBigAmountCode = 'big_amount_blocked';
