import 'package:meta/meta.dart';

import 'package:telepos/domain/discount/discount_policy.dart';

export 'package:telepos/domain/discount/discount_policy.dart'
    show DiscountAuthority, DiscountCap;

/// Что кассе разрешено делать с ценами и скидками на экране продажи.
///
/// Две настройки `ThisPosEntries`, которые экран читал сам
/// (`sale_screen._showEditDialog`). Жили в `SaleCheckoutService` рядом с
/// подготовкой чека к оплате и уехали оттуда вместе с ответом на вопрос «что
/// показать в диалоге правки» (задача 44 плана 2026-09-06): подготовка чека —
/// дело кассы внутри оплаты, и браузеру её звать незачем, а настройки правки
/// строки браузеру нужны.
///
/// **Третьего поля `blockPriceDecrease` больше нет.** Его читал ровно один
/// экранный предпросмотр через `KassaPriceDecreasingBlockedUseCase` — службу,
/// которой в браузере нет вовсе. Запрет снижения цены проверяет касса в
/// `LocalCartService._authorizePriceDecrease` и отказывает названным
/// `denied_policy` на обоих фронтах; второй проверки на экране не нужно.
@immutable
class SalePolicy {
  const SalePolicy({required this.editPrice, required this.sellInDiscount});

  /// Правка цены строки разрешена (`ThisPosEntries.editPrice`).
  ///
  /// **Это не право, а настройка кассы.** Право кассира на правку цены
  /// проверяет касса до вызова обработчика (I44, I162).
  ///
  /// **И само это поле — тоже удобство, а не защита (задача 9 ревизии
  /// 2026-09-19).** До неё оно было защитой поневоле: настройку читал один
  /// экран кассы, и с планшета цену правили мимо неё. Теперь её проверяет
  /// команда корзины (`LocalCartService._requirePriceEditingEnabled`, отказ
  /// `denied_policy`) — на обоих фронтах. Здесь поле осталось затем, чтобы
  /// кассир узнал о запрете **до** ввода, а не после «Сохранить».
  final bool editPrice;

  /// Продажа со скидкой разрешена (`ThisPosEntries.sellInDiscount`).
  final bool sellInDiscount;
}

/// Всё, что диалог правки строки должен знать **до** ввода: настройки кассы,
/// предел скидки вошедшего и символ валюты, которой считаются деньги чека.
///
/// Одним ответом, а не тремя: по проводу это один круг вместо трёх ради
/// одного нажатия «Редактировать».
@immutable
class SaleEditTerms {
  const SaleEditTerms({
    required this.policy,
    required this.cap,
    required this.currencySymbol,
  });

  final SalePolicy policy;

  /// Предел скидки роли — **тем же читателем, каким отказывает касса**
  /// (`DiscountPolicy.capFor`). Второго источника предела нет ни на одном
  /// фронте.
  final DiscountCap cap;

  /// Символ валюты кассы. Касса владеет деньгами чека, и валюта — её
  /// настройка; у браузера своей нет.
  final String currencySymbol;
}

/// Условия правки строки чека — задача 44 плана «Продажа с браузерного
/// терминала».
///
/// # Зачем отдельный контракт
///
/// Экран продажи браузера не мог дать скидку вовсе: кнопка «Редактировать»
/// пряталась проверкой `GetIt.I.isRegistered<SaleCheckoutService>()`, а
/// браузерной реализации у `SaleCheckoutService` не было и быть не должно —
/// `prepare` снимает платежи прежней попытки и живёт внутри оплаты на кассе.
/// От того контракта экрану нужны были только настройки; предел же он брал
/// третьим способом — прямо у `DiscountPolicy`, которого в браузере тоже нет,
/// и на этот случай отдавал «сто процентов, предел не прочитан». Всё это
/// сведено сюда, и у контракта две реализации: кассовая
/// (`LocalSaleEditTerms`) и проводная (`WtSaleEditTerms`, операция
/// `sale.editTerms`).
///
/// # Кто строит [DiscountAuthority]
///
/// Касса-десктоп — из `AppState` вошедшего. По проводу довод **не
/// отправляется**: касса строит полномочия из сеанса кадра
/// (`TillOperations._authorityOf`), иначе вкладка называла бы свою роль сама
/// и получала бы чужой предел. Тем же правилом живут команды скидки
/// (`WtCartService.setDiscountPercent`).
///
/// # Это удобство, а не защита (I44)
///
/// Предел, показанный в диалоге, ничего не разрешает. Скидку и правку цены
/// решает касса на команде корзины: право `op.sellDiscount`, тумблер
/// «продажа со скидкой», предел роли.
abstract interface class SaleEditTermsReader {
  Future<SaleEditTerms> read({required DiscountAuthority by});
}
