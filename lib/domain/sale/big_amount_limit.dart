import 'package:decimal/decimal.dart';

/// Потолок суммы чека по умолчанию.
///
/// # Откуда это число
///
/// Ровно то, что было зашито в `LocalSaleCheckoutService` до схемы v57:
/// миллион. Оно остаётся умолчанием намеренно — касса, работавшая вчера,
/// обязана работать сегодня так же, а не начать отказывать на других
/// суммах после обновления.
///
/// Но умолчанием, а не правилом: миллион тенге — это около двух тысяч
/// долларов, и на американской кассе тот же миллион был в пятьсот раз выше,
/// то есть защиты не было вовсе. Теперь число — настройка кассы
/// (`this_pos_entries.big_amount_limit`), и владелец ставит его сам.
final Decimal kDefaultBigAmountLimit = Decimal.parse('1000000');

/// Потолок этой кассы: настройка, если задана, иначе умолчание.
///
/// Пустая строка и неразбираемое значение читаются как «не задано»: молча
/// пропустить любую сумму из-за опечатки в настройке значило бы снять
/// защиту, ничего об этом не сказав.
Decimal bigAmountLimitOf(String? stored) {
  if (stored == null || stored.trim().isEmpty) return kDefaultBigAmountLimit;
  return Decimal.tryParse(stored.trim()) ?? kDefaultBigAmountLimit;
}
