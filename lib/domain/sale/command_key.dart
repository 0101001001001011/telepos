import 'dart:math';

/// Метка сеанса экрана — половина ключа идемпотентности команды.
///
/// # Почему это отдельный файл, а не две строки в двух контроллерах
///
/// Потому что двумя строками в двух контроллерах оно и было, и это стоило
/// **экрана целиком**.
///
/// `SaleController` и `RefundNotifier` держали побайтово одинаковый код:
///
/// ```dart
/// final rnd = Random();
/// return '${DateTime.now().microsecondsSinceEpoch.toRadixString(36)}'
///     '-${rnd.nextInt(1 << 32).toRadixString(36)}';
/// ```
///
/// В Dart VM `1 << 32` — это 4294967296. **В браузере это ноль**: `<<` в
/// JavaScript 32-битный, и сдвиг на 32 даёт исходное число, сдвинутое на
/// ноль… то есть единицу, сдвинутую в никуда. `Random.nextInt(0)` бросает
/// `RangeError: max must be in range 0 < max ≤ 2^32, was 0`, провайдер
/// уходит в состояние ошибки целиком, и экран **не строится вовсе**: серый
/// прямоугольник во всю страницу.
///
/// Измерено живым прогоном 2026-09-07 на настоящем браузере: экран возврата
/// не открывался никак. Ни одна из 894 проб этого не видела и не могла —
/// все они идут в Dart VM, где `1 << 32` совершенно нормальное число.
/// Копия в продаже нашлась тем же способом днём раньше, и была починена
/// отдельно; после этого копий стало две, а починка — одна. Здесь их обе
/// заменяет один вызов, чтобы третьей не появилось.
///
/// # Почему `0xFFFFFFFF`, а не «исправленный» сдвиг
///
/// Литерал одинаков на всех платформах, а любой `<<` придётся каждый раз
/// сверять с разрядностью цели. `Random.nextInt` принимает `max` в пределах
/// `0 < max ≤ 2^32`; `0xFFFFFFFF` — 2^32 − 1, то есть строго внутри, без
/// хождения по краю допустимого. Потеря одного значения из четырёх с
/// лишним миллиардов на уникальность метки не влияет: вторая её половина —
/// микросекунды.
///
/// # Что эта метка делает
///
/// Ключ повтора команды — `<метка сеанса>:<номер команды>`. Метка обязана
/// быть новой у каждого экрана (иначе два терминала, начавшие работу в одну
/// микросекунду, столкнулись бы ключами) и неизменной внутри одного экрана
/// (иначе повтор команды не опознался бы как повтор — I160).
String newCommandSessionTag([Random? random]) {
  final rnd = random ?? Random();
  return '${DateTime.now().microsecondsSinceEpoch.toRadixString(36)}'
      '-${rnd.nextInt(commandTagRange).toRadixString(36)}';
}

/// Верхняя граница случайной половины метки — 2^32 − 1.
///
/// Названа константой, а не вписана в вызов: сторож
/// `test/architecture/web_safe_shifts_test.dart` требует, чтобы в браузерной
/// сборке не было сдвигов с неочевидной разрядностью, и число, посчитанное
/// сдвигом, здесь появилось бы первым.
const int commandTagRange = 0xFFFFFFFF;
