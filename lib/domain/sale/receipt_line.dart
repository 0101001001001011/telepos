import 'package:decimal/decimal.dart';
import 'package:meta/meta.dart';
import 'package:telepos/domain/sale/cart_view.dart';

/// Строка завершённого чека: что записать вместо цен корзины.
///
/// Считается `SaleCheckoutService.prepare` и записывается **внутри
/// транзакции** `SaleUseCase.perform` — тем же оборотом, которым чек
/// перестаёт быть корзиной (задача 9). Двумя шагами, а не одним, потому
/// что до успеха оплаты корзина обязана остаться корзиной (см. докстринг
/// `SaleCheckoutService`).
///
/// **Живёт в своём файле, а не рядом с контрактом подготовки** (задача 9):
/// её называют оба контракта — `SaleCheckoutService` отдаёт, `SaleUseCase`
/// принимает, — и держать её у одного из них значило бы заставить второй
/// тянуть чужой контракт целиком ради одного типа.
@immutable
class ReceiptLine {
  const ReceiptLine({
    required this.lineId,
    required this.price,
    required this.priceBefore,
    this.discounts = const <CartDiscount>[],
  });

  /// Идентификатор строки корзины (`CartLine.id`).
  final String lineId;

  /// Цена единицы после округлений **и** всех скидок строки — ручной и
  /// акционной. Деньги `Decimal` P18,S3 (I159).
  final Decimal price;

  /// Цена единицы после округлений, но **до** скидок.
  final Decimal priceBefore;

  /// Скидки строки по происхождению — задача 13.
  ///
  /// Едут отдельно от цен нарочно: цены отвечают на вопрос «почём
  /// продано», а этот список — на вопрос «почему дешевле», и второй из
  /// разности цен не выводится. Именно поэтому `SaleDiscounts` — таблица,
  /// а не вычисляемое поле: `priceBefore − price` одинаково выглядит и у
  /// подарка акции, и у уступки кассира.
  ///
  /// Умолчание — пустой список: вызывающий, который сеет строки чека сам и
  /// зовёт `perform` со своими ценами (так делают журналы `test/e2e/` и
  /// стенды `test/integration/`), про происхождение ничего не знает, и
  /// требовать от него выдумки было бы хуже, чем принять молчание.
  final List<CartDiscount> discounts;
}
