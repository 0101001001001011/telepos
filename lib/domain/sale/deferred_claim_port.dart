/// Занятие отложенного чека соседней кассы.
///
/// # Зачем отдельный порт
///
/// Корзина не должна знать ни про CouchDB, ни про обмен вообще: её дело —
/// строки и деньги. А занять чек можно только там, где его видят обе кассы,
/// то есть на общем сервере. Порт и есть эта граница.
///
/// # Почему занятие вообще нужно
///
/// Решение заказчика 2026-09-19: покупатель отложил корзину на первой кассе,
/// вернулся — там очередь, пошёл ко второй, и она обязана корзину поднять.
/// Но как только корзина видна двум кассам, поднять её могут **обе** — и она
/// продастся дважды. Занятие делает подъём исключительным: кто успел записать
/// «занято», тот и поднимает; опоздавший узнаёт номер кассы-победителя.
///
/// Разбор способа — в `CouchDbDocumentMapper.claimedByPosId`: это «сравни и
/// запиши» по ревизии документа, проверка идёт на сервере и атомарна.
abstract interface class DeferredClaimPort {
  /// Занять чек `receiptNo` кассы `posId` в пользу кассы `byPosId`.
  ///
  /// * `null` — **занял я**, подъём разрешён;
  /// * число > 0 — чек уже занят этой кассой, подъём запрещён;
  /// * `0` — занять не удалось и назвать занявшего нечем: связи нет,
  ///   документа нет, сервер ответил невнятно. Подъём тоже запрещён.
  ///
  /// Ноль отдельным значением, а не `null`: «занято неизвестно кем» и
  /// «свободно» — противоположные ответы, и путать их значит продать
  /// корзину дважды.
  Future<int?> claim({
    required int receiptNo,
    required int posId,
    required int byPosId,
  });

  /// Отозвать свой отложенный чек: он больше не предлагается никому.
  ///
  /// # Зачем это нужно и что ломается без этого
  ///
  /// Решение заказчика 2026-09-19: **при закрытии смены отложенные чеки
  /// очищаются**. Покупатель мог не вернуться, и знать этого касса не может;
  /// держать корзину вечно — значит копить мусор, который однажды поднимут.
  ///
  /// Но стереть чек только у себя мало: документ на общем сервере остался бы
  /// отложенным, и соседняя касса продолжала бы показывать корзину, которой
  /// уже нет. Кассир нажал бы «поднять» и получил пустоту вместо товара.
  ///
  /// # Права кассира здесь нет намеренно
  ///
  /// Удалять отложенные чеки кассиру не дают: он мог бы снести чужую
  /// корзину, а владелец узнал бы об этом, только когда покупатель вернётся.
  /// Чистит их закрытие смены — действие, у которого уже есть свой замок.
  ///
  /// Отзыв — **лучшее усилие**: нет связи, нет обмена — закрытие смены всё
  /// равно состоится. Остаться с незакрытой сменой хуже, чем с лишней
  /// строкой в чужом пуле, которая пропадёт при первом же подъёме.
  Future<void> withdraw({required int receiptNo, required int posId});
}
