/// «Партия, которая уйдёт первой, просрочена?» — один вопрос про один товар.
///
/// Пункт 11 ревизии 2026-09-19, решение заказчика 2026-09-18: «в браузере
/// должно работать то же, что в приложении».
///
/// # Что было
///
/// `SaleNotifier._checkExpiryWarning` спрашивал `BatchTrackingUseCase` и
/// `WmsConfigUseCase` **прямо у контейнера**, а браузерная точка входа не
/// привязывает ни того, ни другого: оба тянут базу кассы. Обе развилки были
/// вписаны как ОТКРЫТО в двух сторожах. Кассир за планшетом пробивал
/// просроченный товар и не узнавал об этом ничем.
///
/// # Почему договор, а не «привязать юзкейсы к проводу»
///
/// Потому что на провод поехал бы не вопрос продажи, а **склад**:
/// `BatchTrackingUseCase` — девять методов про партии, `WmsConfigUseCase` —
/// вся настройка WMS, включая методы себестоимости. Экрану продажи из всего
/// этого нужен ровно один ответ: «этот товар уйдёт просроченной партией».
/// Договор в один метод и есть тот ответ; за ним на кассе стоят оба юзкейса,
/// а в браузере — одна операция провода.
///
/// # Почему отдельный вопрос, а не поле в `CartView`
///
/// Ревизия предлагала закрывать это «проверкой партии на кассе при
/// добавлении строки», и проверка действительно ушла на кассу — но
/// **ответом отдельной операции**, а не полем снимка корзины. Довод
/// измеримый: `CartView` — это состояние чека, и подписка `sale.cart`
/// перечитывает его из базы при каждом изменении таблицы
/// (`SaleNotifier._listenToCart`). Предупреждение состоянием чека не
/// является: оно относится к одному действию кассира, а не к чеку. Поле в
/// снимке потухло бы на первом же обновлении подписки — то есть через
/// миллисекунды после появления, — и кассир увидел бы мигание вместо
/// предупреждения. Ровно поэтому `SaleState.warning` живёт мимо
/// `SaleState.fromCart` (та переносит `previous.warning` руками).
///
/// # Чего этот договор НЕ обещает
///
/// - **Что именно эта партия уйдёт при оплате.** Ответ считается
///   стратегией отбора (FEFO/FIFO/LIFO) на момент вопроса; списание идёт
///   позже и своим путём. Это предупреждение кассиру, а не резерв партии.
/// - **Что просроченного товара нет, если ответ `false`.** `false` значит
///   «партии не найдено, срок не задан или не истёк» — три разных случая с
///   одним ответом, и различать их экрану нечем. Отсутствие учёта партий у
///   товара выглядит здесь так же, как годный товар, и это осознанно:
///   предупреждать «партий нет» кассиру не о чем.
/// - **Что товар нельзя продать.** Запретом это не является ни на одном
///   конце — решение принимает кассир.
abstract interface class ExpiryWarningReader {
  /// `true` — партия, которую отбор отдал бы первой, просрочена на момент
  /// вопроса.
  ///
  /// Отказ (нет склада, нет связи) поднимается исключением, а не читается
  /// как `false`: разницу между «не просрочено» и «спросить не удалось»
  /// решает вызывающий, и на экране продажи она сегодня одинакова —
  /// предупреждения нет. Но решает это он, а не договор.
  Future<bool> isPickedBatchExpired(int productId);
}
