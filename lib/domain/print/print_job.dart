import 'dart:typed_data';

import 'package:meta/meta.dart';

/// Где задание находится в своей жизни.
///
/// **Хранится и передаётся по имени, никогда по индексу** (глобальное правило
/// проекта; хранилище — задача 2 плана 2в). Индекс сломался бы от вставки
/// нового состояния в середину этого перечисления, и сломался бы молча:
/// задания, лежащие в базе, поменяли бы смысл.
///
/// Разница между [failed] и [expired] — не оттенок формулировки, а разные
/// действия оператора. Задание в [failed] будет повторено само; задание в
/// [expired] уже не будет, и его надо либо продлить руками
/// ([PrintJob.renewedUntil]), либо отменить. Свести их в одно «не
/// напечаталось» значило бы вернуть ровно тот класс правдоподобно-неверного
/// значения, ради которого этот контракт пишется.
enum PrintJobState {
  /// Принято и ждёт своей очереди. Начальное состояние любого задания.
  queued,

  /// Байты сейчас уходят в принтер. Пока задание в этом состоянии, никакое
  /// другое задание не может писать в тот же принтер — см. «неделимость» в
  /// доке [PrintJob].
  printing,

  /// Принтер подтвердил печать. Терминальное: повторить подтверждённое
  /// задание — значит выдать покупателю второй чек.
  printed,

  /// Попытка не удалась, срок ещё не вышел — задание будет повторено.
  /// Причина в [PrintJob.failureReason].
  failed,

  /// Срок вышел, а задание так и не напечаталось. Терминальное **до решения
  /// оператора**: «висит вечно» и «тихо выброшено» одинаково неверны, поэтому
  /// задание остаётся видимым с причиной, но само себя больше не повторяет.
  expired,

  /// Оператор отменил задание. Терминальное **окончательно**: в отличие от
  /// [expired], отсюда нет пути назад даже вручную — см.
  /// [PrintJob.renewedUntil].
  cancelled,
}

/// Одно задание печати: чей чек, какие именно байты, до какого момента он ещё
/// имеет смысл.
///
/// Реализует четыре свойства И29 (docs/system-architecture.md, раздел 8,
/// «Общий принтер — это очередь, а не общий доступ»), и каждое из них
/// устроено так, чтобы противоположное нельзя было выразить:
///
/// **Владелец — терминал и касса.** Именно так сказано в И29: «у задания есть
/// владелец — терминал и касса, от которых оно пришло». Поэтому владельцев
/// два: [terminalId] и [posId], оба обязательны и оба обязаны быть
/// положительными. Ноль запрещён намеренно: это обычная заглушка для
/// «неизвестно», а задание без владельца некому показать в очереди и некому
/// повторить. Одного [terminalId] не хватает: терминал — это рабочее место, а
/// касса — то, от чьего имени выбит чек и в чью смену он попадёт.
///
/// **Неделимость.** Задание несёт **весь** байтовый поток чека сразу, и у
/// него нет ни одного способа дописать в себя ещё байт: [payloadBytes] —
/// неизменяемое представление собственной копии. Поэтому «половина чека» не
/// выражается на уровне контракта вовсе, и очереди (задача 3) остаётся
/// обеспечить только то, что двух пишущих одновременно не бывает.
///
/// **Идемпотентность.** [id] задаёт **вызывающий**, а не очередь, и это всё
/// содержание идемпотентности. Идентификатор, порождённый внутри
/// (`DateTime.now()` — так было устроено удалённое `PrinterScheduler.PrintJob`),
/// даёт при повторе *новый* идентификатор, и принтерная служба не может
/// узнать в повторе уже подтверждённое задание. Отсюда же равенство: два
/// задания с одним [id] — это **одно** задание, независимо от байтов, срока и
/// числа попыток. Цена этого решения названа прямо: вызывающий, повторно
/// использовавший идентификатор для другого чека, второго чека не получит.
/// Идентификатор поэтому строится от того, что чек и есть — от продажи, — а
/// не от момента отправки.
///
/// **Срок.** [expiresAt] обязателен и обязан быть позже [createdAt].
/// Момент, а не длительность: длительность пришлось бы складывать с чем-то в
/// каждом читателе, и первый же читатель, сложивший её не с тем, получил бы
/// задание, живущее вечно. Срок наступает **по часам**, и это правило
/// применяется в обоих местах, где задание с ним сталкивается: [expireAt] не
/// даёт объявить истёкшим живое задание, [renewedUntil] не даёт вернуть в
/// очередь задание с уже прошедшим сроком.
///
/// Задание неизменяемо. Переходы возвращают новое задание
/// ([beginAttempt], [confirmPrinted], [failWith], [expireAt], [cancelled],
/// [renewedUntil]), а переход из терминального состояния бросает
/// [StateError] — молча остаться в прежнем состоянии значило бы потерять
/// ошибку вызывающего.
@immutable
class PrintJob {
  /// Строит задание. Ни одно поле не подставляется «по умолчанию из
  /// окружения»: ни идентификатор, ни момент создания, ни срок. Домен не
  /// знает, который час, — часы принадлежат вызывающему, и именно поэтому
  /// задание проверяемо.
  ///
  /// Бросает [ArgumentError], если [id] пуст или состоит из пробелов; если
  /// [terminalId] или [posId] не положителен; если [payloadBytes] пуст; если
  /// [attempts] отрицателен; если [expiresAt] не позже [createdAt].
  PrintJob({
    required this.id,
    required this.terminalId,
    required this.posId,
    required Uint8List payloadBytes,
    required this.createdAt,
    required this.expiresAt,
    this.attempts = 0,
    this.state = PrintJobState.queued,
    this.failureReason,
    // Проверка и копирование байтов сделаны здесь, в списке инициализации, а
    // не в теле конструктора, и это не стиль, а защита от конкретной ловушки
    // Dart. В *теле* конструктора имя `payloadBytes` разрешается в
    // **параметр**, а не в поле: параметры видны в теле и затеняют одноимённые
    // поля. Для `this.`-параметров это безобидно (параметр и поле — одно и то
    // же значение), но здесь поле является *преобразованной копией*
    // параметра, и проверка `payloadBytes.isEmpty`, написанная в теле, читала
    // бы не то, что лежит в задании. Сегодня пусты они одновременно, так что
    // дефекта нет, — но форма ровно та же, какой этот контракт был пойман
    // мутацией по `id` (отчёт задачи 1). В списке инициализации поля вообще
    // не в области видимости, поэтому двусмысленности не существует.
  }) : payloadBytes = _checkedPayloadBytes(payloadBytes) {
    if (id.trim().isEmpty) {
      throw ArgumentError.value(
        id,
        'id',
        'идентификатор задания задаёт вызывающий и он не может быть пустым — '
            'это ключ идемпотентности',
      );
    }
    if (terminalId <= 0) {
      throw ArgumentError.value(
        terminalId,
        'terminalId',
        'у задания печати есть владелец — терминал, от которого оно пришло '
            '(И29)',
      );
    }
    if (posId <= 0) {
      throw ArgumentError.value(
        posId,
        'posId',
        'у задания печати есть владелец — касса, от которой оно пришло (И29)',
      );
    }
    if (attempts < 0) {
      throw ArgumentError.value(
        attempts,
        'attempts',
        'не может быть отрицательным',
      );
    }
    if (!expiresAt.isAfter(createdAt)) {
      throw ArgumentError.value(
        expiresAt.toIso8601String(),
        'expiresAt',
        'срок задания должен быть позже его создания '
            '(createdAt=${createdAt.toIso8601String()})',
      );
    }
  }

  static Uint8List _checkedPayloadBytes(Uint8List bytes) {
    if (bytes.isEmpty) {
      throw ArgumentError.value(
        bytes.length,
        'payloadBytes',
        'пустой чек заданием не является',
      );
    }
    return Uint8List.fromList(bytes).asUnmodifiableView();
  }

  /// Ключ идемпотентности, заданный **вызывающим**. См. доку класса.
  final String id;

  /// Рабочее место, с которого пришло задание. Положительный `Terminal.id`.
  final int terminalId;

  /// Касса, от чьего имени выбит чек. Тот же `posId`, что несёт
  /// `SaleReceiptData.posId`
  /// (`lib/domain/services/receipt_print_service.dart:72`) — задание и чек
  /// говорят об одной кассе одним и тем же числом.
  final int posId;

  /// Готовый байтовый поток чека целиком — уже собранный, уже фискализованный
  /// (docs/system-architecture.md, раздел 8: «принтер получает уже полностью
  /// сформированные данные»).
  ///
  /// Неизменяемое представление собственной копии: список, переданный в
  /// конструктор, может меняться дальше сколько угодно, задание это не
  /// затронет, а попытка записи в само это поле бросит [UnsupportedError].
  /// Задание, чьи байты можно поменять после сдачи в очередь, неделимым не
  /// является.
  final Uint8List payloadBytes;

  /// Когда задание создано вызывающим, а не когда оно попало в очередь.
  final DateTime createdAt;

  /// Момент, после которого печатать этот чек уже поздно.
  final DateTime expiresAt;

  /// Сколько раз задание пытались напечатать. Растёт только в [beginAttempt];
  /// ручное продление ([renewedUntil]) обнуляет — оператор начинает заново.
  final int attempts;

  final PrintJobState state;

  /// Почему задание находится в **текущем** состоянии, если оно попало туда
  /// из-за неудачи, — текст, годный к показу как есть.
  ///
  /// Это не «последняя неудача за всю жизнь задания». Поле непусто ровно
  /// тогда, когда объясняет то, что оператор видит сейчас:
  ///
  /// | Состояние | Причина |
  /// | --- | --- |
  /// | [PrintJobState.failed] | всегда непуста — её ставит [failWith] |
  /// | [PrintJobState.expired] | сохраняется: почему не напечаталось до срока |
  /// | [PrintJobState.cancelled] | сохраняется: на что смотрел отменявший |
  /// | [PrintJobState.queued] | всегда `null` |
  /// | [PrintJobState.printing] | всегда `null` — идёт новая попытка |
  /// | [PrintJobState.printed] | всегда `null` — печать удалась |
  ///
  /// Иначе задание, упавшее на «Нет бумаги», повторённое и **успешно
  /// напечатанное**, показывалось бы оператору с надписью «Нет бумаги» рядом
  /// с уже выданным чеком.
  final String? failureReason;

  /// Из этого состояния задание само дальше не пойдёт.
  ///
  /// [PrintJobState.failed] терминальным **не** является — оно означает
  /// «повторим», и именно этим отличается от [PrintJobState.expired].
  bool get isTerminal =>
      state == PrintJobState.printed ||
      state == PrintJobState.expired ||
      state == PrintJobState.cancelled;

  /// Вышел ли срок задания к моменту [now].
  ///
  /// Момент, равный [expiresAt], считается истёкшим: срок — это граница, до
  /// которой печать имеет смысл, а не включительно.
  bool hasExpiredAt(DateTime now) => !now.isBefore(expiresAt);

  /// Задание уходит в принтер: [PrintJobState.printing], [attempts] + 1,
  /// [failureReason] очищается — идёт новая попытка, и прошлая причина
  /// текущего состояния больше не объясняет.
  ///
  /// Бросает [StateError] из терминального состояния — в частности из
  /// [PrintJobState.printed]: повтор подтверждённого задания и есть второй
  /// чек, ради недопущения которого существует [id].
  PrintJob beginAttempt() {
    _refuseIfTerminal('начать попытку печати');
    return _copyWith(
      state: PrintJobState.printing,
      attempts: attempts + 1,
      failureReason: null,
    );
  }

  /// Принтер подтвердил печать. [failureReason] очищается: у напечатанного
  /// чека причины неудачи нет.
  PrintJob confirmPrinted() {
    _refuseIfTerminal('подтвердить печать');
    return _copyWith(state: PrintJobState.printed, failureReason: null);
  }

  /// Попытка не удалась; срок ещё не вышел, задание будет повторено.
  ///
  /// Бросает [ArgumentError] на пустой [reason]: «не удалось» без причины —
  /// не ответ оператору.
  PrintJob failWith(String reason) {
    if (reason.trim().isEmpty) {
      throw ArgumentError.value(
        reason,
        'reason',
        'причина неудачи видна оператору и не может быть пустой',
      );
    }
    _refuseIfTerminal('отметить неудачу');
    return _copyWith(state: PrintJobState.failed, failureReason: reason);
  }

  /// Срок вышел: задание становится видимой проблемой и само себя больше не
  /// повторяет. [failureReason] сохраняется — оператору, увидевшему истёкшее
  /// задание, нужна причина, по которой оно не напечаталось, а не только факт
  /// истечения.
  ///
  /// Бросает [StateError], если к моменту [now] срок ещё **не** вышел. Срок
  /// наступает по часам, а не по решению вызывающего: очередь, объявляющая
  /// задание истёкшим досрочно, выбрасывала бы чеки, которые ещё можно
  /// напечатать.
  PrintJob expireAt(DateTime now) {
    if (!hasExpiredAt(now)) {
      throw StateError(
        'срок задания $id ещё не вышел: '
        'expiresAt=${expiresAt.toIso8601String()}, '
        'now=${now.toIso8601String()}',
      );
    }
    _refuseIfTerminal('отметить истёкшим');
    return _copyWith(
      state: PrintJobState.expired,
      failureReason: failureReason,
    );
  }

  /// Оператор отменил задание. [failureReason] сохраняется: он отменял, глядя
  /// на конкретную причину, и в журнале должно остаться, на какую.
  PrintJob cancelled() {
    _refuseIfTerminal('отменить');
    return _copyWith(
      state: PrintJobState.cancelled,
      failureReason: failureReason,
    );
  }

  /// Ручной повтор из интерфейса (задача 7): тот же чек, тот же ключ
  /// идемпотентности, новый срок, счётчик попыток с нуля, [failureReason]
  /// очищается — задание снова просто стоит в очереди.
  ///
  /// Ключ сохраняется намеренно. Если печать на самом деле прошла, а
  /// подтверждение потерялось, очередь узнаёт в повторе уже подтверждённое
  /// задание по [id] и второго чека не печатает — новый идентификатор здесь
  /// означал бы второй чек.
  ///
  /// **Из [PrintJobState.cancelled] повтор невозможен, и это не симметрия
  /// ради симметрии.** Отмена — решение оператора о том, что такого документа
  /// быть не должно; напечатать задание после отмены значит выдать
  /// покупателю чек, который кассир отменил, и по фискальной части это
  /// документ, которого не должно существовать. [PrintJobState.expired] —
  /// состояние обстоятельств (не успели), и его продлевают; отмена —
  /// состояние решения, и её не переигрывают молча. Кому нужен такой же чек
  /// после отмены, тот заводит **новое** задание с новым идентификатором, то
  /// есть принимает решение заново и явно.
  ///
  /// **Из [PrintJobState.printing] повтор тоже невозможен:** пока байты
  /// уходят в принтер, второй экземпляр того же задания в очереди — ровно то
  /// перемешивание, которое запрещает неделимость. Задание, застрявшее в
  /// [PrintJobState.printing] после перезапуска процесса, сначала объявляется
  /// неудачным ([failWith], например «прервано перезапуском») и только потом
  /// продлевается — так в журнале остаётся, что именно произошло.
  ///
  /// Бросает [StateError], если задание в [PrintJobState.printed],
  /// [PrintJobState.cancelled] или [PrintJobState.printing].
  ///
  /// Бросает [ArgumentError], если [newExpiresAt] не позже [now]. **Срок
  /// проверяется по часам, а не по [createdAt]:** у повторяемого задания
  /// момент создания давно в прошлом, поэтому сравнение с ним пропустило бы
  /// уже прошедший срок, и задание вернулось бы в очередь мёртвым — снова
  /// «висит», ради устранения чего срок и заведён. Это единственное место,
  /// где задание входит в очередь заново, то есть единственное, где правило
  /// «срок наступает по часам» может быть обойдено.
  PrintJob renewedUntil(DateTime newExpiresAt, {required DateTime now}) {
    const renewableStates = <PrintJobState>{
      PrintJobState.queued,
      PrintJobState.failed,
      PrintJobState.expired,
    };
    if (!renewableStates.contains(state)) {
      throw StateError(
        'задание $id в состоянии ${state.name} не повторяется: повторить '
        'можно только стоящее в очереди, неудачное или истёкшее',
      );
    }
    if (!newExpiresAt.isAfter(now)) {
      throw ArgumentError.value(
        newExpiresAt.toIso8601String(),
        'newExpiresAt',
        'новый срок задания $id уже прошёл (now=${now.toIso8601String()}) — '
            'такое задание вернулось бы в очередь мёртвым',
      );
    }
    return PrintJob(
      id: id,
      terminalId: terminalId,
      posId: posId,
      payloadBytes: payloadBytes,
      createdAt: createdAt,
      expiresAt: newExpiresAt,
      attempts: 0,
      state: PrintJobState.queued,
      failureReason: null,
    );
  }

  void _refuseIfTerminal(String action) {
    if (isTerminal) {
      throw StateError(
        'нельзя $action: задание $id уже в состоянии ${state.name}',
      );
    }
  }

  /// [failureReason] здесь **обязателен и не сливается** через `??` с текущим
  /// значением. Слияние означало бы, что причину невозможно снять, и
  /// напечатанный чек навсегда унёс бы с собой «Нет бумаги»: каждый переход
  /// обязан сказать, объясняет ли причина новое состояние.
  PrintJob _copyWith({
    required PrintJobState state,
    required String? failureReason,
    int? attempts,
  }) => PrintJob(
    id: id,
    terminalId: terminalId,
    posId: posId,
    payloadBytes: payloadBytes,
    createdAt: createdAt,
    expiresAt: expiresAt,
    attempts: attempts ?? this.attempts,
    state: state,
    failureReason: failureReason,
  );

  /// Равенство **по идентификатору и только по нему**.
  ///
  /// Это не сокращение, а сам смысл идемпотентности: повтор той же продажи
  /// может прийти с пересобранными байтами, другим сроком и другим числом
  /// попыток и обязан остаться тем же заданием. Сравнение по всем полям
  /// сделало бы повтор новым заданием — то есть вторым чеком.
  @override
  bool operator ==(Object other) => other is PrintJob && other.id == id;

  @override
  int get hashCode => id.hashCode;

  @override
  String toString() =>
      'PrintJob($id, терминал $terminalId, касса $posId, ${state.name}, '
      'попыток $attempts, до ${expiresAt.toIso8601String()})';
}
