import 'package:meta/meta.dart';

/// Какой это документ.
///
/// Хранится и сравнивается **по имени, никогда по индексу**: имя вида уезжает
/// в `PrintJob.id`, то есть в ключ идемпотентности, который переживает
/// перезапуск процесса и лежит в базе. Вставка нового вида в середину этого
/// перечисления поменяла бы смысл уже записанных идентификаторов — молча.
enum PrintDocumentKind {
  /// Чек продажи. Номер — `SaleReceiptData.receiptNo`.
  sale,

  /// Чек возврата. Номер — `RefundReceiptData.refundId`.
  refund,

  /// X-отчёт: снимок смены на момент. Номера у него нет — см.
  /// [PrintDocumentId.number].
  xReport,

  /// Z-отчёт: закрытие смены, один на смену.
  zReport,

  /// Пречек гостю в ресторане. Номера нет.
  preCheck,

  /// Квитанция приёма в сервис. Номер — номер заказа.
  serviceIntake,

  /// Квитанция выдачи из сервиса. Номер — номер того же заказа.
  serviceCompletion,

  /// Пробная печать с экрана настройки чека (И31: «проверка: печать пробного
  /// чека … с видимым результатом»). Не документ, а **событие**, и номера у
  /// него нет.
  sample,

  /// Квитанция кассовой операции — внесения, изъятия, расхода, инкассации.
  /// Номер — `CashOperations.id`, тот самый автоинкремент, под которым
  /// движение денег записано в базе.
  ///
  /// **Отдельный вид, а не «чек с другим текстом», и это не формальность.**
  /// Номер квитанции берётся из своей нумерации, которая идёт вровень с
  /// нумерацией чеков продажи: операция №42 и чек №42 в одной смене одной
  /// кассы — обычное дело, а не совпадение. Слей их в один вид — и один из
  /// двух документов вернул бы `duplicate` и не выдал бы бумаги вовсе.
  cashOperation,

  /// Слип подарочного сертификата — **нефискальный документ**, решение
  /// заказчика 2026-09-16. Номер — номер самой бумажки.
  ///
  /// **Свой вид, а не чек с другим текстом**, и довод тот же, что у
  /// [cashOperation]: номер сертификата живёт в своей нумерации и совпадает
  /// с номером чека продажи запросто (бумажка `C-1` и чек №1). Слей их в
  /// один вид — и один из двух документов вернул бы `duplicate` и не выдал
  /// бы бумаги вовсе.
  ///
  /// Номер здесь **строковый по существу**, а не число, записанное строкой:
  /// на бумажках печатают `C-77-0001`, а у выпущенной возвратом он ещё и
  /// несёт происхождение (`<исходный>-R<возврат>`).
  certificateSlip,
}

/// Долговечная личность печатаемого документа — то, из чего строится ключ
/// идемпотентности задания печати.
///
/// ## Зачем это отдельный тип
///
/// Задача 1 этого плана удалила мёртвую очередь именно за то, что её задание
/// порождало идентификатор внутри себя из `DateTime.now()`: повтор получал
/// **новый** идентификатор, и служба печати не могла узнать в нём уже
/// подтверждённое задание. Тот же дефект, воспроизведённый на этаж выше — в
/// месте вызова, — было бы ещё труднее заметить. Поэтому идентификатор
/// строится здесь, из того, чем документ **является**, и ни одна его часть не
/// берётся из часов вызывающего в момент отправки.
///
/// [value] — чистая функция полей. Тот же документ, разобранный на составные
/// части через год и в другом процессе, даёт ту же строку.
///
/// ## Почему именно эти пять частей
///
/// **Касса ([posId]).** Номер чека принадлежит кассе (docs/system-architecture.md,
/// раздел 7, И21: «номер чека … уникален в пределах кассы»). Без кассы чек №42
/// первой кассы и чек №42 второй — один идентификатор и, значит, один
/// напечатанный чек на двоих.
///
/// **Терминал ([terminalId]).** Владелец задания по И29 — терминал **и**
/// касса, оба. Два терминала одной кассы берут номера из одного счётчика, так
/// что для различения чеков терминал не нужен; он нужен затем, что задание
/// показывается и повторяется на том рабочем месте, откуда пришло.
///
/// **Смена ([shiftId]).** Это **смена, в которую печать запрошена**, а не та,
/// в которую был выбит чек, и разница названа здесь прямо, потому что она
/// видна оператору. Дубликат чека, распечатанный из истории через две смены,
/// получает другой идентификатор и **печатается**, вместо того чтобы молча
/// сойтись с печатью двухдневной давности и не выдать бумаги. Цена: два
/// дубликата одного чека в одной смене — это один идентификатор, и второй
/// возвращает `PrintSubmitStatus.duplicate`. `null` (смены нет — например,
/// печать из истории после закрытия) — это тоже значение, а не «неизвестно»:
/// оно попадает в строку как `noshift`, и все печати вне смены между собой
/// сравниваются на общих основаниях.
///
/// **Номер ([number]).** Свой у каждого вида, см. [PrintDocumentKind].
///
/// **Номер копии ([copyIndex]).** Без него две печати одного чека — это одно
/// задание, и легитимный дубликат оператору не выдать вовсе. С ним повтор
/// **той же** копии узнаётся (второй бумаги нет), а новая копия — новое
/// задание. Оригинал — `0`, дубликат — `1`.
@immutable
class PrintDocumentId {
  /// Бросает [ArgumentError], если [terminalId] или [posId] не положителен
  /// (ноль — обычная заглушка для «неизвестно», а задание без владельца некому
  /// показать и некому повторить — И29); если [number] пуст или содержит
  /// разделитель `/`; если [copyIndex] отрицателен.
  PrintDocumentId({
    required this.terminalId,
    required this.posId,
    required this.shiftId,
    required this.kind,
    required this.number,
    required this.copyIndex,
  }) {
    if (terminalId <= 0) {
      throw ArgumentError.value(
        terminalId,
        'terminalId',
        'у задания печати есть владелец — терминал, от которого оно пришло '
            '(И29)',
      );
    }
    if (posId <= 0) {
      throw ArgumentError.value(
        posId,
        'posId',
        'у задания печати есть владелец — касса, от которой оно пришло (И29)',
      );
    }
    if (number.trim().isEmpty) {
      throw ArgumentError.value(
        number,
        'number',
        'документ без номера неотличим от любого другого документа того же '
            'вида в той же смене',
      );
    }
    if (number.contains(separator)) {
      throw ArgumentError.value(
        number,
        'number',
        'номер не может содержать разделитель "$separator": иначе два разных '
            'документа складываются в одну строку идентификатора',
      );
    }
    if (copyIndex < 0) {
      throw ArgumentError.value(
        copyIndex,
        'copyIndex',
        'номер копии считается с нуля; отрицательная копия не существует',
      );
    }
  }

  /// Разделитель частей в [value].
  ///
  /// Объявлен константой и запрещён внутри [number] в конструкторе: без
  /// запрета документ с номером `1/2` и документ с номером `1` в копии `2`
  /// могли бы дать одну строку — то самое правдоподобно-неверное значение,
  /// которое этот проект ловит жёстче всего.
  static const String separator = '/';

  /// Строка, которой обозначается отсутствие открытой смены.
  static const String noShift = 'noshift';

  final int terminalId;

  final int posId;

  /// Открытая смена в момент запроса печати, или `null`, если её нет.
  final int? shiftId;

  final PrintDocumentKind kind;

  /// Номер документа в нумерации своего вида.
  ///
  /// Строка, а не число, потому что у половины видов номера нет вовсе:
  ///
  /// | Вид | Что здесь стоит |
  /// | --- | --- |
  /// | [PrintDocumentKind.sale] | `receiptNo` |
  /// | [PrintDocumentKind.refund] | `refundId` |
  /// | [PrintDocumentKind.zReport] | момент открытия смены, мс — он взят из
  ///   строки смены и потому долговечен |
  /// | [PrintDocumentKind.xReport] | момент снимка, мс |
  /// | [PrintDocumentKind.preCheck] | стол и момент запроса, мс |
  /// | [PrintDocumentKind.serviceIntake] / [PrintDocumentKind.serviceCompletion] | номер заказа |
  /// | [PrintDocumentKind.sample] | момент запроса, мс |
  /// | [PrintDocumentKind.cashOperation] | `CashOperations.id` |
  ///
  /// **Момент в номере — не то же самое, что порождённый идентификатор.**
  /// X-отчёт, пречек и пробная печать — это снимки: два снимка, снятые в
  /// разные моменты, суть **разные документы**, и момент здесь описывает
  /// документ, а не отправку. У чека продажи момент в номере не стоит именно
  /// поэтому: чек №42 остаётся чеком №42, сколько бы раз его ни печатали.
  final String number;

  /// Какая это по счёту копия документа: `0` — оригинал, `1` — дубликат.
  final int copyIndex;

  /// Ключ идемпотентности задания печати. Чистая функция полей.
  String get value => <String>[
    't$terminalId',
    'p$posId',
    's${shiftId ?? noShift}',
    kind.name,
    number,
    'c$copyIndex',
  ].join(separator);

  @override
  bool operator ==(Object other) =>
      other is PrintDocumentId && other.value == value;

  @override
  int get hashCode => value.hashCode;

  @override
  String toString() => 'PrintDocumentId($value)';
}
