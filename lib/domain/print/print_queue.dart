import 'package:meta/meta.dart';

import 'package:telepos/domain/print/print_job.dart';

/// Чем закончилась сдача задания в очередь.
///
/// Передаётся по имени, никогда по индексу.
enum PrintSubmitStatus {
  /// Задание принято и встало в очередь. **Не означает «напечатано»** — см.
  /// доку [PrintQueue.submit].
  accepted,

  /// Задание с таким идентификатором очереди уже известно: либо стоит в ней,
  /// либо уже подтверждено принтером. Второй раз оно не встало и второго чека
  /// не будет.
  ///
  /// Это **успех вызывающего**, а не отказ: ровно так выглядит корректный
  /// повтор после потерянного подтверждения. Свести его с [rejected] значило
  /// бы заставить экран оплаты показывать ошибку там, где всё правильно.
  duplicate,

  /// Задание не принято, и причина названа в [PrintSubmitOutcome.message].
  rejected,
}

/// Ответ очереди на [PrintQueue.submit].
@immutable
class PrintSubmitOutcome {
  const PrintSubmitOutcome._({
    required this.status,
    required this.jobId,
    required this.message,
  });

  /// Задание встало в очередь.
  factory PrintSubmitOutcome.accepted(String jobId) => PrintSubmitOutcome._(
    status: PrintSubmitStatus.accepted,
    jobId: _checkedJobId(jobId),
    message: 'Задание принято в очередь печати',
  );

  /// Задание с таким идентификатором уже известно очереди — второго чека не
  /// будет.
  factory PrintSubmitOutcome.duplicate(String jobId) => PrintSubmitOutcome._(
    status: PrintSubmitStatus.duplicate,
    jobId: _checkedJobId(jobId),
    message: 'Задание уже принято ранее — повторно не печатается',
  );

  /// Задание не принято. [reason] показывается оператору как есть и потому не
  /// может быть пустым: «не удалось» без причины — не ответ.
  factory PrintSubmitOutcome.rejected(String jobId, String reason) {
    if (reason.trim().isEmpty) {
      throw ArgumentError.value(
        reason,
        'reason',
        'отказ очереди печати обязан называть причину',
      );
    }
    return PrintSubmitOutcome._(
      status: PrintSubmitStatus.rejected,
      jobId: _checkedJobId(jobId),
      message: reason,
    );
  }

  final PrintSubmitStatus status;

  /// Идентификатор задания, о котором идёт речь, — тот самый, что задал
  /// вызывающий.
  final String jobId;

  /// Текст, годный к показу как есть. Всегда непустой.
  final String message;

  /// Задание именно сейчас встало в очередь.
  ///
  /// [PrintSubmitStatus.duplicate] сюда **не** входит намеренно: вызывающему,
  /// который считает попытки печати или пишет запись в журнал, важно
  /// различать «встало» и «уже стояло». Тому, кого интересует только «чек
  /// будет», хватает `!isRejected`.
  bool get isAccepted => status == PrintSubmitStatus.accepted;

  bool get isRejected => status == PrintSubmitStatus.rejected;

  static String _checkedJobId(String jobId) {
    if (jobId.trim().isEmpty) {
      throw ArgumentError.value(jobId, 'jobId', 'не может быть пустым');
    }
    return jobId;
  }

  @override
  String toString() => 'PrintSubmitOutcome(${status.name}, $jobId: $message)';
}

/// Единственный способ что-либо напечатать: задание сдаётся сюда, а не
/// пишется в принтер напрямую.
///
/// Смысл контракта — И29 и И30 вместе (docs/system-architecture.md, раздел 8):
/// задание неделимо и идемпотентно, у него есть владелец и срок, **и при этом
/// ни одна операция здесь не является частью продажи**. Сдача задания
/// возвращает ответ сразу; продажа не ждёт бумаги и не отменяется из-за её
/// отсутствия.
///
/// Контракт живёт в `lib/domain/`, а не рядом с драйверами, именно затем,
/// чтобы экран очереди печати (задача 7) мог его прочитать, не импортируя
/// `lib/hardware/` и `lib/data/`.
abstract interface class PrintQueue {
  /// Ставит задание в очередь.
  ///
  /// **«Принято» — это не «напечатано».** Возврат [PrintSubmitStatus.accepted]
  /// говорит, что задание сохранено и будет напечатано, когда принтер сможет;
  /// бумага к этому моменту не появилась и могла не появиться вовсе. Кто
  /// хочет знать судьбу задания — читает [watch].
  ///
  /// **Повтор безопасен.** Задание с уже известным [PrintJob.id] возвращает
  /// [PrintSubmitStatus.duplicate] и второго чека не печатает — очередь
  /// помнит подтверждённые идентификаторы отдельно от активных заданий
  /// (задача 2).
  ///
  /// **Никогда не бросает.** Отказ — это [PrintSubmitStatus.rejected] с
  /// причиной. Исключение, вылетевшее отсюда, попало бы на путь продажи, где
  /// его ловит `try/catch`, и всё вернулось бы к сегодняшнему положению, при
  /// котором неудачная печать теряется вместе с локальными переменными.
  Future<PrintSubmitOutcome> submit(PrintJob job);

  /// Наблюдаемое состояние очереди: текущий состав заданий сразу при подписке
  /// и новое значение при каждом изменении состава или состояния.
  ///
  /// Поток нужен затем, чтобы застрявшее задание становилось видно оператору
  /// само, а не после нажатия «обновить»: срок, который никто не смотрит, не
  /// делает проблему видимой. Поэтому же отдельного «дай снимок» в контракте
  /// **нет**: подписка отдаёт текущее состояние первым значением, а второй
  /// способ спросить то же самое — это второй способ разойтись с экраном.
  ///
  /// [terminalId] `null` означает «все терминалы» — этим пользуется экран
  /// администратора; касса показывает своё, передавая свой идентификатор.
  Stream<List<PrintJob>> watch({int? terminalId});

  /// Ручной повтор истёкшего или неудачного задания: дать ему ещё [extendBy]
  /// времени.
  ///
  /// **Этот метод нельзя выразить через [submit].** Повторная сдача задания с
  /// известным идентификатором по определению возвращает
  /// [PrintSubmitStatus.duplicate] и ничего не делает — именно в этом смысл
  /// идемпотентности. Ручной повтор — единственная операция, которой
  /// разрешено вернуть уже лежащее в очереди задание в работу, и поэтому она
  /// отдельная.
  ///
  /// Идентификатор сохраняется, поэтому повтор уже **подтверждённого**
  /// задания возвращает [PrintSubmitStatus.duplicate] и второго чека не
  /// печатает.
  ///
  /// **Здесь длительность, а не момент, и это решение, а не упущение.**
  /// `PrintJob.expiresAt` — момент, и остаётся моментом: это *хранимое
  /// состояние*, а длительность в хранимом состоянии каждый читатель обязан
  /// был бы к чему-то прибавлять, и первый же прибавивший не к тому получил
  /// бы задание, живущее вечно. Но это — *запрос*, и он пересекает границу
  /// машин.
  ///
  /// У контракта будет вторая привязка поверх HTTP, где вызывающий — браузер,
  /// а очередь живёт на кассе. Момент, вычисленный по часам браузера, — не
  /// момент по часам кассы. Пока по проводу едет абсолютный срок, часы
  /// вызывающего и часы очереди спорят, и спор виден так: у браузера часы на
  /// десять минут позади, оператор просит «ещё полчаса», касса получает срок,
  /// который по её часам уже прошёл, и **отказывает в повторе исправного
  /// задания**. Ровно тот класс правдоподобно-неверного значения, который
  /// этот проект ловит жёстче всего.
  ///
  /// Передавать вдобавок «сейчас» вызывающего, чтобы очередь вычла одно из
  /// другого, — это и есть длительность, только записанная двумя полями и с
  /// обязанностью каждой реализации правильно их вычесть. А параметр, который
  /// реализация обязана проигнорировать, хуже отсутствующего: он выглядит
  /// работающим.
  ///
  /// Поэтому по проводу не едет ничего, выведенного из часов. Момент строит
  /// **владелец очереди**, у которого часы те же, которыми он же и меряет
  /// истечение срока: `now + extendBy`, дальше `PrintJob.renewedUntil(now +
  /// extendBy, now: now)`. Часы реализации подставляются в неё же — это
  /// обычная внедрённая зависимость, и проверяется она в задаче 3, где у
  /// очереди есть тело.
  ///
  /// Возвращает [PrintSubmitStatus.rejected] с причиной, а не молчание, если
  /// [jobId] неизвестен; если задание **отменено** оператором (напечатать
  /// отменённый чек нельзя — см. `PrintJob.renewedUntil`); если задание прямо
  /// сейчас печатается; и если [extendBy] не положительна — «повторить и сразу
  /// просрочить» не является осмысленной просьбой.
  ///
  /// Обязательного значения по умолчанию здесь нет намеренно: умолчание,
  /// выбираемое реализацией, — это две реализации, разошедшиеся в поведении
  /// на том, о чём контракт молчит.
  Future<PrintSubmitOutcome> retry(
    String jobId, {
    required Duration extendBy,
  });

  /// Отменяет задание. Возвращает `false`, если задание неизвестно или уже
  /// в терминальном состоянии.
  Future<bool> cancel(String jobId);
}
