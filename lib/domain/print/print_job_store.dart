import 'package:telepos/domain/print/print_job.dart';

/// Долговечная память очереди печати.
///
/// **Зачем отдельный контракт.** Сегодня неудачная печать теряется вместе с
/// локальными переменными асинхронной функции экрана оплаты: деньги взяты, чек
/// в базе, бумаги нет, повторить нечего. Удалённая задачей 1 очередь
/// (`PrinterScheduler`) держала задания целиком в памяти — то есть повторяла
/// тот же дефект, только на один уровень выше. Хранилище существует ровно
/// затем, чтобы сданное задание пережило **перезапуск процесса**: реализация,
/// которая держит задания в поле класса, этот контракт не выполняет, каким бы
/// зелёным ни был её прогон.
///
/// **Две памяти, а не одна.** Активные задания и **подтверждённые
/// идентификаторы** хранятся раздельно и убираются раздельно:
///
/// - [removeFinishedBefore] убирает сами задания, дошедшие до терминального
///   состояния;
/// - [forgetExpiredConfirmations] убирает память о подтверждённых, и только
///   она.
///
/// Свести их в одну уборку — значит получить идемпотентность, живущую ровно до
/// первой уборки: задание, повторённое после потерянного подтверждения, уже не
/// будет узнано, и покупатель получит второй чек. Для фискального чека это не
/// косметика. Поэтому строка подтверждения **не** ссылается на строку задания
/// внешним ключом: она обязана пережить её.
///
/// **Срок — момент, а не длительность.** [PrintJob.expiresAt] хранится как
/// момент времени. Длительность («30 секунд») после перезапуска не значит
/// ничего: задание получало бы свежие тридцать секунд при каждом открытии
/// приложения — то самое «висит вечно», которое И29 запрещает
/// (docs/system-architecture.md, раздел 8).
abstract interface class PrintJobStore {
  /// Сколько хранится память о подтверждённом задании.
  ///
  /// **Правило и его цена.** Девяносто дней — это заведомо больше любого
  /// осмысленного окна повтора: ручной повтор из интерфейса (задача 7) делает
  /// оператор в ту же смену, автоматический — в пределах срока задания,
  /// который измеряется минутами. Квартал выбран как ближайшая граница, за
  /// которой «этот чек уже печатали» перестаёт быть вопросом кассира и
  /// становится вопросом отчётности, где ответ ищут в продажах, а не в очереди
  /// печати.
  ///
  /// Одного срока мало: он ограничивает возраст, но не количество. Поэтому
  /// вместе с ним действует [maxRememberedConfirmations] — жёсткий потолок
  /// строк, при превышении которого выбрасываются **самые старые**. Одного
  /// потолка тоже мало: он ограничивает рост, но оставил бы на тихой кассе
  /// идентификаторы многолетней давности, то есть память, которую никто не
  /// может объяснить.
  static const Duration confirmationRetention = Duration(days: 90);

  /// Потолок числа запомненных подтверждений.
  ///
  /// **Считать надо задания, а не чеки, и в разных режимах это разные
  /// числа.** В рознице продажа даёт одно задание, и пятьсот продаж в день
  /// упираются в потолок примерно за двести дней — то есть первым срабатывает
  /// [confirmationRetention]. В ресторане одна продажа порождает несколько
  /// заданий сразу (чек гостю плюс марки на кухню и бар), и при пяти заданиях
  /// на продажу тот же поток выбирает сто тысяч строк примерно за сорок дней
  /// — там первым срабатывает **потолок**, а не срок. Обе границы поэтому не
  /// страховка друг для друга, а рабочие: какая из них наступит раньше,
  /// зависит от режима точки.
  ///
  /// Что этот потолок стоит, названо прямо: касса, набравшая сто тысяч
  /// подтверждений быстрее, чем за [confirmationRetention], забудет самые
  /// старые раньше срока, и повтор задания, подтверждённого более ста тысяч
  /// заданий назад, напечатает второй чек. Неограниченный рост базы на
  /// кассе, которая не обслуживается годами, — худший из двух исходов, и это
  /// осознанный размен, а не недосмотр.
  ///
  /// Строка — около шестидесяти байт, так что потолок ограничивает эту
  /// таблицу единицами мегабайт. Заметно больше весит `PrintJobs`: там у
  /// каждой строки лежат байты чека целиком, и её ограничивает
  /// [removeFinishedBefore], у которой своего умолчания нет — момент выбирает
  /// вызывающий.
  static const int maxRememberedConfirmations = 100000;

  /// Противоречит ли запись [job] уже имеющемуся подтверждению печати.
  ///
  /// Условие ровно одно — «состояние не [PrintJobState.printed]», — и живёт
  /// оно **здесь**, одной строкой, а не отдельно в хранилище и отдельно в
  /// очереди. Два условия одного смысла в двух слоях одинаковыми не остаются,
  /// и это не предположение: пока правило звучало как «нетерминальное
  /// состояние», хранилище уже проверяло «не `printed`», очередь проверяла «не
  /// терминальное», а дока прямо над этой строкой описывала третье. Разошлись
  /// они молча и держались вместе только тем, что никто не записывал
  /// подтверждённое задание как `cancelled`.
  ///
  /// Почему именно `printed`, а не «терминальное»: записать подтверждённое
  /// задание как `cancelled` или `expired` второго чека не даёт, но оставляет
  /// в журнале утверждение, что оператор отменил чек, который физически вышел
  /// из принтера. В фискальной записи неверное объяснение хуже отсутствия
  /// объяснения — оно выглядит достоверным.
  static bool contradictsConfirmation(PrintJob job) =>
      job.state != PrintJobState.printed;

  /// Сохраняет задание — вставляет или заменяет по [PrintJob.id].
  ///
  /// Если задание сохраняется в состоянии [PrintJobState.printed], хранилище
  /// **тем же действием** запоминает его идентификатор как подтверждённый.
  /// Отдельного вызова для этого нет намеренно: вызывающий, забывший его
  /// сделать, получил бы очередь без идемпотентности, и узнал бы об этом на
  /// втором чеке у покупателя.
  ///
  /// Бросает [StateError], если задание с уже подтверждённым идентификатором
  /// пытаются записать в состоянии, для которого истинна
  /// [contradictsConfirmation].
  ///
  /// ## Тому, кто заведёт очереди второго писателя — читать до правки
  ///
  /// **Это место сломается молча в тот день, и предупреждение стоит здесь
  /// именно потому, что открывать вы будете его.**
  ///
  /// Сегодня единственный вызывающий — `PrintQueueLocal`
  /// (`lib/data/print/print_queue_local.dart`), и он спрашивает
  /// [isConfirmedPrinted] **отдельным вызовом до** [put], а не полагается на
  /// исключение отсюда. Между вопросом и записью есть щель. Безопасна она
  /// ровно потому, что в этой щели некому оказаться: печатью занят один
  /// проход очереди, и второго писателя нет.
  ///
  /// Общая очередь на несколько касс (план серверной установки) этого условия
  /// не сохранит. Отказ будет выглядеть так: зелёный прогон, чистый журнал,
  /// **второй чек у покупателя**. Ни один существующий тест его не поймает —
  /// щель открывается только при втором писателе, а его сегодня нельзя
  /// построить.
  ///
  /// Лечится это не осторожностью вызывающего и не порядком его вызовов, а
  /// тем, что «уже подтверждено» становится **ответом** [put] — одна запись,
  /// одно решение, одна транзакция, — а не отдельным вопросом к нему.
  /// Проверка и запись, разнесённые по двум вызовам, атомарными не станут ни
  /// от какой аккуратности.
  Future<void> put(PrintJob job);

  /// Задание по идентификатору или `null`, если такого задания нет.
  ///
  /// `null` **не** означает «не печаталось»: выполненное задание могло быть
  /// убрано [removeFinishedBefore]. Ответ на вопрос «печаталось ли» даёт
  /// [isConfirmedPrinted], и только он.
  Future<PrintJob?> jobById(String jobId);

  /// Печаталось ли уже задание с этим идентификатором.
  ///
  /// Читает память подтверждений, а не состояние задания: задания уже может не
  /// быть, а ответ обязан остаться прежним.
  Future<bool> isConfirmedPrinted(String jobId);

  /// Известные задания, в порядке создания (раньше созданное — раньше в
  /// списке).
  ///
  /// [terminalId] `null` — все кассы; [activeOnly] `true` — только те, что
  /// сами дойдут до печати или ждут решения оператора, то есть
  /// `!PrintJob.isTerminal`.
  Future<List<PrintJob>> jobs({int? terminalId, bool activeOnly = false});

  /// То же, что [jobs], но новым значением при каждом изменении.
  ///
  /// Нужен затем, чтобы застрявшее задание становилось видно само, а не после
  /// нажатия «обновить»: срок, который никто не смотрит, проблему видимой не
  /// делает.
  Stream<List<PrintJob>> watchJobs({int? terminalId, bool activeOnly = false});

  /// Объявляет неудачными задания, застрявшие в [PrintJobState.printing], и
  /// возвращает их в новом состоянии. [reason] попадает в
  /// [PrintJob.failureReason] и виден оператору, поэтому не может быть пустым
  /// ([ArgumentError]).
  ///
  /// **Это путь восстановления после перезапуска, и он принадлежит
  /// хранилищу.** Строка в состоянии [PrintJobState.printing] означает ровно
  /// одно: процесс умер, пока байты уходили в принтер. Ни очередь, ни драйвер
  /// об этом задании ничего не знают — в их памяти его нет, — так что найти
  /// его может только тот, кто пережил перезапуск, то есть база.
  ///
  /// Почему не продлить такое задание сразу: [PrintJob.renewedUntil]
  /// отказывается повторять [PrintJobState.printing] намеренно, и обход этого
  /// отказа стёр бы из журнала сам факт обрыва. Задание сначала становится
  /// неудачным с названной причиной, и только потом — снова повторяемым; в
  /// журнале остаётся, что именно случилось, а не тихо появившееся заново
  /// задание.
  ///
  /// Вызывается один раз при старте, до того как очередь начнёт печатать.
  /// Не вызвать его — значит оставить задание висеть в [PrintJobState.printing]
  /// навсегда: оно не терминально, поэтому уборка его не тронет, и не
  /// повторяемо, поэтому само не поедет.
  Future<List<PrintJob>> failInterruptedPrinting(String reason);

  /// Убирает задания в терминальном состоянии, последний раз изменённые до
  /// [cutoff]. Возвращает число убранных.
  ///
  /// **Память подтверждений не трогает.** См. доку класса.
  Future<int> removeFinishedBefore(DateTime cutoff);

  /// Применяет правило хранения подтверждений на момент [now]:
  /// старше [confirmationRetention] — забыть; сверх
  /// [maxRememberedConfirmations] — забыть самые старые. Возвращает число
  /// забытых.
  Future<int> forgetExpiredConfirmations(DateTime now);
}
