/// Источник штрихкодов эмулятора — **контракт**, а не класс.
///
/// Заведён не для красоты слоёв, а потому что сторож
/// `test/architecture/browser_routes_test.dart` покраснел и был прав:
/// примесь `BarcodeScannerMixin` живёт в шести экранах, один из которых —
/// экран продажи, а он едет в браузерную сборку. Прямой импорт
/// `lib/emulators/emulated_scanner.dart` из примеси притянул туда `dart:io`
/// по цепочке
///
/// ```
/// main_web.dart → setup_router.dart → sale_screen.dart
///               → barcode_scanner_mixin.dart → emulated_scanner.dart → dart:io
/// ```
///
/// Собранная страница не собралась бы вовсе — это не деградация одного
/// экрана, а белый экран целиком. `flutter build web` при этом прошёл: он
/// вырезал недостижимое. Сторож строже сборки, и это тот случай, когда он
/// прав, а сборка молчит.
///
/// Реализация (`lib/emulators/emulated_scanner.dart`) регистрируется в
/// `service_locator.dart` **только** при сборочном ключе `TELEPOS_EMULATORS`
/// и только на кассе. Примесь спрашивает у `GetIt`, есть ли фабрика, и
/// ничего не знает про то, что за ней стоит.
///
/// # Чего этот контракт НЕ обещает
///
/// * **Что штрихкод прочитан сканером.** Строку называют руками.
/// * **Что клавиатурный клин работает.** Настоящий сканер идёт через
///   `HardwareKeyboard`, и межсимвольный зазор — самая хрупкая часть того
///   пути; эмулятор его **обходит**.
library;

/// Как источник называют в `GetIt`: фабрика, а не экземпляр — источник
/// поднимается на время жизни экрана и гасится в `dispose`.
typedef EmulatedScannerSourceFactory =
    EmulatedScannerSource Function({required String file, String refuse});

abstract interface class EmulatedScannerSource {
  /// Поднимает источник. Отказ приходит **значением** (текст причины), а не
  /// исключением: источник штрихкодов не имеет права уронить экран продажи
  /// (И144). `null` — источник поднят.
  Future<String?> start();

  /// Штрихкоды, «просканированные» с момента [start].
  Stream<String> get barcodes;

  /// Дверь остановки. Без неё каждый заход на экран продажи оставлял бы за
  /// собой читателя одного и того же файла.
  Future<void> stop();
}
