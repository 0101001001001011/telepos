import 'package:telepos/domain/refund/refund_service.dart';

/// Печать чека возврата — задача 20 плана «Продажа с браузерного терминала».
///
/// # Зачем контракт, если печать всё равно одна
///
/// До задачи 20 чек возврата собирал **экран**
/// (`refund_screen._printRefundReceipt`): он читал из базы смену, кассира,
/// счета оплаты исходного чека и реквизиты продавца, разносил сумму возврата
/// по тем же счетам и звал `ReceiptPrintService`. Полторы сотни строк работы
/// с деньгами в презентационном слое — и ровно тот код, который на браузерном
/// терминале выполнить нечем.
///
/// Печать — железо и база кассы (шаг 7 спеки: «фискализация, печать, ящик
/// остаются кассой; терминал их только запускает и получает исход»), поэтому
/// она уехала **под** контракт возврата, а не рядом с ним: зовёт её
/// `LocalRefundService.complete`, то есть та же касса, которая отдала деньги.
/// Возврат, оформленный с планшета, печатается на кассе — как и был обещан
/// картой.
///
/// # Почему отдельным контрактом, а не прямо в `LocalRefundService`
///
/// Печать не входит в деньги: `LocalRefundService` обязан провести возврат и
/// без принтера, а его пробы (`test/data/refund/local_refund_service_test.dart`)
/// не должны поднимать очередь печати ради проверки арифметики. Отдельный
/// необязательный довод даёт и то и другое: `null` — печати нет, и это не
/// ошибка.
abstract interface class RefundReceiptPrinter {
  /// Отправляет чек возврата в очередь печати.
  ///
  /// **Отправляет, а не ждёт.** Правило дерева «оплата не ждёт железа»
  /// (`project_telepos_rebrand_2026-07`) действует и здесь, и по проводу оно
  /// важнее вдвое: к задержке принтера добавилась бы ещё и сеть. Вызывающий
  /// не ждёт этот `Future` и не показывает его исход — недоступный принтер
  /// оставляет задание в хранилище, а деньги уже отданы.
  ///
  /// Не бросает: отказ печати не имеет права отменить состоявшийся возврат.
  Future<void> printRefund({
    required RefundOutcome outcome,
    required List<RefundLine> lines,
    required int userId,
  });
}
