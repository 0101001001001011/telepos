/// Одна строка черновика возврата.
///
/// **Строка опознаётся своим [id], а не товаром — круг правки 1.** Первая
/// версия опознавала товаром и потому сводила строки чека по товару, а
/// цену считала средней. Проба разбора: чек `3×100 + 1×90`, возвращают одну
/// штуку — вернули 97.5, цену, которой не стоила **ни одна** проданная
/// единица, и в фискальный документ ушло «как продано: 4 × 97.5». То есть
/// сведение теряло поштучную цену, которая в базе есть. Правило теперь то
/// же, что у корзины (`LocalCartService._mergeTarget`): **сводятся только
/// строки с совпадающей ценой**, разные цены живут разными строками, и
/// адресовать их можно только идентификатором.
@immutable
class RefundLine {
  const RefundLine({
    required this.id,
    required this.productId,
    required this.name,
    required this.quantity,
    required this.price,
    this.maxQuantity,
    this.barcode,
  });

  /// Идентификатор строки внутри черновика — не идентификатор товара: один
  /// и тот же товар может лежать в возврате двумя строками, если в чеке он
  /// продан по двум ценам.
  ///
  /// В возврате по чеку это номер строки чека (`SaleProducts.id`) —
  /// настоящий, а не выдуманный: по нему видно, какую именно проданную
  /// строку возвращают. В возврате без чека — `p<код товара>`: там строка у
  /// товара одна, цена берётся из каталога и второй быть неоткуда.
  final String id;

  final int productId;

  final String name;

  /// Сколько возвращается.
  final Decimal quantity;

  /// Цена единицы. В возврате по чеку — та, по которой продано (со
  /// скидкой), а не каталожная: возвращают ровно те деньги, которые взяли.
  final Decimal price;

  /// Сколько было продано — потолок для [quantity]. `null` в возврате без
  /// чека: там потолка нет, потому что нет и чека, с которым сверяться.
  final Decimal? maxQuantity;

  final String? barcode;

  Decimal get total => price * quantity;

  @override
  bool operator ==(Object other) =>
      other is RefundLine &&
      other.id == id &&
      other.productId == productId &&
      other.name == name &&
      other.quantity == quantity &&
      other.price == price &&
      other.maxQuantity == maxQuantity &&
      other.barcode == barcode;

  @override
  int get hashCode =>
      Object.hash(id, productId, name, quantity, price, maxQuantity, barcode);

  @override
  String toString() => 'RefundLine($id: $productId × $quantity @ $price)';
}

/// Снимок черновика возврата — то, что касса отдаёт браузерному терминалу.
@immutable
class RefundView {
  const RefundView({
    required this.posId,
    required this.terminalId,
    required this.version,
    required this.lines,
    this.draftNo,
    this.saleReceiptNo,
    this.salePosId,
    this.destinations = const [],
  });

  final int posId;

  /// Куда уйдут деньги, если возврат завершить сейчас — задача 26.
  ///
  /// Считает **касса** той же раскладкой, которой проведёт возврат
  /// (`RefundAllocation`), и отдаёт готовыми строками: терминал показывает
  /// их до подтверждения и ничего не пересчитывает. Пусто — черновика нет
  /// или возвращать нечего.
  final List<RefundDestination> destinations;

  /// Владелец черновика — рабочее место, которое его ведёт.
  final int terminalId;

  /// Версия снимка. Растёт на каждое применённое изменение; это то самое
  /// поле, с которым сверяется [CartCommandMeta.baseVersion].
  final int version;

  final List<RefundLine> lines;

  /// Номер черновика возврата — то, что едет в [CartCommandMeta.receiptNo].
  ///
  /// **Это не номер чека продажи, и подменять одно другим нельзя.** У
  /// возврата без чека номера чека нет вовсе, и два таких черновика подряд
  /// были бы неотличимы: версия у каждого начинается с нуля, а запоздавшая
  /// команда от первого легла бы во второй молча — ровно та проба, которая
  /// в задаче 7 потребовала завести опознание отдельно от версии (круг
  /// правки 2, докстринг `CartCommandMeta`). Поэтому черновик получает свой
  /// счётчик, растущий на кассе, а номер возвращаемого чека едет отдельно
  /// ([saleReceiptNo]).
  ///
  /// `null` — черновика нет.
  final int? draftNo;

  /// Чек, по которому идёт возврат. `null` — возврат без чека **или**
  /// черновика нет вовсе; различает эти два случая [draftNo].
  final int? saleReceiptNo;

  final int? salePosId;

  /// Черновик заведён? Ложь — рабочее место возврат не начинало.
  bool get started => draftNo != null;

  /// Возврат идёт по чеку?
  bool get byReceipt => saleReceiptNo != null;

  /// Сумма к возврату — сумма строк.
  Decimal get total => lines.fold(Decimal.zero, (s, l) => s + l.total);

  /// Сравнение по значению, включая строки — вручную, поэлементно: список
  /// `==` в Dart сравнивает по ссылке, а не по содержимому (тот же повод,
  /// что у `CartView`).
  @override
  bool operator ==(Object other) {
    if (other is! RefundView) return false;
    if (other.posId != posId ||
        other.terminalId != terminalId ||
        other.version != version ||
        other.draftNo != draftNo ||
        other.saleReceiptNo != saleReceiptNo ||
        other.salePosId != salePosId ||
        other.lines.length != lines.length ||
        other.destinations.length != destinations.length) {
      return false;
    }
    for (var i = 0; i < lines.length; i++) {
      if (other.lines[i] != lines[i]) return false;
    }
    for (var i = 0; i < destinations.length; i++) {
      if (other.destinations[i] != destinations[i]) return false;
    }
    return true;
  }

  @override
  int get hashCode => Object.hash(
    posId,
    terminalId,
    version,
    draftNo,
    saleReceiptNo,
    salePosId,
    Object.hashAll(lines),
    Object.hashAll(destinations),
  );

  @override
  String toString() =>
      'RefundView(draft: $draftNo, v$version, lines: ${lines.length})';
}

