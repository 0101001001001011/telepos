/// Возврат как контракт — задача 18 плана «Продажа с браузерного терминала»,
/// шаг 9 спеки.
///
/// Чистый Dart: ни Flutter, ни drift. Реализаций две — кассовая
/// (`LocalRefundService`, эта же задача) и браузерная поверх провода
/// (задача 20); экран возврата один и тот же, под ним меняется только
/// реализация.
///
/// # Что здесь есть и чего нет
///
/// Из четырнадцати операций `refund_controller.dart` по проводу едут три
/// (шаг 9 спеки): **работа с чеком** ([loadReceipt]), **поиск**
/// ([addProduct] — на кассе он и есть «нашёл товар и положил его в
/// возврат») и **завершение** ([complete]). Выделение строк, режим и
/// причины остаются экраном и по проводу не ездят вовсе.
///
/// Четвёртая, [startWithoutReceipt], — не операция экрана, а **отдельное
/// право**: возврат без чека проверяется ключом `opRefundWithoutReceipt`, и
/// свести его с [loadReceipt] в одну операцию значило бы, что проверять это
/// право нечем — сторож провода смотрит на **операцию**, а не на содержимое
/// тела (задача 19).
///
/// # Три правила изменяющей команды — те же, что у корзины
///
/// Приём взят у `CartService` (`lib/domain/sale/cart_service.dart`, задача
/// 7) целиком, и это не сходство, а перенос: терминал у обоих узлов один и
/// тот же, и правила, по которым он повторяет команду и узнаёт об
/// устаревшем снимке, не имеют права различаться.
///
/// 1. **Владелец.** Каждая команда несёт `terminalId` и работает только с
///    черновиком **этого** рабочего места. Чужой черновик командой не
///    достать.
///
///    **Требование безопасности к тому, кто вызывает контракт с провода
///    (задачи 19 и 20).** `terminalId` — обычный довод метода, и сам
///    контракт проверить его происхождение не может. Разбирающий кадр
///    **обязан** брать имя рабочего места из **сеанса** и отвергать кадр, в
///    котором оно названо. То же требование и по той же причине, что у
///    `CartService`.
/// 2. **Опознание черновика и версия.** [CartCommandMeta.receiptNo] здесь
///    несёт **[RefundView.draftNo]** — номер черновика возврата, а не номер
///    чека продажи (см. докстринг [RefundView.draftNo]: у возврата без чека
///    номера чека нет вовсе, и опознавать по нему было бы нечем).
///    [CartCommandMeta.baseVersion] — версия снимка. Разошёлся номер —
///    отказ [refundWrongDraftCode]; тот же номер, но разошлась версия —
///    отказ [refundStaleCode]. Беды разные, и коды разные: первая значит
///    «команда адресована черновику, которого у меня уже нет», вторая —
///    «черновик тот, но он уехал вперёд».
/// 3. **Ключ повтора.** [CartCommandMeta.key] помнится кассой вместе с
///    самим изменением, под одной и той же очередью команд. Повтор с тем же
///    ключом возвращает тот же ответ и черновик второй раз не меняет.
///
/// Порядок проверок — **сначала ключ, потом номер черновика, потом
/// версия**, ровно как у корзины и по той же причине: повтор приходит с уже
/// устаревшей версией, и обратный порядок отказывал бы каждому честному
/// повтору.
///
/// # Честный предел: черновик живёт в кассе, но не переживает её перезапуск
///
/// У корзины правда одна — база: `Sales`/`SaleProducts` получили колонки
/// владельца, версии и ключа повтора миграцией v37 (задача 2). У возврата
/// таких колонок **нет**: `Refunds` не знает ни `terminalId`, ни
/// `cartVersion`, ни `lastCommandKey` (проверено чтением
/// `lib/data/database/tables/refund_tables.dart` — тринадцать колонок, ни
/// одной из трёх), а завести их значит бумажную миграцию v38, которая в
/// этом плане принадлежит **другой** задаче и идёт сейчас в соседней ветке
/// (`task-15-brief.md:5`, `progress.md`: «2 → 15 | обе правят миграции
/// `app_database.dart` (v37 и v38)»). Два разных v38 — это не конфликт
/// слияния, а расхождение схемы у уже установленных касс.
///
/// Поэтому черновик возврата живёт **в памяти кассы**, по одному на рабочее
/// место, и три правила держатся общей очередью команд, а не транзакцией
/// базы. Очередь при этом разводит вызовы **своей реализации, и только
/// их**: экранный путь возврата (`RefundNotifier.processRefund`) сегодня
/// зовёт `RefundInitiationUseCase` и `RefundUseCase` напрямую, мимо неё, в
/// том же изоляте. Пока живы оба пути, «очередь вместо транзакции» верно
/// наполовину — так и записано, а не подразумевается. Что из этого следует,
/// названо здесь, а не обнаруживается:
///
/// - **перезапуск кассы теряет черновик.** Это не ухудшение: сегодня он
///   живёт в памяти *экрана* (`RefundState.items`) и теряется от одного
///   перехода по маршруту. Кассовая память как минимум переживает уход с
///   экрана и обрыв связи с терминалом;
/// - **повтор [complete] после перезапуска кассы получает отказ
///   [refundNotStartedCode], а не второй возврат.** Безопасно по деньгам
///   (двойного возврата не будет), но терминал не узнает, что его возврат
///   всё-таки прошёл. Для возврата **по чеку** этот случай закрыт базой:
///   повторный [loadReceipt] того же чека даёт
///   [refundAlreadyRefundedCode], потому что завершённый возврат лежит в
///   `Refunds` и находится по чеку. Для возврата **без чека** — не закрыт
///   ничем, и это записано пределом, а не спрятано;
/// - **слот повтора [complete] живёт ровно до следующего черновика.** Он
///   чистится заведением нового ([loadReceipt], [startWithoutReceipt]) —
///   круг правки 1, и предел до него был описан **не в ту сторону**: слот
///   не чистился никогда, и повтор старого ключа после нового возврата
///   возвращал **старый исход**, не выполнив новый (проба разбора: «исход
///   300 при ожидаемых 1500, остаток не изменился, черновик остался»).
///   Терминал получал успех с чужой суммой. Теперь поздний честный повтор
///   получает [refundWrongDraftCode] — отказ, а не подделку;
/// - **условная запись по прочитанной версии** (то, что у корзины делает
///   `WHERE cart_version = ...`) здесь сверяется по снимку черновика перед
///   самой заменой. На общей очереди эта ветка недостижима — та же
///   оговорка, что у `LocalCartService._writeVersion`.
///
/// # Отказ — значение, исключение — транспорт
///
/// Команды бросают `WireRefusal` (`lib/domain/wire/wire_refusal.dart`).
/// Наружу, на провод, он уезжает **значением** — кадром отказа с кодом и
/// текстом (I144). Коды перечислены константами ниже, чтобы терминал
/// отличал причину по коду, а не по подстроке в тексте.
///
/// # Деньги
///
/// `Decimal` P18,S3, никогда `double` (I159). По проводу — строкой, через
/// `wireMoney` (задача 19).
abstract interface class RefundService {
  /// Черновик возврата этого рабочего места сейчас и при каждом изменении.
  ///
  /// Первое значение приходит сразу; «черновика нет» — это снимок с
  /// `started == false`, пустым списком строк и версией ноль, а не
  /// отсутствие значения (иначе экран ждал бы первого возврата вечным
  /// индикатором — тот же довод, что у `CartService.watch`).
  Stream<RefundView> watch(int terminalId);

  /// Возврат по чеку: черновик заводится заново и наполняется строками чека
  /// [receiptNo]/[posId] — по количеству и цене, как продано.
  ///
  /// Прежний черновик этого места заменяется целиком, поэтому [meta]
  /// сверяется строго: терминал обязан подтвердить, что видел именно тот
  /// черновик, который сейчас потеряет. Черновика не было — `meta.receiptNo`
  /// пуст, `meta.baseVersion` ноль.
  Future<RefundView> loadReceipt(
    int terminalId,
    int receiptNo,
    int posId,
    CartCommandMeta meta,
  );

  /// Возврат без чека: пустой черновик, в который товары кладёт
  /// [addProduct].
  ///
  /// Отдельная команда, а не довод к [loadReceipt], потому что у неё
  /// **другое право** (`opRefundWithoutReceipt`, задача 19): право
  /// проверяет касса по имени операции, а не по содержимому тела.
  Future<RefundView> startWithoutReceipt(int terminalId, CartCommandMeta meta);

  /// Кладёт в возврат **без чека** товар [productId] в количестве
  /// [quantity] по каталожной цене продажи; ноль убирает его строку.
  ///
  /// **Только в черновике без чека — круг правки 1.** В возврате по чеку
  /// эта команда отказывает [refundLineNotInReceiptCode] всегда, а не
  /// только для товара, которого в чеке нет: «возврат по чеку» значит
  /// «возвращают то, что в этом чеке продано», и добавлять туда каталог
  /// нечем. Менять количество уже набранных строк — [setLineQuantity], в
  /// обоих видах черновика.
  ///
  /// Товара без цены продажи вернуть без чека нельзя
  /// ([refundInvalidAmountCode]): `RefundUseCase` отвергает такую строку
  /// исключением, и по проводу оно уехало бы одним именем типа.
  Future<RefundView> addProduct(
    int terminalId,
    int productId,
    Decimal quantity,
    CartCommandMeta meta,
  );

  /// Ставит строке [lineId] количество [quantity].
  ///
  /// **Это единственный способ передать кассе выделение строк.** Само
  /// выделение остаётся экраном (шаг 9 спеки), но касса обязана узнать его
  /// итог до того, как отдаст деньги: кассир снял выделение — экран шлёт
  /// сюда ноль, и строка уходит из черновика; уменьшил количество — шлёт
  /// новое. Ноль удаляет строку тем же правилом, каким
  /// `CartService.setQuantity` удаляет строку корзины, а снятая строка
  /// возвращается тем же вызовом с ненулевым количеством: чек помнится
  /// целиком, а не через текущий набор.
  ///
  /// **Оговорка, на которой споткнётся задача 20: обратный ход работает
  /// только в возврате по чеку.** Там касса помнит, что чек вообще
  /// позволяет вернуть, и снятую строку берёт оттуда. В возврате **без
  /// чека** такого списка нет: снятая строка исчезает совсем, и
  /// [refundLineNotFoundCode] на неё — правило, а не сбой; класть товар
  /// заново надо [addProduct].
  ///
  /// **Количество снятой строки касса не помнит** ни в одном из двух видов
  /// черновика. Вернув строку, экран обязан назвать количество сам; держит
  /// его терминал.
  ///
  /// В черновике по чеку количество не бывает больше проданного по этой
  /// строке ([refundInvalidAmountCode]) — иначе «возврат по чеку»
  /// перестаёт значить то, что говорит. Строки с таким [lineId] в
  /// черновике нет — [refundLineNotFoundCode].
  ///
  /// **Пакетной формы нет, и это стоит круга по проводу на строку.**
  /// «Выделить всё» на чеке в тридцать строк это тридцать вызовов, а при
  /// правиле «одна команда в полёте» (I161) — тридцать кругов подряд;
  /// отказ на середине оставляет терминал и кассу при разных мнениях о
  /// том, что выделено. Заметка задаче 19: не вытянет замер круга —
  /// нужна операция, принимающая список `(lineId, quantity)` целиком.
  /// Здесь она не заведена потому, что её цена меряется на проводе, а не
  /// в контракте.
  Future<RefundView> setLineQuantity(
    int terminalId,
    String lineId,
    Decimal quantity,
    CartCommandMeta meta,
  );

  /// Завершает возврат: деньги обратно покупателю, товар обратно на
  /// остаток.
  ///
  /// Возвращает [RefundOutcome] и **очищает черновик** — у рабочего места
  /// после завершения возврата в работе ничего нет. Повтор с тем же ключом
  /// отдаёт тот же [RefundOutcome] (правило 3), пока касса не перезапущена
  /// (предел назван в докстринге класса).
  ///
  /// # Два предела, названные, но не закрытые
  ///
  /// **Окно «проверил — сделал».** Сверки — состояние чека, отсутствие
  /// прежнего возврата, открытая смена — стоят **не в одной транзакции** с
  /// самим проведением: `RefundUseCase.perform` открывает свою. Круг
  /// правки 2 это измерил: состояние чека, изменённое через один оборот
  /// цикла событий после сверки, деньги уже не останавливает. Достижимость
  /// сегодня ничтожна (очередь команд, один изолят, а сам оборот надо
  /// подгадать), но форма реальна, и закрывается она не проверкой, а
  /// переносом сверок внутрь транзакции проведения — то есть правкой
  /// `RefundUseCase`, за границей этой задачи.
  ///
  /// **Форма фискального документа расходится с экранной.** Строки одного
  /// товара с одной ценой сводятся в одну (`3×100` вместо `2×100` и
  /// `1×100`), а экранный путь их не сводит. Сумма и количество те же,
  /// состав строк — нет.
  Future<RefundOutcome> complete(int terminalId, CartCommandMeta meta);

  /// Беды железа, случившиеся **после** проведённого возврата [refundLocalId]
  /// рабочего места [terminalId], — сегодня это денежный ящик.
  ///
  /// # Откуда метод, измеренной приёмкой 2026-09-17
  ///
  /// Возврат чека «сертификат 3000 + наличные 200» называл кассиру маршрут
  /// «Наличными из ящика — 200», проводил фискальный возврат и печатал
  /// документ, а ящик **не открывался**: ни один путь возврата его не звал
  /// (журнал стенда — `printCertificateSlip`, `fiscalizeRefund`,
  /// `printRefund` и ни одного `paymentDrawerPort`, тогда как у продажи с
  /// наличной частью он есть всегда). Теперь [complete] открывает ящик,
  /// когда из него ушли деньги, и **не ждёт** его — правило «оплата не ждёт
  /// железа» у выдачи денег то же, что у их приёма.
  ///
  /// # Это не второй механизм, а тот же, что у продажи
  ///
  /// Форма и правила взяты у `PaymentService.hardwareTroubles` дословно, и
  /// разбор живёт там: спрашивать **после** того, как кассиру сказано об
  /// успехе; чтение **разрушающее** (вторая выдача той же беды — пустой
  /// список) и **по владельцу** (беда отдаётся рабочему месту, проводившему
  /// возврат, а не любому, кто назовёт номер: номера возвратов
  /// последовательны, и перебрать их ничего не стоит). Тип беды тот же —
  /// `CompletionTrouble` с видом `CompletionTroubleKind.drawer`, — и в поле
  /// `receiptNo` лежит **номер возврата** ([RefundOutcome.refundLocalId]):
  /// своего номера чека у возврата нет, а спрашивают его по этому.
  ///
  /// **Возврата беда не отменяет**: деньги по книгам выданы, товар на
  /// остатке, документ ушёл. Кассир открывает ящик ключом.
  ///
  /// Пустой список — «ничего не сломалось», «спросил не тот» или «касса уже
  /// не помнит» (запись без читателя вытесняется следующими возвратами).
  Future<List<CompletionTrouble>> hardwareTroubles(
    int terminalId,
    int refundLocalId,
  );

  /// Забыть черновик рабочего места целиком — вместе со слотом повтора
  /// [complete].
  ///
  /// **Не команда терминала, а событие жизни рабочего места, и своей
  /// операции провода у неё нет** (задача 19). Зовёт её касса, когда за
  /// место сел другой человек: обработчик `auth.login`
  /// (`lib/backend/till_operations.dart`) — единственный вызывающий.
  ///
  /// # Зачем, измеренной пробой
  ///
  /// Черновик лежит под ключом рабочего места **и только его**: пользователя
  /// он не помнит и выход из системы переживает. Пока этого метода не было,
  /// проба разбора круга 1 задачи 19 проходила целиком:
  ///
  /// ```
  /// старший (оба права)  → startWithoutReceipt → успех
  /// младший (только op.refund) → startWithoutReceipt → forbidden ← право работает
  /// тот же младший → addProduct 10 шт → успех
  /// тот же младший → complete         → успех ← деньги ушли
  /// ```
  ///
  /// То есть роль, которой возврат без чека **закрыт сознательно**,
  /// наполняла чужой безчековый черновик каталожным товаром и отдавала по
  /// нему деньги. Право охраняло только первое нажатие. Довод «черновик уже
  /// заведён тем, у кого право было» верен ровно для одного кассира и
  /// разваливается на первой же пересменке — а она на рабочем месте каждый
  /// день.
  ///
  /// # Почему по входу, а не по паре «место и человек»
  ///
  /// Пара была бы точнее, но **личности вызывающего у кассы нет**: сторож
  /// разбирает токен в сеанс и обработчику его не отдаёт (решение задачи 10
  /// закрытия долга, докстринг `WireHandler`). Два дешёвых заменителя
  /// измерены и отвергнуты:
  ///
  /// - **«кто входил на этой QUIC-сессии»** — не переживает F5: вкладка
  ///   восстанавливает токен из хранилища и заводит только подписку
  ///   `auth.session`, `auth.login` не зовёт вовсе
  ///   (`login_controller.dart`, `_restoreSession`). Касса перестала бы
  ///   узнавать своего же кассира после перезагрузки страницы;
  /// - **«кто сейчас живой на этом месте»** — неоднозначно:
  ///   `SessionRegistry.mint` не гасит прежний сеанс того же терминала, так
  ///   что живых сеансов на одном месте бывает два.
  ///
  /// Поэтому граница проведена по **входу**: вход на рабочее место
  /// начинает работу с чистого листа. Это **строже** пары «место и человек»
  /// — черновик пропадает и когда тот же кассир вошёл заново, — и строгая
  /// сторона здесь безопасная: возврат по чеку восстанавливается одним
  /// [loadReceipt] (чек никуда не делся, он в базе), а безчековый обязан
  /// быть начат заново тем, у кого на это есть право.
  ///
  /// **Предел назван прямо:** человек, севший за чужую **незакрытую**
  /// вкладку и работающий чужим токеном, входа не совершает — и черновик
  /// ему достанется. Это не про возврат: с чужим действующим токеном ему
  /// достаётся всё, и лечится это сроком бездействия сеанса, а не здесь.
  ///
  /// Идемпотентна: забывать нечего — не ошибка.
  Future<void> abandon(int terminalId);
}

