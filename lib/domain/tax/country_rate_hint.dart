/// Общая ставка страны — подсказкой для мастера.
///
/// # Зачем договор, а не прямое чтение наборов
///
/// Наборы лежат в ресурсах и читаются слоем данных. Мастер живёт в
/// презентации, и тянуть каталог наборов туда значит нарушить И5 — что и
/// вышло с первой редакцией: сторожа поймали её и нарушением слоёв, и
/// сломанной браузерной сборкой, у которой ресурсов кассы нет вовсе.
///
/// # Почему «подсказка», а не «ставка»
///
/// Это не то, по чему считают налог. Считают по НАСТРОЙКЕ кассы, заведённой
/// из набора и правимой владельцем. Здесь — только число, которое мастер
/// показывает человеку, выбравшему страну, чтобы он узнал своё раньше, чем
/// дойдёт до настроек.
abstract interface class CountryRateHint {
  /// Общая ставка страны по её коду ISO 3166-1 alpha-2, строкой.
  ///
  /// `null` — набора нет (США: ставка задаётся городом), их несколько или
  /// прочитать не удалось. Мастер тогда честно говорит, что ставку назовёт
  /// настройка: названное наугад число читается как обещание.
  Future<String?> standardRatePercent(String isoCode);
}
