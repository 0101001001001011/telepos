import 'package:decimal/decimal.dart';

/// Деньги целыми тысячными — **одно выражение на дерево**.
///
/// # Зачем это вынесено
///
/// Тысячные завёл сертификат (задача 21) и завёл по измеренной причине:
/// остаток — единственное денежное число, которое **уменьшается и
/// сравнивается внутри SQL**, а `RealColumn ... map(DecimalConverter())`
/// кладёт на диск `double`. `500 − 0.1 − 0.1` в двойной точности даёт
/// `499.79999999999995`, и `DecimalConverter.fromSql` поднимет это как
/// деньги, которых никто не вводил.
///
/// Рассрочка — **второе** такое число: разнесение платежа по графику это
/// условная запись `paid_millis + :x <= total_due_millis`, и написать её
/// на стороне Dart нельзя — тогда между чтением и записью снова
/// открывается окно, ради закрытия которого всё и делается.
///
/// Два перевода одного и того же — это два ответа на один вопрос, ждущие,
/// когда разойдутся: округление вниз в одном месте и к ближайшему в
/// другом дают разные деньги на одном и том же числе. Поэтому выражение
/// здесь одно, а `GiftCertificate.millisOf`/`amountOf` на него ссылаются.
///
/// P18,S3 (I159) при этом соблюдён: тысячная и есть третий знак.
abstract final class MoneyMillis {
  /// Деньги → целые тысячные.
  ///
  /// `round()`, а не `truncate()`: довод в том, что на входе уже деньги
  /// P18,S3, у которых четвёртого знака быть не должно, и всякое
  /// отклонение здесь — признак испорченного числа, а не законная
  /// дробь. Округление к ближайшему теряет на таком числе меньше, чем
  /// отбрасывание.
  static int of(Decimal amount) =>
      (amount * Decimal.fromInt(1000)).round().toBigInt().toInt();

  /// Целые тысячные → деньги.
  static Decimal amount(int millis) =>
      (Decimal.fromInt(millis) / Decimal.fromInt(1000)).toDecimal(
        scaleOnInfinitePrecision: 3,
      );
}
