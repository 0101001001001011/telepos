/// Высокоэнтропийный секрет терминала — выдаётся кассой один раз при
/// заведении ([TerminalRepository.register]), задача 4 плана
/// «знакомство терминала с кассой» (шаг 2 спеки,
/// `docs/internal/superpowers/specs/2026-08-23-terminal-enrolment-design.md`).
///
/// # Почему не переиспользован `SecurityEventDao.fingerprintOfSecret`
///
/// Такой функции больше нет — волна закрытия долга безопасности
/// (2026-08-22) сняла её целиком: она была несолёным, неитерированным
/// `sha256` без единого вызывающего, а докстринг `SecurityEventDao` прямо
/// говорит, что она бы не замаскировала настоящий секрет продукта того
/// времени (четырёхзначный PIN — 10⁴ прообразов, перебираются мгновенно), а
/// обратимо закодировала. Тот же докстринг называет условие, при котором
/// функцию заводят заново: «появится настоящий вызывающий с высокоэнтропийным
/// секретом… функцию заводят рядом с ним, солёной и названной по секрету,
/// который она в самом деле маскирует». Этот файл — то место: секрет здесь
/// не PIN, а 256 случайных бит, и приём — тот же самый (`package:crypto`,
/// `sha256.convert(utf8.encode(...))`), которым уже пользуется цепочка
/// журнала безопасности (`SecurityEventDao._fingerprintOfRow`) — не второй
/// придуманный заново примитив, тот же самый пакет и та же самая свёртка,
/// только соль своя и имя — про то, что она защищает.
///
/// # Сколько энтропии и почему хватает
///
/// [generate] берёт 32 байта (256 бит) из `Random.secure()` — криптографического
/// генератора платформы, тем же приёмом, что и `PairingInvites.mint()`
/// (`lib/backend/pairing_invites.dart`) — код привязки, который живёт только
/// 15 минут. **Числа разошлись с `2fb3671`** (правка «код привязки —
/// Crockford Base32, набираемый руками», 2026-08-24): код привязки — уже не
/// 12 байт, а 10 знаков Crockford Base32 (5 бит на знак, 50 бит энтропии
/// целиком, `PairingInvites._codeLength`) — формат, пригодный набрать
/// вручную. Секрет терминала живёт неограниченно (до удаления терминала) и
/// вручную никогда не набирается (см. докстринг [generate] про формы), так
/// что сравнение по числу байт больше не то же самое сравнение, что было на
/// момент написания этого абзаца — но соотношение осталось тем же по духу:
/// секрету, который живёт неограниченно, положена энтропия на порядки шире,
/// чем коду на 15 минут. 2²⁵⁶ значений — пространство, на
/// переборе которого не строится ни одна практическая атака ни на каком
/// доступном горизонте, в отличие от четырёхзначного PIN (10⁴, докстринг
/// `SecurityEventDao`/`PinCredential`), для которого и соль, и замедление
/// (PBKDF2) обязательны именно потому, что пространство мало. Здесь
/// замедление не нужно — есть что защищать перебором, только если у секрета
/// есть шанс совпасть с чужим или быть предположенным, а с 256 битами шанса
/// нет структурно.
///
/// # Зачем тогда соль, если перебор и так не грозит
///
/// Соль здесь не замедляет перебор (`fingerprint` — одна свёртка, не тысячи
/// итераций PBKDF2) — она не даёт двум отпечаткам совпасть буквенно, если
/// когда-нибудь совпадут сами секреты (астрономически маловероятно при 256
/// битах, но соль делает эту защиту structural, а не полагающейся на
/// вероятность), и не даёт заранее посчитанной таблице отпечатков сработать
/// против всех терминалов сразу, если этот приём когда-нибудь применят к
/// секрету с менее очевидной энтропией.
library;

import 'dart:convert';
import 'dart:math';

import 'package:crypto/crypto.dart';

/// Генерация и проверка секрета терминала. Только статические члены —
/// секрет живёт в строке ([generate]) и в отпечатке ([fingerprint]), не в
/// объекте с состоянием.
class TerminalSecret {
  TerminalSecret._();

  /// 32 байта = 256 бит — см. докстринг файла.
  static const int lengthBytes = 32;

  static const int saltLengthBytes = 16;

  static final Random _secureRandom = Random.secure();

  /// Новый секрет. `base64Url` без паддинга — удобная для URL форма.
  /// **Не та же форма, что и у кода привязки** (`PairingInvites.mint()`) —
  /// это разошлось `2fb3671` (2026-08-24): код привязки набирают руками, и
  /// с той правки у него отдельный, читаемый формат (Crockford Base32, 10
  /// знаков — докстринг файла, «сколько энтропии и почему хватает»), а
  /// секрет терминала руками никогда не набирают — он едет из `register()`
  /// в тело ответа и сохраняется программой ([TerminalSecretStorage],
  /// `login_controller.dart`), человек его не видит и не вводит. `base64Url`
  /// здесь остаётся ровно потому, что читаемость вручную ему не нужна —
  /// нужна компактная сериализация для JSON-тела кадра и `localStorage`.
  ///
  /// `random` — довод тестов (детерминированный `Random` для воспроизводимого
  /// прогона); рабочий путь всегда берёт `Random.secure()` умолчанием.
  static String generate({Random? random}) {
    final rng = random ?? _secureRandom;
    final bytes = List<int>.generate(lengthBytes, (_) => rng.nextInt(256));
    return base64Url.encode(bytes).replaceAll('=', '');
  }

  /// Отпечаток [secret] — то, что хранится на кассе. Самоописывающаяся
  /// строка `sha256$<соль>$<свёртка>`, тем же приёмом самоописания, что и
  /// `PinCredential` (`lib/core/security/pin_credential.dart`), но без поля
  /// итераций: секрет здесь высокоэнтропийный по построению, замедлять
  /// перебор нечего — перебор и так неосуществим (см. докстринг файла).
  ///
  /// `random` — тот же довод тестов, что и у [generate], только определяет
  /// соль, а не сам секрет.
  static String fingerprint(String secret, {Random? random}) {
    final rng = random ?? _secureRandom;
    final saltBytes = List<int>.generate(
      saltLengthBytes,
      (_) => rng.nextInt(256),
    );
    final salt = base64Url.encode(saltBytes);
    return _fingerprintWithSalt(secret, salt);
  }

  static String _fingerprintWithSalt(String secret, String salt) {
    final digest = sha256.convert(utf8.encode('$salt:$secret'));
    return 'sha256\$$salt\$$digest';
  }

  /// Сверяет [secret] с уже сохранённым [storedFingerprint] — задача 5
  /// плана «знакомство терминала с кассой» (шаг 2 спеки): вкладка предъявляет
  /// секрет обратно на новой QUIC-сессии, и это единственное место, которое
  /// умеет ответить, свой он или чужой.
  ///
  /// `false` на любом входе, который не позволяет ответить утвердительно —
  /// `storedFingerprint == null` (терминал никогда не получал секрет,
  /// например строка, заведённая до миграции v35→v36, задача 4), пустая
  /// строка, форма не `sha256$<соль>$<свёртка>` (три части, испорченное
  /// хранилище), — не бросает исключение: вызывающему («резонный ли это
  /// секрет для этого терминала») нужен один булев ответ, а не разбор по
  /// типу отказа. Причина не смешивается с «сам терминал не существует» —
  /// это решает вызывающий ([LocalTerminalRepository.resume]), а не эта
  /// функция: она отвечает только про сам секрет.
  ///
  /// # Соль берётся из хранимого, а не генерируется заново
  ///
  /// [fingerprint] каждый раз берёт случайную соль — пересчитать отпечаток
  /// [secret] и сравнить результат с [storedFingerprint] напрямую никогда не
  /// совпало бы, даже для настоящего секрета. Соль здесь — часть
  /// самоописывающегося формата, а не секрет сама по себе (докстринг файла,
  /// «зачем тогда соль»): извлечена из уже сохранённой строки и
  /// использована, чтобы пересчитать то же самое значение, которое сохранил
  /// [fingerprint] в момент заведения.
  ///
  /// # Константное время
  ///
  /// Сравнение — байт за байтом с накоплением через `^`/`|=`, без раннего
  /// выхода на первом расхождении: тот же приём, что и
  /// `PinCredential._equalInConstantTime`
  /// (`lib/core/security/pin_credential.dart`) — время ответа не обязано
  /// выдавать, на каком символе разошлось совпадение. Секрет здесь
  /// высокоэнтропийный (256 бит, докстринг файла), и атака по времени против
  /// него так же непрактична, как и прямой перебор, — сравнение в константное
  /// время здесь не единственная защита, а тот же самый приём, применённый
  /// последовательно, а не выборочно.
  static bool matches(String secret, String? storedFingerprint) {
    if (storedFingerprint == null || storedFingerprint.isEmpty) return false;
    final parts = storedFingerprint.split(r'$');
    if (parts.length != 3 || parts[0] != 'sha256') return false;
    final salt = parts[1];
    final expected = _fingerprintWithSalt(secret, salt);
    return _equalInConstantTime(
      utf8.encode(expected),
      utf8.encode(storedFingerprint),
    );
  }

  static bool _equalInConstantTime(List<int> a, List<int> b) {
    if (a.length != b.length) return false;
    var diff = 0;
    for (var i = 0; i < a.length; i++) {
      diff |= a[i] ^ b[i];
    }
    return diff == 0;
  }
}
