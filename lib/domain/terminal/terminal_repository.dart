import 'package:telepos/domain/sale/payment_service.dart';

import 'terminal.dart';

/// Что отдаёт [TerminalRepository.register] — заведённый терминал и его
/// секрет. Запись, а не два отдельных довода: секрет без терминала не
/// вызывающему нечего сохранять, а терминал без секрета из этого метода —
/// вообще не то, что он обещает.
///
/// # Секрет едет здесь и только здесь
///
/// [TerminalRepository.list]/[TerminalRepository.watchAll]/
/// [TerminalRepository.self]/[TerminalRepository.watchSelf] отдают
/// [Terminal] — без секрета структурно, самим типом, а не по забывчивости
/// писателя. Задача 4 плана «знакомство терминала с кассой» — выдача и
/// хранение: секрет выдаётся один раз, в момент заведения, вторично узнать
/// его у кассы нельзя — только завести новый терминал (см. докстринг
/// `LocalTerminalRepository.register` про то, как это обеспечено на
/// хранении).
///
/// # Кто сегодня пользуется [secret]
///
/// Неверно с задачи 5 (правка ниже датирована задачей 4 — оставлена
/// исправленной, а не удалённой, потому что решение «секрет едет здесь и
/// только здесь» выше по-прежнему верно и объяснено этим же абзацем не
/// было бы, не назови он, зачем секрет вообще едет отдельным полем).
/// `login_controller.dart` (`_resolveTerminalId`) сохраняет [secret] в
/// [TerminalSecretStorage] (`localStorage`, не `sessionStorage`) сразу после
/// каждого успешного `register()` и предъявляет его обратно через
/// [TerminalRepository.resume] на следующей QUIC-сессии — раньше, чем звать
/// `register()` заново: касса привязывает **тот же** `terminalId` к новой
/// сессии вместо того, чтобы заводить новую строку. Личность терминала
/// переживает F5, закрытие вкладки и перезапуск браузера (не переживает
/// только очистку `localStorage` или удаление терминала на кассе — тогда
/// [resume] отказывает [TerminalSecret.matches], гейт просит новый код
/// привязки).
typedef TerminalEnrollment = ({Terminal terminal, String secret});

/// Терминалы установки.
///
/// До появления этого контракта устройства лежали в настройках установки, то
/// есть на всех терминалах был один принтер. Настройки устройств принадлежат
/// терминалу, а не установке — docs/system-architecture.md, И27 — но с плана
/// 2, задачи 4 это отдельный контракт,
/// `DeviceBindingRepository` (`lib/domain/terminal/device_binding_repository.dart`),
/// а не метод здесь: см. доку на нём для полного обоснования, почему.
abstract interface class TerminalRepository {
  Future<List<Terminal>> list();

  /// Те же терминалы, но потоком: появившийся виден сразу, а не когда экран
  /// догадается перечитать список.
  ///
  /// # Почему рядом с [list], а не вместо него
  ///
  /// Это разные вопросы, а не два способа задать один. [watchAll] — состояние,
  /// за которым следит экран; [list] — значение, нужное один раз внутри
  /// операции (`TerminalRoutes` проверяет существование терминала, прежде чем
  /// пустить проверку устройства). Подписка ради одного значения обязала бы
  /// каждого такого вызывающего заводить и снимать её вручную — то есть писать
  /// `list()` заново, только руками.
  ///
  /// Двух реализаций одного при этом не появляется: обе половины читают одну
  /// таблицу и один разбор, а по проводу [list] — первое значение той же самой
  /// подписки.
  Stream<List<Terminal>> watchAll();

  /// Терминал, от имени которого работает этот клиент. Создаётся при первом
  /// обращении, если его ещё нет.
  ///
  /// Бросает [InstallationNotConfiguredException], если мастер настройки ещё
  /// не прошёл: настоящего имени кассы пока нет. Плейсхолдер вроде
  /// `'Касса-1'` был бы той же самой ловушкой, что уже была закрыта на пути
  /// миграции v25→v26 (`lib/data/database/app_database.dart`) — такая строка
  /// никогда не заменяется на настоящее имя, потому что дальнейшие вызовы
  /// [self] находят уже существующий `isSelf`-терминал и возвращают его как
  /// есть. Отказ явно — единственный вариант, который не подсовывает
  /// оператору название кассы, которое он никогда не вводил.
  Future<Terminal> self();

  /// Терминал этого клиента потоком: переименование доезжает без вопроса.
  ///
  /// `null` вместо [InstallationNotConfiguredException] — и это не смягчение
  /// правила, а другой вопрос. [self] спрашивают, чтобы **действовать** от
  /// имени терминала (напечатать чек, провести оплату), и действовать от имени
  /// несуществующего нельзя — отсюда отказ. За [watchSelf] следит экран, и
  /// «его ещё нет» для экрана — обычное состояние свежей установки, которое он
  /// обязан показать, а не упасть на нём.
  ///
  /// Строку **не создаёт**, в отличие от [self]: наблюдение не имеет права
  /// менять то, за чем наблюдает — иначе открытая вкладка заводила бы терминал.
  Stream<Terminal?> watchSelf();

  /// Регистрирует новый терминал. Отдаёт [TerminalEnrollment] — терминал и
  /// его секрет, задача 4 плана «знакомство терминала с кассой»
  /// (`docs/internal/superpowers/specs/2026-08-23-terminal-enrolment-design.md`, шаг
  /// 2). Секрет — высокоэнтропийная строка ([TerminalSecret.generate]),
  /// выдаётся этим вызовом единственный раз: касса хранит только её
  /// отпечаток ([TerminalSecret.fingerprint]), значение нигде не остаётся.
  /// Повторно узнать секрет уже заведённого терминала нельзя — только
  /// завести новый.
  ///
  /// Имя обязательно и хранится в обрезанном ([String.trim]) виде: пустая
  /// или состоящая только из пробелов строка отклоняется. Оба биндинга
  /// контракта обязаны отклонять её одинаково — [TerminalRoutes] отвечает
  /// 422 `terminal_name_required`, а локальный биндинг бросает
  /// [ArgumentError]. Без этого правила, записанного здесь, ни одна из двух
  /// сторон не авторитетна, и они расходятся на одном и том же плохом входе.
  ///
  /// [code] — код привязки (`PairingInvites`, `/terminal-pairing`), задача 6
  /// плана «знакомство терминала с кассой» (шаг 3 спеки): до неё регистрация
  /// была открыта любому, кто дотянулся до кассы по QUIC. Довод здесь, а не
  /// новый метод, потому что это тот же вопрос «завести терминал», только с
  /// доказательством права его задавать — так же, как [resume] несёт
  /// [secret] доводом того же вопроса «кто ты», а не отдельным методом.
  ///
  /// Умолчание `''` — не «код не нужен»: это единственная форма, которая не
  /// заставляет [LocalTerminalRepository] (десктоп, минуя провод — реальный
  /// вызывающий здесь ровно один и не браузер, докстринг `TillOperations
  /// .askHandlers[terminalRegister.name]`) знать о `PairingInvites`, которого
  /// у неё нет и не должно быть. Проверяет код не эта реализация и не
  /// [WtTerminalRepository] — только `TillOperations.askHandlers
  /// [terminalRegister.name]` (`lib/backend/till_operations.dart`), у
  /// которого один есть `PairingInvites`, тот же список, что и у `/ca.crt`.
  /// [LocalTerminalRepository.register] довод принимает и не смотрит на
  /// него вовсе — десктопная касса не проходит эту точку по проводу
  /// (`login_controller.dart`, `_resolveTerminalId`, ветка `ownsData ==
  /// true`, зовёт [self], не [register]), а прямые вызывающие в процессе
  /// (стенды, тесты) доверены самим фактом, что они внутри процесса кассы.
  Future<TerminalEnrollment> register({required String name, String code = ''});

  /// Возвращает уже заведённый терминал [terminalId] на новую QUIC-сессию,
  /// предъявив его [secret] — задача 5 плана «знакомство терминала с кассой»
  /// (шаг 2 спеки): вкладка, пережившая F5 или закрытие и повторное
  /// открытие, хранит секрет, который получила единственный раз от
  /// [register], и предъявляет его здесь вместо того, чтобы заводить новую
  /// строку заново.
  ///
  /// # Почему это не второй `self()`
  ///
  /// [self] отвечает за терминал самой кассы (`isSelf`) — вопрос без
  /// довода, потому что касса всегда знает, кто она сама. Здесь вызывающий
  /// называет **чужую** для этого репозитория строку по id и обязан
  /// доказать право говорить от её имени — секретом, а не одним только
  /// именем или id, которые оба видны через [list]/[rename] и секретом не
  /// являются (докстринг [register] про то, почему дедупликация по имени
  /// была дырой).
  ///
  /// # Отказ, а не чужой идентификатор
  ///
  /// Бросает [WireRefusal] с кодом `terminal_secret_invalid`, если:
  /// - `terminalId` не называет существующую строку;
  /// - строка существует, но `secretFingerprint == null` (терминал заведён
  ///   до миграции v35→v36 и секрета никогда не получал — задача 4);
  /// - секрет не сходится с сохранённым отпечатком ([TerminalSecret.matches]).
  ///
  /// Один код на все три причины — иначе тот, кто перебирает `terminalId`,
  /// узнавал бы по коду отказа, какие id вообще существуют на кассе, не
  /// зная ни одного настоящего секрета. Честному вызывающему с испорченным
  /// или устаревшим хранилищем разница тоже не важна: путь один — забыть
  /// сохранённое и завести терминал заново через [register].
  Future<Terminal> resume({required int terminalId, required String secret});

  /// Переименовывает терминал. Та же обязательность имени, что у [register]:
  /// хранится обрезанная строка, пустая после обрезки — отказ.
  Future<void> rename(int terminalId, String name);

  /// Назначает рабочему месту набор разрешённых видов оплаты — задача 15
  /// плана «Продажа с браузерного терминала», решение заказчика №5.
  ///
  /// **Пустое множество означает «все виды»**, а не «ни одного»: полный
  /// разбор — докстринг [Terminal.allowedPaymentTypes]. Передать пустое —
  /// законный способ снять ранее назначенный запрет.
  ///
  /// **Члены — только тендеры** ([tenderPaymentTypes]). [PaymentType.mixed]
  /// отвергается `WireRefusal('bad_request')`: смешанная — форма оплаты, а
  /// не тендер, и набор с ней делал рабочее место немым (круг правки 1).
  ///
  /// Метод здесь, а не отдельным контрактом (в отличие от
  /// `DeviceBindingRepository`), потому что это свойство самой строки
  /// терминала, ровно как имя у [rename]: у него нет ни своей таблицы, ни
  /// своего жизненного цикла, и заводить ради одной колонки второй
  /// репозиторий значило бы завести второй источник правды об одной строке.
  ///
  /// **Запретом это делает не он, а касса.** Значение, записанное здесь,
  /// проверяет `LocalPaymentService` перед тем, как двинуть деньги (I44,
  /// I162); экран вправе спрятать запрещённую кнопку, но спрятанная кнопка
  /// запретом не является.
  Future<void> setAllowedPaymentTypes(int terminalId, Set<PaymentType> types);

  /// Удаляет терминал безвозвратно — задача 8 закрытия долга («замок
  /// кассы»). Строки копились с самого начала: `TerminalDao` не имел ни
  /// одного способа их убрать, и задача 7 (потолок в 200 заведённых
  /// терминалов) прямо назвала это недостающим следующим шагом.
  ///
  /// Привязки устройств удалённого терминала уходят вместе с ним, а не
  /// остаются сиротами — см. `TerminalDao.remove`
  /// (`lib/data/database/daos/terminal_dao.dart`) про каскад на стороне базы.
  ///
  /// Терминал, помеченный `isSelf` — тот, которым касса пользуется сама
  /// (`self`/`ensureSelf`) — удалить нельзя: это понятие «своего терминала»,
  /// которое известно **этому слою** — вызов без единого сеанса рядом
  /// (десктопная касса, минуя провод, — см. обоснование у
  /// [LocalTerminalRepository.delete]). Отказ — тем же `WireRefusal`, что и у
  /// [register] на потолке.
  ///
  /// Терминал вызывающей браузерной вкладки — другое понятие «своего», и с
  /// задачи 9 закрытия долга оно тоже защищено, но не здесь: `AuthSession`
  /// (`lib/domain/auth/auth_outcome.dart`) с этой задачи несёт `terminalId`,
  /// с которым выписан сеанс, и сверяет его с запрошенным `terminals.delete`
  /// в `TillOperations.askHandlers` — единственном месте, которому вообще
  /// достаётся сеанс вызывающей стороны (`lib/backend/till_operations.dart`).
  /// Этот метод о сеансе не знает вовсе и знать не должен: десктопная касса
  /// зовёт его напрямую, без провода и без сеанса какой-либо вкладки.
  ///
  /// Отказывает и на несуществующем `terminalId` — тем же кодом
  /// `unknown_terminal`, которым `auth.login` уже отвечает на чужой id
  /// (`TillOperations.askHandlers`, `lib/backend/till_operations.dart`).
  Future<void> delete(int terminalId);
}

/// Установка ещё не сконфигурирована мастером настройки — у [TerminalRepository.self]
/// нет настоящего имени кассы и он отказывается его выдумывать.
class InstallationNotConfiguredException implements Exception {
  const InstallationNotConfiguredException();

  @override
  String toString() =>
      'InstallationNotConfiguredException: мастер настройки ещё не '
      'завершался, настоящего имени кассы нет';
}

/// `AuthAttempt.terminalId`, запомненный этим клиентом, больше не называет
/// существующий терминал — например, касса восстановлена из резервной копии,
/// терминалы пересозданы с новыми id, а `TerminalIdentity` этой вкладки
/// пережила восстановление и всё ещё называет старый.
///
/// # Почему это домен, а не провод
///
/// Отличить эту причину от любой другой ошибки обмена умеет только
/// биндинг, который видит сам кадр (`WtAuthRepository`,
/// `lib/web/wt_auth_repository.dart`) — он смотрит на код `unknown_terminal`
/// (`WireRefusal`, `lib/domain/wire/wire_refusal.dart`), которым
/// `TillOperations.askHandlers[authLogin]` отказывает на незаведённый
/// `terminalId`. Опознавать этот единственный случай по коду обязан один
/// биндинг, а не каждый вызывающий `AuthRepository.login` — отсюда доменный
/// тип: сторона, умеющая опознать причину, переводит её сюда один раз, и
/// дальше с ней работает обычный `catch`, не знающий о проводе вовсе.
///
/// [LocalAuthRepository] (`lib/data/auth/local_auth_repository.dart`) этого
/// не бросает никогда: на кассе `terminalId` проверяется в `TillOperations`
/// (`lib/backend/till_operations.dart`) до вызова `login`, и десктопная
/// касса своего терминала не забывает.
class UnknownTerminalException implements Exception {
  const UnknownTerminalException();

  @override
  String toString() =>
      'UnknownTerminalException: терминал, запомненный этим клиентом, '
      'больше не существует на кассе';
}
