import 'package:meta/meta.dart';

import 'package:telepos/domain/sale/payment_service.dart';

/// Кто и как пользуется терминалом. Свойство терминала, а не сборки: один и тот
/// же файл на двух машинах даёт кассира и самообслуживание.
/// См. docs/system-architecture.md, И32.
enum PointMode { cashier, selfService, unattended, kitchen }

/// Рабочее место: экран, руки оператора, свой комплект устройств.
///
/// Устройства терминала больше не поле здесь — раньше это был плоский набор
/// (`printerType`, `printerAddress`, `scannerType`, `scalePort`,
/// `scaleBaudRate`, `drawerViaPrinter`, `displayPort`, `TerminalDevices`),
/// который допускал максимум один принтер одного протокола на терминал.
/// Устройства терминала — это [DeviceBinding]
/// (`lib/domain/terminal/device_binding.dart`), и читаются/пишутся через
/// отдельный контракт, [DeviceBindingRepository]
/// (`lib/domain/terminal/device_binding_repository.dart`) — не метод здесь,
/// потому что `TerminalRepository` уже имеет два биндинга
/// (`LocalTerminalRepository`, `HttpTerminalRepository`), и оба реализуют
/// `implements`, которое не наследует тело метода: новый абстрактный метод
/// здесь сломал бы компиляцию того биндинга, который его ещё не реализует, в
/// файле, которым владеет другая задача. См. доку на
/// `DeviceBindingRepository` для полного обоснования (план 2, задача 4).
@immutable
class Terminal {
  const Terminal({
    required this.id,
    required this.name,
    required this.pointMode,
    this.allowedPaymentTypes = const {},
  });

  final int id;
  final String name;
  final PointMode pointMode;

  /// Виды оплаты, разрешённые **этому** рабочему месту — решение заказчика
  /// №5 задачи 15 плана «Продажа с браузерного терминала»: «планшет у кассы
  /// берёт всё, в зале — только безнал».
  ///
  /// **Пустое множество означает «все», и это не удобство, а требование
  /// миграции.** Колонка появляется в v38 пустой у каждой уже существующей
  /// строки; читай пустое как «ничего нельзя» — и установка, поднявшаяся на
  /// новую версию, перестала бы принимать деньги вовсе. Ровно это
  /// проверяется пробой «терминал, которому видов не назначали, немым не
  /// становится» (`test/backend/payment_types_test.dart`).
  ///
  /// Следствие, названное прямо: «запретить всё» этим полем невозможно.
  /// Рабочее место, которому не положено принимать деньги ни в каком виде,
  /// — это не терминал с пустым набором, а терминал без права `nav.sale`,
  /// и запрещается он правом, а не этим полем.
  ///
  /// **Круг правки 1: до него это обещание было неправдой.** Набор
  /// `{mixed}` собирал именно немое рабочее место — наличные, карта и долг
  /// отбивались по заявленному виду, а сама смешанная по составным частям,
  /// — и собирался он с экрана одним снятием галочки. Обещание стало
  /// верным ровно тогда, когда словарем набора стали **тендеры**
  /// ([tenderPaymentTypes]): какой бы набор оператор ни назначил, в нём
  /// остаётся хотя бы один тендер, а пустой означает «все».
  ///
  /// Множество состоит **только** из [tenderPaymentTypes]; чужое значение
  /// отвергает единственный писатель колонки,
  /// `LocalTerminalRepository.setAllowedPaymentTypes`.
  final Set<PaymentType> allowedPaymentTypes;

  /// Разрешён ли [type] этому рабочему месту.
  ///
  /// Единственный читатель правды о видах оплаты, которому положено ею
  /// пользоваться, — **касса** (`LocalPaymentService`, I44/I162). Экран
  /// вправе спрятать запрещённый вид для удобства кассира, но спрятанная
  /// кнопка запретом не является: отказ приходит от кассы.
  bool allows(PaymentType type) =>
      allowedPaymentTypes.isEmpty || allowedPaymentTypes.contains(type);
}

/// Тендеры — виды оплаты, которыми **можно ограничить рабочее место**.
///
/// Их два: наличные и карта. Это ровно те два способа, которыми рабочее
/// место **берёт деньги**, и ровно то различение, которое назвал заказчик:
/// «планшет у кассы берёт всё, в зале — только безнал».
///
/// # Почему здесь нет `mixed` (круг правки 1)
///
/// Смешанная — не тендер, а **форма**: способ разложить один чек на уже
/// существующие тендеры (`_plan`, `LocalPaymentService`). Пока она стояла в
/// словаре наравне с остальными, набор проверялся дважды с одним множеством,
/// но **разной семантикой** — первая проверка читала `mixed` как тендер,
/// вторая раскладывала его на наличные и карту, — и это дало три измеренных
/// следствия:
///
/// - **набор `{mixed}` делал рабочее место немым**: наличные, карта и долг
///   отбивались первой проверкой, а сама смешанная — второй, по составным
///   частям;
/// - **`{cash, card}` без `mixed` отвергал смешанную**, хотя обе её половины
///   разрешены, — запрет шире названного;
/// - **касса расходилась сама с собой по порядку**: на `{card}` `pay.card`
///   проходила до устройства, а `pay.complete` с `type: mixed` затем
///   отказывала по виду. Карта списана, чек завершить нельзя;
///   этому состоянию в дереве уже дано имя — `card_charge_unsettled`.
///
/// # Почему здесь нет `debt` (круг правки 2)
///
/// Тот же дефект, переехавший на соседнюю галочку, и найден он тем же
/// способом — измерением, а не чтением. Набор `{debt}` собирал рабочее
/// место, которое **не берёт ни одного тенге** ни с кого, кроме заведённого
/// должника с расчётным счётом: наличные, карта и обе смешанные отбивались
/// по виду, долг доходил до `debt_customer_required`, платежей в базе ноль.
/// С экрана это собиралось в два нажатия из умолчания `{card}` — поставить
/// «В долг», снять «Карта», — и сторож «последнюю галочку не снять»
/// пропускал: множество ведь непусто.
///
/// Решение — **убрать долг из словаря, а не запрещать наборы без наличных и
/// карты**, и вот почему из двух возможных выбрано это:
///
/// 1. **Долг уже загорожен**, и своим собственным механизмом:
///    `PermissionKeys.opSellDebt`, который сторож провода читает **по телу
///    кадра** до вызова обработчика (`payExtraPermissions`, `pay_ops.dart`).
///    Набор видов был бы **третьим** способом запретить одно и то же —
///    ровно тот параллельный механизм, которого проект не держит.
/// 2. **Долг уже ограничивается и по месту — существующим механизмом.**
///    Первая редакция этого довода гласила «долг не про место, а про
///    человека», и **дерево ей противоречит**: `PointModePermissions`
///    (`lib/domain/terminal/point_mode_permissions.dart`) снимает
///    `opSellDebt` у режимов `selfService`, `unattended` и `kitchen`, а
///    режим точки — колонка терминала (`Terminals.pointMode`). То есть
///    запрет долга по рабочему месту в продукте **есть**, и работает он
///    сужением прав роли (`PointModePermissions.effective`). Набор видов
///    стал бы **вторым** запретом по месту поверх него — и тогда один и тот
///    же вопрос «продаёт ли это место в долг» имел бы два разных ответа в
///    двух разных таблицах.
///
///    **Насколько именно есть — сказано точно, а не шире дерева.** Запрет
///    по месту **частичный**: у кассирского режима набор запретов пустой
///    (`_denied[PointMode.cashier] == {}`), а остальные три снимают долг
///    **в связке ещё с полутора десятками прав** — возвраты, настройки,
///    отчёты, инкассация, правка цены. То есть запретить долг на
///    **кассирском** рабочем месте, ничего больше не отнимая, сегодня
///    нельзя. Это не довод в пользу галочки: понадобится такой запрет —
///    его место рядом с существующим механизмом режима точки, а не во
///    втором механизме поверх него.
/// 3. **Немоту это закрывает структурно, без второго правила.** Словарь из
///    двух элементов: любое непустое подмножество содержит тендер, которым
///    деньги действительно берут. Вариант «долг оставить, но запретить
///    набор без наличных и карты» потребовал бы отдельного инварианта,
///    который пришлось бы объяснять и повторять на экране.
///
/// **Следствие названо прямо, а не спрятано:** рабочее место с `{card}`
/// по-прежнему может продать в долг, если у кассира есть `op.sellDebt`. Это
/// то же поведение, что было до задачи 15, — она его не сужает. Кому долг в
/// зале не нужен, снимает право у тех, кто там работает; захочется запрещать
/// долг по месту — это отдельное решение со своей спекой, а не галочка,
/// молча дублирующая право.
const tenderPaymentTypes = <PaymentType>{PaymentType.cash, PaymentType.card};

/// Имеет ли смысл **предлагать** кассиру вид [type] на рабочем месте с
/// набором [allowed] — задача 15, «селектор читает разрешения места».
///
/// # Это не второй запрет, а перевод первого на язык экрана
///
/// Запрет один и живёт у кассы (`LocalPaymentService._requireAllowedTypes`,
/// I162); эта функция ничего не запрещает и никем не вызывается на пути
/// денег. Она отвечает на вопрос экрана: «если кассир нажмёт эту кнопку и
/// доведёт дело до «Оплатить», касса откажет?» — чтобы кассир не набирал
/// сумму наличными на планшете «только безнал» и не узнавал об этом
/// последним действием.
///
/// # Почему не хватило [Terminal.allows]
///
/// `allows` отвечает на вопрос кассы про **один** вид, и `mixed` для неё
/// вид как вид. Но касса смешанную по виду не проверяет вовсе: `_plan`
/// раскладывает её на наличную и безналичную половины и спрашивает
/// `_requireAllowedTypes` про **каждую посчитанную половину**. Значит
/// «смешанная разрешена» на языке экрана — это «разрешены оба тендера», и
/// вывести это из `allows(mixed)` нельзя: на наборе `{card}` он даёт
/// `false`, хотя смешанная с нулевой наличной половиной проходит, а на
/// наборе `{cash, card}` — `false` же, хотя проходит любая. Оба ответа
/// неверны для экрана, и оба верны для кассы: вопросы разные.
///
/// # Долг здесь всегда предлагается
///
/// Набор видов долга не сторожит — его сторожит право `op.sellDebt`, и
/// [tenderPaymentTypes] не содержит `debt` намеренно (разбор там же).
/// Гасить кнопку долга по набору значило бы завести на экране запрет,
/// которого нет у кассы, — то есть соврать в другую сторону.
bool paymentTypeOfferable(Set<PaymentType> allowed, PaymentType type) {
  // Пустое означает «все» — то же правило, что у [Terminal.allows], и
  // читается оно здесь, а не переписывается: ветка ниже на пустом наборе
  // дала бы «ничего не предлагать», то есть ровно обратное.
  if (allowed.isEmpty) return true;
  return switch (type) {
    PaymentType.cash || PaymentType.card => allowed.contains(type),
    PaymentType.mixed =>
      allowed.contains(PaymentType.cash) && allowed.contains(PaymentType.card),
    // Долг и рассрочка набором не сторожатся — их сторожит право
    // `op.sellDebt` и тумблер кассы `sellInDebt`. Гасить их кнопки по
    // набору значило бы завести на экране запрет, которого нет у кассы,
    // — то есть соврать в другую сторону.
    PaymentType.debt || PaymentType.installment => true,
  };
}

/// Имена видов оплаты в порядке [PaymentType.values] — **канонический**
/// вид набора для хранения и для провода.
///
/// Порядок фиксирован перечислением, а не порядком множества: два одинаковых
/// набора обязаны давать одну и ту же строку, иначе сравнение хранимого
/// значения (и всякая сверка «изменилось ли») зависело бы от того, в каком
/// порядке кассир нажимал галочки.
List<String> paymentTypeNames(Set<PaymentType> types) => [
  for (final type in PaymentType.values)
    if (types.contains(type)) type.name,
];

/// Читает набор видов оплаты из имён — обратная [paymentTypeNames].
///
/// **Незнакомое имя — отказ, а не «выбросить и жить дальше».** Это то же
/// правило, по которому `LocalTerminalRepository._pointModeFromStored`
/// отказывается угадывать режим, но здесь у него есть вторая, более
/// острая причина, чем осторожность: пустое множество означает «все». Набор
/// `{вид, которого эта версия не знает}` при молчаливом выбрасывании
/// превратился бы в **пустой**, то есть в разрешение на всё — включая
/// ровно то, что этому терминалу запрещали. Сужение прав на непонятном
/// входе здесь недостижимо структурно; выбор стоит между отказом и
/// молчаливым расширением, и отказ — единственный честный.
Set<PaymentType> paymentTypesFromNames(
  Iterable<String> names, {
  required int terminalId,
}) {
  final result = <PaymentType>{};
  for (final name in names) {
    final type = PaymentType.byWireName(name);
    if (type == null) {
      throw StateError(
        'Терминал #$terminalId несёт вид оплаты "$name", которого не знает '
        'PaymentType.values '
        '(${PaymentType.values.map((t) => t.name).join(', ')}). Похоже, '
        'запись сделала более новая версия. Отказываюсь выбрасывать его '
        'молча: пустой набор означает «все виды», и незнакомое имя '
        'превратилось бы в разрешение вместо запрета.',
      );
    }
    result.add(type);
  }
  return result;
}
