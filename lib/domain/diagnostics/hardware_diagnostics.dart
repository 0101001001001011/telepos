/// Какой вызов породил строку на дисплее.
///
/// Свой перечень по тому же доводу, что [DrawerKickPath]: кассовый
/// `CustomerDisplayCall` живёт в `lib/hardware/`, а подпись вкладка
/// переводит.
enum DisplayCallKind { price, total, text, welcome, change, clear }

/// Одна строка, отправленная на дисплей покупателя.
class DisplayLineDiagnostics {
  const DisplayLineDiagnostics({
    required this.at,
    required this.kind,
    required this.text,
    this.refusal,
  });

  final DateTime at;

  final DisplayCallKind kind;

  /// То, что кассе полагалось показать, — **той же записью, что ушла в
  /// порт**.
  ///
  /// Сумму форматирует касса (`CustomerDisplayJournal`, `toStringAsFixed(2)`
  /// как в `BaseDisplayManager.formatAmount`), а не вкладка. Вкладка,
  /// форматирующая сумму сама, стала бы второй раскладкой строки дисплея —
  /// и первая редакция журнала на этом уже обожглась, показывая «1250» там,
  /// где на стекле «1250.00».
  final String text;

  /// Почему отправка не удалась, дословно, либо `null`.
  final String? refusal;

  bool get accepted => refusal == null;
}

/// Что касса отправляла на дисплей покупателя.
class DisplayDiagnosticsView {
  const DisplayDiagnosticsView({
    required this.available,
    required this.lines,
    this.current,
  });

  /// Память о строках на этой кассе есть вовсе — см.
  /// [DrawerDiagnosticsView.available].
  final bool available;

  /// Строки, новые первыми.
  final List<DisplayLineDiagnostics> lines;

  /// Что на стекле **сейчас** — последняя принятая строка.
  ///
  /// # Почему полем, а не вычислением во вкладке
  ///
  /// «Последняя принятая» — это правило, и живёт оно **одно**, в
  /// `CustomerDisplayJournal.current`. Вычисли его вкладка обходом [lines],
  /// правило оказалось бы в двух местах, и разошлись бы они в тот день, когда
  /// журнал начнёт считать текущей, скажем, любую строку, включая отказанную.
  ///
  /// `null` — на стекле нет ничего, что касса признала бы ушедшим: строк не
  /// было вовсе либо все до одной отказаны.
  final DisplayLineDiagnostics? current;
}

// --- Весы -----------------------------------------------------------------

/// Что прибор сказал о показании.
///
/// Четыре значения, а не три кассовых: к `stable`/`unstable`/`overload`
/// добавлено [failed]. Кассовый `ScalesReading` держит беду **отдельным**
/// полем `errorMessage` поверх статуса, и вкладке приходилось разбирать это
/// сочетание самой — четыре ветви в `switch`-е по объекту. Здесь сочетание
/// уже разобрано кассой, в том же порядке приоритета, в каком вкладка
/// разбирала его раньше: зашкал **вперёд** беды и вперёд устойчивости, потому
/// что перегруженные весы умеют присылать «стабильно», и слово «стабильно» на
/// зашкале — прямая неправда.
enum ScalesReadingStatus { stable, unstable, overload, failed }

/// Одно показание весов глазами диагностики.
class ScalesReadingDiagnostics {
  const ScalesReadingDiagnostics({
    required this.weight,
    required this.unit,
    required this.status,
    this.errorMessage,
  });

  /// Вес **готовой строкой с тремя знаками**, а не числом.
  ///
  /// # Почему не `Decimal` и не `double`
  ///
  /// Потому что три знака — это разрешение прибора, и теряется оно молча.
  /// `Decimal` печатает 1.250 как «1.25»: вкладка, зовущая `toString`,
  /// показала бы граммы килограммовых весов короче, чем их прислали. Правило
  /// «три знака» живёт **у кассы** — там же, где `ScalesReading.toString`, —
  /// и второго форматировщика на планшете нет вовсе.
  ///
  /// Это то же решение, что у текста чека и тела запроса к оператору: по
  /// проводу едет готовое значение, а не сырьё, потому что второй разбор —
  /// второй ответ, и расходятся они молча.
  final String weight;

  /// Единица, **как её назвал прибор** (`kg`, `g`, `lb`).
  ///
  /// Строкой, а не перечнем, и в отличие от [DrawerKickPath] это осознанно:
  /// вкладка единицу **не переводит** — показывает как есть, потому что `kg`
  /// на весах написано латиницей на любом языке кассы.
  final String unit;

  final ScalesReadingStatus status;

  /// Что именно сказала касса, когда показания получить не удалось.
  ///
  /// Не `null` ровно при [ScalesReadingStatus.failed]: «весы молчат» и «весы
  /// прислали мусор» разбираются разными действиями, и общее слово «ошибка»
  /// не разбирает ни одну жалобу.
  final String? errorMessage;
}

/// Что показывают весы.
class ScalesDiagnosticsView {
  const ScalesDiagnosticsView({
    required this.bound,
    this.port,
    this.baudRate = 0,
    this.protocol = '',
    this.connected = false,
    this.reading,
  });

  /// Весы к этой кассе привязаны вовсе.
  ///
  /// Отдельно от `reading == null` **обязательно**: пустое поле на кассе без
  /// весов неотличимо от весов, молчащих из-за оборванного провода, — ровно
  /// тот случай, когда пустота отвечает «ничего нет» на два противоположных
  /// вопроса.
  final bool bound;

  /// Порт, скорость и говор — то, по чему наладчик проверяет привязку.
  final String? port;
  final int baudRate;
  final String protocol;

  /// Порт открыт. Не «весы исправны»: открытый порт молчащих весов выглядит
  /// точно так же.
  final bool connected;

  /// Последнее показание, либо `null` — прибор не прислал ещё ничего.
  final ScalesReadingDiagnostics? reading;
}

/// Что вкладки диагностики знают о кассе.
///
/// Две реализации: `LocalHardwareDiagnostics` на кассе и
/// `WtHardwareDiagnostics` по проводу. Вкладка не различает их ничем — в
/// этом и смысл того, что вкладка одна.
abstract interface class HardwareDiagnosticsRepository {
  /// Задания печати — сейчас и при каждом изменении.
  ///
  /// **Подписка, а не вопрос**, и это не украшение: наладчик держит вкладку
  /// открытой и печатает пробный чек с другого экрана. Вопрос был бы верен
  /// ровно в миг постройки экрана, и пробный чек не появился бы на нём
  /// вовсе — то есть вкладка отвечала бы «касса ничего не печатала» сразу
  /// после печати.
  ///
  /// Рабочего места доводом нет намеренно. Вопрос, на который отвечает эта
  /// вкладка, — «что отправила **эта касса**», и решает это касса по себе
  /// (`TerminalRepository.self`). Прими метод чужой `terminalId` с планшета,
  /// вкладка читала бы чеки соседнего рабочего места (И29: у задания есть
  /// владелец — терминал и касса), и право `settings.hardware` этого не
  /// закрывает: оно про настройку своего оборудования, а не про чужие чеки.
  Stream<PrinterDiagnosticsView> watchPrinter();

  /// Обмен с фискальным оператором — снимок на момент вопроса.
  ///
  /// **Вопрос, а не подписка**, и это решение: у очереди фискализации нет
  /// сигнала изменения, который касса уже держит (у заданий печати он есть —
  /// `PrintQueue.watch`). Завести его значило бы построить подписку ради
  /// экрана, который наладчик и так обновляет потягиванием вниз, — вкладка
  /// кассы устроена именно так с первого дня.
  Future<FiscalDiagnosticsView> fiscal();

  /// Импульсы денежного ящика — сейчас и при каждом новом.
  ///
  /// **Подписка, а не вопрос**, и довод ровно тот же, что у принтера, вплоть
  /// до сценария: наладчик держит вкладку открытой и жмёт «Открыть ящик» с
  /// соседнего экрана — или просит кассира пробить чек. Вопрос был бы верен в
  /// миг постройки экрана, то есть вкладка отвечала бы «ящик не звали» сразу
  /// после того, как его позвали.
  ///
  /// Сигнал у кассы уже есть — `CashDrawerJournal.watch()`, — и строить под
  /// эту подписку ничего не пришлось: тем и отличается от фискальной очереди,
  /// где сигнала нет и подписку пришлось бы **заводить ради экрана**.
  ///
  /// # Почему здесь нет даже `TerminalRepository.self`
  ///
  /// Тело у операции пустое по тому же запрету, что у [watchPrinter]: чьи
  /// данные показывать, планшет не называет. Но у заданий печати касса
  /// **выбирает** рабочее место (`self()`), а здесь выбирать не из чего:
  /// журнал ящика один на процесс кассы, а не на стойку. Прибор физически
  /// один, и делить его по рабочим местам было бы выдумкой — И29 тут
  /// выполняется самим устройством памяти, а не отбором.
  ///
  /// То же верно для [watchDisplay] и [watchScales].
  Stream<DrawerDiagnosticsView> watchDrawer();

  /// Строки дисплея покупателя — сейчас и при каждой новой.
  ///
  /// **Подписка**, тем же доводом: наладчик пробивает товар на кассе и
  /// смотрит на планшет — строка обязана появиться в момент отправки.
  /// Сигнал есть готовый (`CustomerDisplayJournal.watch()`).
  Stream<DisplayDiagnosticsView> watchDisplay();

  /// Показание весов — живьём, **прореженное кассой**.
  ///
  /// # Решение о частоте кадров, и почему именно такое
  ///
  /// Весы — единственный из трёх приборов, у которого данные не события, а
  /// **поток**: `ScalesService` опрашивает порт каждые 200 мс и шлёт
  /// показание на каждую разобранную строку. Гнать это на планшет как есть
  /// значило бы держать поток ради вкладки, которую смотрят минуту.
  ///
  /// Рассматривались три устройства, и два отпали по существу:
  ///
  /// 1. **вопрос по требованию** — неверен по предмету. Вкладка весов
  ///    существует ровно затем, чтобы наладчик положил груз на чашу и увидел,
  ///    как число **едет**: так проверяют и живые весы, и эмулятор, где вес
  ///    задают его пультом. Вопрос показал бы одно застывшее число, а «ещё
  ///    раз» наладчик жал бы вместо того, чтобы смотреть на чашу;
  /// 2. **подписка только пока вкладка открыта** — не отдельный выбор, а
  ///    описание того, чем подписка и является. Поток провода живёт ровно
  ///    столько, сколько на него подписан экран: закрытая вкладка снимает
  ///    подписку, касса закрывает поток. Выбирать тут нечего, и записывать
  ///    это как решение значило бы выдать устройство провода за свою заслугу;
  /// 3. **подписка с прореживанием — взято.** Прореживает **касса**, до
  ///    провода, двумя правилами сразу:
  ///
  ///    - **не повторяться.** Показание, неотличимое от предыдущего на
  ///      экране, кадром не становится. Это главный выигрыш, а не
  ///      второстепенный: весы с неподвижным грузом шлют одно и то же
  ///      значение по нескольку раз в секунду **бесконечно**, и без этого
  ///      правила простаивающая вкладка стоила бы столько же, сколько
  ///      работающая. С ним простой стоит ноль кадров;
  ///    - **не чаще предела.** Пока идёт взвешивание, кадры режутся окном
  ///      (`LocalHardwareDiagnostics.scalesFrameInterval`): первый уходит
  ///      сразу, остальные — не чаще одного в окно. Человек всё равно не
  ///      читает число быстрее, а сеть на планшете бывает хуже проводной.
  ///
  ///    Прореживание **хвостовое**: последнее показание окна уходит всегда,
  ///    даже если после него прибор замолчал. Это не украшение, а то, ради
  ///    чего вкладка нужна: последнее показание — это **установившийся вес**,
  ///    то самое число, по которому продают товар. Отбрось его прореживание,
  ///    вкладка показывала бы предпоследний вес и называла его устоявшимся.
  ///
  /// # Чего этот поток НЕ доказывает
  ///
  /// Что весы верны. Касса показывает то, что прибор о себе сообщил;
  /// поверка — дело поверителя. И **частоту прибора он тоже не показывает**:
  /// кадры прорежены, и считать по ним, как часто отвечают весы, нельзя.
  Stream<ScalesDiagnosticsView> watchScales();
}

