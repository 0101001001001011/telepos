/// Каким путём шла команда открыть ящик.
///
/// **Свой перечень, а не `CashDrawerPath` из `lib/hardware/`**, и это то же
/// решение, что у всего файла: `lib/hardware/` в браузерную сборку не
/// собирается вовсе (сторож `browser_routes_test`, `_forbiddenWebRoots`).
///
/// # Почему перечнем, а не именем-строкой, как `opType` у оператора
///
/// Разница в том, **кто читает значение**. Род фискальной операции вкладка
/// показывает как есть — строка годится. Путь ящика вкладка **переводит**:
/// «последовательный порт» и «через принтер» — слова из словаря, и казахский
/// наладчик обязан прочитать их по-казахски. Со строкой перевод пришлось бы
/// выбирать `switch`-ем по тексту с `default`, а `default` здесь — это
/// молчаливая подстановка неверного пути при первом же новом значении.
///
/// Перевод из кассового перечня делает **исчерпывающий** `switch` в
/// `LocalHardwareDiagnostics`: добавь кто-нибудь третий путь ящика, этот файл
/// не соберётся, и узнается это на сборке, а не на стекле у наладчика.
enum DrawerKickPath {
  /// Отдельный ящик на последовательном порту.
  serialPort,

  /// `ESC p` через чековый принтер.
  viaPrinter,
}

/// Одна попытка открыть ящик глазами диагностики.
///
/// # «Команда принята» — не «ящик открыт»
///
/// Поле называется [accepted] намеренно. Обратной связи от соленоида нет ни
/// на одном из двух путей: успехом считается «байты ушли и порт не отказал».
/// Порт, назвавший это `opened`, соврал бы **в определении типа**, и вкладке
/// пришлось бы знать, что верить ему нельзя.
class DrawerKickDiagnostics {
  const DrawerKickDiagnostics({
    required this.at,
    required this.path,
    required this.accepted,
    this.note,
  });

  final DateTime at;

  final DrawerKickPath path;

  /// Приняли ли байты к отправке без отказа — и **только это**.
  final bool accepted;

  /// Причина отказа или пояснение к запасному пути, дословно.
  final String? note;
}

/// Что касса отправляла в денежный ящик.
class DrawerDiagnosticsView {
  const DrawerDiagnosticsView({required this.available, required this.kicks});

  /// Память об импульсах на этой кассе есть вовсе.
  ///
  /// Различать это и пустой список обязательно, тем же доводом, что у
  /// [PrinterDiagnosticsView.available]: «ящик ни разу не звали» и «спросить
  /// нечем» — для наладчика разные ответы, и на первом он пошёл бы искать
  /// обрыв в проводке ящика, который исправен.
  final bool available;

  /// Попытки, новые первыми. Порядок задаёт **касса** (`CashDrawerJournal
  /// .recent`), а не вкладка: обе поверхности обязаны показывать один.
  final List<DrawerKickDiagnostics> kicks;
}

