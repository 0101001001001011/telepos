/// Диагностика оборудования как **порт**, а не как экран поверх `GetIt`
/// кассы — пункт «Достижимость с браузерного терминала» плана
/// `docs/internal/superpowers/plans/2026-09-19-hardware-diagnostics.md` и
/// решение заказчика 2026-09-18, дословно: «в браузере должно работать то
/// же, что в приложении».
///
/// # Чего до этого файла не было
///
/// Вкладки диагностики читали кассу **напрямую**: `PrintQueue`,
/// `ReceiptPrintService`, `AppDatabase.webkassaReceiptDao`,
/// `FiscalQueueStore`. Три из четырёх живут в `lib/data/` и `lib/hardware/`,
/// то есть в браузерную сборку не собираются вовсе (сторож
/// `browser_routes_test`, `_forbiddenWebRoots`). Наладчик, у которого вместо
/// кассы планшет, не мог увидеть ни одного байта, ушедшего в принтер, и ни
/// одного тела запроса к оператору фискализации.
///
/// Сегодня эти четыре развилки вписаны в
/// `test/architecture/presentation_is_registered_test.dart` словами «на
/// планшете вкладка говорит, что показывать нечем». Порт их закрывает: у
/// вкладки остаётся **один** договор, и у него две реализации —
/// `LocalHardwareDiagnostics` на кассе и `WtHardwareDiagnostics` по проводу.
///
/// # Главное свойство: чек разбирает КАССА, и разборщик остаётся один
///
/// [PrintJobDiagnostics.text] приезжает **готовой строкой**, а не байтами.
/// Это не экономия кадра, а то же решение и тот же довод, что у
/// предпросмотра шаблона (докстринг
/// `lib/domain/receipt/receipt_template_setup.dart`):
///
/// 1. **касса шлёт байты, вкладка разбирает их сама.** `renderEscPosAsText`
///    живёт в `lib/hardware/`, которого в браузере быть не может, — файл
///    пришлось бы переселить. А главное: разбор стал бы **вторым местом в
///    дереве, где рождается текст чека на экране**. Ровно того рода, из-за
///    которого копии раскладки уже разошлись однажды и предпросмотр
///    показывал не то, что выходило из принтера (докстринг
///    `escpos_text_preview.dart`);
/// 2. **касса разбирает своей же единственной функцией и шлёт текст.**
///    Вкладка не знает о чеке ничего — ни ширины ленты, ни выравнивания, ни
///    кодовой страницы. Раскладка остаётся **одна на всё дерево**, и держится
///    это не бдительностью, а тем, что во второй половине её нет вовсе.
///
/// Взято второе. Тем же правилом едет и тело запроса к оператору
/// ([FiscalQueuedDocument.payloadJson]): касса форматирует его **как есть**,
/// с отступами, и вкладка показывает строку. Второй форматировщик JSON во
/// вкладке разошёлся бы с первым ровно там, где этот текст сверяют с тем,
/// что ждёт оператор.
///
/// # Ни одного типа из `lib/data/` здесь нет, и это обязательное свойство
///
/// `FiscalQueueStatus`, `FiscalQueueOp`, `WebkassaReceipt` живут в
/// `lib/data/` и в браузерную сборку не собираются. Поэтому род операции
/// едет **именем** ([FiscalQueuedDocument.opType] — `String`), а отказ —
/// признаком ([FiscalQueuedDocument.failed]), а не перечислением. Возьми
/// порт хоть один тип оттуда, вкладка перестала бы собираться в браузере — и
/// узнали бы об этом не здесь, а на `flutter build web`.
///
/// Исключение ровно одно: [PrintJobState] из `lib/domain/print/print_job
/// .dart` — он чистый Dart (`dart:typed_data` и `package:meta`), живёт в
/// домене и в браузере собирается.
///
/// # Чего этот порт НЕ доказывает
///
/// Что чек вышел на бумаге и что ящик открылся. Он возит **то, что кассе
/// известно**: байты, ушедшие в порт, состояние задания в очереди, тело
/// запроса к оператору и его ответ. Соленоида ящика и бумаги в лотке касса
/// не видит ни в каком режиме, и порт, делающий вид, что видит, был бы хуже
/// молчания.
///
/// Не доказывает он и того, что **за портом принтера стоит эмулятор**:
/// плашка на кассовом экране считается по адресу привязки прибора
/// (`diagnostics_screen.dart`), и по проводу она сегодня не едет. Завести её
/// вторым вычислением здесь значило бы получить два источника правды об
/// одном; названо в отчёте как оставшееся.
library;

import 'package:telepos/domain/print/print_job.dart';

/// Одно задание печати глазами диагностики.
///
/// Сокращение [PrintJob], а не он сам, и это решение: задание несёт
/// `payloadBytes` — весь поток ESC/POS, — а везти по проводу байты значило бы
/// отдать вкладке разбор (см. докстринг файла). Здесь вместо байтов [text],
/// уже разобранный кассой.
class PrintJobDiagnostics {
  const PrintJobDiagnostics({
    required this.id,
    required this.state,
    required this.attempts,
    required this.createdAt,
    required this.text,
    this.failureReason,
  });

  /// Идентификатор задания, как его задал вызывающий (`PrintJob.id`).
  final String id;

  final PrintJobState state;

  final int attempts;

  /// Когда задание попало в очередь. Порядок показа задаёт **реализация**, а
  /// не вкладка: обе поверхности обязаны показывать один и тот же порядок,
  /// а сортировка на экране была бы вторым местом, где он решается.
  final DateTime createdAt;

  /// Чек текстом — **разбор тех самых байтов**, которые ушли (или уйдут) в
  /// порт, сделанный единственным разборщиком дерева.
  final String text;

  /// Почему не напечаталось — дословно, как сказал драйвер.
  ///
  /// `null` — причины нет, а не «причина неизвестна»: задание, которое ждёт
  /// очереди или уже напечаталось, причины отказа не имеет вовсе.
  final String? failureReason;
}

/// Что касса отправила в чековый принтер.
class PrinterDiagnosticsView {
  const PrinterDiagnosticsView({required this.available, required this.jobs});

  /// Очередь печати на этой кассе есть вовсе.
  ///
  /// Различать это и пустой список **обязательно**: «касса пока ничего не
  /// печатала» и «печатать нечем» для наладчика разные ответы, а пустой
  /// список неотличим от первого. Тот же довод, что у [FiscalDiagnosticsView
  /// .configured].
  final bool available;

  /// Задания, новые первыми.
  final List<PrintJobDiagnostics> jobs;
}

/// Документ, который фискальный оператор **принял**.
///
/// Это доказательство работы, а не отсутствия беды: очередь держит только
/// то, что не уехало, и на исправной кассе пуста — пустота эта неотличима от
/// «оператор не настроен вовсе».
class FiscalAcceptedDocument {
  const FiscalAcceptedDocument({
    required this.fiscalNo,
    required this.operatorReceiptNo,
    required this.receiptNo,
    required this.offline,
  });

  /// Фискальный признак. `null` — признака нет, и это видно словами.
  final String? fiscalNo;

  /// Номер документа у оператора — то, по чему документ ищут в его кабинете.
  final String? operatorReceiptNo;

  /// Номер чека кассы.
  final String? receiptNo;

  /// Признак выдан **автономно** — кассой по правилам оператора, а не самим
  /// оператором. Названо отдельным полем, потому что это разные вещи, и
  /// наладчик обязан их различать.
  final bool offline;
}

/// Строка очереди фискализации: чем отправляли, сколько раз и чем кончилось.
class FiscalQueuedDocument {
  const FiscalQueuedDocument({
    required this.idempotencyKey,
    required this.opType,
    required this.attempts,
    required this.failed,
    required this.payloadJson,
    this.lastError,
  });

  final String idempotencyKey;

  /// Род операции **именем** (`FiscalQueueOp.name`), а не перечислением:
  /// перечисление живёт в `lib/data/`, которого в браузере нет (докстринг
  /// файла).
  final String opType;

  final int attempts;

  /// Строка отказана окончательно (`FiscalQueueStatus.failed`).
  ///
  /// Признаком, а не статусом целиком: вкладка различает ровно это — красить
  /// строку или нет, — и полный перечень статусов ей не нужен ни для чего.
  final bool failed;

  /// Тело запроса **как есть**, с отступами, как его отформатировала касса.
  ///
  /// Диагностика фискального обмена — это сверка с тем, что ждёт оператор, и
  /// приглаженное представление здесь врёт ровно там, где его читают. Именно
  /// этого просил заказчик 2026-09-19 — «подробные данные по ОФД-передаче».
  final String payloadJson;

  /// Последняя ошибка оператора, дословно.
  final String? lastError;
}

/// Что касса передала фискальному оператору и что он ответил.
class FiscalDiagnosticsView {
  const FiscalDiagnosticsView({
    required this.configured,
    required this.accepted,
    required this.queued,
    this.onLoopback = false,
  });

  /// Фискальный оператор на этой кассе настроен вовсе.
  ///
  /// Пустые списки на ненастроенной кассе выглядели бы исправной кассой без
  /// документов — то же различение, что у [PrinterDiagnosticsView.available].
  final bool configured;

  /// Принятые документы, новые первыми.
  final List<FiscalAcceptedDocument> accepted;

  /// Ожидающие и отказанные строки очереди.
  final List<FiscalQueuedDocument> queued;

  /// Адрес оператора ведёт на **этот же компьютер** — значит за ним эмулятор.
  ///
  /// # Почему признак считает касса, а не вкладка
  ///
  /// Вкладка одна на обе поверхности: на кассе и на планшете. Разбор адреса
  /// требует `dart:io`, которого в браузерной сборке нет вовсе — измерено при
  /// сведении 2026-09-19: занесённый во вкладку `import 'dart:io'` уронил три
  /// сторожа браузерной таблицы разом, и веб перестал собираться.
  ///
  /// Но дело не только в сборке. Тот же довод, по которому касса присылает
  /// **готовый текст** чека, а не байты: второй разбор — второй ответ, и
  /// расходятся они молча. Адрес оператора знает касса; вкладка показывает
  /// то, что ей сказали.
  ///
  /// `false`, если касса промолчала: «не знаю» и «за адресом эмулятор» —
  /// разные ответы, и врать вторым вместо первого хуже, чем промолчать.
  final bool onLoopback;
}

