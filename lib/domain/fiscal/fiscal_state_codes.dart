/// Стабильные числа [FiscalState] для базы — объявленные **отдельно от
/// порядка членов**.
///
/// # Зачем это, если у перечисления уже есть `index`
///
/// Потому что `index` — это не число состояния, а его место в списке.
/// Задача 5 вставила в [FiscalState] два новых члена **в середину**
/// ([FiscalState.operatorAbsent] и [FiscalState.fiscalModuleAbsent]), и
/// два потребителя повели себя по-разному:
///
/// * **Провод пережил.** `pay_ops.dart` перебирает `FiscalState.values` и
///   сверяет по **имени** (`state.name == name`) — измерено чтением, а не
///   предположено. Новые слова поехали сами.
/// * **База не пережила бы.** Колонка `Sales.fiscalState` (задача 14)
///   хранит число. Храни она `index`, каждая уже записанная строка после
///   релиза молча сменила бы смысл: `done` стало бы `operatorAbsent`,
///   `failed` — `queued`. Ни один запрос не упал бы; соврал бы отчёт.
///
/// Поэтому число объявлено картой ниже. Перестановка членов его не
/// двигает — в этом весь смысл. Добавление члена без кода роняет сторожа
/// `test/domain/fiscal/fiscal_state_codes_test.dart`, а не тихо получает
/// чужое число.
///
/// # Почему `0` — это «не спрашивали», а не `notRequired`
///
/// Потому что это разные утверждения. «Документ не был нужен» — ответ на
/// вопрос; «поле не заполняли» — отсутствие вопроса. Платёжный черновик
/// путал их ровно потому, что `notRequired` стоит в перечислении первым и
/// `index` у него `0`: строка со значением по умолчанию читалась как
/// осмысленное «документ не требовался». Здесь `0` не занят ни одним
/// живым состоянием, и [fromCode] на нём возвращает `null`, а не догадку.
library;

import 'package:telepos/domain/sale/payment_service.dart';

/// Соответствие «состояние ↔ стабильное число».
abstract final class FiscalStateCodes {
  /// «Не спрашивали»: поля нет, оно не заполнено, или число незнакомо.
  ///
  /// **Не совпадает ни с одним живым состоянием** — это закреплено
  /// сторожем и является требованием, а не совпадением.
  static const int unknown = 0;

  /// Числа перечислены здесь и **только здесь**. Порядок строк в этой
  /// карте ни на что не влияет: ключ — член, а не позиция.
  ///
  /// Число, однажды выданное члену, не меняется никогда: в базе уже лежат
  /// строки, написанные им. Удалённый член освобождает своё число
  /// навсегда — переиспользовать его нельзя по той же причине.
  static const Map<FiscalState, int> _codes = {
    FiscalState.notRequired: 1,
    FiscalState.operatorAbsent: 2,
    FiscalState.fiscalModuleAbsent: 3,
    FiscalState.done: 4,
    FiscalState.queued: 5,
    FiscalState.failed: 6,
    FiscalState.unchanged: 7,
  };

  /// Число, которым состояние ложится в базу.
  ///
  /// Бросает, если члену не выдали кода. Это выбор: молчаливое
  /// [unknown] означало бы записывать в колонку «не спрашивали» вместо
  /// настоящего ответа — второй раз соврать в ту же сторону. Сторож
  /// ловит такое до релиза, перебирая `FiscalState.values`.
  static int of(FiscalState state) {
    final code = _codes[state];
    if (code == null) {
      throw StateError(
        'FiscalState.${state.name} не имеет стабильного кода. '
        'Добавьте его в FiscalStateCodes._codes новым числом — '
        'не переиспользуя ни одно уже выданное.',
      );
    }
    return code;
  }

  /// Состояние по числу из базы, либо `null`.
  ///
  /// `null` — честный ответ и на [unknown], и на число, записанное
  /// будущей версией: догадываться о смысле чужого числа касса не имеет
  /// права.
  static FiscalState? fromCode(int code) {
    for (final entry in _codes.entries) {
      if (entry.value == code) return entry.key;
    }
    return null;
  }
}
