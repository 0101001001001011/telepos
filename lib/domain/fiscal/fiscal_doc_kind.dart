/// **Род фискального документа** — то, чего у строки `webkassa_receipts`
/// не было, и из-за чего строки затирали друг друга.
///
/// # Находка, ради которой род заведён (замер 2026-09-19)
///
/// Первичным ключом таблицы был **один** `operation_id`, а номера в него
/// клали три разные последовательности:
///
/// * продажа — `Sales.receiptNo`, счётчик чеков кассы;
/// * возврат — `Refunds.localId`, автоинкремент своей таблицы;
/// * аванс — `CashOperations.id`, автоинкремент третьей таблицы.
///
/// Совпадение номеров не редкость, а **правило на новой кассе**: у первой
/// продажи номер 1, у первого возврата 1, у первого аванса 1. Замер
/// показал ровно это: вторая вставка падает
/// `UNIQUE constraint failed: webkassa_receipts.operation_id`, а
/// `FiscalServiceImpl._persistReceipt` глотает падение в `catch` строкой
/// журнала. То есть документ у оператора есть, а у кассы записи о нём нет
/// — и это **сегодняшнее** поведение для пары «продажа №N и возврат №N»,
/// ещё до всякого аванса.
///
/// Поэтому ключ строки — пара `(operationId, docKind)`, а не число.
/// Добавлять аванс в таблицу без рода значило бы починить одну дыру,
/// расширив другую: чек аванса №1 затирался бы продажей №1 молча.
///
/// # Почему это НЕ `isSale`
///
/// Колонка `isSale` в таблице есть и остаётся — её читают печать
/// реквизитов, обмен и сборка чека. Но она отвечает на другой вопрос:
/// «приход это или возврат». Продажа и приём аванса обе `true`, возврат
/// товара и выдача аванса обе `false` — то есть ключом она быть не может
/// ни в каком сочетании.
///
/// # Чего этот род НЕ доказывает
///
/// Он не делает номера сквозными: два документа разного рода по-прежнему
/// могут нести один номер, и это нормально — их различает пара. Он не
/// чинит и уже записанную историю: строки, потерянные до v50 из-за
/// столкновения, восстановить не из чего (документ уехал оператору, а
/// локальной записи не осталось вовсе).
///
/// Индекс члена лежит на диске (`webkassa_receipts.doc_kind`): новые
/// члены — **только в конец**.
library;

enum FiscalDocKind {
  /// Чек продажи. Номер — `Sales.receiptNo`.
  sale,

  /// Чек возврата товара. Номер — `Refunds.localId`.
  refund,

  /// Чек **приёма** аванса. Номер — `CashOperations.id`.
  prepayment,

  /// Чек **выдачи** аванса деньгами. Номер — `CashOperations.id` той
  /// проводки, которой деньги вышли из кассы.
  prepaymentRefund;

  /// Приход ли это для кассы — то, что хранит колонка `is_sale`.
  ///
  /// Выводится родом, а не пишется вторым решением: два поля об одном
  /// разойдутся в первую же правку.
  bool get isSale =>
      this == FiscalDocKind.sale || this == FiscalDocKind.prepayment;

  /// Умолчание для строк старше v50 и для чужих сборок.
  ///
  /// Незнакомое число — **не бросок**: строка приехала от кассы более
  /// новой сборки, и читать её всё равно надо. Тот же приём, что у
  /// `OffsetFiscalLayout.byIndex`.
  static FiscalDocKind byIndex(int? value) =>
      value != null && value >= 0 && value < values.length
      ? values[value]
      : FiscalDocKind.sale;
}
