import 'package:telepos/domain/account/account_type.dart';

/// **«Типы счетов 4 и 7 — это бонус» — объявлено здесь и больше нигде.**
///
/// # Зачем отдельный файл под одно условие
///
/// Правило короткое, и в этом вся беда: его дешевле переписать, чем найти.
/// Измерено на этом дереве перед задачей 13 — две руки, писавшие одно и то
/// же условие независимо:
///
/// - `AccountPosting.isRedemption` — знак движения по счёту;
/// - `SaleReceiptComposer._paymentLine` — слово «Бонус» на печатном чеке.
///
/// Разъехались бы они молча. Заведи кто-нибудь третий род бонусного счёта
/// (программа лояльности сети, подарочный сертификат), и касса начала бы
/// считать остаток по одному правилу, а печатать по другому: на бумаге
/// «Карта», в балансе — списание. Ни одна проба про это не спросила бы,
/// потому что обе половины по отдельности верны.
///
/// К двум читателям задача 13 добавляет ещё двух — миграцию v40 (стартовые
/// остатки бонусного журнала) и сам [BonusService] (какое движение вообще
/// подлежит журналу). Четыре копии одного условия — это уже не риск, а
/// расписание.
///
/// # Почему числа, а не перечисление
///
/// [AccountType] в этом дереве — `abstract class` со `static const int`, а
/// не `enum`, и намеренно: значения лежат на диске в `accounts.type`, их
/// менять нельзя. Здесь та же причина, плюс вторая: [sqlInList] нужен
/// миграциям, которые ходят `customStatement`-ом и никакого Dart-типа не
/// видят. Один список — оба читателя.
///
/// # Чего здесь нет
///
/// Здесь нет знака движения: он в [AccountPosting], и это не дубль, а
/// разделение. «Какие счета бонусные» — факт о справочнике счетов; «что
/// делать со знаком» — правило учёта. Второе читает первое.
abstract final class BonusAccountTypes {
  /// Роды счёта, на которых накопленное **тратится**, а не приходит.
  ///
  /// Порядок значим только для [sqlInList] — он попадает в текст запроса и
  /// потому обязан быть воспроизводимым.
  static const List<int> values = <int>[
    AccountType.agentCashback,
    AccountType.cashback,
  ];

  /// Бонусный ли это род счёта.
  ///
  /// Единственное место в дереве, где сказано «4 и 7». Сторож на форму —
  /// `test/domain/fiscal/bonus_account_types_guard_test.dart`: он читает
  /// исходники и краснеет, если условие завелось где-то ещё.
  static bool isBonus(int accountType) => values.contains(accountType);

  /// То же множество для SQL: `... WHERE type IN (4, 7)`.
  ///
  /// Собирается из [values], а не пишется строкой: миграция, отставшая от
  /// списка на один род, — ровно та порча, ради которой этот файл и заведён,
  /// и она бы не покраснела нигде (мигрировала бы меньше счетов, чем нужно,
  /// и разошлась бы с журналом только у тех клиентов, у кого такой счёт
  /// есть).
  static final String sqlInList = '(${values.join(', ')})';
}
