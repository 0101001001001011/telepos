/// Личность фискального документа продажи — ключ, по которому оператор
/// узнаёт повтор.
///
/// Живёт отдельным файлом намеренно: ключ строят **два** разных пути
/// (`FiscalServiceImpl.fiscalizeSale` — первая линия, и
/// `WebKassaServiceImpl.fiscalizeSale` — путь сервисного заказа и обмена),
/// и до этой правки каждый писал формат строкой у себя. Одинаковыми они
/// были по совпадению, а не по построению: разойдись они на один символ —
/// и **на одну продажу приехали бы два фискальных документа**, потому что
/// дедупликация оператора узнаёт документ только по ключу.
///
/// # Чем был плох `sale-<чек>-<касса>`
///
/// Номер чека выдаёт `ReceiptNumbers.withNext` как `findLastReceiptNo() +
/// 1`, а `SaleDao.findLastReceiptNo` — это `max(receipt_no)` **по таблице
/// `Sales`**, и ничего больше. `OldSaleCleanupService` удаляет продажи
/// старше срока хранения (автономный режим — 90 дней, онлайновый — **7**).
/// Касса, простоявшая дольше срока, теряет все строки `Sales`; `max`
/// становится `null` → `0`, и нумерация чеков **начинается заново с 1**.
///
/// Оператор при этом помнит `sale-1-1`, `sale-2-1` и далее — они у него
/// зарегистрированы навсегда. Каждая новая продажа приходит к нему с уже
/// занятым ключом и получает код 14. С 2026-09-18 это честный отказ
/// `duplicate` вместо прежнего «успеха с пустым признаком», то есть беда
/// стала видна, — но документа у продажи по-прежнему нет, а деньги взяты.
///
/// # Почему эпохой стало время самой продажи
///
/// Разбирались три названных кандидата.
///
/// **ЗНМ/РНМ кассы** и **идентификатор установки** отпадают по одной и той
/// же причине, и причина эта не «неудобно достать», а «не работает»: оба
/// **постоянны**. Они различают кассы, а столкновение происходит на одной
/// и той же кассе — до уборки и после неё. Приписав константу, получим
/// `sale-<ЗНМ>-1-1` и после уборки снова ровно `sale-<ЗНМ>-1-1`. Ключ
/// стал бы длиннее, а дефект остался бы целиком.
///
/// **Время открытия смены** эпохи различает — но не всегда. Уборка сносит
/// продажи старше отсечки; смена, не закрывавшаяся дольше срока хранения
/// (в онлайновом режиме — дольше семи суток), теряет свои же ранние
/// продажи, нумерация в ней начинается заново, а время открытия у неё всё
/// то же. Столкновение возвращается целиком, и заметить его будет нечем.
///
/// **Время завершения самой продажи** (`Sales.time`, unix-секунды)
/// различает эпохи **по построению, а не по везению**: уборка удаляет
/// только то, у чего `time < отсечка`, а у новой продажи `time` — это
/// «сейчас», которое отсечки заведомо больше. Разница между удалённым
/// чеком и новым чеком с тем же номером не меньше срока хранения (минимум
/// его — 30 суток, `CleanupSettings.minimumRetentionDays`). Доказательство
/// не опирается ни на смену, ни на настройки оператора, ни на то, как
/// часто касса перезапускается.
///
/// # Три требования к эпохе, и почему они выполнены
///
/// * **не меняется от уборки продаж** — `time` принадлежит самой строке
///   продажи; уборка её не правит, а удаляет вместе со строкой, и удалить
///   может только то, что старше отсечки;
/// * **не меняется от перезапуска** — значение лежит в базе, а не в
///   памяти процесса;
/// * **одинаков у повторной отправки того же документа** — читается из
///   той же строки, поэтому две сборки ключа для одной продажи дают одну
///   строку. Это и есть то, ради чего ключ существует: повтор обязан быть
///   повтором.
///
/// # Почему переход не даёт второй регистрации у оператора
///
/// Документы, уже стоящие в очереди, уедут со **своими старыми** ключами:
/// ключ хранится колонкой рядом со строкой (`DriftFiscalQueueStore`), а
/// повтор (`OfflineQueueingProvider.replay`/`retryFailed`) собирает заявку
/// из сохранённого payload — пересобирать её из базы ради того же ключа
/// прямо запрещено докстрингом `retryFailed`. Новый формат получают только
/// документы, собираемые заново, то есть те, которых у оператора ещё нет.
library;

abstract final class FiscalIdempotency {
  /// Ключ продажи: `sale-<время чека>-<номер чека>-<касса>`.
  ///
  /// Порядок доводов в строке выбран, а не достался: эпоха стоит впереди
  /// пары «чек-касса», поэтому ключи старого формата (`sale-1-1`) и
  /// нового (`sale-1758…-1-1`) не могут совпасть ни при каком значении
  /// номера чека — у них разное число разделителей и разная голова.
  static String sale({
    required int saleTime,
    required int receiptNo,
    required int posId,
  }) => 'sale-$saleTime-$receiptNo-$posId';

  /// Отказ: строки продажи нет, и собирать ключ не из чего.
  ///
  /// На боевом пути недостижимо — `LocalPaymentService` зовёт
  /// фискализацию после того, как `SaleUseCase.perform` записал строку
  /// (и её `time`). Но отказать **значением с названной причиной**
  /// дешевле, чем отправить документ под ключом, про который уже известно,
  /// что он может быть занят: чек напечатается «НЕФИСКАЛЬНЫЙ» с причиной,
  /// и беда будет видна, а не молча зарегистрирована вторым документом.
  static const String saleRowMissing =
      'Продажи нет в базе — ключ фискального документа собрать не из чего';

  /// Отказ: строка продажи есть, но не завершена (`time = 0`).
  ///
  /// `SaleInitiationUseCase` заводит чек с `time: 0`, а проставляет время
  /// `SaleUseCase.perform` при завершении. Ноль здесь означает «чек ещё в
  /// работе»: эпохи у него нет, и ключ, собранный с нулём, склеился бы со
  /// всеми такими же — то есть вернул бы ровно тот дефект, ради которого
  /// эпоха и заводилась.
  static const String saleTimeMissing =
      'Чек не завершён (нет времени) — ключ фискального документа '
      'собрать не из чего';
}
