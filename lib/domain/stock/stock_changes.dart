/// «Остатки этой кассы изменились» — через границу рабочего места.
///
/// Пункт 12 ревизии 2026-09-19, решение заказчика 2026-09-18: «в браузере
/// должно работать то же, что в приложении».
///
/// # Что было и почему этого мало
///
/// `StockRevision` (`lib/presentation/controllers/app/stock_revision.dart`)
/// — счётчик **внутри одного контейнера Riverpod**. Он честно чинил свою
/// беду (после продажи каталог и выдача поиска показывали старый остаток),
/// но предел был назван прямо в его докстринге: продажа, проведённая
/// **другим** рабочим местом, его не поднимает. В магазине с кассой и двумя
/// планшетами это значит, что после продажи с планшета остаток на экране
/// кассы и на втором планшете устаревает молча — а «молча» здесь хуже
/// ошибки: цифра выглядит свежей.
///
/// # Почему поток, а не «спросить остаток»
///
/// Договор отвечает не «сколько лежит», а «что-то изменилось». Спрашивать
/// количество здесь значило бы завести второй источник правды рядом с
/// каталогом и реестром остатков; подписанный на это сообщение
/// перечитывает **себя** своим обычным путём. Ровно тот же приём, каким
/// устроен сам `StockRevision`, и тот же довод: `ref.invalidate`
/// каталога — это импорт каталога, а он тянет базу кассы, которой в
/// браузере нет.
///
/// # Номер, а не «свисток»
///
/// [watch] отдаёт **номер ревизии**: первое значение — текущий,
/// дальнейшие — по изменению. Число, а не `void`, по требованию рода
/// `Watch` на проводе (первый кадр подписки обязан нести текущее
/// значение) и потому, что оно отличает «подписался» от «изменилось» у
/// того, кому это важно.
abstract interface class StockChanges {
  /// Текущий номер ревизии остатков, затем — каждое изменение.
  Stream<int> watch();
}

/// Пишущая половина: «остатки только что изменились».
///
/// Отдельным договором, а не методом [StockChanges], по тому же правилу,
/// что у `ScannerRulesReader`/`ScannerRulesRepository`: подписчику запись
/// не нужна, и сузить его договор значит, что он не сможет поднять
/// счётчик даже по ошибке. А в браузере писать и некому — остатки двигает
/// касса.
abstract interface class StockChangeSink {
  void stockChanged();
}
