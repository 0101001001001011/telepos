/// Отказ, который обработчик формулирует сам и адресует человеку.
///
/// До этого типа причина такого отказа ехала как текст произвольного
/// исключения (`ArgumentError`, `StateError`) — `till_wire.dart` подставлял
/// его в `ErrorFrame` через `'$error'`, и это был канал утечки: закрытие
/// утечки (`safeErrorText`, `lib/core/errors/safe_error_text.dart`) отдаёт для
/// чужих исключений только имя типа, и текст, который был доводом для
/// человека («имя обязательно», «терминала с таким id не существует»),
/// перестал доезжать вовсе.
///
/// В отличие от любого другого исключения, текст [WireRefusal] **безопасен
/// по построению**: его пишет обработчик, а не база и не чужая библиотека —
/// значит в нём не может оказаться параметр запроса или хэш пароля, которые
/// безопасный текст обязан скрывать. Поэтому он единственный доезжает до
/// терминала целиком, минуя `safeErrorText` (`lib/data/transport/till_wire.dart`
/// ловит его раньше общего `on Object`).
final class WireRefusal implements Exception {
  const WireRefusal(this.code, this.message);

  /// Код отказа — то же поле, что и `ErrorFrame.code`. По нему терминал
  /// отличает причину, а не по подстроке в тексте.
  final String code;

  /// Текст для человека.
  final String message;

  @override
  String toString() => 'WireRefusal($code: $message)';
}
