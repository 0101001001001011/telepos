/// Каталог операций возврата — задача 19 плана «Продажа с браузерного
/// терминала» (спека 2026-09-06).
///
/// Шесть операций, а не пять. Набросок задачи объявлял пять (`view`,
/// `loadReceipt`, `startWithoutReceipt`, `addProduct`, `complete`); круг
/// правки 1 задачи 18 завёл шестую — [setLine]. Довод измеренный, не
/// стилистический: в чеке один и тот же товар бывает продан по двум ценам,
/// сведение таких строк по товару платило **среднюю** цену (проба разбора:
/// чек `3×100 + 1×90`, возврат одной штуки вернул 97.5 — цену, которой не
/// стоила ни одна проданная единица), поэтому строка возврата опознаётся
/// своим `lineId`, а [addProduct] в возврате по чеку отказывает **всегда**.
/// Без [setLine] выделение строк не доехало бы с терминала до кассы вовсе.
///
/// Седьмая — [troubles] — заведена приёмкой 2026-09-17: возврат с наличной
/// частью не открывал ящик, а когда стал открывать, беде ящика понадобился
/// путь к кассиру браузерного терминала. Черновика она не меняет.
///
/// # Ради чего эта задача существует: два ключа `op.*` впервые с читателем
///
/// `op.refund` и `op.refundWithoutReceipt` объявлены в `PermissionKeys`,
/// показаны в форме прав, розданы ролям — и **не читались ни одной строкой
/// `lib/`**. Замерено обходом, а не взято из брифа:
///
/// ```
/// grep -rn "opRefund\|op\.refund" lib/ --include=*.dart
/// → permission_keys.dart (объявление, список, roleDefaults, подписи),
///   point_mode_permissions.dart (ВЫЧИТАНИЕ у роли по режиму точки),
///   refund_service.dart / local_refund_service.dart (докстринги, обещание
///   этой задачи)
/// ```
///
/// То есть до этой задачи ни одна проверка не спрашивала «есть ли у тебя
/// `op.refund`»: вычитание права по режиму точки сужает то, что выдаётся
/// сеансу, но само ничего не проверяет. Теперь спрашивает сторож —
/// `WireGuard.check`, ветка `SessionAccess`, **до** вызова обработчика.
///
/// # Почему возврат без чека — отдельная операция, а не довод к загрузке
///
/// Сторож смотрит на **имя операции**, а не на содержимое тела: `needs`
/// живёт в описании операции (`wire_access.dart`, «почему это довод
/// операции, а не таблица на кассе»). Свести [loadReceipt] и
/// [startWithoutReceipt] в одну команду с признаком «чек не указан» значило
/// бы, что `op.refundWithoutReceipt` проверить **нечем**: право отличало бы
/// не операцию, а поле, которое пишет тот же, кто пробует его обойти. Две
/// операции — два имени в словаре доступа — два разных права.
///
/// # Имя рабочего места в теле не едет ни у одной из них
///
/// Контракт возврата требует **отвергать** кадр, в котором оно названо
/// (докстринг `RefundService`, правило 1; решение заказчика того же смысла
/// для корзины — круг 5 задачи 7). Готовый механизм владения
/// (`SessionAccess.ownTerminal`) требует ровно обратного — `terminalId` в
/// теле, — и потому здесь неприменим: сторож с ним отказал бы каждой
/// команде возврата. Имя места берёт обработчик кассы из того, что **эта же
/// QUIC-сессия** сама завела (`_sessionTerminals`,
/// `lib/backend/till_operations.dart`).
///
/// **Довод именно такой — контрактный, а не про защиту.** Круг правки 1
/// снял с него приписанную дельту безопасности: `ownTerminal` пускает и
/// терминал самой кассы, а `terminals.selfEnsure` тогда ещё и привязывал эту
/// строку к любой сессии, так что общий черновик у двух вкладок
/// воспроизводился и с механизмом владения. Сам чёрный ход круг правки 4
/// закрыл (`selfEnsure` места не привязывает), но довод в пользу
/// контрактного выбора от этого не изменился: `ownTerminal` требует
/// `terminalId` в теле, а контракт возврата требует его отвергать.
///
/// # Разбор ответа не пишется здесь заново
///
/// Каждый `decode` зовёт готовую половину пары из `refund_codec.dart`.
/// Написать разбор здесь ещё раз значило бы завести второго читателя формы
/// ровно там, где пары и заводились ради одного.
library;

import 'package:telepos/core/constants/permission_keys.dart';
import 'package:telepos/domain/refund/refund_service.dart';
import 'package:telepos/domain/sale/cart_view.dart';
import 'package:telepos/domain/sale/payment_service.dart'
    show CompletionTrouble;
import 'package:telepos/domain/wire/pay_ops.dart' show troublesFromWireJson;
import 'package:telepos/domain/wire/refund_codec.dart';
import 'package:telepos/domain/wire/wire_access.dart';
import 'package:telepos/domain/wire/wire_op.dart';

abstract final class RefundOps {
  /// Черновик возврата этого рабочего места сейчас и при каждом изменении.
  ///
  /// **Подписка, а не вопрос.** Черновик живёт на кассе (докстринг
  /// `RefundService`), и экран обязан увидеть его изменение в момент
  /// изменения — иначе терминал показывал бы своё представление о возврате,
  /// а касса отдавала деньги по своему.
  ///
  /// Право `op.refund`: просмотр черновика — часть возврата, а не соседняя
  /// возможность. «Право, закрытое наполовину, — не право» (находка 3 круга
  /// 1 задачи 9): читающая половина без права показала бы, что именно
  /// вернули на этой кассе, тому, кому возврат закрыт.
  ///
  /// **Отказ сторожа приходит на открытии потока.** Экран без права обязан
  /// не подписываться вовсе, а не показывать пустой черновик; сегодня этого
  /// никто не сторожит — то же требование и к той же задаче 20, что уже
  /// записано у `sale.deferredList`.
  static const view = Watch<void, RefundView>(
    'refund.view',
    access: SessionAccess(needs: PermissionKeys.opRefund),
    encode: _nothing,
    decode: _decodeView,
  );

  /// Возврат по чеку: черновик заводится заново и наполняется строками чека.
  static const loadReceipt = Ask<ReceiptKey, RefundView>(
    'refund.loadReceipt',
    access: SessionAccess(needs: PermissionKeys.opRefund),
    encode: receiptKeyToWireJson,
    decode: _decodeView,
  );

  /// Возврат без чека — **отдельная операция именно ради права**.
  ///
  /// Не переставлять на `opRefund` и не сводить с [loadReceipt]: довод в
  /// докстринге класса, раздел «почему возврат без чека — отдельная
  /// операция». Это единственный читатель ключа
  /// `op.refundWithoutReceipt` во всём дереве.
  static const startWithoutReceipt = Ask<CartCommandMeta, RefundView>(
    'refund.startWithoutReceipt',
    access: SessionAccess(needs: PermissionKeys.opRefundWithoutReceipt),
    encode: refundCommandMetaToWireJson,
    decode: _decodeView,
  );

  /// Положить товар в возврат **без чека** по каталожной цене; ноль убирает
  /// строку.
  ///
  /// Право `op.refund`, а не `op.refundWithoutReceipt`, хотя команда
  /// работает только на черновике без чека: право охраняет **начало** такого
  /// возврата, а наполнение — та же работа, что и наполнение чекового, и
  /// делить её вторым ключом значило бы, что кассир начал возврат и не может
  /// положить в него товар.
  ///
  /// # Чем это держится — и почему не рассуждением
  ///
  /// **Не пишите здесь «черновик уже заведён тем, у кого право было».** Так
  /// было написано, и круги правки 1–3 задачи 19 опровергли это пробой
  /// **трижды**: черновик лежит под ключом рабочего места, а за местом
  /// человек меняется — и меняется способами, которых прежний список не
  /// знал. Сам этот список — утверждение того же рода, и он уже один раз
  /// оказался неполным, так что читать его надо как «сегодня измерено
  /// столько», а не как доказательство.
  ///
  /// Сегодня измерено три условия, и **снятие любого возвращает дыру**:
  ///
  /// 1. **место сеанса совпадает с местом сессии сейчас** — сторож,
  ///    `WireGuard._boundTerminalId`, код отказа `terminal_changed` (круг 3).
  ///    Без него «место» существует в двух смыслах: гашение смотрит на
  ///    место в токене, ключ черновика — на место сессии, а
  ///    `terminals.resume`/`terminals.register` переставляют второе на
  ///    живой сессии, не перевыписывая токен;
  /// 2. **за одним местом одновременно один человек** —
  ///    `SessionRegistry.mint` гасит живые сеансы того же места, выписанные
  ///    другому (круг 2). Без него порядок входов обходит уборку
  ///    очерёдностью, и младший тратит права старшего **своим** токеном;
  /// 3. **вход на место начинает работу с чистого листа** —
  ///    `RefundService.abandon` из обработчика `auth.login` (круг 1).
  ///
  /// Пробы: `test/backend/refund_shift_change_test.dart` (деньги и черновик)
  /// и `test/backend/session_terminal_binding_test.dart` (сеанс и место).
  /// Каждый механизм красит свою — проверено диверсиями поимённо. До круга 3
  /// ни одна проба не краснела от того, что сеанс сменил место после входа:
  /// механизма не было, и отсутствие пробы этого не показывало.
  static const addProduct = Ask<RefundLineRequest, RefundView>(
    'refund.addProduct',
    access: SessionAccess(needs: PermissionKeys.opRefund),
    encode: refundLineRequestToWireJson,
    decode: _decodeView,
  );

  /// Поставить строке черновика количество; ноль снимает её.
  ///
  /// Шестая операция — та, которой не было в наброске (докстринг класса).
  /// **Пакетной формы нет, и это стоит круга по проводу на строку:**
  /// «выделить всё» на чеке в тридцать строк — тридцать вызовов, а при
  /// правиле «одна команда в полёте» (I161) — тридцать кругов подряд.
  /// Заметка была адресована этой задаче (`RefundService.setLineQuantity`);
  /// решение здесь — **не заводить**, потому что цена меряется на проводе, а
  /// на проводе возврат сегодня ещё никем не вызывается (задача 20). Заведи
  /// я её вслепую — на кассе появилась бы седьмая команда, чей единственный
  /// довод «наверное, будет медленно».
  static const setLine = Ask<RefundLineQuantity, RefundView>(
    'refund.setLine',
    access: SessionAccess(needs: PermissionKeys.opRefund),
    encode: refundLineQuantityToWireJson,
    decode: _decodeView,
  );

  /// Завершить возврат: деньги покупателю, товар на остаток.
  static const complete = Ask<CartCommandMeta, RefundOutcome>(
    'refund.complete',
    access: SessionAccess(needs: PermissionKeys.opRefund),
    encode: refundCommandMetaToWireJson,
    decode: _decodeOutcome,
  );

  /// Чем кончились отправленные действия железа проведённого возврата —
  /// сегодня денежный ящик (приёмка 2026-09-17: возврат с наличной частью
  /// ящика не открывал вовсе).
  ///
  /// Близнец `pay.troubles`, и разбор тот же: ящик уходит с кассы
  /// `unawaited`, его исход не может ехать в ответе [complete], терминал
  /// спрашивает **после** того, как сказал кассиру об успехе. Кадр ответа —
  /// та же пара кодеков, что у продажи (`troublesToWireJson` /
  /// `troublesFromWireJson`): второй формы одной и той же беды заводить
  /// незачем. В теле — номер возврата ([RefundOutcome.refundLocalId]);
  /// рабочее место касса берёт из сеанса, как у остальных шести.
  ///
  /// Право `op.refund`: беда называет то, что случилось с возвратом этого
  /// же рабочего места, — часть возврата, а не соседняя возможность.
  static const troubles = Ask<int, List<CompletionTrouble>>(
    'refund.troubles',
    access: SessionAccess(needs: PermissionKeys.opRefund),
    encode: _encodeTroubles,
    decode: troublesFromWireJson,
  );

  /// Все операции возврата. Список ведётся руками, тем же приёмом и по той
  /// же причине, что `TillOps.all`: в Dart нет способа перечислить
  /// объявленные константы класса без зеркал, а зеркала запрещены в сборке
  /// под браузер.
  static const all = <WireOp<Object?, Object?>>[
    view,
    loadReceipt,
    startWithoutReceipt,
    addProduct,
    setLine,
    complete,
    troubles,
  ];
}

/// Обмен без доводов. Пустое тело, а не отсутствие тела — тем же приёмом,
/// что `TillOps._nothing`: кадр обязан быть разбираемым одним и тем же
/// способом независимо от того, есть ли в нём что сказать.
Map<String, Object?> _nothing(void _) => const {};

Map<String, Object?> _encodeTroubles(int refundLocalId) => {
  'refundLocalId': refundLocalId,
};

RefundView _decodeView(Map<String, Object?> body) =>
    refundViewFromWireJson(body);

RefundOutcome _decodeOutcome(Map<String, Object?> body) =>
    refundOutcomeFromWireJson(body);
