/// Единственная дверь для денег, пересекающих провод (инвариант I159,
/// `global-constraints.md`) — заведена кругом правки 2 задачи 6 плана
/// «Продажа с браузерного терминала».
///
/// **Почему дверь, а не правило про форму текста.** Круги правки 1–2 этой
/// задачи испробовали два текстовых сторожа над формой значения —
/// «не звать `toDouble()`» (пропустил `roundToDouble()` — тот же класс
/// метода, другое имя) и «значение не похоже на число» (пропустил голую
/// переменную `line.price`, выражение `(1.0 / 3)`, целый литерал `5` —
/// внешне безобидные формы, которые всё равно кладут не то, что нужно, или
/// маскируют то, что уже случилось раньше в выражении). Текстовый сторож не
/// умеет узнавать **тип** значения — только его текст, а типов, которые на
/// вид не отличить друг от друга (`5.0` — оно и число «пять», оно и то, что
/// осталось от `Decimal`, потерявшего дробную часть), сколько угодно.
///
/// Вместо того чтобы перечислять запрещённые формы (список неполон по
/// построению — переразбор показал это дважды), эта дверь делает
/// **единственную разрешённую форму проверяемой напрямую**: денежное поле
/// обязано быть результатом вызова [wireMoney], и ничем иным. Сторож
/// (`test/architecture/money_over_wire_test.dart`) проверяет не «значение не
/// выглядит плохим», а «значение — вызов этой функции, текстом, и ничего
/// больше» — и это утверждение полно **для каждого проверенного имени
/// ключа**: никакая форма, кроме буквального `wireMoney(...)` без
/// дальнейшей склейки или цепочки вызовов, не пройдёт эту проверку (круг
/// правки 3 закрыл именно склейку/цепочку — см. докстринг сторожа).
///
/// **Что [wireMoney] проверяет, а что — нет (круг правки 3, честный выбор,
/// а не умолчание).** Функция **не проверяет и не обрезает** ни точность,
/// ни разрядность значения — `Decimal.toString()` печатает ровно то, что
/// есть в значении, каким бы оно ни было. P18,S3 — соглашение о том, каким
/// должен быть `Decimal` в деньгах этого проекта, и оно обеспечивается не
/// здесь, а там, где `Decimal` рождается (ввод суммы, чтение из базы,
/// денежные колонки drift) — та же граница, что и везде в проекте (money
/// arithmetic at boundaries, `qa-depth`). Дешевле и честнее не притворяться,
/// что дверь на выходе способна поймать то, что уже было испорчено на входе
/// — `wire_money_test.dart` прямо проверяет, что число с восемью знаками
/// после запятой (больше, чем позволяет S3) проходит через дверь без
/// обрезания, а не считает это дефектом двери.
library;

import 'package:decimal/decimal.dart';

/// Кладёт [value] в кадр провода — единственный разрешённый способ.
///
/// Печатает [value] через `Decimal.toString()` без каких-либо изменений —
/// ни округления, ни проверки разрядности (см. докстринг файла). Дальше в
/// кадре — просто текстовое поле JSON, как и всё остальное на проводе.
String wireMoney(Decimal value) => value.toString();
