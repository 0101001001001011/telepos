/// Описание одной операции провода — общее для кассы и терминала.
///
/// Живёт в `domain/` и не тянет ни транспорта, ни `dart:ffi`, ни
/// `dart:js_interop`: оба конца собираются из одного описания, поэтому
/// разойтись молча они не могут.
///
/// # Почему здесь нет путей URL
///
/// Маршрутов больше не существует, есть операции. До 2026-08-04 согласование
/// концов держалось на строке пути в двух местах: `api_server.dart` объявлял
/// маршрут, `lib/web/*` набирал его вручную, и расхождение обнаруживалось
/// только в браузере — кодом 404. В тот день это стоило белого экрана без
/// единого слова, потому что 404 приходил страницей HTML, а разбор ждал JSON.
///
/// # Почему род операции — это тип, а не поле
///
/// Разбор на кассе выбирает поведение по роду. Строковое поле позволило бы
/// прислать «подписка» туда, где обработчик одноразовый, и подписка повисла бы
/// на потоке, который никто не закроет. Тип это исключает на сборке.
library;

import 'package:telepos/domain/wire/wire_access.dart';

sealed class WireOp<Req, Res> {
  const WireOp(
    this.name, {
    required this.access,
    required this.encode,
    required this.decode,
  });

  /// Имя на проводе: `setup.state`, а не `/api/setup/state`.
  final String name;

  /// Что операция требует от того, кто её зовёт.
  final WireAccess access;

  /// Как запрос ложится в тело кадра.
  final Map<String, Object?> Function(Req) encode;

  /// Как тело кадра становится ответом.
  ///
  /// Разбор живёт здесь, в одном месте на операцию, а не в каждом
  /// репозитории: пока он размазан, один и тот же отказ приходится чинить
  /// столько раз, сколько мест его повторяют.
  final Res Function(Map<String, Object?>) decode;
}

/// Спросить один раз и получить один ответ.
///
/// Поток закрывается сразу после ответа: обмен окончен, и держать его открытым
/// значило бы копить потоки, которые никто не закроет.
final class Ask<Req, Res> extends WireOp<Req, Res> {
  const Ask(
    super.name, {
    required super.access,
    required super.encode,
    required super.decode,
  });
}

/// Подписаться на состояние.
///
/// Первый кадр — текущее значение, дальнейшие — изменения. Поток живёт, пока
/// жив подписчик; отписка — его закрытие.
///
/// Это и есть цель смены транспорта: касса говорит первой. Операция, которая
/// могла быть подпиской, но осталась вопросом, — не мелочь, а отказ от
/// единственной выгоды, ради которой всё менялось.
final class Watch<Req, Res> extends WireOp<Req, Res> {
  const Watch(
    super.name, {
    required super.access,
    required super.encode,
    required super.decode,
  });
}

/// Длинная работа: кадры хода выполнения и один завершающий.
///
/// Заведена не про запас. Восстановление из копии и загрузка данных
/// организации идут минутами, и до 2026-08-04 код честно писал о себе, что
/// канала для хода выполнения у него нет и что придумывать промежуточные числа
/// он отказывается. Канал появился здесь.
final class Run<Req, Res> extends WireOp<Req, Res> {
  const Run(
    super.name, {
    required super.access,
    required super.encode,
    required super.decode,
  });
}
