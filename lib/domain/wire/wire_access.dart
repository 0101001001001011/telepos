/// Что операция требует от того, кто её зовёт.
///
/// # Почему это довод операции, а не таблица на кассе
///
/// Таблица позволяет забыть. Новая операция, не попавшая в неё, оказалась бы
/// открытой — а именно так провод и прожил до 2026-08-21: сеанс был, и его не
/// проверял никто. Здесь требование обязательно доводом, и операция без него
/// не компилируется вовсе.
///
/// Тот же приём уже взят для рода обмена: род — это тип `Ask`/`Watch`/`Run`, а
/// не строковое поле (`wire_op.dart`).
///
/// # Почему нет отдельного рода «нужен привязанный терминал»
///
/// Права роли пересечены с режимом терминала **на входе**
/// (`PointModePermissions.effective`, `local_auth_repository.dart:264-299`),
/// и это сделала работа входа, — значит режим точки учтён в самих правах
/// ещё до выдачи сеанса. `AuthSession` (`auth_outcome.dart`) с задачи 9
/// закрытия долга несёт `terminalId` и после выдачи сеанса — до неё поле было
/// только у `AuthAttempt`, использовалось на входе и терялось.
///
/// # Владение терминалом — задача 10
///
/// До этой задачи принадлежность **конкретному** терминалу при вызове
/// операции сторож не проверял вовсе: `terminals.rename`, `deviceBindings`,
/// `deviceBindingSave` и `deviceCheck` брали `terminalId` из тела запроса, и
/// никто не сверял его с сеансом — кассир с правом `settings.hardware` мог
/// напечатать пробный чек и открыть денежный ящик **чужого** терминала.
/// [SessionAccess.ownTerminal] закрывает это: сторож сверяет `terminalId` из
/// тела с `session.terminalId` сам, до вызова обработчика (`wire_guard.dart`).
///
/// Довод — не булев признак, а [TerminalOwnership]: задача 9 успела завести
/// свою, обратную проверку для `terminals.delete` («не удаляй терминал, под
/// которым сидит сама вкладка») обработчиком, доводом `WireHandler`. Здесь оба
/// смысла сведены в сторож одним механизмом с двумя полярностями — булев
/// признак различал бы только «нужна проверка или нет», а не то, каким
/// должно быть совпадение. Второй довод `WireHandler` (сеанс) снят: после
/// того как сторож стал закрывать оба смысла сам, у обработчика не осталось
/// причины его получать — единственный читатель (`terminalDelete`) сверял
/// ровно то же самое, что теперь делает сторож, и ничего сверх этого.
library;

/// Как тело запроса обязано относиться к терминалу сеанса — довод
/// [SessionAccess.ownTerminal].
enum TerminalOwnership {
  /// `terminalId` в теле обязан совпасть с `session.terminalId`: операция
  /// действует только на терминал вызывающей вкладки. Так для `terminals.rename`,
  /// `terminals.deviceBindings`, `terminals.deviceBindingSave` и
  /// `terminals.deviceCheck` — печать пробного чека и открытие ящика чужого
  /// терминала были и есть точка, ради которой заведена вся задача 10.
  same,

  /// `terminalId` в теле обязан НЕ совпасть с `session.terminalId`: операция
  /// не имеет права нацелиться на терминал вызывающей вкладки. Единственный
  /// сегодняшний читатель — `terminals.delete`, запрет «не удаляй терминал,
  /// под которым сидишь сама» (задача 9 закрытия долга).
  different,
}

sealed class WireAccess {
  const WireAccess();
}

/// Открыто всегда.
///
/// Только то, без чего касса недостижима сама себе: подъём, вопрос «есть ли
/// вообще кому входить», сам вход, терминал самой кассы (`terminals.self`/
/// `terminals.selfEnsure` — десктоп, минуя провод в реальной работе, но
/// достижимо и по нему) и возврат уже заведённого терминала по секрету
/// (`terminals.resume` — задача 5: секрет, а не сеанс, — довод самого
/// запроса, и сторожу сверх факта его наличия в теле проверять нечего, всё
/// остальное — работа [LocalTerminalRepository.resume]/
/// [TerminalSecret.matches]).
///
/// `terminals.register` здесь **больше нет** — задача 6 плана «знакомство
/// терминала с кассой» (шаг 3 спеки) закрыла его отдельным типом,
/// [EnrolmentAccess]: до неё открытая регистрация заводила терминал любому,
/// кто дотянулся до кассы по QUIC, без единого довода — потолок в 200
/// терминалов был достижим неаутентифицированно.
final class OpenAccess extends WireAccess {
  const OpenAccess();
}

/// Нужен живой сеанс, а при [needs] — ещё и право в его действующем множестве.
final class SessionAccess extends WireAccess {
  const SessionAccess({this.needs, this.ownTerminal});

  /// Ключ из `PermissionKeys`. `null` — достаточно самого сеанса.
  final String? needs;

  /// `null` — тело не сверяется с сеансом вовсе (большинство операций:
  /// `terminals.list`, `terminals.deviceDiscovery` и другие не нацелены на
  /// один конкретный терминал или не несут `terminalId` в теле). Иначе сторож
  /// требует `terminalId` в теле и сверяет его с `session.terminalId` по
  /// правилу [TerminalOwnership] — тело без `terminalId` отказывает, а не
  /// проходит умолчанием.
  final TerminalOwnership? ownTerminal;
}

/// Открыто, пока касса не настроена; после — закрыто навсегда.
///
/// Свежую кассу настроить надо, а войти на ней некому: пользователей ещё нет.
/// Настроенную — перезаписывать нельзя, иначе кто угодно со вкладкой сотрёт
/// работающий магазин.
final class SetupOnlyAccess extends WireAccess {
  const SetupOnlyAccess();
}

/// Структурно открыто сторожу (сеанс не нужен — операция зовётся раньше
/// `auth.login`), но обработчик требует довод в теле: код привязки,
/// который выдаёт `/terminal-pairing` и который тратится ровно один раз.
/// Задача 6 плана «знакомство терминала с кассой» (шаг 3 спеки) —
/// единственный сегодняшний читатель — `terminals.register`.
///
/// # Почему сторож не проверяет код сам
///
/// Задача 10 закрытия долга безопасности увела проверку владения терминалом
/// ([SessionAccess.ownTerminal]) из обработчиков в сторож — ради одной точки
/// проверки на **несколько** операций (`terminals.rename`,
/// `deviceBindings`, `deviceBindingSave`, `deviceCheck`, `delete`). Этот
/// довод здесь не работает: код привязки нужен ровно **одной** операции, и
/// заводить для неё общий механизм значило бы городить второй ради
/// единственного читателя.
///
/// Сильнее того: сторож (`lib/domain/wire/wire_guard.dart`) живёт в
/// `lib/domain/` и не должен знать ни базы, ни репозиториев — только сеанс,
/// доступный портом, и функции состояния настройки. `PairingInvites` —
/// список выданных кодов — живёт в `lib/backend/`, у него своё время жизни
/// (в памяти процесса, не в базе) и он уже дан `TillOperations` для той же
/// цели ([ApiServer.invites]). Протащить его в `WireGuard` значило бы
/// нарушить границу, которую сторожит `test/architecture/layering_test.dart`
/// (`lib/domain` — чистый Dart, без знания о `lib/backend/`) ради одной
/// операции — и завести домену зависимость, которая ему не нужна нигде
/// больше.
///
/// Поэтому сторож пропускает [EnrolmentAccess] тем же способом, что и
/// [OpenAccess] (см. [WireGuard.check]), а настоящую проверку — тратит ли
/// код `PairingInvites.redeem`, и то ли имя стоит в теле, — делает
/// `TillOperations.askHandlers[TillOps.terminalRegister.name]`
/// (`lib/backend/till_operations.dart`) до вызова
/// `TerminalRepository.register`. Отказ уходит тем же типом, что и у
/// [SessionAccess] — `WireRefusal` с названным кодом
/// (`pairing_code_invalid`), а не молчаливым проходом.
final class EnrolmentAccess extends WireAccess {
  const EnrolmentAccess();
}
