/// Род счёта — число, лежащее в `accounts.type`.
///
/// # Почему это домен, а не DAO
///
/// Объявление жило в `AccountDao` — там, где по нему делались выборки. Но
/// читает его не только база: [AccountPosting] отвечает по нему на вопрос
/// о **знаке** движения, а домену запрещено ходить в `lib/data`
/// (`test/architecture/layering_test.dart`, И6). Числа те же, место
/// правильное; `account_dao.dart` переэкспортирует их, поэтому ни один
/// прежний читатель не тронут.
///
/// Значения — часть данных на диске: их менять нельзя.
abstract class AccountType {
  static const int pos = 0;
  static const int customBank = 1;
  static const int customCash = 2;
  static const int agentMain = 3;
  static const int agentCashback = 4;
  static const int teleposMain = 5;
  static const int teleposBonus = 6;
  static const int cashback = 7;

  /// Обязательство кассы по подарочным сертификатам — задача 21, v42.
  ///
  /// **Обязательство, а не выручка, и это главное про сертификат в учёте.**
  /// Деньги за сертификат пришли в кассу раньше — тогда, когда его купили,
  /// — и уже посчитаны выручкой той смены. Положить их в выручку второй
  /// раз, при гашении, значит **удвоить выручку**: один и тот же тенге
  /// уехал бы к оператору и в отчёт дважды, из двух разных смен.
  ///
  /// Поэтому выпуск наращивает остаток этого счёта (касса должна товара
  /// на эту сумму), а гашение его уменьшает (долг закрыт товаром). Знак
  /// выбирает [AccountPosting], а не вызывающий: род перечислен в
  /// `AccountPosting.isRedemption` рядом с бонусными, и там же объяснено,
  /// почему рядом — но **не в** [BonusAccountTypes].
  ///
  /// # Почему предоплате (задача 23) своего рода не понадобилось, а
  /// сертификату понадобился
  ///
  /// Вопрос поставлен координатором прямо: «второй род счёта ради одного
  /// вида оплаты — дорого». Он справедлив, и ответ на него — не «так
  /// удобнее», а свойство самой бумажки.
  ///
  /// Предоплата **всегда названа контрагентом**: это аванс известного
  /// покупателя по известному документу, и его законное место — расчётный
  /// счёт этого покупателя ([agentMain]), где плюс значит «внёс вперёд», а
  /// минус — «должен». Второго рода там действительно не нужно.
  ///
  /// Подарочный сертификат — **предъявительский**. Его покупает один, а
  /// отоваривает тот, у кого он в руках, и это не край, а его назначение:
  /// бумажку дарят. Отсюда три следствия, и каждого хватило бы по
  /// отдельности:
  ///
  /// 1. **Покупателя, на чей счёт класть, при гашении нет.** Положить
  ///    обязательство на [agentMain] можно только назвав контрагента —
  ///    то есть потребовав покупателя и при выпуске, и при гашении. Если
  ///    это разные люди (а это обычный случай), аванс списался бы у того,
  ///    кто товара не получил.
  /// 2. **Обязательство здесь сводное, а не персональное.** Магазин
  ///    должен товара на сумму всего непогашенного тиража; это одно число
  ///    магазина, а не сумма чужих счетов.
  /// 3. **Без рода нечем спросить «это сертификат?».** Продажа и возврат
  ///    узнают сертификатную строку по роду счёта-получателя вида
  ///    (`_isCertificateKind`), а не по `kindId == 5`: справочник
  ///    настраиваемый, и оператор вправе завести **свой** вид сертификата.
  ///    Сравнение с системным числом объявило бы настраиваемость выдумкой
  ///    — ровно то, чего задача 14 избегала везде.
  static const int certificateLiability = 8;
}
