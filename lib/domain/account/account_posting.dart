import 'package:decimal/decimal.dart';
import 'package:telepos/domain/account/account_type.dart';
import 'package:telepos/domain/fiscal/bonus_account_types.dart';

/// Знак движения по счёту — **один ответ на весь код**.
///
/// # Зачем это отдельный файл
///
/// Счёт бывает двух родов, и они складываются по-разному. На кассовом,
/// банковском, агентском расчётном счёте платёж — это приход: баланс
/// растёт. На бонусном платёж — это **списание накопленного**: покупатель
/// расплатился своими бонусами, и их стало меньше. Одно и то же число
/// `+300` означает `+300` на одном счёте и `−300` на другом.
///
/// До этого файла ответ на этот вопрос знал ровно один вызывающий —
/// `SaleUseCaseImpl.perform`, где стояла ветка `isCashbackRedemption`.
/// Возврат её не знал и вычитал единообразно по всем счетам получателя.
/// Измерено: покупатель с 300 бонусами платит ими за чек на 1000, возврат
/// чека оставляет ему **−300** вместо +300 — минус шестьсот на покупке,
/// где он потратил триста, и отрицательный остаток, которого у бонусного
/// счёта быть не может вовсе.
///
/// Правило переехало из вызывающего в правило именно поэтому: пока оно
/// живёт в ветке одного метода, каждый следующий, кто тронет счёт, обязан
/// вспомнить про бонусы сам. Никто не вспомнил за всё время жизни возврата.
///
/// # Как этим пользоваться
///
/// Не считать новый остаток самому, а назвать **движение**:
/// `AccountDao.post(id, amount)`. Платёж несёт `amount = +R`, сторно —
/// `amount = −R`. Дальше знак выбирает [apply], и выбрать его неверно
/// вызывающий уже не может.
///
/// [AccountDao.updateBalance] остаётся для счетов, где никакого рода нет,
/// и сторожит бонусные: попытка посчитать их остаток самому — `StateError`.
abstract final class AccountPosting {
  /// Счета, где платёж уменьшает остаток, а не увеличивает.
  ///
  /// Условие живёт в [BonusAccountTypes] — **одним выражением на дерево**
  /// (задача 13). Здесь оно только читается.
  ///
  /// Прежняя редакция утверждала в докстринге, что это «единственное место
  /// в дереве»; измерено сторожем `bonus_account_types_guard_test.dart` —
  /// мест было два: второе печатало слово «Бонус» на чеке
  /// (`SaleReceiptComposer._paymentLine`). Утверждение в комментарии
  /// сторожем не является.
  ///
  /// Разделение остаётся: «какие счета бонусные» — факт о справочнике
  /// счетов, «что делать со знаком» — правило учёта, и оно здесь.
  /// # Почему множество шире бонусного — задача 21
  ///
  /// К бонусным родам прибавился счёт обязательства по подарочным
  /// сертификатам ([AccountType.certificateLiability]). Правило знака у них
  /// одно: платёж **уменьшает** остаток. У бонуса — потому что покупатель
  /// тратит накопленное; у сертификата — потому что касса закрывает товаром
  /// взятое на себя обязательство.
  ///
  /// **Но множества это не сливает, и вот почему.** Условие «какие счета
  /// бонусные» читают ещё двое, и им сертификат не бонус:
  ///
  /// - `SaleUseCaseImpl.perform` отправляет бонусные движения **в журнал**
  ///   `bonus_entries` вместо счёта. Сертификату там делать нечего: его
  ///   движения записаны строками `Payments` с номером в `reference`, и
  ///   второй журнал был бы вторым ответом на тот же вопрос;
  /// - `SaleReceiptComposer._paymentLine` печатает на чеке слово «Бонус».
  ///   Сертификат, напечатанный «Бонусом», — вранье покупателю на бумаге.
  ///
  /// Поэтому [BonusAccountTypes] остаётся ровно тем, чем был («4 и 7»), а
  /// расширяется **правило учёта** — здесь, где оно и живёт. Ровно тот
  /// случай, который докстринг [BonusAccountTypes] назвал заранее: «заведи
  /// кто-нибудь третий род… подарочный сертификат».
  static bool isRedemption(int accountType) =>
      BonusAccountTypes.isBonus(accountType) ||
      accountType == AccountType.certificateLiability;

  /// Остаток счёта рода [accountType] после движения на [amount].
  ///
  /// Платёж несёт положительный [amount], сторно — отрицательный.
  static Decimal apply({
    required int accountType,
    required Decimal balance,
    required Decimal amount,
  }) => isRedemption(accountType) ? balance - amount : balance + amount;
}
