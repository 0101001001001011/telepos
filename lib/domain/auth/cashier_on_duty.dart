/// Кто сейчас вошёл на **самой кассе** — для операций, которые касса зовёт
/// мимо провода и которым нужен кассир, а не рабочее место.
///
/// # Зачем (решение заказчика 2026-09-15)
///
/// Замок перебора сертификатов на кассе считал всех, кто сидит за ней, одним
/// счётом «место за кассой» (`desktopSeatKey`). Заказчик: «кассы — это
/// разные кассиры, и каждый всегда работает в своей смене, а не в общей».
/// Значит счёт — по кассиру. На проводе кассир приезжает с сеансом
/// (`AuthSession.userId`), а на кассе сеанс живёт в памяти экрана входа
/// (`LoginNotifier._token`, состояние Riverpod) — контейнеру зависимостей
/// его не видно. Этот порт — то, что экран входа пишет, а контейнер читает.
///
/// # По кассиру, а не по смене
///
/// Смена на кассе одна открытая за раз (`ShiftDao.findOpenedShift`), и вход
/// кассира к владельцу смены не привязан (`LocalAuthRepository` выписывает
/// сеанс с `shiftOpen: openShift != null`). Ключ по смене отдавал бы
/// запертому кассиру свежий счёт за закрытие и открытие смены; ключ по
/// кассиру переживает и повторный вход, и новую смену, и совпадает с ключом
/// провода (`u:<userId>`) — тот же человек с планшета и с кассы упирается в
/// один счёт.
library;

abstract interface class CashierOnDuty {
  /// `null` — на кассе никто не вошёл.
  int? get userId;
}

/// Память процесса кассы. Пишет экран входа: [signIn] на выписанном сеансе,
/// [signOut] на выходе и на кончившемся сеансе.
final class CashierOnDutyHolder implements CashierOnDuty {
  int? _userId;

  @override
  int? get userId => _userId;

  void signIn(int userId) => _userId = userId;

  void signOut() => _userId = null;
}
