/// Есть ли сейчас живой сеанс, выписанный на этот терминал.
///
/// Узкий порт, тем же приёмом, что [SessionLookup]
/// (`lib/domain/auth/session_lookup.dart`) рядом: уборке неиспользуемых
/// строк `terminals` (`TillOperations._pruneUnusedTerminals`, довесок фазы
/// 3/4 закрытия долга) нужно знать ровно одно — «сидит ли сейчас
/// кто-то живой на этом терминале», не читая ни токена, ни остальных деталей
/// реестра сеансов. Тянуть туда `SessionRegistry` целиком значило бы связать
/// уборку строк терминалов со всем устройством реестра — а он живёт в
/// `lib/backend/`, тогда как терминалы и их уборка эту границу переходить не
/// обязаны.
abstract interface class TerminalSessionCheck {
  /// `true`, если хотя бы один ещё не погасший сеанс сейчас выписан на
  /// [terminalId].
  bool hasLiveSession(int terminalId);
}
