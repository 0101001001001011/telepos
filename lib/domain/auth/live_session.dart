/// Одна строка экрана списка живых сеансов — то, что можно показать
/// человеку, решающему, кого отозвать.
///
/// # Почему здесь нет токена
///
/// `AuthSession.token` предъявляется кассе каждой операцией — это пропуск в
/// чужой аккаунт, живущий в памяти кассы и в `sessionStorage` одной-
/// единственной вкладки. Экран списка сеансов читает не хозяин сеанса, а
/// тот, кто решает его отозвать (задача 19 закрытия долга безопасности), —
/// и токен в этом списке был бы готовым пропуском для каждого, кто на этот
/// экран посмотрел, а не действием «отозвать». [SessionRegistry.live]/
/// [SessionRegistry.watchLiveSessions] строят эту запись из полного
/// `AuthSession` сами и токен туда не кладут — не полагаясь на то, что
/// вызывающий код не прочитает поле, которого он не забыл проверить: поля
/// физически нет.
///
/// Отзыв («погасить») называет сеанс по [terminalId], не по токену: ровно
/// та же причина — операции провода, которым нужен адресат, но не должен
/// быть нужен чужой пропуск (`TillOps.authSessionRevoke`).
typedef LiveSession = ({
  int terminalId,
  int userId,
  String name,
  String role,
  DateTime issuedAt,
  DateTime expiresAt,
});
