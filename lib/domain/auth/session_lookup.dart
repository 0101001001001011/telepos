import 'package:telepos/domain/auth/auth_session.dart';

/// Чтение живого сеанса по токену.
///
/// Узкий порт, а не весь реестр: проверка на проводе живёт в
/// `lib/data/transport/`, а реестр — в `lib/backend/`, и тянуть одно в другое
/// значило бы связать транспорт с устройством кассы.
///
/// Чтение **продлевает** сеанс: сеанс спрашивают ради действия, а действие и
/// есть активность. Отдельный «продлить» рано или поздно забыли бы позвать.
abstract interface class SessionLookup {
  /// Живой сеанс или `null`, если токен неизвестен или срок вышел.
  AuthSession? sessionFor(String token);
}
