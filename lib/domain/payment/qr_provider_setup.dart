/// Настройка провайдера QR с экрана кассы — пункт 8 C (2026-09-15).
///
/// # Чего до этого файла не было
///
/// Строку `qr_provider_configs` писала только дверь стенда
/// `stand/qr-provider` (`test/manual/wt_stand.dart`): у владельца настоящей
/// кассы включить оплату по QR было нечем.
///
/// # Ключ провайдера не выходит отсюда наружу
///
/// [QrProviderView] **не имеет поля ключа** — только [QrProviderView.keySet].
/// Экран не может показать ключ, потому что ему его не отдают, а не потому,
/// что поле ввода скрывает символы. Ключ едет только внутрь:
/// [QrProviderSetupRepository.save] с `newApiKey`.
///
/// Порт живёт в домене, реализация — у единственного читателя настройки
/// (`QrPaymentDesk`, сторож `qr_secret_never_reaches_terminal_test.dart`,
/// «настройку провайдера читает один класс»).
///
/// # С 2026-09-18 у порта есть и вторая реализация — по проводу
///
/// Решение заказчика того же дня: «это не граница, а пробел — в браузере
/// должно работать то же, что в приложении». До него экран настройки жил
/// только на кассе, и владелец, у которого вместо кассы планшет, включить
/// оплату по QR не мог ничем.
///
/// Провод ничего не меняет в главном свойстве: **ключ едет только внутрь**.
/// [QrProviderView] поля ключа не имеет, и потому кадр ответа его не несёт
/// — не «мы не кладём», а «класть нечего». Сторож — проба
/// `qr_setup_secret_test.dart`: она пишет ключ с браузера и просматривает
/// **каждый кадр, отправленный кассой терминалу**.
library;

import 'package:meta/meta.dart';

/// Что экран знает о настройке QR. Ключа здесь нет — см. докстринг файла.
@immutable
class QrProviderView {
  const QrProviderView({
    required this.configured,
    required this.baseUrl,
    required this.code,
    required this.keySet,
    required this.patience,
    required this.kindActive,
  });

  /// Строка настройки заведена.
  final bool configured;
  final String baseUrl;
  final String code;

  /// Ключ заведён. Сам ключ экрану не отдаётся.
  final bool keySet;

  /// Сколько касса ждёт оплаты по коду.
  final Duration patience;

  /// Вид оплаты QR (`SystemPaymentKindIds.qr`) включён в справочнике.
  final bool kindActive;
}

abstract interface class QrProviderSetupRepository {
  Future<QrProviderView> read();

  /// Сохранить адрес, код и терпение.
  ///
  /// [newApiKey] `null` или пустой — **прежний ключ остаётся**: экран не
  /// знает ключа и не может отправить его обратно, и пересохранение адреса
  /// не имеет права молча стереть ключ. Стереть — [clearApiKey].
  Future<void> save({
    required String baseUrl,
    required String code,
    required Duration patience,
    String? newApiKey,
    bool clearApiKey = false,
  });

  /// Снять настройку целиком — касса перестаёт показывать коды.
  Future<void> clear();

  /// Включить или выключить вид оплаты QR.
  Future<void> setKindActive(bool active);
}

/// Эта касса настройки провайдера QR не держит вовсе.
///
/// Тот же род отказа, что `certificates_unavailable` и
/// `prepayment_intake_unavailable`: голый процесс `bin/telepos_backend.dart`
/// не поднимает контейнера зависимостей, и стойки QR у него нет. Отвечать
/// «сохранено» без записи — худшее из возможного: владелец ушёл бы с экрана,
/// считая кассу настроенной, а покупателю код не показался бы.
const qrSetupUnavailableCode = 'qr_setup_unavailable';

/// Касса, у которой есть стойка QR, — и та же самая, которой она берёт деньги.
///
/// # Почему порт достаётся через оплату, а не отдельным сотрудником кассы
///
/// Самый очевидный ход — завести `ApiServer`/`TillOperations` ещё один
/// необязательный довод «настройка QR». Он неверен, и цена названа
/// измерением, а не вкусом:
///
/// * **настройку провайдера обязан читать ровно один класс.** Это не
///   пожелание, а проверяемое свойство: сторож
///   `qr_secret_never_reaches_terminal_test` требует, чтобы обращение к
///   таблице настройки жило в единственном файле, — второй читатель есть
///   второй путь для ключа. Отдельный довод позволил бы собрать кассу, у
///   которой деньги берёт одна стойка, а настройку правит **другая**: код
///   один, экземпляра два, и правка адреса не сбрасывала бы того клиента
///   провайдера, который на самом деле звонит.
/// * **необязательные сотрудники расходятся молча.** `stand_matches_till_test`
///   заведён ровно на это и перечисляет три случая, когда стенд живой
///   проверки оказался обрезанной кассой. Порт, снятый с оплаты, не может
///   разойтись по построению: собрал кассе оплату — получил и настройку.
///
/// Отсюда: [qrProviderSetup] отдаёт **ту же стойку**, которой пользуется
/// приём денег. `null` — у этой реализации оплаты стойки нет (браузерная
/// половина: настройку она сама и спрашивает по проводу).
abstract interface class QrProviderSetupHost {
  QrProviderSetupRepository? get qrProviderSetup;
}
