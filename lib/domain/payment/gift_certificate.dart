/// Подарочный сертификат — **тендер со своим учётом**, задача 21.
///
/// # Почему у него своя таблица, а у предоплаты её нет
///
/// Разница не в размере, а в том, что у сертификата есть **жизнь до чека и
/// после чека**. Предоплата — это документ-основание: она приходит вместе с
/// чеком, гасится вместе с ним и в `Payments.reference` помещается целиком
/// (спека, ярус 6). Сертификат живёт сам по себе: он выпущен одним чеком,
/// гасится другим — может быть, через полгода, — гасится **частями**, у него
/// свой срок и своё «уже потрачен». Ни один из этих четырёх фактов из строки
/// `Payments` не выводится.
///
/// Проверить это дешевле всего вопросом «что будет, если таблицу убрать».
/// Убрать — значит выводить остаток как «номинал минус сумма строк оплаты с
/// этим номером». Тогда:
///
/// 1. **номинала неоткуда взять** — он был бы записан только в чеке выпуска,
///    а чек выпуска мог быть пробит на другой кассе сети;
/// 2. **гонка становится неразрешимой**: «посчитать сумму и решить» — это
///    чтение с последующей записью, и два гонщика читают одно и то же.
///    Остаток колонкой позволяет условную запись (`CertificateDao.redeem`),
///    и она и есть настоящий заслон;
/// 3. **срок и ПИН записать некуда** вовсе.
///
/// # Деньги здесь целыми тысячными, а не `double`
///
/// Остаток — единственное денежное число в дереве, которое **уменьшается и
/// сравнивается внутри SQL**: заслон от двойного гашения это условная запись
/// `... SET balance = balance - :x WHERE balance >= :x`, и написать её на
/// стороне Dart нельзя — тогда между чтением и записью снова открывается
/// окно, ради закрытия которого всё и делается.
///
/// `RealColumn ... map(DecimalConverter())`, которым в этом дереве хранятся
/// все прочие деньги, кладёт на диск `double`. Вычитание `double` внутри SQL
/// теряет копейки, и теряет их молча: `500 − 0.1 − 0.1` в двойной точности
/// даёт `499.79999999999995`, а `DecimalConverter.fromSql` честно поднимет
/// это как `Decimal.parse('499.79999999999995')` — испорченные деньги,
/// которых никто не вводил. Три гашения по десять тиынов — и остаток врёт.
///
/// Поэтому на диске лежит **целое число тысячных** ([millisOf]), точное по
/// построению, а `Decimal` собирается на границе DAO. P18,S3 (I159) при этом
/// соблюдён: тысячная и есть третий знак.
@immutable
class GiftCertificate {
  const GiftCertificate({
    required this.id,
    required this.number,
    required this.nominal,
    required this.balance,
    required this.status,
    required this.issuedAt,
    this.pinHash,
    this.expiresAt,
    this.issuedReceiptNo,
    this.issuedPosId,
    this.issuedByUserId,
    this.liabilityAccountId,
  });

  final int id;

  /// Номер, напечатанный на бумажке. Уникален на кассе.
  final String number;

  /// На какую сумму выпущен. Не меняется никогда.
  final Decimal nominal;

  /// Сколько осталось. Уменьшается **условной записью** и только ею.
  final Decimal balance;

  final CertificateStatus status;

  /// ПИН, если он есть, — **хэшем** ([PinCredential]), а не текстом.
  ///
  /// Номер и ПИН рядом в открытом виде — это один экспорт базы,
  /// обнуляющий весь тираж: номера печатаются подряд, и, зная ПИН к
  /// одному, вор знает формат ко всем. Хэш стоит того же, что и у ПИНа
  /// кассира, — pbkdf2 с параметрами, едущими вместе со значением.
  final String? pinHash;

  /// Секунды эпохи.
  final int issuedAt;

  /// Когда истекает, секундами эпохи. `null` — бессрочный.
  ///
  /// Сравнивается **при попытке гашения**, и там же проставляется
  /// [CertificateStatus.expired] — разбор в докстринге члена.
  final int? expiresAt;

  final int? issuedReceiptNo;
  final int? issuedPosId;
  final int? issuedByUserId;

  /// Счёт обязательства кассы, на который лёг номинал при выпуске.
  final int? liabilityAccountId;

  /// Сколько уже погашено.
  Decimal get spent => nominal - balance;

  /// Годен ли к предъявлению **по состоянию** (срок проверяется отдельно:
  /// он зависит от «сейчас», а объект о времени не знает).
  bool get isLive => status == CertificateStatus.active;

  /// Целые тысячные — то, что лежит на диске. Разбор — в докстринге класса.
  ///
  /// **Выражение живёт в [MoneyMillis], а здесь только ссылка на него** —
  /// правка задачи 24. Рассрочка стала вторым хранителем денег целыми
  /// тысячными (условная запись `paid_millis + :x <= total_due_millis`),
  /// и второй перевод рядом с этим был бы вторым ответом на один вопрос:
  /// округление вниз в одном месте и к ближайшему в другом дают разные
  /// деньги на одном и том же числе, и разойтись им негде покраснеть.
  static int millisOf(Decimal amount) => MoneyMillis.of(amount);

  /// Обратный перевод: целые тысячные в деньги.
  static Decimal amountOf(int millis) => MoneyMillis.amount(millis);

  @override
  String toString() =>
      'GiftCertificate($number, $balance из $nominal, ${status.code})';
}

/// Состояние сертификата — **стабильный код-строка на диске**.
///
/// Строка, а не индекс члена: тот же довод, что у
/// `PaymentKinds.fiscalTreatment`. Индекс меняется от перестановки в
/// объявлении, а на диске лежат сертификаты, выпущенные три года назад.
enum CertificateStatus {
  /// Годен: остаток больше нуля, срок не вышел.
  active,

  /// Погашен целиком. Остаток ноль.
  redeemed,

  /// Срок вышел. **Проставляется при попытке гашения, а не вычисляется
  /// фильтром.**
  ///
  /// Разница не косметическая, и стоит она разговора с покупателем. Срок,
  /// вычисляемый на лету (`WHERE expires_at > :now`), делает просроченный
  /// сертификат **невидимым**: касса отвечает «такого нет», кассир говорит
  /// «нет такого сертификата», а покупатель держит бумажку в руках. Это
  /// подлог того же рода, что «чек уже оплачен» о чеке без единой строки
  /// оплаты. Записанное состояние даёт сказать словами: «сертификат истёк
  /// такого-то числа», и это лечится разговором с владельцем магазина, а
  /// не спором у кассы.
  ///
  /// Проставляется **до** транзакции продажи (`LocalPaymentService._plan`),
  /// а не внутри неё: отказ откатил бы транзакцию вместе с отметкой, и
  /// сертификат приходил бы «активным» на каждой следующей попытке.
  expired,

  /// Отозван оператором: утерян, испорчен, выпущен по ошибке.
  cancelled;

  String get code => name;

  static CertificateStatus? byCode(String? value) {
    for (final v in values) {
      if (v.name == value) return v;
    }
    return null;
  }
}

// ── отказы ──────────────────────────────────────────────────────────────
