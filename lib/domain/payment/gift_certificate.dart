// Коды — `const String`, а не члены перечисления: тем же приёмом и в том же
// семействе, что коды `payment_service.dart`. Каждый называет **своё**
// лечение; одно слово на две беды отправило бы кассира не туда.

/// Сертификата с таким номером на кассе нет.
///
/// Достижимо и опечаткой, и чужим сертификатом (сети сертификатов у нас
/// нет — «на каждой кассе свои», спека, раздел границ), и подделкой.
/// Различить их касса не может и не делает вид, что может.
const certificateUnknownCode = 'certificate_unknown';

/// ПИН не подошёл.
///
/// Отдельный код от [certificateUnknownCode] намеренно, и это осознанная
/// уступка: он подтверждает вору, что номер существует. Цена названа и
/// принята — кассир обязан отличить «не та бумажка» от «не те цифры», иначе
/// он будет перенабирать номер вместо ПИНа. Перебор ПИНа при этом не
/// бесплатен: он идёт через живого кассира у живой кассы, а не по сети.
const certificatePinWrongCode = 'certificate_pin_wrong';

/// У сертификата есть ПИН, а его не набрали (пусто или одни пробелы).
///
/// Отдельно от [certificatePinWrongCode] с 2026-09-15: кассир, забывший
/// поле ПИНа, читал «ПИН не подошёл» и перенабирал номер. Новой утечки код
/// не открывает — «номер есть и у него ПИН» говорил и прежний ответ.
///
/// **Замку это такая же попытка подбора**, как и два соседних исхода
/// (`certificateGuessCodes`): иначе пустой ПИН стал бы бесплатной пробой
/// существования номера — выдуманный номер копил бы счёт, настоящий нет.
const certificatePinRequiredCode = 'certificate_pin_required';

/// Слишком много неудачных проверок сертификата — касса отказывает на время.
///
/// Бросает `CertificateThrottle` (`lib/backend/certificate_throttle.dart`)
/// на `pay.certificate` и `pay.complete` с сертификатами, **до** проверки:
/// по кассиру, по рабочему месту и по номеру. Уступка [certificatePinWrongCode]
/// («подтверждает вору, что номер существует») стала ограниченной именно им:
/// перебор идёт уже не «через живого кассира у живой кассы», а скриптом с
/// сеансом кассира, и цену ему задаёт замок, а не скорость пальцев.
///
/// Лечится ожиданием, а не перенабором — отсюда своё слово.
const certificateRateLimitedCode = 'certificate_rate_limited';

/// Срок сертификата вышел. Отметка [CertificateStatus.expired] уже
/// проставлена — см. докстринг члена.
const certificateExpiredCode = 'certificate_expired';

/// Остатка на сертификате нет: он уже потрачен, отозван или предъявлен
/// повторно после полного гашения.
const certificateExhaustedCode = 'certificate_exhausted';

/// Один и тот же сертификат назван в одной оплате дважды.
///
/// Отказ **до раскладки**, а не «сложить два и списать один раз». Две
/// строки на 300 с сертификата на 500 порознь проходят проверку остатка
/// (500 ≥ 300 обе), а вместе требуют 600, и первым это заметил бы условный
/// `UPDATE` — уже внутри транзакции продажи, сырым откатом вместо
/// названного отказа.
const certificateDuplicateCode = 'certificate_duplicate';

/// Остаток изменился между проверкой и списанием: сертификат погашен
/// другой кассой или другим чеком **в ту же секунду**.
///
/// Это не «ошибка кассы», а исход гонки, и он обязан иметь своё слово:
/// лечится он повтором, в отличие от [certificateExhaustedCode], который
/// повтором не лечится никогда.
const certificateRaceCode = 'certificate_race';

/// У кассы нет счёта обязательства под сертификаты
/// (`AccountType.certificateLiability`).
///
/// Лечится настройкой, а не действием кассира. Отдельный код от
/// `payment_account_missing`: тот про счёт **денег**, этот про счёт
/// **обязательства**, и заводятся они разными руками.
const certificateAccountMissingCode = 'certificate_account_missing';

/// Сертификат с таким номером уже выпущен.
///
/// Достижимо повтором команды выпуска и переиспользованием номера из
/// прошлого тиража. Второй выпуск под тем же номером обнулил бы остаток
/// первого — то есть отнял бы у покупателя деньги, которые тот внёс.
const certificateDuplicateNumberCode = 'certificate_number_taken';

/// Номинал сертификата не положителен.
const certificateNominalInvalidCode = 'certificate_nominal_invalid';

/// Деньги за **сам сертификат** касса наличными не возвращает — решение
/// заказчика 2026-09-16, пункт 3.
///
/// # Почему это отказ, а не выдача из ящика
///
/// Сертификат — **аванс**, а не товар: покупатель внёс деньги за то, что
/// ещё не получил. Наличными аванс не обналичивают (разъяснения КГД РК о
/// сертификате как авансе), а п.36 Правил внутренней торговли (приказ
/// №290-НҚ от 24.07.2024) говорит прямо: остаток «возвращается по
/// требованию предъявителя **на указанные им реквизиты**». Реквизиты — не
/// ящик.
///
/// Довод не только бумажный. Денег за бумажку в сегодняшнем ящике нет: они
/// пришли при выпуске, может быть — в другую смену, может быть — полгода
/// назад, и лежат **обязательством**, а не наличностью. Выдать их из
/// сегодняшнего ящика значит отдать чужие деньги: инкассация сойдётся с
/// недостачей, а отчёт смены соврёт на всю сумму. Тот же довод, по которому
/// у вида `givesChange = false`.
///
/// Лечится **указанием реквизитов**, а не повтором, — отсюда своё слово.
const certificateCashRefundRefusedCode = 'certificate_cash_refund_refused';

/// Строка чека уходит **на бумажку**, а номера бумажки у неё нет —
/// находка ревизии 2026-09-19, измеренная, а не выведенная.
///
/// # Что случалось без этого отказа
///
/// `RefundUseCaseImpl`, ветвь `RefundRoute.certificate`: новая бумажка
/// выпускается, **только если у строки оплаты есть документ-основание**
/// (`Payments.reference` — номер погашенного сертификата), а
/// `releaseCredit` двигает счёт обязательства **безусловно**. Строка без
/// номера проходила обе проверки молча: обязательство кассы росло на всю
/// сумму, бумажки не появлялось, из ящика не выходило ни тенге.
///
/// Измерено пробой, а не прочитано: возврат чека на 1000, у строки оплаты
/// стёрт `reference` — `бросок=null`, обязательство `0 → 1000`,
/// сертификат в базе по-прежнему один (погашенный), ящик пуст. То есть
/// **покупатель не получил ничего**, а по книгам касса стала должна 1000
/// тому, у кого на руках нет ни одной бумажки, и равенство «выпущено −
/// погашено» разошлось ровно на эту сумму.
///
/// # Почему такая строка вообще бывает
///
/// Маршрут `certificate` выбирается по **роду счёта вида оплаты**
/// (`RefundAllocation.routeOf`: `payeeAccountType ==
/// AccountType.certificateLiability`), а не по наличию номера. Свой вид
/// оператора, заведённый на счёт обязательства, и строка, приехавшая
/// синхронизацией с кассы другой сборки, дают ровно эту пару: маршрут
/// есть, документа нет.
///
/// # Почему отказ, а не выпуск бумажки с выдуманным номером
///
/// Потому что номер новой бумажки строится от старого
/// (`'$number-R$refundLocalId'`), и придумать его здесь значило бы завести
/// тираж, которого нет ни в одном чеке. Отказ честен: он называет причину
/// до того, как деньги тронулись, — тем же правилом, по которому рядом
/// стоят [certificateCashRefundRefusedCode] и `refundKindUnknownCode`.
///
/// Лечится не повтором, а разбором строки чека, — отсюда своё слово.
const certificateRefundNoSourceCode = 'certificate_refund_no_source';

/// Сертификатом платят за покупку **другого сертификата** — запрещено,
/// решение заказчика 2026-09-16, пункт 6.
///
/// # Почему запрет, а не «ну и пусть»
///
/// Потому что это **бесконечный цикл аванса**. Сертификат — обязательство
/// кассы, взятое за полученные деньги. Погасив одну бумажку выпуском
/// другой, касса не получает ни тенге, но обязательство переписывает на
/// новый срок: бумажку на 100 000 можно катать по кассе годами, каждый раз
/// отодвигая `expiresAt` и ни разу не отдав товара. Живых денег в этой
/// цепочке не появляется вовсе, а по книгам обязательство выглядит
/// свежим.
///
/// Второе следствие, денежное: гашение старой бумажки уменьшает
/// обязательство, выпуск новой увеличивает его на ту же сумму, и
/// счёт `AccountType.certificateLiability` остаётся на месте — то есть
/// операция, за которую касса не получила денег, проходит **сбалансированно**
/// и потому незаметно для любой сверки по счёту.
///
/// Лечится живыми деньгами за новую бумажку, а не перенабором.
const certificatePaysCertificateCode = 'certificate_pays_certificate';
