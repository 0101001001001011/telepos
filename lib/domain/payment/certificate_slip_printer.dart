import 'package:meta/meta.dart';

import 'package:telepos/domain/payment/gift_certificate.dart';

/// Печать слипа подарочного сертификата — решение заказчика 2026-09-16:
/// «без печати схема у прилавка не работает, покупатель уходит с пустыми
/// руками».
///
/// # Почему отдельным контрактом, а не прямо в выпуске
///
/// Тот же довод, что у `RefundReceiptPrinter`: **печать не входит в деньги**.
/// Выпуск обязан состояться и на кассе без принтера, а пробы выпуска
/// (`certificate_ledger_test.dart`, `certificate_issue_op_test.dart`) не
/// должны поднимать очередь печати ради проверки обязательства. Отдельный
/// необязательный порт даёт и то и другое: `null` — печати нет, и это не
/// ошибка.
///
/// # Один порт на две дороги
///
/// Бумажка появляется двумя путями — выпуском при продаже
/// (`pay.certificateIssue` → `LocalCertificateIssuer.issue`) и выпуском новой
/// при возврате (`RefundUseCaseImpl`, ветвь `RefundRoute.certificate`). Слип
/// у обеих один и тот же, поэтому и порт один: две печати одного документа
/// разошлись бы молча, как разошлись бы две раскладки одного возврата.
abstract interface class CertificateSlipPrinter {
  /// Отправляет слип выпущенной бумажки в очередь печати.
  ///
  /// **Отправляет, а не ждёт.** Правило дерева «оплата не ждёт железа»
  /// действует и здесь: отсутствие принтера и его отказ не отменяют выпуск и
  /// не откатывают возврат.
  ///
  /// **Не бросает.** Беда печати обязана остаться бедой печати: исключение
  /// отсюда попало бы на путь, где обязательство уже взято, а при возврате —
  /// внутрь операции, которая уже отдала деньги.
  ///
  /// [refundLocalId] и [sourceNumber] заполняются только у бумажки,
  /// выпущенной возвратом, — она обязана объяснить себя покупателю.
  Future<void> printIssued({
    required GiftCertificate certificate,
    int? userId,
    int? refundLocalId,
    String? sourceNumber,
  });

  /// Слипы, не дошедшие до очереди, — **читаются один раз и снимаются**.
  ///
  /// Тем же приёмом и с тем же ограничением, что беды железа у продажи
  /// (`PaymentService.hardwareTroubles`): это сигнал одному вызывающему, а не
  /// хранилище исходов. Без читателя записи вытесняются.
  ///
  /// Долговечное место для того, что не напечаталось, — сама очередь печати,
  /// у неё свой экран с повтором (`printer_settings_screen.dart`).
  List<CertificateSlipTrouble> takeTroubles();

  /// Всё, что уже отправлено в печать. **Нужно пробам**, чтобы отличить
  /// «отправлено» от «не случилось»; продукт этот `Future` не ждёт.
  ///
  /// Тот же приём, что `LocalPaymentService.pendingSideEffects`.
  Future<void> get pending;
}

/// Слип, который не дошёл до очереди печати.
///
/// Номер бумажки здесь обязателен: без него кассиру нечего искать и нечего
/// перепечатать, а сообщение «слип не напечатался» без номера — это
/// сообщение ни о чём.
@immutable
class CertificateSlipTrouble {
  const CertificateSlipTrouble({required this.number, required this.message});

  final String number;

  /// Причина словами, годная к показу как есть. Текста исключения не
  /// содержит (I144).
  final String message;

  @override
  bool operator ==(Object other) =>
      other is CertificateSlipTrouble &&
      other.number == number &&
      other.message == message;

  @override
  int get hashCode => Object.hash(number, message);

  @override
  String toString() => 'CertificateSlipTrouble($number: $message)';
}

/// Повтор печати слипа — **решение заказчика 2026-09-18**: «в браузере должно
/// работать то же, что в приложении».
///
/// # Почему свой порт, а не второй [CertificateSlipPrinter]
///
/// Потому что печатать по проводу нечего. [CertificateSlipPrinter.printIssued]
/// принимает **готовый** [GiftCertificate], и браузерная реализация могла бы
/// только переслать его поля кассе — то есть дать вкладке назвать номинал на
/// бумажке, которую касса напечатает как своё обязательство. Слип с
/// выдуманной суммой — подделка, и неважно, что выдумала её своя же вкладка.
///
/// Значит касса обязана **сама** найти бумажку, а вкладка — назвать только
/// то, чем её находят: номер и ПИН. Это другой контракт, а не другая
/// реализация того же.
///
/// # Почему ПИН едет вместе с номером
///
/// Слип несёт номер и остаток. Напечатать его тому, кто бумажки в руках не
/// держит, значит выдать чужой сертификат по одному подобранному номеру —
/// ровно от этого [CertificateIssuer.lookup] и спрашивает ПИН. Операция
/// провода идёт через тот же `lookup` и под тем же замком перебора
/// (`CertificateThrottle`), что и `pay.certificate`: иначе она была бы
/// дверью в соседнюю операцию.
///
/// # Чего этот порт НЕ делает
///
/// Не печатает слип **при выпуске** — там он печатается сам, внутри
/// `LocalCertificateIssuer.issue`, и с планшета тоже: выпуск с планшета
/// исполняет касса (`pay.certificateIssue`), а вместе с ним и печать. Этот
/// порт нужен ровно для второго случая — когда бумажка не вышла и кассир
/// просит её заново.
abstract interface class CertificateSlipReprinter {
  /// Найти бумажку и отправить её слип в очередь печати.
  ///
  /// Возвращает найденное — экрану есть что показать («слип №… отправлен»), и
  /// отвечать «готово» без единого доказательства того, что бумажка
  /// существует, было бы хуже.
  ///
  /// Отказы — броском `WireRefusal` с кодами `gift_certificate.dart`
  /// (`certificate_unknown`, `certificate_pin_wrong`, `certificate_expired`):
  /// их даёт [CertificateIssuer.lookup], и второго слова на ту же беду здесь
  /// не заводится.
  ///
  /// **Беда печати бедой поиска не становится.** Отправка слипа не ожидается
  /// и не бросает (докстринг [CertificateSlipPrinter.printIssued]); что слип
  /// до очереди не дошёл, кассир читает из
  /// [CertificateSlipPrinter.takeTroubles] или видит на экране очереди.
  Future<GiftCertificate> reprint({
    required String number,
    String? pin,
    int? userId,
  });
}
