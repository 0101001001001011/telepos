import 'package:decimal/decimal.dart';
import 'package:telepos/domain/discount/discount_policy.dart';
import 'package:telepos/domain/payment/gift_certificate.dart';

/// Выпуск сертификата и его предъявление — **две разные работы, и в этом
/// вся задача 21**.
///
/// # Продажа сертификата — не оплата, а выпуск
///
/// Соблазн сделать её «ещё одним видом оплаты» велик и неверен. Когда
/// покупатель платит 5000 за сертификат, деньги в кассу **приходят**:
/// наличными или картой, обычной строкой `Payments`, обычной выручкой
/// смены. Сертификат в этом чеке — не то, чем платят, а то, что покупают.
/// Сделать его строкой оплаты значило бы записать, что чек на 5000
/// оплачен сертификатом на 5000, — то есть что денег не приходило вовсе.
///
/// Поэтому [issue] не участвует в раскладке оплаты ни одной ветвью. Она
/// делает ровно две вещи: заводит бумажке остаток и **берёт на кассу
/// обязательство** — счёт рода `AccountType.certificateLiability` растёт
/// на номинал. Обязательство и есть смысл выпуска: касса получила деньги
/// за товар, которого ещё не отдала.
///
/// # Предъявление — зачёт, а не деньги
///
/// [lookup] отвечает, годна ли бумажка и сколько на ней осталось.
/// Списание же живёт не здесь, а в `CertificateDao.redeem`, и зовётся
/// **внутри транзакции продажи**: гашение отдельно от продажи — это либо
/// подарок, повторяемый бесконечно, либо отданный даром товар. Разделение
/// намеренное и названо здесь, чтобы следующий читатель не искал
/// `redeem` в этом файле.
abstract class CertificateIssuer {
  /// Выпустить сертификат.
  ///
  /// Отказы приходят **значением** `WireRefusal` (I144):
  /// [certificateDuplicateNumberCode], [certificateNominalInvalidCode],
  /// [certificateAccountMissingCode].
  ///
  /// # Право — обязательным доводом [by] (ревизия второго фронта 2026-09-19)
  ///
  /// `op.issueCertificate` проверяет **сама операция**, а не маршрут и не
  /// экран. До ревизии право читали три места, и ни одно не было выпуском:
  /// сторож провода (только для браузера), карта маршрутов (только для
  /// `redirect`) и экран (только для нажатой кнопки). Любой другой путь к
  /// `GetIt.I<CertificateIssuer>()` выписывал обязательство магазина на
  /// любую сумму — I162 дословно: спрятанная кнопка правом не является.
  ///
  /// Приём тот же, что у корзины (`LocalCartService._requireRight`):
  /// полномочия приходят **доводом**, и забыть их нельзя по сборке. Отказ —
  /// `WireDenied.forbidden`, тем же словом, каким отказывает сторож провода:
  /// кассир у прилавка и кассир за планшетом обязаны получить одну причину.
  ///
  /// Проверка стоит **первой**, раньше номера и номинала. Это не порядок
  /// ради порядка: кассир без права, получивший
  /// [certificateDuplicateNumberCode], узнал бы перебором, какие номера уже
  /// выпущены.
  ///
  /// **Довод отдельно от [userId] намеренно.** [by] отвечает «кому можно» и
  /// приходит из сеанса или из `AppState`; [userId] — «кого записать в
  /// бумажку», и у выпуска по проводу его сегодня нет вовсе (`TillOperations`
  /// строит вызов из полей заявки). Свести их в одно поле значило бы менять
  /// записанное в базе заодно с проверкой права — две правки под одним
  /// именем.
  ///
  /// **Чего [by] НЕ закрывает.** [cancel] довода не принимает: отзыв
  /// по-прежнему держат маршрут и экран. Названо, чтобы следующий не читал
  /// «сертификаты закрыты правом» шире, чем написано.
  Future<GiftCertificate> issue({
    required DiscountAuthority by,
    required String number,
    required Decimal nominal,
    String? pin,
    int? expiresAt,
    int? receiptNo,
    int? posId,
    int? userId,
  });

  /// Что касса знает о бумажке, которую ей подали.
  ///
  /// **Проставляет `expired`, если срок вышел** — и потому не является
  /// чистым чтением. Разбор, почему отметка ставится здесь, а не внутри
  /// транзакции продажи, — в докстринге [CertificateStatus.expired].
  ///
  /// Отказ значением, а не `null` с догадкой: «нет такого» и «не тот ПИН»
  /// лечатся по-разному.
  Future<GiftCertificate> lookup({required String number, String? pin});

  /// Отозвать: утерян, испорчен, выпущен по ошибке.
  Future<void> cancel(String number);
}

/// Сколько сертификат покроет в этом чеке — **решение, а не расчёт**.
///
/// # Остаток остаётся на сертификате; сдачи наличными нет
///
/// Сертификат на 5000, предъявленный за чек на 1200, гасится на 1200.
/// Оставшиеся 3800 остаются на бумажке. Кассир не открывает ящик.
///
/// Три довода, и каждый самостоятельный:
///
/// 1. **Сдача превращает сертификат в способ обналичить.** Купил
///    сертификат картой на 100 000, отоварил на 500, забрал 99 500
///    наличными — это вывод денег из кассы через подарочную бумажку, и
///    ровно поэтому у вида `givesChange = false` (задача 14, шаг 3).
/// 2. **Денег на сдачу в ящике нет.** Деньги за сертификат пришли раньше
///    — может быть, в другую смену, может быть, на другой кассе сети —
///    и лежат **обязательством**, а не наличностью. Выдать их из
///    сегодняшнего ящика значит отдать чужие деньги: инкассация сойдётся
///    с недостачей, а отчёт смены соврёт на всю сумму сдачи.
/// 3. **Остаток есть кому хранить.** Он возможен ровно потому, что у
///    сертификата своя таблица со своим остатком; будь сертификат
///    «строкой оплаты и всё», выбора между сдачей и остатком не было бы
///    вовсе — остаток некуда было бы записать. Эта функция и таблица —
///    две стороны одного решения.
///
/// Обратная сторона названа честно: **разменять сертификат нельзя**.
/// Покупатель с сертификатом на 5000 и чеком на 1200 уходит с бумажкой на
/// 3800, а не с деньгами. Это цена решения, а не его подарок; лечится она
/// правилом магазина («сертификат не разменивается»), напечатанным на
/// самой бумажке, а не веткой в кассе.
///
/// # Здесь нет ни полей, ни объекта — и это не забывчивость
///
/// Первая редакция завела `CertificateApplication` со ссылкой на бумажку,
/// списываемой суммой и парой производных (`rest`, `coversPartially`). Ни
/// одно из них не понадобилось: раскладка считает сумму и кладёт строку
/// оплаты, а остаток читает потом из базы, где он и есть правда. Объект,
/// который никто не строит, — это второй ответ на тот же вопрос, ждущий,
/// когда с ним разойдётся первый. Осталось правило, ради которого файл и
/// написан.
abstract final class CertificateApplication {
  /// `min(остаток, сколько осталось доплатить)`.
  static Decimal amountFor({
    required Decimal balance,
    required Decimal toPay,
  }) => balance < toPay ? balance : toPay;
}
