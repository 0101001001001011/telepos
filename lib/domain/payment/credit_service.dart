/// Платёж больше, чем осталось по договору.
///
/// # Почему отказ, а не «взять сколько должны, остальное в аванс»
///
/// Соблазн велик: остаток договора лежит на расчётном счёте покупателя
/// (`AccountType.agentMain`), и переплата естественно превратилась бы в
/// кредитовое сальдо — то есть в аванс, ровно тот, который завела задача
/// 23. Одно число, один счёт, никакой второй правды.
///
/// И всё-таки нет, по двум доводам:
///
/// 1. **Это другой документ.** Погашение договора и приём аванса —
///    разные операции с разными основаниями. Склеив их, касса приняла бы
///    аванс без документа на приём: покупатель, пришедший за своим
///    остатком, услышал бы «у вас аванс», которого он не вносил.
/// 2. **Переплата — почти всегда опечатка.** Досрочное погашение целиком
///    — это `amount == outstanding`, число, которое касса умеет назвать
///    сама; всё, что больше, — лишний ноль. Названный остаток лечит
///    опечатку за одно движение, а зачисленный аванс лечится разбором.
///
/// Недоплата при этом принимается молча и без слова, потому что она и
/// есть **нормальный ход договора**: покупатель вносит месячный взнос.
const creditOverpaymentCode = 'credit_overpayment';

