import 'package:telepos/domain/payment/credit_contract.dart';

/// Рассрочка как контракт — задача 24.
///
/// Чистый Dart: ни Flutter, ни drift. Реализация кассовая
/// (`LocalCreditService` поверх `CreditDao`).
///
/// # Здесь НЕТ метода «заключить договор», и это решение
///
/// Договор рождается **внутри транзакции продажи**
/// (`SaleUseCaseImpl.perform`), а не отдельным вызовом рядом с ней. Тот же
/// довод, что у гашения сертификата, и он ломается в обе стороны, и обе
/// денежные:
///
/// * завести договор **до** продажи — и упавшая продажа оставляет
///   покупателю долг за товар, которого он не получил;
/// * завести **после** — и упавшее заведение оставляет чек, оплаченный
///   рассрочкой, у которой договора нет. Товар отдан, обязательства нет:
///   подарок, который никто не заметит, потому что чек сошёлся по строкам.
///
/// Публичный `open` был бы приглашением сделать именно это. Раскладка
/// оплаты отдаёт [CreditContractDraft], а записывает его продажа.
///
/// # Граница с банковским модулем
///
/// Названа в докстринге [CreditContract] и повторяется здесь одной
/// строкой, потому что именно этот контракт соблазнительно расширить:
/// **касса хранит подписанный график и то, что по нему заплачено; всё,
/// что меняет график после подписи, — банковский модуль.** Ни пени, ни
/// реструктуризации, ни начисления процентов во времени здесь не будет.
abstract class CreditService {
  /// Договор с графиком по номеру. `null` — такого нет.
  Future<CreditContractView?> byNumber(String number);

  /// Договор, заключённый этим чеком. `null` — чек не рассрочный.
  ///
  /// Читается возвратом: возврат рассрочного чека **отказывается**, и
  /// узнать, рассрочный ли он, надо до единой записи.
  Future<CreditContractView?> byReceipt({
    required int receiptNo,
    required int posId,
  });

  /// Живые договоры покупателя, по возрастанию даты подписи.
  Future<List<CreditContractView>> activeFor(int agentLocalId);

  /// Есть ли у покупателя просрочка на момент [asOf].
  ///
  /// # Это и есть ответ на «что, если никто не смотрит»
  ///
  /// Просрочка вычисляемая (шаг 3), и вычислить её может кто угодно —
  /// значит, никто. Молчаливое «всё хорошо» здесь недопустимо, поэтому у
  /// вычисления есть **обязательный читатель на денежном пути**:
  /// раскладка оплаты спрашивает этот метод перед тем, как продать в
  /// рассрочку ещё раз (`LocalPaymentService._plan`, отказ
  /// [creditOverdueCode]).
  ///
  /// То есть просрочку замечает не экран и не отчёт, а **та операция,
  /// которой она дороже всего обойдётся**: выдача второго товара тому,
  /// кто не заплатил за первый. Экран и печать её тоже показывают, но на
  /// них ничего не держится — их можно не открыть.
  Future<bool> hasOverdue(int agentLocalId, {DateTime? asOf});

  /// Принять платёж по договору.
  ///
  /// Разносится **FIFO по `seq`** (шаг 6): любое другое правило требует
  /// выбора человеком, а кассир его сделать не может — договора у него
  /// перед глазами нет.
  ///
  /// Недоплата — обычный случай (покупатель платит месячный взнос, а не
  /// весь договор): разносится сколько есть, остальное остаётся должным.
  /// **Переплата — отказ** ([creditOverpaymentCode]) с названным
  /// остатком: взять больше, чем должны, значит превратить погашение в
  /// приём аванса, а это другой документ. Разбор — в докстринге кода.
  ///
  /// Отказы приходят **значением** (`WireRefusal`, I144).
  ///
  /// [receivingAccountId] — куда легли **живые деньги**: счёт кассы или
  /// банковский. Довод, почему это обязательный довод, а не умолчание:
  /// погашение двигает **два** счёта, и забыть второй значит уменьшить
  /// долг покупателя деньгами, которых никуда не положили. Именно этим и
  /// болеет сегодняшнее погашение долга контрагентом
  /// (`CustomerPaymentUseCaseImpl` двигает счёт покупателя, а счёт кассы
  /// правит **экранный контроллер** `CustomerPaymentController
  /// ._creditPosAccount`, вне транзакции и в другом ярусе).
  Future<CreditRepayment> repay({
    required String contractNumber,
    required Decimal amount,
    required int userId,
    required int receivingAccountId,
    DateTime? at,
  });
}

