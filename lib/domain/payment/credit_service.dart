/// Возврат рассрочного чека **отказывается** — шаг 7 задачи 24.
///
/// # Довод измерен, а не выведен
///
/// `RefundUseCaseImpl` двигает баланс покупателя **безусловно**
/// (`if (customerLocalId != null) await _updateAgentBalance(...)`), и
/// раскладка возврата отдаёт из ящика долю каждой строки оплаты, кроме
/// отложенных. На рассрочном чеке это дало бы вот что: чек 10 000, первый
/// взнос 2 000 наличными, рассрочка 8 000. Возврат целиком выдал бы из
/// ящика 2 000 (доля наличной строки) и сдвинул бы счёт покупателя на
/// 8 000 в плюс — то есть **вернул бы деньги, которых покупатель не
/// платил**, и при этом оставил бы договор живым: строки графика
/// `credit_schedule_entries` возврат не читает ни одной веткой, и
/// покупатель остался бы должен по договору за товар, который вернул.
///
/// # Почему отказ, а не «правильный возврат»
///
/// Потому что правильный возврат рассрочки — это **расторжение
/// договора**, и оно не операция кассы: надо решить, что делать с уже
/// внесёнными взносами, с надбавкой, с частичным возвратом (вернули один
/// товар из трёх — договор уменьшается или переподписывается?), и каждое
/// из этих решений меняет **подписанный** график. Всё, что меняет график
/// после подписи, лежит за границей — в банковском модуле.
///
/// Отказ — честная граница: он называет причину и не портит денег.
/// Молчаливый неправильный возврат портил бы их каждый раз.
const refundInstallmentRefusedCode = 'refund_installment_refused';
