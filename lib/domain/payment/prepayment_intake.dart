/// Приём аванса покупателя — требование заказчика 2026-09-18.
///
/// # Почему контракт, а не «ещё один метод кассы»
///
/// До этой работы приём аванса умел ровно один экран — кассовый диалог
/// `RecordCustomerPaymentDialog`, который звал `CustomerPaymentUseCase`
/// напрямую из `GetIt`. У браузерного терминала был **только зачёт**: он
/// умел спросить остаток (`pay.prepayment`) и зачесть его в чеке
/// (`PaymentRequest.prepaymentUsed`), а внести деньги вперёд — нет. Живая
/// приёмка 2026-09-17 это и намерила.
///
/// Контракт заведён затем, чтобы у браузера появилась **вторая
/// реализация того же действия**, а не второй путь к деньгам: кассовая
/// половина — сам `CustomerPaymentUseCase` (он объявлен реализующим этот
/// контракт), браузерная — `WtPrepaymentIntakeService` поверх операции
/// провода `pay.prepaymentIntake`. Деньги в обоих случаях записывает
/// **одна и та же** кассовая реализация; терминал только приносит заявку.
///
/// # Почему решение не едет по проводу
///
/// У `CustomerPaymentUseCase` есть [CustomerPaymentDecision]: деньги можно
/// положить на расчётный счёт покупателя (аванс) или на бонусный
/// (депозит). По проводу едет **только аванс**, и выбора в кадре нет
/// вовсе: бонусный счёт гасится скидкой, а не зачётом, чеком приёма аванса
/// не сопровождается и авансом не является (докстринг
/// `CustomerPaymentUseCaseImpl._fiscalizeAdvance`). Положить решение в
/// кадр значило бы дать терминалу выбирать, на какой счёт лягут деньги, —
/// то есть отдать вкладке правило учёта.
///
/// # Отказы — значением, а не текстом (I144)
///
/// Каждый отказ этого контракта назван кодом ниже; текст при коде —
/// довод для журнала, а не фраза для кассира. Фразу берёт словарь
/// (`sale_refusal_keys.dart` → `error_localizer.dart` → `intl_*.arb`), и
/// сторож `sale_refusal_codes_localized_test.dart` читает **этот файл**:
/// `lib/domain/payment` стоит корнем в его разведке, значит новый код без
/// перевода сюда не пройдёт.
library;

import 'package:decimal/decimal.dart';
import 'package:meta/meta.dart';

/// Сумма не положительна — ноль или минус.
///
/// Отдельным кодом, а не общим «отказано»: это единственная беда заявки,
/// которую кассир исправляет сам, не сходя с экрана.
const prepaymentAmountInvalidCode = 'prepayment_amount_invalid';

/// Вид оплаты не годится в приём денег.
///
/// Аванс принимается **живыми деньгами и только ими** — наличными, картой,
/// по QR (`PaymentSettlement.tender`). Зачёт (бонус, сертификат, сам аванс)
/// или долг здесь означали бы «покупатель внёс аванс сертификатом», то есть
/// обналичивание бумажки через счёт покупателя.
const prepaymentTenderInvalidCode = 'prepayment_tender_invalid';

/// У кассы нет счёта, **на который лечь принятым деньгам**.
///
/// Наличные ищут счёт кассы, безнал — счёт эквайринга; ни того ни другого
/// нет — принимать некуда. До 2026-09-18 этот случай был **молчаливым**:
/// сальдо покупателя росло, касса о деньгах не знала, и расходились они
/// ровно на сумму приёма. Отказ идёт **до первой записи** — «принять
/// нечем» не имеет права превратиться в «принято наполовину».
const prepaymentTillAccountMissingCode = 'prepayment_till_account_missing';

/// В заявке нет ключа повтора — принимать нельзя.
///
/// Кадр без ключа приходит только от вкладки, собравшей его мимо экрана
/// (`PrepaymentIntakeScreen` ключ кладёт всегда). Принять такой кадр значило
/// бы вернуть дефект 2026-09-18 ровно в том виде, в каком он жил: касса,
/// принявшая деньги без ключа, второй такой же кадр отличить не сможет и
/// примет их снова.
///
/// Отказ **до первой записи**, тем же правилом, что
/// [prepaymentTillAccountMissingCode]: «принимать нечем» и «принимать
/// вслепую» одинаково не имеют права превращаться в «принято наполовину».
const prepaymentIntakeKeyMissingCode = 'prepayment_intake_key_missing';

/// Деньги записать не удалось, и причина названа кассой не была.
///
/// Запасной выход: касса отвечает по-русски текстом (нет счёта у
/// покупателя, отказ базы), а кассиру нужна фраза на его языке. Текст
/// уходит в журнал, код — на экран.
const prepaymentIntakeFailedCode = 'prepayment_intake_failed';

/// Эта касса приёма аванса по проводу не проводит.
///
/// Тот же род отказа, что `certificates_unavailable` у выпуска
/// сертификата: голый процесс `bin/telepos_backend.dart` не поднимает
/// контейнера зависимостей, и реализации у операции нет. Отвечать
/// «принято» без записи денег — худшее из возможного.
const prepaymentIntakeUnavailableCode = 'prepayment_intake_unavailable';

/// Аванса на счёте меньше, чем просят выдать.
///
/// # Почему отдельный код, а не [prepaymentIntakeFailedCode]
///
/// Потому что это единственная беда выдачи, которую кассир **исправляет
/// сам, не сходя с экрана**: уменьшить сумму. Тот же довод, что у
/// [prepaymentAmountInvalidCode].
///
/// # Почему не `prepayment_insufficient`
///
/// Тот код уже занят зачётом аванса в продаже, и его фраза говорит
/// «аванс уже зачли другим чеком» — про гонку двух чеков. Здесь беда
/// другая и неподвижная: на счёте лежит меньше, чем просят, и второй
/// кассир к этому отношения не имеет. Одна фраза на две разные беды
/// отправила бы кассира искать чужой чек там, где надо просто убавить
/// сумму.
///
/// Сама проверка стоит **условной записью внутри транзакции денег**
/// (`AccountDao.claimCredit`), а не чтением перед ней: между чтением
/// остатка и выдачей помещается второй кассир, выдающий те же деньги.
const prepaymentRefundExceedsBalanceCode = 'prepayment_refund_exceeds_balance';

/// Что кассир просит принять.
///
/// `terminalId` здесь нет намеренно — и это не забывчивость, а то же
/// правило, по которому его нет у `CardAsk` и `CompleteAsk`: сальдо
/// покупателя одно на кассу, рабочего места операция не читает вовсе.
@immutable
class PrepaymentIntakeRequest {
  const PrepaymentIntakeRequest({
    required this.key,
    required this.customerId,
    required this.amount,
    required this.tenderKindId,
    this.note,
  });

  /// Ключ заявки — **чем касса узнаёт повтор**.
  ///
  /// # Что стоило его отсутствие
  ///
  /// До 2026-09-18 заявка несла покупателя, сумму, вид оплаты и примечание —
  /// и ничего, по чему касса отличила бы «то же самое ещё раз» от «ещё
  /// столько же». Живая приёмка намерила, чем это кончается: провод рвётся
  /// (`stream_failed: Connection lost`) **после** того, как деньги приняты,
  /// ответ до вкладки не доезжает, экран показывает отказ — и кассир,
  /// поверив экрану, жмёт «Принять» второй раз. Покупателю записывается
  /// вдвое больше, чем он дал, а ящик сходится с первой суммой: расхождение
  /// живёт до сверки сальдо, то есть недели.
  ///
  /// # Почему ключ приходит от вкладки, а не рождается на кассе
  ///
  /// Потому что повтор знает только тот, кто повторяет. Касса видит два
  /// одинаковых кадра и не может решить, одна это заявка или две:
  /// покупатель, честно вносящий тысячу дважды за смену, шлёт кадры,
  /// отличающиеся лишь секундами. Любое правило «одинаковое в пределах N
  /// секунд — повтор» съело бы законный второй взнос и при этом пропустило
  /// бы повтор, доехавший на N+1 секунде.
  ///
  /// Где именно ключ рождается и когда обновляется — в докстринге
  /// `PrepaymentIntakeScreen._intakeKey`; коротко: он живёт ровно столько,
  /// сколько живёт **заполненная форма**, и умирает от всякой её правки.
  ///
  /// Обязателен, а не `String?`: необязательность здесь была бы способом
  /// забыть — тот же довод, каким обязательно рабочее место у операций
  /// провода. Кадр без ключа отказывается названной причиной
  /// ([prepaymentIntakeKeyMissingCode]), а не принимается «по старинке».
  final String key;

  /// Покупатель — тот же `localId` картотеки, который отдаёт поиск по
  /// телефону (`PaymentService.findLoyalty`).
  final int customerId;

  final Decimal amount;

  /// Чем приняты деньги: вид оплаты рода `PaymentSettlement.tender`.
  /// Обязателен — до v47 приём не хранил вида, и аванс, принятый картой,
  /// уезжал оператору наличными.
  final int tenderKindId;

  /// Примечание проводки — **данные записи**, а не фраза экрана: оно
  /// ложится в `cash_operations.note` и читается потом человеком в
  /// журнале. Поэтому по проводу едет как есть.
  final String? note;
}

/// Чем кончился приём.
///
/// Фискального **признака достаточно, а исхода очереди — нет**: чек приёма
/// аванса уходит оператору синхронно или ложится в очередь, и оба случая
/// для кассира одинаковы — деньги приняты. Отказ оператора приезжает
/// [fiscalError] и денег не отменяет: тот же довод, что у продажи
/// (`SaleOutcome.fiscal`).
@immutable
class PrepaymentIntakeOutcome {
  const PrepaymentIntakeOutcome({
    required this.operationId,
    required this.balance,
    this.fiscalSign,
    this.fiscalError,
  });

  /// Строка `cash_operations`, которой приём записан.
  final int operationId;

  /// Сальдо расчётного счёта покупателя **после** приёма.
  final Decimal balance;

  /// Фискальный признак чека приёма аванса; `null` — чека не было
  /// (настройка выключена, узла нет, или весь взнос ушёл на погашение
  /// долга).
  final String? fiscalSign;

  /// Почему чек не выписан, хотя был нужен. Деньги при этом приняты.
  final String? fiscalError;
}

/// Принять деньги вперёд на расчётный счёт покупателя.
///
/// Две реализации: `CustomerPaymentUseCaseImpl` на кассе и
/// `WtPrepaymentIntakeService` в браузере. Третьей быть не должно — это
/// единственная дверь к авансу, и она же считает и выписывает чек.
abstract interface class PrepaymentIntakeService {
  /// Отказы — броском `WireRefusal` с одним из кодов этого файла; успех —
  /// значением. Исключений иного рода реализация не бросает: они уехали
  /// бы на провод именем типа вместо названной причины (I144).
  ///
  /// # Повтор обязан выглядеть успехом, потому что он им и является
  ///
  /// Заявка с уже принятым [PrepaymentIntakeRequest.key] отвечает **тем же
  /// самым** [PrepaymentIntakeOutcome], каким ответила первая попытка, и
  /// денег второй раз не принимает. Не отказом «уже принято»: кассир,
  /// нажавший «Принять» после оборванного провода, не сделал ничего
  /// неправильного — он не знает, доехала ли первая попытка, и узнать не
  /// может. Отказ на этом месте научил бы его не верить ни успеху (вдруг
  /// не доехало), ни отказу (вдруг доехало) — то есть не верить кассе
  /// вовсе, и сверять сальдо руками после каждого взноса.
  Future<PrepaymentIntakeOutcome> acceptPrepayment(PrepaymentIntakeRequest ask);
}

// --- Выдача аванса деньгами: решение заказчика 2026-09-18 ---------------

/// В заявке на выдачу нет ключа повтора — выдавать нельзя.
///
/// # Почему у выдачи свой код, а не общий с приёмом
///
/// Потому что фраза кассиру называет **что именно** не поехало, и «заявка
/// приёма без ключа» на экране выдачи отправила бы его искать беду не там.
/// Беда же одна и та же, и довод тот же, что у
/// [prepaymentIntakeKeyMissingCode], только цена выше: касса, выдавшая
/// деньги без ключа, второй такой же кадр отличить не сможет и **выдаст
/// живые деньги из ящика второй раз**. У приёма расхождение видно сверкой
/// сальдо; здесь его видно недостачей.
///
/// Отказ **до первой записи**.
const prepaymentRefundKeyMissingCode = 'prepayment_refund_key_missing';

/// Деньги выдать не удалось, и причина названа кассой не была.
///
/// Запасной выход, тот же, что [prepaymentIntakeFailedCode] у приёма: касса
/// отвечает по-русски текстом (нет счёта у покупателя, отказ базы), а
/// кассиру нужна фраза на его языке. Текст уходит в журнал, код — на экран.
const prepaymentRefundFailedCode = 'prepayment_refund_failed';

/// Эта касса выдачи аванса по проводу не проводит.
///
/// Тот же род отказа, что [prepaymentIntakeUnavailableCode]: голый процесс
/// `bin/telepos_backend.dart` не поднимает контейнера зависимостей, и
/// реализации у операции нет. Отвечать «выдано» без записи — худшее из
/// возможного, а здесь ещё и без денег в руках покупателя.
const prepaymentRefundUnavailableCode = 'prepayment_refund_unavailable';

/// Что кассир просит выдать.
///
/// `terminalId` здесь нет по тому же правилу, что у [PrepaymentIntakeRequest]:
/// сальдо покупателя одно на кассу, рабочего места операция не читает вовсе.
@immutable
class PrepaymentRefundRequest {
  const PrepaymentRefundRequest({
    required this.key,
    required this.customerId,
    required this.amount,
    required this.tenderKindId,
    this.intakeOperationId,
    this.note,
  });

  /// Ключ заявки — **чем касса узнаёт повтор**.
  ///
  /// # Почему он обязателен здесь, хотя у кассового экрана его нет
  ///
  /// Потому что ключ нужен ровно там, где между кассиром и деньгами лежит
  /// провод, способный проглотить ответ. У кассового экрана
  /// (`/prepayment-refund`) кассир стоит перед ящиком и видит исход своими
  /// глазами: повторить «вслепую» он не может. У вкладки всё наоборот —
  /// обрыв **после** записи денег выглядит на экране отказом, и кассир,
  /// поверив экрану, нажимает «Выдать» второй раз.
  ///
  /// Это не предположение: ровно так измерена та же беда у приёма
  /// 2026-09-18 (`stream_failed: Connection lost` после записи денег).
  /// Докстринг `CustomerPaymentUseCase.refundPrepayment` называл отсутствие
  /// ключа открытым вопросом словами «появится провод — понадобится ключ».
  /// Провод появился этой работой, и ключ заведён **до** того, как операция
  /// поехала, а не после первой недостачи.
  ///
  /// Где ключ рождается — в докстринге `PrepaymentIntakeScreen._intakeKey`:
  /// он живёт ровно столько, сколько живёт заполненная форма, и умирает от
  /// всякой её правки. Тот же механизм на том же экране обслуживает оба
  /// направления — и смена направления правит форму, то есть рождает новую
  /// заявку.
  ///
  /// Обязателен, а не `String?`: необязательность была бы способом забыть.
  /// Кадр без ключа отказывается [prepaymentRefundKeyMissingCode] до первой
  /// записи.
  final String key;

  /// Покупатель — тот же `localId` картотеки, который отдаёт поиск по
  /// телефону (`PaymentService.findLoyalty`).
  final int customerId;

  final Decimal amount;

  /// Чем выдаются деньги: вид оплаты рода `PaymentSettlement.tender`.
  /// Зачёт или долг здесь означали бы не выдачу, а перекладывание
  /// обязательства ([prepaymentTenderInvalidCode]).
  final int tenderKindId;

  /// Проводка приёма, чей чек станет основанием документа возврата, если
  /// кассир её назвал. `null` значит «не назван», а не «не было»: аванс это
  /// пул, и сходить за последним чеком покупателя самой значило бы для кассы
  /// сослаться на чужой документ.
  final int? intakeOperationId;

  /// Примечание проводки — **данные записи**, а не фраза экрана: оно ложится
  /// в `cash_operations.note` и читается потом человеком в журнале.
  final String? note;
}

/// Чем кончилась выдача.
///
/// # Почему свой класс, а не [PrepaymentIntakeOutcome]
///
/// Поля совпадают по составу и **расходятся по смыслу**: [balance] здесь
/// меньше прежнего, а [fiscalSign] принадлежит документу **возврата**
/// аванса, а не чеку приёма. Один класс на оба исхода читался бы как
/// «аванс» до тех пор, пока кто-нибудь не сверил бы знак, — и первая же
/// правка, верная для приёма, стала бы неверной для выдачи молча.
@immutable
class PrepaymentRefundOutcome {
  const PrepaymentRefundOutcome({
    required this.operationId,
    required this.balance,
    this.fiscalSign,
    this.fiscalError,
  });

  /// Строка `cash_operations` рода «расход», которой выдача записана.
  final int operationId;

  /// Сальдо расчётного счёта покупателя **после** выдачи.
  final Decimal balance;

  /// Фискальный признак документа возврата аванса; `null` — документа не
  /// было (настройка выключена, узла нет).
  final String? fiscalSign;

  /// Почему документ не выписан, хотя был нужен. **Деньги при этом выданы**:
  /// отказ оператора выдачи не отменяет — тот же довод, что у приёма и у
  /// продажи. Показывать его отказом значило бы предложить кассиру выдать
  /// деньги второй раз.
  final String? fiscalError;
}

/// Выдать аванс обратно деньгами.
///
/// Две реализации: `CustomerPaymentUseCaseImpl` на кассе и
/// `WtPrepaymentRefundService` в браузере. Третьей быть не должно — это
/// единственная дверь наружу для денег, лежащих на счёте покупателя.
///
/// Отдельным контрактом рядом с [PrepaymentIntakeService], а не методом в
/// нём: у браузерной половины это **другая операция провода** со своим
/// кодеком, и один контракт на две заставил бы вкладку, умеющую только
/// принимать, объявлять метод выдачи заглушкой.
abstract interface class PrepaymentRefundService {
  /// Отказы — броском `WireRefusal` с одним из кодов этого файла; успех —
  /// значением. Исключений иного рода реализация не бросает: они уехали бы
  /// на провод именем типа вместо названной причины (I144).
  ///
  /// # Повтор обязан выглядеть успехом
  ///
  /// Заявка с уже исполненным [PrepaymentRefundRequest.key] отвечает **тем
  /// же самым** [PrepaymentRefundOutcome], каким ответила первая попытка, и
  /// денег второй раз не выдаёт. Разбор, почему не отказ, — в докстринге
  /// [PrepaymentIntakeService.acceptPrepayment]; здесь он вдвое весомее:
  /// кассир, получивший отказ «уже выдано», пошёл бы сверять ящик, а не
