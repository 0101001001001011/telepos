/// Шаблон чека как **порт**, а не как экран поверх базы — решение заказчика
/// 2026-09-18, дословно: «это не граница, а пробел — в браузере должно
/// работать то же, что в приложении».
///
/// # Чего до этого файла не было
///
/// Шапку, подвал и содержимое чека правили два экрана
/// (`receipt_templates_screen.dart`, `receipt_template_editor_screen.dart`),
/// и оба ходили в `AppDatabase` **напрямую**: `receiptTemplateDao`,
/// `thisPosDao`, `ReceiptTemplatesCompanion` с `Value` из drift. В браузер
/// такой экран не собирается вовсе — `lib/data/` тянет `dart:ffi` через
/// `package:sqlite3`, и сторож `browser_routes_test` запрещает этот каталог
/// в замыкании браузерной сборки по построению. Владелец, у которого вместо
/// кассы планшет, поправить текст чека не мог ничем.
///
/// Порт снимает обе беды разом: экран перестаёт знать базу (одно из 74
/// нарушений слоёв), и у него появляется вторая реализация — по проводу.
///
/// # Главное свойство: предпросмотр — это бумага, а не третья раскладка
///
/// Это не пожелание, а то, ради чего [preview] вообще объявлен **методом
/// порта**, а не работой экрана.
///
/// Разбор уже записан в докстринге `lib/hardware/printer/escpos_text_preview
/// .dart` и стоил он дорого: до него предпросмотр рисовал
/// `_PreviewTextRenderer` — вторая, независимая копия раскладки чека. Копии
/// разошлись; предпросмотр переносил ссылку проверки чека по словам, а байты
/// обрезали её по ширине ленты. «Экран, показывающий не то, что напечатается,
/// хуже экрана без предпросмотра».
///
/// Починка тогда свела число раскладок к **одной**:
/// `ReceiptPrintService.renderSalePreviewText` собирает настоящий поток
/// ESC/POS тем же `_buildSaleReceipt`, которым печатает, и разбирает его
/// обратно в текст. Браузерная половина обязана это число не увеличить.
///
/// ## Почему касса считает байты и присылает текст, а не наоборот
///
/// Рассматривались ровно два устройства, и выбор между ними не вкусовой:
///
/// 1. **касса шлёт байты ESC/POS, вкладка разбирает их сама.** Свойство при
///    этом формально держится — байты те же. Но `renderEscPosAsText` живёт в
///    `lib/hardware/`, которого в браузерной сборке быть не может, и файл
///    пришлось бы переселить; а главное — разбор оказался бы **вторым
///    местом в дереве, где рождается текст чека на экране**. Ровно того
///    рода, из-за которого копии и разошлись в прошлый раз. Сторожу пришлось
///    бы сличать два разборщика вместо того, чтобы их не заводить.
/// 2. **касса считает байты, разбирает их своей же единственной функцией и
///    шлёт готовый текст.** Вкладка не знает о чеке ничего — ни ширины
///    ленты, ни выравнивания, ни кодовой страницы: она показывает строку.
///    Раскладка остаётся **одна на всё дерево**, и это свойство держится не
///    бдительностью, а тем, что во второй половине её нет вовсе.
///
/// Взято второе. Цена названа вслух: [preview] — `Future`, а не чистая
/// функция, и кассовый экран из-за браузерного стал перерисовывать
/// предпросмотр с задержкой, а не в `build`. Это плата за то, что
/// раскладка одна; обратное — раскладка в браузере — уже было и уже стоило
/// круга правок.
///
/// Сторож — `test/backend/receipt_template_op_test.dart`, «предпросмотр с
/// браузера — тот же текст, что касса покажет у себя»: он поднимает обе
/// половины провода на настоящей базе и сличает строку, приехавшую во
/// вкладку, с тем, что `renderSalePreviewText` отдаёт на кассе для **того же
/// черновика**. Рядом с ним продолжает работать
/// `test/unit/hardware/receipt_template_wire_test.dart`, «предпросмотр
/// шаблона — те же строки, что вышли на бумагу», который сличает тот же
/// вызов с бумагой настоящего эмулятора через настоящий сокет. Цепочка
/// сомкнута торцами: вкладка = касса = бумага.
///
/// # Образец чека собирает касса, и это часть того же свойства
///
/// [preview] и [testPrint] принимают **только черновик шаблона**. Название
/// магазина, БИН, имя рабочего места, номер образцового чека — всё это
/// касса берёт у себя (`thisPosDao`, `sampleSaleReceiptData`). Вкладке их не
/// присылают и у неё не спрашивают: собери она образец сама, у чека
/// появился бы второй источник реквизитов, и предпросмотр на планшете мог бы
/// показать не тот магазин, который напечатает.
library;

/// Одна строка списка «Шаблоны чеков».
class ReceiptTemplateRow {
  const ReceiptTemplateRow({
    required this.id,
    required this.name,
    required this.builtIn,
    required this.selected,
    required this.optionsJson,
  });

  final int id;
  final String name;

  /// Встроенный шаблон (`ReceiptTemplates.isDefault`): его нельзя удалить.
  ///
  /// Имя поля здесь **не** `isDefault`, и это не вкусовщина: в базе рядом
  /// живёт `isSelected`, и «default» человек читает как «выбранный по
  /// умолчанию», тогда как означает оно «пришёл с установкой». Два
  /// соседних булевых поля, которые путают друг с другом, — готовый дефект.
  final bool builtIn;

  /// Этим шаблоном касса печатает **сейчас** (`ReceiptTemplates.isSelected`).
  final bool selected;

  /// Настройка шаблона как её хранит база — `ReceiptOptions.encode()`.
  ///
  /// Строкой, а не разобранным [ReceiptOptions], нарочно: разбор — дело
  /// экрана (`ReceiptOptions.decode`), а порт и провод возят **то, что
  /// лежит в базе**. Разбери порт настройку у себя, и у формы хранения
  /// появился бы второй читатель, отстающий на одну правку.
  final String optionsJson;
}

/// Что экран шаблонов знает о кассе.
class ReceiptTemplateCatalog {
  const ReceiptTemplateCatalog({
    required this.templates,
    required this.paperWidthMm,
  });

  final List<ReceiptTemplateRow> templates;

  /// Ширина ленты **привязанного принтера** — та, на которой касса напечатает
  /// и на которой собран предпросмотр.
  ///
  /// Не часть шаблона и экраном не правится (докстринг `ReceiptPaperWidth`):
  /// шаблон, помнивший ширину со дня мастера, и был причиной «узкого чека
  /// при выбранном широком». Здесь она только показывается.
  final int paperWidthMm;
}

/// Шаблон чека кассы: список, правка, выбор и предпросмотр.
///
/// Две реализации: `LocalReceiptTemplateSetup` на кассе и
/// `WtReceiptTemplateSetup` в браузере. Экран не различает их ничем — в
/// этом и смысл того, что экран один.
abstract interface class ReceiptTemplateSetupRepository {
  /// Список шаблонов и ширина ленты. Встроенный шаблон засевается здесь же,
  /// если его ещё нет, — тем же вызовом, каким это делал экран.
  Future<ReceiptTemplateCatalog> read();

  /// Записать шаблон. [id] `null` — завести новый.
  ///
  /// Признака «встроенный» здесь нет **полем**, а не по забывчивости:
  /// прежний экран читал `isDefault` из строки и писал обратно то же
  /// значение, то есть изменить его не мог никогда. Возить по проводу поле,
  /// которое некому менять, значило бы дать вкладке единственный способ его
  /// поменять — объявить свой шаблон встроенным и стать неудаляемым.
  /// Правка сохраняет признак строки, новый шаблон встроенным не бывает.
  Future<void> save({
    int? id,
    required String name,
    required String optionsJson,
  });

  /// Печатать этим шаблоном.
  Future<void> select(int id);

  /// Удалить. Встроенный не удаляется — отказ держит касса, а не экран.
  Future<void> remove(int id);

  /// Предпросмотр черновика — **те же байты, что уйдут в принтер**,
  /// разобранные в текст. Разбор целиком — в докстринге файла.
  Future<String> preview(String optionsJson);

  /// Пробная печать на принтере кассы.
  ///
  /// **Черновика не принимает, и это не упущение переноса, а перенос
  /// поведения без правки.** Кассовая кнопка «Пробная печать» звала
  /// `ReceiptPrintService.printSampleReceipt`, а та собирает образец
  /// **выбранным сохранённым** шаблоном (`_resolveOptions`), не тем, что
  /// набран в полях. Так было до этой работы и на кассе; дать вкладке
  /// печатать черновик значило бы сделать браузер способнее кассы на одном
  /// экране из двух — расхождение поверхностей ровно того рода, которое эта
  /// работа закрывает. Несовпадение названо в отчёте как найденное и не
  /// чиненное.
  ///
  /// `false` — принтер не взял задание. Отказ печати не отказ операции:
  /// кассир увидит «не напечаталось», а не красный экран.
  Future<bool> testPrint();
}

/// Эта касса шаблонов чека не держит вовсе.
///
/// Тот же род отказа, что у соседей — `certificates_unavailable`,
/// `prepayment_intake_unavailable`, `qr_setup_unavailable`: голый процесс
/// `bin/telepos_backend.dart` не поднимает контейнера зависимостей, и порта
/// шаблонов у него нет.
///
/// Отвечать «сохранено» без записи — худшее из возможного: владелец ушёл бы
/// с экрана, считая чек настроенным, а из принтера вышел бы прежний.
const receiptTemplatesUnavailableCode = 'receipt_templates_unavailable';

/// Шаблон без названия — отказ, а не подстановка умолчания.
///
/// Экран проверяет то же самое и до кассы (прежний кассовый экран показывал
/// `receiptTemplateNameRequired` снекбаром), но запрет обязан держать **и**
/// касса: кадр можно собрать мимо экрана, а строка без имени в списке
/// шаблонов неотличима от строки, которую забыли отрисовать, — владелец
/// решит, что шаблон пропал, и заведёт второй.
const receiptTemplateNamelessCode = 'receipt_template_nameless';

/// Касса, у которой есть шаблон чека, — и та же самая, которая печатает.
///
/// # Почему порт достаётся через оплату, а не отдельным сотрудником кассы
///
/// Тот же приём, что у `QrProviderSetupHost`, но довод **свой и измеримый**,
/// а не скопированный.
///
/// Шаблон кассы кэшируется внутри службы печати: `ReceiptPrintServiceImpl`
/// держит `_optionsCache` и перечитывает его только по
/// `invalidateReceiptOptionsCache()`. Значит правка шаблона обязана
/// сбрасывать кэш **того самого экземпляра, который напечатает следующий
/// чек**, — иначе владелец поправит подвал, увидит правку в предпросмотре и
/// получит из принтера прежний текст, и так до перезапуска кассы.
///
/// Отдельный необязательный сотрудник `ApiServer`/`TillOperations` позволил
/// бы собрать кассу, у которой печатает одна служба печати, а кэш сбрасывает
/// **другая**: класс один, экземпляра два. Здесь порт снимается с той самой
/// раскладки оплаты, которая чек и печатает, — разойтись им негде.
///
/// `null` — у этой реализации оплаты службы печати нет вовсе (браузерная
/// половина; `bin/telepos_backend.dart` без контейнера зависимостей). Тогда
/// операция честно отказывает [receiptTemplatesUnavailableCode], а не
/// отвечает «сохранено».
abstract interface class ReceiptTemplateSetupHost {
  ReceiptTemplateSetupRepository? get receiptTemplates;
}
