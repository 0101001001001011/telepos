/// Род кассовой операции — **один дом для чисел, которыми он записан**.
///
/// До 2026-09-22 коды 0/1/2 разбирались в четырёх местах разными правилами,
/// и одно из них (`LocalShiftDesk._cashTotals`) само предупреждало в
/// докстринге: «тип 3, появись он завтра, у экрана вычитался бы, а здесь —
/// молча нет». Тип 3 появился, и предупреждение сбылось бы.
///
/// # Почему сведение — отдельный род, а не внесение с изъятием
///
/// Сведение не двигает деньги: оно приводит **журнал** к тому, что человек
/// пересчитал руками. Записывать его внесением значило бы:
///
/// * посчитать его дважды в ожидании смены — объявленные подъёмные уже
///   стоят слагаемым `openingCash`, а строка внесения легла бы в
///   `investmentTotal` поверх них;
/// * соврать в отчёте по операциям: «изъято из кассы» включало бы недостачи,
///   которых никто не изымал.
///
/// Поэтому [isCashMovement] ложен у сведения, и оба читателя сумм смены
/// спрашивают именно его, а не перечисляют коды заново.
library;

/// Внесение наличных в ящик: деньги в кассу положили.
const int kCashOpInvestment = 0;

/// Изъятие наличных: деньги из кассы забрали.
const int kCashOpExpense = 1;

/// Выплата собственнику.
const int kCashOpDividend = 2;

/// Сведение смены с пересчётом при ЗАКРЫТИИ: излишек или недостача против
/// того, сколько должно было быть.
///
/// Знак несёт не число (оно всегда положительно, как у прочих родов), а сам
/// код: [kCashOpReconciliationOverage] против
/// [kCashOpReconciliationShortage].
const int kCashOpReconciliationOverage = 3;

/// Недостача смены — см. [kCashOpReconciliationOverage].
const int kCashOpReconciliationShortage = 4;

/// Сведение с пересчётом при ОТКРЫТИИ: объявленное кассиром против того,
/// что осталось в журнале с прошлого раза.
///
/// # Почему повод — часть рода, а не примечания
///
/// При закрытии слова «излишек» и «недостача» верны: есть ожидание, и
/// пересчёт с ним разошёлся. При открытии ожидания ещё нет — есть только
/// счёт ящика. Подписать первое внесение в новую кассу «излишком» значит
/// обвинить деньги, которые кассир только что положил.
///
/// Сторона всё равно нужна машине (цвет строки, разбор отчёта), поэтому
/// кодов два, а подпись у них одна.
const int kCashOpOpeningCountOverage = 5;

/// Недостача при открытии — см. [kCashOpOpeningCountOverage].
const int kCashOpOpeningCountShortage = 6;

/// Двигает ли операция этого рода деньги в ящике.
///
/// Ложь у всякого сведения: оно правит **запись о деньгах**, а не деньги.
/// Суммы смены («должно быть») складываются только из движений.
bool isCashMovement(int type) => !isReconciliation(type);

/// Сведение ли это — при открытии или при закрытии, любой стороны.
bool isReconciliation(int type) =>
    type == kCashOpReconciliationOverage ||
    type == kCashOpReconciliationShortage ||
    type == kCashOpOpeningCountOverage ||
    type == kCashOpOpeningCountShortage;

/// Основания операций, которые ставит САМА касса.
///
/// # Пространство кодов
///
/// `CashOperations.reasonCode` хранит одно число на два диапазона:
///
/// * **0–5** — роды расхода, ровно `ExpenseType.index`. Второго
///   перечисления для того же понятия нет намеренно: два списка для одного
///   смысла расходятся на первой же правке одного из них.
/// * **от 100** — основания, которые касса ставит сама, без выбора
///   человеком. Они начинаются со ста, чтобы новый род расхода никогда не
///   наехал на них номером.
///
/// Диапазоны различимы и без договорённости: у расхода `type` равен
/// [kCashOpExpense], у прочих — нет.
///
/// # Зачем они вообще
///
/// До схемы v58 эти основания писались в примечание ПРОЗОЙ: «Погашение
/// рассрочки №12», «Вложение на счёт покупателя». Слово для человека,
/// записанное в историю, нельзя перевести — на английской кассе подпись
/// оставалась русской.
const int kCashReasonCreditRepayment = 100;

/// Пополнение счёта покупателя — см. [kCashReasonCreditRepayment].
const int kCashReasonCustomerTopUp = 101;
