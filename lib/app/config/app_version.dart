/// Версия продукта — одна на всё приложение.
///
/// # Зачем отдельная константа
///
/// До 2026-09-21 версий в интерфейсе было **две, и обе неверные**: боковая
/// панель отчётов показывала запечённое `TelePOS v1.6.0`, строка состояния —
/// `v1.0.0` из `String.fromEnvironment('VERSION')`, у которого умолчание
/// было `'1.0.0'`. В `pubspec.yaml` при этом стояло `3.6.0+21`.
///
/// Нашлось это на съёмке маркетингового ролика: обе строки попали в один
/// кадр и разошлись друг с другом на глазах у зрителя.
///
/// # Почему не `package_info_plus`
///
/// Он читает версию из собранного пакета, и это правильно для выпуска, но
/// требует новой зависимости и не работает в виджет-пробах, где пакета нет
/// вовсе. Здесь версия нужна ещё и на экране, снимаемом сценарной дорожкой.
///
/// # Что держит её в согласии с `pubspec.yaml`
///
/// Сторож `test/architecture/app_version_matches_pubspec_test.dart`. Без
/// него константа разошлась бы с `pubspec.yaml` на первом же выпуске —
/// ровно так, как разошлось запечённое `1.6.0`.
///
/// Собранный выпуск по-прежнему может переопределить версию доводом
/// `--dart-define=VERSION=…`; эта константа — не запрет, а честное
/// умолчание вместо выдуманного.
library;

import 'package:telepos/core/constants/app_constants.dart';

/// Версия из `pubspec.yaml`, без номера сборки.
///
/// # Почему значение берётся у `AppConstants`, а не пишется здесь
///
/// Здесь стоял СВОЙ литерал, и это было третье место одной версии:
/// `pubspec.yaml`, `AppConstants.appVersion` и эта константа. Сборщик
/// установщика — объявленный единственным способом менять версию — знал о
/// первых двух. На выпуске 3.7.0 приложение снова сообщало 3.6.0, ровно
/// тем же образом, каким на 3.5.1 сообщало 3.5.0, и об этом прямо написано
/// в комментарии самого сборщика.
///
/// Третье регулярное выражение в сборщике отложило бы повтор, но не сняло:
/// четвёртое место завелось бы так же. Литерал остался ОДИН, там, где его
/// правит сборщик; здесь — ссылка.
///
/// Направление зависимости верное: `lib/app` знает о `lib/core`, обратно —
/// нет.
const String kAppVersion = AppConstants.appVersion;
