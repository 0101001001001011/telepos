import 'package:flutter/widgets.dart';

/// Единственное место в проекте, где живут числа оформления.
///
/// Экраны не объявляют отступов, радиусов и высот — они берут их отсюда.
/// Правило проверяется тестом `test/theme/no_style_literals_test.dart`, и
/// именно проверка делает его правилом: до неё стиль жил в экранах, и
/// `initial_setup_screen.dart` на 3042 строки был тому доказательством.
class AppTokens {
  AppTokens._();

  // Шкала отступов, шаг 4.
  //
  // Шаг, а не произвольные числа: набор из девяти величин, между которыми
  // нельзя вставить десятую, — это и есть то, что заставляет разные экраны
  // выглядеть одинаково. Отступ «на глаз» всегда оказывается новым.
  static const double space4 = 4;
  static const double space8 = 8;
  static const double space12 = 12;
  static const double space16 = 16;
  static const double space20 = 20;
  static const double space24 = 24;
  static const double space32 = 32;
  static const double space40 = 40;
  static const double space48 = 48;

  // Геометрия.
  //
  // Радиусов три, и они не совпадают: секция скруглена сильнее контрола,
  // контрол сильнее чипа. Прежние 4/5/8 читались как Material; телеграмные
  // 12/10/8 — как Telegram, и разница видна именно на сопоставлении, а не на
  // отдельном элементе.
  static const double radiusSection = 12;
  static const double radiusControl = 10;
  static const double radiusChip = 8;

  /// Размер объясняющей иконки рядом с подписью поля.
  ///
  /// Названа размером, а не отступом: совпадение с `space20` случайно, и
  /// подгонять шкалу отступов под иконки — значит связать две несвязанные
  /// вещи. Двадцать — тот размер, на котором иконка обязана оставаться
  /// различимой; на нём же её проверяет голден набора.
  static const double iconSizeHint = 20;

  /// Размер знака завершения на последнем экране мастера.
  ///
  /// Раньше на его месте стоял залитый зелёным круг 120 px с белой галочкой —
  /// самый громкий элемент во всём мастере, притом на экране, где делать уже
  /// нечего. Контурная иконка говорит то же самое и не кричит.
  static const double iconSizeSuccess = 48;

  /// Высота строки секции под палец.
  ///
  /// Ровно 48: ниже палец промахивается, и это предел, названный и Material, и
  /// Apple, а не предпочтение.
  ///
  /// Было 52 «с запасом». Запас снят 2026-08-04: он давал ту самую разреженность,
  /// из-за которой экран не походил на Telegram, а порог доступности от этого не
  /// страдает — 48 и есть порог. Совпадение с ритмом Telegram не случайно: там
  /// считают то же самое.
  static const double rowHeightTouch = 48;

  /// Высота строки секции под курсор.
  ///
  /// Выбирается **режимом ввода, а не шириной экрана**: касса на Windows с
  /// сенсорным монитором широкая, но пальцевая, и 40 на ней означают промахи.
  /// См. `WizardMetrics`.
  ///
  /// 40 — плотность списка Telegram Desktop под мышью, где промах стоит одного
  /// движения, а не потерянного чека.
  static const double rowHeightPointer = 40;

  /// Размер иконки в строке навигации.
  ///
  /// Двадцать, а не двадцать четыре: в списке Telegram иконка — это метка
  /// строки, а не самостоятельный объект, и на 24 она начинает спорить с
  /// подписью. Названа отдельно от [iconSizeHint], хотя число то же:
  /// совпадение случайное, и связывать размер иконки навигации с размером
  /// подсказки у поля значило бы, что правка одного молча правит другое.
  static const double iconSizeNav = 20;

  /// Высота шапки.
  ///
  /// Пятьдесят четыре, а не материальные 56: полоса Telegram Desktop ниже, и
  /// на кассе с экраном 800 точек в высоту каждая пара пикселей уходит
  /// содержимому. Тень не снимается «до нуля» — её просто нет; границу шапки
  /// держит волосок снизу.
  static const double appBarHeight = 54;

  /// Ширина левой колонки назначений.
  ///
  /// Фиксированная, а не «по содержимому». Рельс Material мерил себя сам, и
  /// колонка дышала при смене режима работы: в рознице одна ширина, в
  /// ресторане другая, потому что «Синхронизация» длиннее «Столов». Список,
  /// который переставляется при переключении режима, читается как сбой.
  static const double navColumnWidth = 260;

  /// Ширина свёрнутой колонки назначений.
  ///
  /// Заведена 2026-08-27: развёрнутые 260 точек занимают четверть ширины
  /// кассового экрана 1024×768 под список, в который смотрят раз в смену.
  ///
  /// 60 — не «примерно узко», а сумма того, из чего строка состоит:
  /// [iconSizeNav] 20 плюс [space12] слева и справа (`20 + 12 + 12 = 44`),
  /// плюс [space8] с обеих сторон у самого списка (`44 + 8 + 8 = 60`).
  /// Меньше — и строка не попала бы в [rowHeightTouch] пальцем; больше —
  /// осталась бы пустота, ради которой всё и затевалось.
  static const double navColumnCollapsedWidth = 60;

  /// Высота нижней панели на узком экране.
  ///
  /// Иконка 20 + зазор 4 + подпись 18 = 42, остальное — поля. Безопасная зона
  /// прибавляется сверх этого, а не съедает его.
  static const double bottomBarHeight = 56;

  /// Сегментированный рельс прогресса — подпись мастера.
  static const double railHeight = 3;
  static const double railGap = space4;

  // Иллюстрация. Только на трёх шагах из одиннадцати: в Telegram настройки не
  // иллюстрируют, и картинка на каждой форме подряд удешевляет, а не украшает.
  static const double heroHeightMobile = 160;
  static const double heroHeightTablet = 200;
  static const double heroHeightDesktop = 240;

  /// Ширина колонки контента на планшете.
  static const double columnMaxWidthTablet = 560;

  /// Ширина колонки контента на десктопе.
  ///
  /// Ограничение существует потому, что до него его не было: на мониторе 1920
  /// поля ввода растягивались во всю ширину, и строка «Название» с полем в
  /// метр длиной — это не форма, а таблица.
  static const double columnMaxWidthDesktop = 640;

  // Поля страницы.
  static const double pageMarginMobile = space16;
  static const double pageMarginTablet = space24;
  static const double pageMarginDesktop = space32;

  /// Длительность смены состояния: нажатие, подсветка, доливка сегмента.
  static const Duration durationFast = Duration(milliseconds: 150);

  /// Длительность перехода: раскрытие подсказки, появление секции.
  ///
  /// Обе заметно короче 400 мс. Анимация длиннее читается на кассе как
  /// задержка, а не как движение, и кассир начинает жать второй раз.
  static const Duration durationNormal = Duration(milliseconds: 250);

  /// Толщина разделителя — один **физический** пиксель, а не логический.
  ///
  /// На экране с `devicePixelRatio` 2 логическая единица даёт линию в два
  /// пикселя, и сгруппированный список сразу читается грубо. Это тот случай,
  /// когда разница в один пиксель видна каждому, хотя назвать её мало кто
  /// возьмётся.
  static double hairlineOf(BuildContext context) =>
      1 / MediaQuery.devicePixelRatioOf(context);
}
