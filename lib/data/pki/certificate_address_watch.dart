/// Наблюдение за тем, не уехал ли адрес из-под выписанного листа.
///
/// # Зачем это вообще
///
/// Лист живёт семь суток и перевыпускается на подъёме кассы. Адрес по DHCP
/// живёт столько, сколько решил роутер, и меняется без предупреждения — при
/// смене подсети, при переезде на другую точку доступа, просто по истечении
/// аренды. Между этими двумя событиями касса отвечает на адресе, которого её
/// сертификат не называет, и рукопожатие падает.
///
/// Падает оно **молча** — и это главное. С терминала видно «сертификат не для
/// этого узла», что читается как «касса сломалась» или «сеть сломалась»; с
/// кассы не видно ничего вовсе, потому что до её кода такое соединение не
/// доходит: его обрывает TLS. Измерено 2026-08-05 на настоящем устройстве —
/// `curl` по адресу отвечал `http=000`, и по этому ответу отличить «касса
/// выключена» от «адрес не в листе» нельзя.
///
/// Этот наблюдатель превращает молчание в строку лога. Он **не чинит**: см.
/// [CertificateAddressWatch] о том, почему перевыпуск на ходу был бы хуже
/// отказа.
library;

import 'dart:async';

import 'package:telepos/data/pki/certificate_addresses.dart';

/// Сколько раз в час спрашивать у системы её адреса.
///
/// Минута. Не чаще — перечисление интерфейсов это системный вызов, и смысла
/// звать его на каждый кадр нет: аренда DHCP меняется часами, а не кадрами. Не
/// реже — потому что минута это верхняя граница того, сколько касса будет
/// молчать о собственной недоступности, и минута молчания — это уже потерянная
/// продажа, а не мелочь.
const Duration _defaultPeriod = Duration(minutes: 1);

/// Следит, покрывает ли лист адреса, на которых машина отвечает сейчас.
///
/// # Почему только сообщает, а не перевыпускает
///
/// Перевыпуск меняет отпечаток листа. Браузерный терминал не ходит по цепочке,
/// он прикалывает отпечаток (`serverCertificateHashes`) в момент открытия
/// страницы. Перевыпуск на ходу оборвал бы **все** живые сессии — включая те,
/// у которых с адресом всё в порядке, — ради адреса, которым, возможно, никто
/// не собирался пользоваться. Это лечение хуже болезни: сейчас недоступен один
/// путь, а стало бы недоступно всё.
///
/// Поэтому здесь — сообщение, а починка на следующем подъёме: `TillCertificates`
/// перевыпускает лист, если сегодняшних адресов в нём нет (см.
/// `webTransportCredential`). Касса, которую перезапустили, чинится сама;
/// касса, которую не перезапустили, хотя бы говорит почему.
///
/// # Почему сообщение приходит на смене, а не каждый тик
///
/// Иначе за ночь в лог ляжет 480 одинаковых строк, и тот, кто их читает,
/// научится их пролистывать. Сообщение приходит, когда набор непокрытых
/// адресов **изменился**, — в том числе когда он стал пустым, потому что
/// «починилось» это тоже событие, и без него лог оставляет кассу навсегда
/// сломанной.
class CertificateAddressWatch {
  CertificateAddressWatch({
    required List<String> certifiedAddresses,
    required void Function(List<String> unnamed) onChange,
    Future<List<String>> Function() sample = certificateAddresses,
    Duration period = _defaultPeriod,
  }) : _certified = List<String>.unmodifiable(certifiedAddresses),
       _onChange = onChange,
       _sample = sample,
       _period = period;

  final List<String> _certified;
  final void Function(List<String> unnamed) _onChange;
  final Future<List<String>> Function() _sample;
  final Duration _period;

  Timer? _timer;

  /// Что было в прошлый раз. Начальное значение — «непокрытых нет», и это не
  /// предположение: пустой набор на подъёме это норма, а норма в лог не
  /// пишется. Начни мы с `null`, первая же проверка исправной кассы написала
  /// бы строку о том, что всё в порядке, и таких строк было бы столько же,
  /// сколько запусков.
  List<String> _lastUnnamed = const <String>[];

  /// Начинает следить. Первую проверку делает сразу, не через период: касса,
  /// поднявшаяся с уже уехавшим адресом, обязана сказать это на подъёме, а не
  /// через минуту.
  ///
  /// Повторный вызов ничего не делает — второй таймер удвоил бы строки в логе.
  void start() {
    if (_timer != null) return;
    _timer = Timer.periodic(_period, (_) => unawaited(checkNow()));
    unawaited(checkNow());
  }

  /// Одна проверка. Отдельно от таймера, потому что проверяемо именно решение,
  /// а не то, что таймер тикает.
  ///
  /// Никогда не бросает: [certificateAddresses] отвечает пустым списком на
  /// машине, которая не перечисляет интерфейсы, и пустой список здесь означает
  /// «непокрытых адресов нет» — что для машины без сети правда.
  Future<void> checkNow() async {
    final live = await _sample();
    final unnamed = addressesOutsideCertificate(
      live: live,
      certified: _certified,
    );
    if (_sameAs(unnamed, _lastUnnamed)) return;
    _lastUnnamed = unnamed;
    _onChange(unnamed);
  }

  /// Останавливает слежение. Идемпотентно.
  void stop() {
    _timer?.cancel();
    _timer = null;
  }

  /// Набор, а не список: порядок интерфейсов задаёт система, и перестановка
  /// двух адресов местами — не событие.
  static bool _sameAs(List<String> a, List<String> b) =>
      a.length == b.length && a.toSet().containsAll(b);
}
