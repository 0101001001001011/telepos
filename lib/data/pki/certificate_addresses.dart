/// Какие адреса попадают в лист кассы, и что делать, когда адрес уехал.
///
/// # Зачем отдельный файл, а не две строки в `main.dart`
///
/// Правило выбора адресов — решение кассы, а не библиотеки. `rk_pki` отказалась
/// его принимать намеренно и написала почему: «эта библиотека видит один список
/// интерфейсов, а машина может быть в пяти сетях». Значит правило надо принять
/// здесь и здесь же обосновать — иначе оно осядет параметром вызова, который
/// через месяц никто не сможет объяснить.
///
/// Второе, ради чего файл существует: адрес, выданный по DHCP, меняется, а лист
/// живёт семь суток. Между сменой адреса и следующим запуском касса отвечает на
/// адресе, которого нет в её сертификате, и рукопожатие падает **молча** — с
/// той стороны это выглядит как «касса сломалась». [addressesOutsideCertificate]
/// делает это состояние вопросом, на который есть ответ.
library;

import 'package:telepos/data/transport/host_addresses.dart';

/// Адреса, которые касса кладёт в свой лист как `iPAddress`.
///
/// # Почему ровно эти интерфейсы, а не все и не меньше
///
/// Источник — [localIPv4Addresses], и он не сужается здесь ни на один адрес.
/// Это решение, а не лень, и у него три измеренных основания.
///
/// **Первое: лист обязан покрывать объявление.** Тот же список уходит в mDNS
/// как записи `A`. Терминал, разрешивший имя в адрес, которого нет в листе,
/// получает отказ рукопожатия — ровно тот дефект, ради которого этот файл и
/// написан. Если сузить лист, но не объявление, дефект вернётся с другой
/// стороны и будет выглядеть так же. Поэтому сужать оба списка можно только
/// вместе, то есть в `host_addresses.dart`, где их видит один читатель.
///
/// **Второе: цена ошибки несимметрична.** Запись `iPAddress` не пробуется —
/// она *сверяется*. Лишний адрес в листе не стоит терминалу ничего: он к нему
/// не пойдёт. Недостающий стоит всего — рукопожатие не состоится. У mDNS
/// наоборот: объявленный адрес именно *пробуется*, и лишний стоит терминалу
/// таймаута. Это разные задачи, и жадность здесь безопасна, а там нет.
///
/// **Третье: по строке адреса «настоящую» сеть от виртуальной не отличить.**
/// Измерено на машине разработчика 2026-08-05: из восьми интерфейсов Dart
/// [localIPv4Addresses] оставляет четыре — `192.168.1.210` (Wi-Fi магазина),
/// `10.8.10.23` (тоннель WireGuard), `172.23.48.1` и `172.19.208.1`
/// (коммутаторы Hyper-V и WSL). Отбросить два последних хотелось бы: терминалу
/// они недостижимы, а мельтешение docker/WSL шумело бы в проверке ниже. Но
/// сделать это можно только по **имени интерфейса**, которого
/// [localIPv4Addresses] не отдаёт, а по префиксу адреса — нельзя: `172.16/12` и
/// `10/8` это и адреса Hyper-V, и совершенно законные сети магазина. Правило,
/// отбрасывающее `172.16/12`, отбросило бы настоящую кассу. Такого правила тут
/// не будет.
///
/// Итог: отсев — тот, что уже сформулирован в [localIPv4Addresses] и обоснован
/// там же: интерфейс поднят, адрес не петля и не `169.254/16`. Отсев по имени
/// интерфейса, если он когда-нибудь понадобится, делается в том файле, а не
/// здесь.
///
/// # Про IPv6
///
/// Не кладём, и это тоже решение, а не пропуск. [localIPv4Addresses] спрашивает
/// только IPv4 и объясняет почему: адрес в сертификате, к которому никто ни
/// разу не подключался, — заявление, а не возможность. Измерено на той же
/// машине: глобального IPv6 у неё нет вовсе — `NetworkInterface.list` без
/// фильтра по семейству вернула четыре адреса, все IPv4. То есть класть сейчас
/// было бы нечего даже при желании. `rk_pki` принимает двоеточную форму в том
/// же списке, так что в день, когда IPv6 измерят, меняется один вызов.
Future<List<String>> certificateAddresses() => localIPv4Addresses();

/// Адреса, на которые касса отвечает сейчас, но которых её лист не называет.
///
/// Пустой список — всё хорошо. Непустой — рукопожатие по каждому из этих
/// адресов упадёт, и упадёт так, что с той стороны причину не видно: браузер
/// скажет «сертификат не для этого узла», а касса не скажет ничего вовсе.
/// Поэтому проверка односторонняя и **несимметричная**:
///
/// * адрес есть у машины, но нет в листе — это отказ, о нём надо кричать;
/// * адрес есть в листе, но нет у машины — это ничего. Лист хранит вчерашний
///   адрес, к которому никто не придёт. Перевыпускать из-за этого нельзя:
///   перевыпуск меняет отпечаток, а отпечаток приколот каждой уже открытой
///   страницей терминала (`serverCertificateHashes`), и мы бы уронили живые
///   сессии ради записи, которая никому не мешает.
///
/// Чистая функция, потому что решение «кричать или нет» проверяемо, а таймер,
/// внутри которого оно принято, — нет.
List<String> addressesOutsideCertificate({
  required List<String> live,
  required List<String> certified,
}) {
  final named = certified.toSet();
  return <String>[
    for (final address in live)
      if (!named.contains(address)) address,
  ];
}

/// Имена, которыми касса себя называет сейчас, но которых её лист не называет.
///
/// Тот же перекос, что и у адресов, и по той же причине. Отдельная функция, а
/// не общая с адресами, потому что перепутать эти два списка на вызове —
/// именно та ошибка, от которой `rk_pki` отделила `dnsNames` от `ipAddresses`:
/// клиент, идущий по адресу, читает только второй, и имя, положенное в него,
/// выписывает лист, который выглядит правильным и не работает.
List<String> namesOutsideCertificate({
  required List<String> live,
  required List<String> certified,
}) {
  final named = certified.map((name) => name.toLowerCase()).toSet();
  return <String>[
    for (final name in live)
      if (!named.contains(name.toLowerCase())) name,
  ];
}
