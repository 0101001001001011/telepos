import 'dart:io';

/// Просит установщик доверять корню этой кассы прямо сейчас.
///
/// # Зачем это здесь
///
/// Корень магазина создаёт **касса**, а не установщик: он свой у каждой
/// установки и живёт в профиле пользователя
/// (`%APPDATA%\TelePOS\TelePOS\pki\certs\ca.cert.pem`). Поэтому вшить его в MSI
/// нельзя в принципе, и установщик вместо этого регистрирует задачу
/// планировщика `\TelePOS\SyncRootTrust`, которая находит корень и кладёт его в
/// доверенные корневые центры **этого же пользователя**. Полное обоснование —
/// `docs/internal/windows-installer.md`, раздел «Корневой сертификат магазина».
///
/// Задача срабатывает при входе пользователя в систему. Без этого вызова между
/// «касса выписала корень» и «браузер на этой машине ему доверяет» стоял бы
/// один выход из системы: кассир открыл бы терминал на `https://localhost` и
/// увидел предупреждение о недоверенном сертификате в свой первый рабочий день,
/// то есть ровно тогда, когда объяснить это некому. Задача разрешена к запуску
/// группе «Пользователи» именно затем, чтобы касса могла позвать её сама.
///
/// # Почему это не «поставить сертификат»
///
/// Ставит его `trust.ps1` под задачей, а не мы. Класть корень в хранилище
/// отсюда значило бы завести вторую реализацию того же действия — со своим
/// журналом отпечатков, который разошёлся бы с журналом установщика, и тогда
/// деинсталляция сняла бы не всё. У установщика этот журнал уже есть
/// (`HKCU\SOFTWARE\TelePOS\TrustedRoots`), и он же обязан остаться
/// единственным.
///
/// # Отказ приходит значением (И144)
///
/// Задачи может не быть вовсе: касса, запущенная из каталога сборки, никакого
/// установщика не видела. Это обычное состояние разработки, а не поломка, и
/// открытию смены оно мешать не должно.
Future<RootTrustSyncOutcome> syncRootTrust() async {
  if (!Platform.isWindows) {
    // Задача планировщика — механизм Windows. На приборе корень ставит образ,
    // на macOS/Linux десктопной установки у нас пока нет. Молчаливое «ничего
    // не сделано» отличается от отказа: искать причину недоверия здесь не надо.
    return const RootTrustSyncOutcome.skipped(
      'не Windows: задачи планировщика здесь нет',
    );
  }

  try {
    final result = await Process.run('schtasks', const [
      '/Run',
      '/TN',
      r'\TelePOS\SyncRootTrust',
    ]);
    if (result.exitCode != 0) {
      // Самый частый случай — «задача не найдена»: кассу запустили не из-под
      // установщика. Текст отдаётся как есть, потому что второй по частоте
      // случай (задача есть, но отключена политикой) отличается только им.
      final message = '${result.stdout}${result.stderr}'.trim();
      return RootTrustSyncOutcome.failed(
        'schtasks вернул ${result.exitCode}'
        '${message.isEmpty ? '' : ': $message'}',
      );
    }
    return const RootTrustSyncOutcome.started();
  } catch (e) {
    // `schtasks` может отсутствовать в `PATH` на урезанной сборке Windows.
    return RootTrustSyncOutcome.failed('$e');
  }
}

/// Чем закончилась просьба к установщику обновить доверие.
///
/// Значение, а не исключение: ни один из трёх исходов не является поводом не
/// открыть смену.
class RootTrustSyncOutcome {
  const RootTrustSyncOutcome.started()
    : started = true,
      reason = 'задача \\TelePOS\\SyncRootTrust запущена';
  const RootTrustSyncOutcome.skipped(this.reason) : started = false;
  const RootTrustSyncOutcome.failed(this.reason) : started = false;

  /// Задача действительно запущена. Это ещё не «доверие появилось»: `schtasks
  /// /Run` возвращается сразу, а скрипт работает своим ходом. Обещать здесь
  /// результат значило бы отчитаться за работу, которой мы не видели.
  final bool started;

  final String reason;

  @override
  String toString() => reason;
}
