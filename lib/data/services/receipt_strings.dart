/// Язык ПЕЧАТНЫХ документов: чека, X- и Z-отчёта, сертификата.
///
/// # Зачем это понадобилось
///
/// До 2026-09-21 каждая строка печатного документа была русским литералом в
/// слое данных: «Касса», «ИТОГО», «НАЛИЧНЫМИ», «Спасибо за покупку!».
/// Интерфейс к тому времени говорил на пяти языках, а бумага — на одном, и
/// это не зависело ни от настройки кассы, ни от страны.
///
/// Нашлось на съёмке урока 1.3: вкладка диагностики показывает чек текстом,
/// раскодированным из байтов, ушедших в порт, — и в английском ролике этот
/// чек оказался русским. То есть дефект был виден пользователю ровно там,
/// где продукт обещает прозрачность.
///
/// # Почему держатель, а не довод у каждого вызова
///
/// Печать зовут из десятка мест, и половина — фоновые задачи без
/// `BuildContext`: досылка задержанного Z, повтор задания из очереди,
/// квитанция кассовой операции. Тянуть язык доводом через всю эту цепочку
/// значит менять подписи там, где о языке знать нечего.
///
/// # Почему не `SharedPreferences` напрямую
///
/// Её нет в `get_it` (см. `service_locator.dart`), и заводить её там ради
/// одного чтения — лишняя связь. Язык кладёт сюда `LocaleNotifier`, который
/// и так единственный хозяин выбора языка.
///
/// # Как подменить в пробе
///
/// `ReceiptPrintServiceImpl` принимает `strings` доводом. Проба задаёт свой
/// и не трогает глобальное состояние — иначе прогоны влияли бы друг на
/// друга порядком запуска.
library;

import 'dart:ui';

import 'package:telepos/core/locale/till_language.dart';
import 'package:telepos/l10n/app_localizations.dart';

/// Как печать получает слова. Довод, а не обращение к глобальному
/// состоянию: пробе нужно подменить язык, не влияя на соседние прогоны.
typedef ReceiptStringsResolver = AppLocalizations Function();

/// Умолчание: словарь на языке, выбранном в кассе.
///
/// Сам выбор живёт в ядре (`TillLanguage`), а словарь по нему строится
/// здесь: ядру о словаре знать незачем, а если бы знало — слой данных
/// уехал бы в браузерную сборку по цепочке импортов, и страница не
/// собралась бы вовсе. Это не догадка, это поймали сторожа.
AppLocalizations defaultReceiptStrings() =>
    lookupAppLocalizations(Locale(TillLanguage.current.languageCode));
