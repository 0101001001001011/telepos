import 'package:telepos/data/database/app_database.dart';

/// Выдача номера чека — **атомарно вместе со строкой, которую он
/// нумерует**, не отдельным шагом до неё.
///
/// **Круг правки 1 (2026-09-06): почему `next()` из первой версии этого
/// файла был дефектом, а не «достаточно хорошо».** Первая версия отдавала
/// голый номер и **отдельно** вставляла бронирующую строку без состояния
/// (`state = NULL`, `userId = 0` — заглушка) — настоящие данные (владелец,
/// кассир, состояние) дописывались вызывающим следующим, отдельным
/// оператором. Между этими двумя операциями было окно: если процесс
/// умирал в нём (сбой питания, крах кассы), бронь оставалась в `Sales`
/// **навсегда**, а `SaleDao.findLastReceiptNo()` — голый `MAX(receipt_no)`
/// без единого условия по состоянию, которым в этом дереве уже пользуется
/// живой пункт меню «Печать последнего чека»
/// (`additional_screen.dart:_printLastReceipt`) — считает эту бронь
/// настоящим последним чеком. Кассир нажимает кнопку и получает **дубликат
/// чека на нулевую сумму, без товаров и оплат, с кассиром-заглушкой**:
/// фальшивый чек по продаже, которой не было. Это новый регресс: до задачи
/// 4 строка заводилась одной атомарной вставкой, и состояния «строка есть,
/// а состояния нет» не существовало вовсе.
///
/// **Правка: строка рождается сразу полной.** [withNext] не возвращает
/// голый номер сам по себе — он прогоняет [writeSale] **внутри той же
/// транзакции**, что вычислила номер, и именно [writeSale] обязан вставить
/// настоящую, полную строку `Sales` (состояние, владелец, кассир, сумма,
/// время) прямо с этим номером. Шага «бронь, потом дозаполнение» не
/// существует — значит, аварии между ними тоже не существует: либо
/// транзакция целиком закоммичена (строка полна с первого байта на диске),
/// либо не закоммичено ничего (аварийный обрыв откатывает всё, включая
/// уже выполненные внутри [writeSale] операторы — SQLite не пишет на
/// диск до `COMMIT`). Доказано тестом на симуляции краха
/// (`test/data/sale/receipt_numbers_test.dart`: исключение внутри
/// `writeSale` после настоящей вставки — строки после этого в базе нет).
///
/// **Почему `withNext` — с повтором, а не одной попыткой.** Число
/// становится по-настоящему выданным только тогда, когда для пары
/// `(receiptNo, posId)` в `Sales` появляется строка — это часть составного
/// первичного ключа таблицы (`sale_tables.dart`), и вторую такую же
/// строку база вставить не даст. Повтор по конфликту этого ключа — это
/// то, что делает `withNext` корректным для **любого** количества
/// одновременных вызывающих на одной базе (`sale_initiation_use_case_impl`,
/// `create_table_order_use_case_impl`, `service_order_transition_use_case_impl`
/// — все три делят один и тот же счётчик через одну и ту же таблицу).
///
/// **Честно о пределе — сегодня эта ветка недостижима, и это проверено.**
/// Касса открывает `AppDatabase` одним соединением на процесс; у
/// браузерного терминала своего соединения к базе нет вовсе — он говорит
/// с кассой по проводу, а не с файлом sqlite напрямую. Конкурирующие
/// вызовы `_db.transaction()` **на одном и том же соединении** drift не
/// перемежает: второй вызов встаёт в очередь и начинает читать
/// `findLastReceiptNo()` только после того, как первый уже закоммитил
/// свою вставку — то есть при единственном сегодняшнем соединении
/// конфликт первичного ключа никогда не возникает, и ветка повтора ниже
/// тестом не пройдена (не покрыта, а не «не нашлось способа» — разобрано
/// по исходнику drift, не только не найдено эмпирически). Она оставлена
/// как страховка на случай, если это когда-нибудь перестанет быть верным
/// (второе соединение к той же базе, другой драйвер, другая платформа) —
/// следующий читатель не должен принимать её за работающую защиту,
/// подтверждённую прогоном: подтверждена только сама атомарность вставки.
///
/// **Круг правки 3 (2026-09-06): у повтора нет предела попыток.** `while
/// (true)` без счётчика и без паузы — сужение needle (круг 2) убрало
/// **одну** уже найденную причину ложного повтора (чужой конфликт по
/// `Payments`), но ничего не гарантирует, что «свой» конфликт когда-нибудь
/// перестанет повторяться. Появись второй писатель с фиксированным
/// номером, или начни `findLastReceiptNo()` из-за будущей ошибки
/// возвращать одно и то же — симптом тот же, что был измерен при проверке
/// круга 2 (см. `test/data/sale/receipt_numbers_test.dart`): плотный цикл
/// «начать транзакцию, вставить, упасть на конфликте по ключу продажи,
/// откатить, повторить» без остановки и без единого слова в логе. Правка:
/// потолок в [maxAttempts] попыток, по превышении — [ReceiptNumberExhausted]
/// с номером кассы и числом попыток, а не тихое зависание.
class ReceiptNumbers {
  ReceiptNumbers(this._db);

  final AppDatabase _db;

  /// Потолок попыток закрепить номер за один вызов [withNext]. Взято с
  /// запасом над «сколько раз подряд может реально столкнуться конфликт
  /// на одной кассе» (при единственном соединении конфликт недостижим
  /// вовсе, см. докстринг класса) — не тонкая настройка производительности,
  /// а граница между «повтор чинит гонку» и «повтор прячет поломку».
  static const maxAttempts = 8;

  /// Текст, которым sqlite сообщает именно о конфликте на составном
  /// первичном ключе `Sales(receipt_no, pos_id)` — измерено напрямую
  /// (вставка дубликата в тестовой базе): `SqliteException(1555): while
  /// executing statement, UNIQUE constraint failed: sales.receipt_no,
  /// sales.pos_id, constraint failed (code 1555)`. Названы обе колонки и
  /// таблица — этого достаточно, чтобы не совпасть с конфликтом на чужом
  /// уникальном ключе, даже если тот тоже упоминает `receipt_no`/`pos_id`
  /// в своём списке колонок (см. докстринг класса: конфликт по
  /// `Payments.uniqueKeys` — `{receiptNo, posId, payeeAccountId}` — даёт
  /// `UNIQUE constraint failed: payments.receipt_no, payments.pos_id,
  /// payments.payee_account_id`, с другим именем таблицы в начале того же
  /// текста).
  static const _salesReceiptNoConflictNeedle =
      'UNIQUE constraint failed: sales.receipt_no, sales.pos_id';

  /// [posId] несётся только ради диагностики — сама выдача номера сквозная
  /// на кассу и от него не зависит (см. тест «разные рабочие места не
  /// мешают друг другу»). Без него [ReceiptNumberExhausted] сказал бы
  /// оператору не больше, чем «зависло», — то, ради чего эта правка и
  /// делалась.
  Future<T> withNext<T>(
    int posId,
    Future<T> Function(int receiptNo) writeSale,
  ) async {
    var attempt = 0;
    while (true) {
      attempt++;
      try {
        return await _db.transaction(() async {
          final last = await _db.saleDao.findLastReceiptNo() ?? 0;
          return writeSale(last + 1);
        });
      } catch (e) {
        // Тот же приём и та же причина, что `AppDatabase.isExpectedSchemaError`
        // сам документирует: касса запускает базу на фоновом изоляте
        // (`NativeDatabase.createInBackground`), и ошибка приходит обёрнутой в
        // `DriftRemoteException`, а не голым `SqliteException` — `on
        // SqliteException` здесь совершил бы ту же ошибку, что уже стоила
        // одной живой кассы (см. докстринг `isExpectedSchemaError`). Ветка
        // недостижима сегодня (см. докстринг класса) — оставлена на будущее.
        //
        // Круг правки 2: распознавание сужено до конфликта именно по ключу
        // продажи. `writeSale` сервисного пути (задача 4,
        // `ServiceOrderTransitionUseCaseImpl`) вставляет ещё и `Payments`,
        // чей `uniqueKeys` тоже содержит `{receiptNo, posId, ...}` — общий
        // текст `UNIQUE constraint failed` совпал бы и с тем конфликтом, и
        // повтор запустился бы **с новым номером чека там, где номер ни
        // при чём**: маскирует настоящую ошибку и повторяет попытку с уже
        // испорченными (частично написанными до конфликта) данными. Узкая
        // строка ниже совпадает только с конфликтом на `Sales(receipt_no,
        // pos_id)` — на всё остальное срабатывает `rethrow`.
        if (!AppDatabase.isExpectedSchemaError(
          e,
          _salesReceiptNoConflictNeedle,
        )) {
          rethrow;
        }
        // Круг правки 3: узкое условие не гарантирует, что «свой» конфликт
        // когда-нибудь перестанет повторяться — потолок превращает тихое
        // зависание в диагностируемую ошибку.
        if (attempt >= maxAttempts) {
          throw ReceiptNumberExhausted(posId: posId, attempts: attempt);
        }
      }
    }
  }
}

/// Брошено [ReceiptNumbers.withNext], когда конфликт по ключу продажи
/// `Sales(receipt_no, pos_id)` повторился [attempts] раз подряд для кассы
/// [posId] — вместо тихого вечного цикла (круг правки 3, задача 4).
///
/// Не несёт текста исходной ошибки sqlite в [toString] — это диагностика
/// внутреннего слоя, не отказ, идущий на провод (I144), но неизвестно
/// заранее, куда её в итоге пробросят вызывающие; безопаснее не давать
/// ей стать источником сырой интерполяции исключения на границе, которую
/// стережёт `no_raw_exception_on_wire_test.dart`.
final class ReceiptNumberExhausted implements Exception {
  const ReceiptNumberExhausted({required this.posId, required this.attempts});

  final int posId;
  final int attempts;

  @override
  String toString() =>
      'ReceiptNumberExhausted: касса $posId — номер чека не закрепился за '
      '$attempts попыток подряд (конфликт по ключу продажи не расходится)';
}
