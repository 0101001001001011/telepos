/// Ограничивает, сколько проверок PIN идёт в изоляте одновременно.
///
/// # Зачем это здесь
///
/// Правка 1 волны закрытия долга безопасности (2026-08-22) снимает у
/// [LoginThrottle][lt] цепную очередь ожиданий — та превращала N чужих
/// неудач по одному ключу в стену, растущую суммой их задержек, и запирала
/// честного кассира на часы (докстринг [LoginThrottle], «БЛОКЕР»). После
/// снятия очереди задержка `LoginThrottle` больше не растягивает подбор во
/// времени сама по себе для нападающего, слающего попытки параллельно, не
/// дожидаясь ответов, — каждая его попытка ждёт свой личный, ограниченный
/// потолком [LoginThrottle.maxDelay] таймер, и все они тикают одновременно.
///
/// Единственный настоящий ограниченный ресурс, который остаётся, — сама
/// проверка PIN: `PinCredential.check` — PBKDF2, ~206 мс на кандидата
/// (измерено 2026-08-02, `pin_credential.dart`), и `LocalAuthRepository
/// ._matchAll` считает её в отдельном изоляте (`Isolate.run`). Спавн изолята
/// без ограничения — по изоляту на каждую попытку разом — не бесплатен: это
/// настоящий поток ОС и настоящая память рантайма Dart на каждый, и
/// нападающий, открывший тысячи параллельных попыток, получил бы тысячи
/// изолятов одновременно.
///
/// [Pbkdf2Gate] ограничивает это число — при достижении предела следующий
/// вызов **ждёт своей очереди**, а не отказывает и не проскакивает мимо.
/// «Очередь, а не пропуск» — тот же принцип, что уже дважды нарушали в этой
/// работе: `maxConcurrentPenalties` в [LoginThrottle] (докстринг там,
/// «предел одновременных ожиданий снят») отвечал `tooBusy` мгновенно, с
/// нулевой задержкой, и превращал собственный предел в калитку в обход
/// подбора. Здесь предел есть, но за ним не отказ — ожидание своей очереди,
/// то есть предел просто откладывает, а не пропускает.
///
/// # БЛОКЕР волны закрытия долга (2026-08-22), часть А: очередь вернулась в
/// новом месте
///
/// До этой правки `run` держал одну общую FIFO-очередь ожидающих — тот же
/// порок, ради снятия которого убрали `_queueTail` у [LoginThrottle], только
/// переехавший на этаж ниже. Вход зовёт `penalizeFailure` **и** `_matchAll`
/// (`LocalAuthRepository.login`), и второе идёт через этот класс — общий на
/// все одновременные попытки входа, честной FIFO без предела длины. Залп в
/// N попыток одного нападающего вставал в ту же очередь, что и попытка
/// честного кассира, и честный ждал своей позиции в общем хвосте — то самое
/// число, которое отчёт `throttle-cap-report.md` посчитал как «цену
/// нападающему» (10⁴ → ~17 минут), было на самом деле ценой, посчитанной **с
/// двух сторон одной очереди**: она же и держала честного кассира.
///
/// # Правка: справедливая очередь по [key], круговая, а не общая FIFO
///
/// [run] принимает необязательный [key] — ключ справедливости. Слоты
/// раздаются по кругу между **различными ключами**, у которых есть ждущие, а
/// не по порядку прихода среди всех ждущих разом: как только слот
/// освобождается, право на него получает следующий ключ в обходе, а не
/// следующий по времени постановки в очередь запрос. Один и тот же ключ,
/// сколько бы у него ни накопилось ждущих, получает не больше одного слота
/// за один оборот.
///
/// Ключ — QUIC-**сессия**, не `userId` жертвы: нападающий выбирает `userId`
/// свободно (это чужое имя, не его), а сессий у него ровно столько, сколько
/// он смог завести — и это число ограничено потолком регистрации терминалов
/// (200, `TillOperations`) и ленивой уборкой. У честного кассира сессия
/// одна. При круговой раздаче он получает слот раз в N **сессий**
/// нападающего, а не раз в N его **попыток** — секунды вместо часов даже при
/// 200 сессиях сразу. См. `LocalAuthRepository.login`/`_matchAll`, где [key]
/// приходит от `AuthAttempt.sessionKey`, и `TillOperations` — где
/// `WireHandler`'s составной `sessionId` до неё доходит.
///
/// Без ключа (`key: null`, десктопный вызов в обход провода — там сессии
/// нет вовсе, один процесс на кассу) — все такие вызовы делят один общий
/// «ключ» `null`, что при единственном десктопном источнике попыток эквивалентно
/// прежней FIFO.
///
/// [lt]: package:telepos/backend/login_throttle.dart
library;

import 'dart:async';
import 'dart:collection';

/// Считающий семафор со справедливой круговой очередью по ключу.
///
/// Не поле-счётчик с ручной проверкой — тот и был `_activePenalties`,
/// найденной дырой (`login_throttle.dart`): проверка предела и решение
/// «ждать или нет» синхронны, а вот ожидание своей очереди — это то, что тот
/// код не делал вовсе. [run] ждёт всегда, если слотов не осталось, и никогда
/// не отвечает отказом.
class Pbkdf2Gate {
  Pbkdf2Gate({this.maxConcurrent = 2}) : assert(maxConcurrent > 0);

  /// Сколько проверок PIN считаются в изоляте одновременно.
  ///
  /// 2, а не 1 и не число ядер процессора. Не 1: одна кассирская смена на
  /// маленьком магазине — это уже два живых терминала (десктоп и браузерный
  /// у второй кассы), и `maxConcurrent: 1` сериализовал бы их настоящие,
  /// одновременные, ничем не подозрительные входы одного за другим — на
  /// кассе с несколькими рабочими местами это заметная задержка на каждый
  /// вход, а не только на подбор. Не число ядер: оно read-only только у
  /// самой машины, разное на десктопной кассе и на RPi5 appliance, и не
  /// тестируемо детерминированно. 2 — компромисс, а не измеренный оптимум:
  /// пропускает пару настоящих одновременных входов без сериализации, и в то
  /// же время держит нападающего на PBKDF2 как на настоящем ограничителе, а
  /// не на удобном обходе через параллельные изоляты. Число видно в отчёте
  /// (`throttle-cap-report.md`) как то, чем посчитана итоговая цена полного
  /// перебора.
  final int maxConcurrent;

  int _running = 0;

  /// Ждущие по каждому ключу справедливости, в порядке прихода (FIFO внутри
  /// ключа — очерёдность между попытками одного и того же нападающего
  /// сохраняется, только между разными ключами она круговая, а не общая).
  final Map<Object?, Queue<Completer<void>>> _waitingByKey = {};

  /// Порядок кругового обхода ключей — только те, у которых сейчас есть хотя
  /// бы один ждущий. Ключ покидает обход сразу после того, как его
  /// последний ждущий получил слот, и появляется заново, если у него снова
  /// кто-то встал в очередь.
  final Queue<Object?> _keyRotation = Queue();

  /// Считает [job] через семафор — если слотов нет, встаёт в очередь своего
  /// [key] и ждёт хода по кругу, никогда не отвечая отказом.
  ///
  /// [key] — ключ справедливости (см. докстринг класса и файла): у
  /// разных ключей — независимые FIFO-очереди, и свободный слот при
  /// освобождении переходит следующему по кругу **ключу**, а не следующему
  /// по времени постановки ждущему.
  Future<T> run<T>(Future<T> Function() job, {Object? key}) async {
    if (_running < maxConcurrent) {
      _running++;
    } else {
      final waiter = Completer<void>();
      final queue = _waitingByKey.putIfAbsent(key, () {
        _keyRotation.add(key);
        return Queue<Completer<void>>();
      });
      queue.add(waiter);
      await waiter.future;
      // Правка А-2 БЛОКЕРА: слот сюда **передан** releaser'ом в
      // [_dispatchNext] — не увеличиваем `_running` здесь. Прежняя версия
      // делала `_running++` в этой точке, уже после того, как отдельным
      // `if` (не циклом) проверила предел один раз, до ожидания; между
      // синхронным `_running--` releaser'а и пробуждением этого continuation
      // (оно всегда планируется отдельным микротаском — `Completer.complete`
      // не резюмирует `await` синхронно) успевал синхронно войти новый
      // вызывающий, увидеть уменьшенный `_running` и тоже занять «тот же»
      // слот — доказано прогоном (`pbkdf2_gate_test.dart`, группа «правка
      // А-2»): `live=3 peak=3` при `maxConcurrent: 2`. Передача владения
      // без промежуточного decrement закрывает окно гонки на уровне
      // инварианта, а не только повторной проверкой: `_running` меняется
      // только в двух местах (`run` — только когда слотов физически не
      // хватало и вызывающий сам его занял, `_dispatchNext` — только когда
      // отдаёт слот совсем, без ждущих) и никогда дважды за один и тот же
      // слот.
    }
    try {
      return await job();
    } finally {
      _dispatchNext();
    }
  }

  /// Освобождает слот, только что занятый завершившимся [run] — либо
  /// передаёт его следующему ждущему по кругу ключей, либо, если ждущих нет
  /// вовсе, по-настоящему уменьшает счётчик.
  ///
  /// Выполняется целиком синхронно (без `await`) внутри `finally` вызвавшего
  /// `run` — между чтением состояния очереди и решением «передать» или
  /// «освободить» ни одна другая задача выполниться не может (однопоточный
  /// Dart-event-loop), поэтому здесь нет окна для гонки, которая была в
  /// прежней реализации (докстринг [run]).
  void _dispatchNext() {
    while (_keyRotation.isNotEmpty) {
      final key = _keyRotation.removeFirst();
      final queue = _waitingByKey[key];
      if (queue == null || queue.isEmpty) {
        // Защитный случай — при нормальной работе не должен встречаться:
        // ключ не остаётся в обходе с пустой или отсутствующей очередью.
        _waitingByKey.remove(key);
        continue;
      }
      final waiter = queue.removeFirst();
      if (queue.isNotEmpty) {
        // У ключа остались другие ждущие — его очередь в обходе, но в
        // конец: сначала ход получат остальные ключи, у кого тоже кто-то
        // ждёт, и только потом он снова.
        _keyRotation.add(key);
      } else {
        _waitingByKey.remove(key);
      }
      // Слот передаётся этому ждущему без изменения `_running` — он уже
      // учтён в счётчике с тех пор, как был занят предыдущим владельцем.
      waiter.complete();
      return;
    }
    // Никто не ждёт ни по одному ключу — слот освобождается по-настоящему.
    _running--;
  }
}
