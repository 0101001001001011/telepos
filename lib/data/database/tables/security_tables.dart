import 'package:drift/drift.dart';

/// Журнал событий безопасности — схема v34
/// (`lib/data/database/app_database.dart`), план «замок кассы», фаза 8,
/// задача 20. Закрывает структуру для И66–И69
/// (`docs/system-architecture.md`, раздел 15): до этой задачи подсистемы
/// аудита в приложении не было вовсе — ни таблицы, ни службы, ни вызова.
/// Эта таблица — структура и цепочка; точки вставки (кто на самом деле
/// пишет сюда при входе, отзыве сеанса и так далее) — задача 21, отдельная
/// от этой.
///
/// # Только пополнение
///
/// У этой таблицы нет пути править или стирать уже записанную строку — ни в
/// `SecurityEventDao` (см. его докстринг), ни, значит, на проводе, который
/// всегда идёт через DAO. Это требование задачи, а не то, что просто не
/// понадобилось: журнал безопасности, который можно исправить или стереть
/// тем же доступом, каким его читают, не годится в улику против того, кто
/// этим доступом злоупотребил. Тест на разрыв цепочки в
/// `test/data/database/security_journal_test.dart` вырезает строку в обход
/// DAO, напрямую через drift, — ровно потому, что через сам DAO вырезать
/// нечем.
///
/// # Состав записи
///
/// - [occurredAtEpochMs] — когда. Целые миллисекунды epoch UTC, а не
///   drift-овский `dateTime()`: тот по умолчанию хранит секунды, срезая
///   дробную часть (то же решение и по той же причине, что у
///   `PrintJobs.createdAtEpochMs`, `lib/data/database/tables/print_tables.dart`).
/// - [userId] — **субъект**, не обязательно действующий. Допускает `null`:
///   у события ещё нет опознанного субъекта, например у неверного PIN, для
///   которого не нашлось ни одного совпадающего пользователя — записать
///   событие обязаны и в этом случае, а угадывать личность по неверному PIN
///   нельзя.
///
///   Пункт 4 закрытия долга безопасности (2026-08-22): у `wire.denied`/
///   `auth.login`/`session.issued` субъект и действующий — одно и то же лицо
///   (сеанс выписывается тому, кто вошёл), но у `user.pinChanged`/
///   `user.permissionsChanged`/`user.userDeleted`/`user.roleChanged`
///   (`user_management_screen.dart`) и у части `session.revoked`
///   (`session_registry.dart`, `revoke()`) они **разные**: строка
///   `user.pinChanged, userId=B` — «PIN сменили У B», не «B сменил свой
///   PIN». Отдельного поля для действующего в этой таблице нет — решение
///   сознательное, а не забытое: добавить его значило бы регенерировать
///   сгенерированный код drift для всей 87-таблицной базы
///   (`app_database.g.dart`) ради столбца, использованного на сегодня двумя
///   точками вставки; довод и цена — в докстринге
///   `_recordUserSecurityEvent` (`user_management_screen.dart`). Читающий
///   журнал обязан знать эту границу, а не считать `userId` действующим по
///   умолчанию.
/// - [terminalId] — откуда. Терминал, с которого пришло действие;
///   `NOT NULL` — событие безопасности без места происхождения не несёт
///   смысла, каждый вызывающий это место знает всегда.
/// - [eventType] — что. Строка рода события (например `auth.login`,
///   `session.revoke`) — свободный текст здесь и словарь конкретных родов
///   там, где события реально заводятся (задача 21), а не в этой таблице:
///   у задачи 20 нет ни одной настоящей точки вставки, откуда было бы видно
///   исчерпывающий список.
/// - [outcome] — исход (например `success`/`failure`) — тем же приёмом.
/// - [correlationId] — сквозной идентификатор действия через уровни (И69).
/// - [previousFingerprint] — отпечаток предыдущей записи журнала, см.
///   докстринг `SecurityEventDao` про то, как строится и проверяется
///   цепочка (И67), и её объявленную границу.
///
/// # Маскирование (И68)
///
/// Ни одна колонка не названа и не предназначена хранить ПИН, хэш пароля
/// или значение токена как есть. Если событию нужно нести секрет как
/// улику — секрет несётся его отпечатком, не значением; `safeErrorText`
/// (`lib/core/errors/safe_error_text.dart`) — готовая функция ровно для
/// того же класса задачи применительно к исключениям.
///
/// Волна закрытия долга безопасности (2026-08-22) сняла
/// `SecurityEventDao.fingerprintOfSecret` — общий несолёный `sha256`-помощник,
/// на который ссылался этот абзац, — за отсутствием хоть одного вызывающего
/// в `lib/` и за то, что настоящий секрет продукта (четырёхзначный PIN) он
/// бы не замаскировал, а обратимо закодировал (см. докстринг
/// `SecurityEventDao`). Пока новой точки вставки, которой нужно нести
/// высокоэнтропийный секрет уликой, нет — маскировать нечего; когда
/// появится, помощник заводится рядом с ней, солёным и по секрету,
/// который он в самом деле маскирует.
class SecurityEvents extends Table {
  IntColumn get id => integer().autoIncrement()();

  IntColumn get occurredAtEpochMs => integer()();

  IntColumn get userId => integer().nullable()();

  IntColumn get terminalId => integer()();

  TextColumn get eventType => text()();

  TextColumn get outcome => text()();

  TextColumn get correlationId => text()();

  TextColumn get previousFingerprint => text()();
}
