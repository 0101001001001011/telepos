import 'package:drift/drift.dart';

/// Память кассы о принятых авансах — схема v49, дефект живой приёмки
/// 2026-09-18.
///
/// # Зачем помнить то, что и так записано в `cash_operations`
///
/// Затем, что по `cash_operations` **повтор не отличить от второго взноса**.
/// Покупатель, внёсший тысячу дважды за смену, и покупатель, чей единственный
/// взнос касса записала дважды из-за оборванного провода, оставляют в журнале
/// побайтово одинаковые пары строк: та же сумма, тот же счёт, тот же вид
/// оплаты, разница в секундах. Никакой запрос это не разделит, потому что
/// разделяет их не содержимое проводки, а **намерение кассира** — одна заявка
/// или две.
///
/// Именно намерение и лежит здесь: ключ заявки, который родила вкладка
/// (`PrepaymentIntakeRequest.key`). Один ключ — одна заявка, сколько бы раз
/// она ни доехала до кассы.
///
/// # Цена отсутствия этой таблицы измерена, а не предположена
///
/// Живая приёмка 2026-09-18: провод оборвался
/// (`WireRefusal(stream_failed: WebTransportError: Connection lost)`) уже
/// **после** того, как касса приняла деньги и увеличила сальдо покупателя.
/// Ответ до вкладки не доехал, экран показал отказ, кассир нажал «Принять»
/// второй раз — и покупателю записался второй взнос. Ящик при этом сходится
/// с первой суммой: расхождение видно только сверкой сальдо, то есть через
/// недели, когда вспомнить, что там было, уже некому.
///
/// # Почему своя таблица, а не колонка в `cash_operations`
///
/// Потому что здесь хранится **исход**, а не проводка. Ответ повтору обязан
/// быть тем же самым `PrepaymentIntakeOutcome`, что и ответ первой попытке:
/// номер проводки, сальдо **после** взноса и фискальный признак. Сальдо в
/// `cash_operations` не лежит и лежать не должно — там сумма движения, а не
/// остаток счёта; вывести остаток задним числом нельзя, потому что между
/// повтором и первой попыткой счёт покупателя мог измениться зачётом в чеке.
/// Колонка ключа в `cash_operations` дала бы опознание повтора и не дала бы
/// ответа на него.
///
/// Второй довод: `cash_operations` — журнал **всех** движений кассы, и приём
/// аванса по проводу в нём одна строка из сотен. Колонка, осмысленная у одной
/// строки из ста, читается как «обычно пусто» и заполняться перестаёт.
///
/// # Ключ — не украшение, а сам заслон
///
/// [uniqueKeys] по [intakeKey] — **вторая линия**, тем же приёмом и с тем же
/// доводом, что пара `{refundLocalId, sourceNumber}` у
/// `CertificateRefundLinks`. Первая линия — чтение памяти перед приёмом, она
/// отвечает кассиру прежним исходом; между чтением и вставкой есть окно, и
/// закрывает его только ключ. Строка кладётся **в той же транзакции**, что и
/// сами деньги (`CustomerPaymentUseCaseImpl._writeMoney`) — ровно тем же
/// правилом, каким `Sales.lastCommandKey` пишется вместе с изменением
/// корзины: ключ, записанный отдельным шагом, не защищает от падения между
/// шагами.
///
/// # Удаления нет
///
/// Строка объясняет, почему у покупателя именно такое сальдо, и живёт ровно
/// столько, сколько живёт спор о деньгах. Стереть её значит вернуть тот самый
/// дефект: следующий повтор того же ключа примет деньги второй раз.
@DataClassName('PrepaymentIntakeRow')
class PrepaymentIntakes extends Table {
  IntColumn get id => integer().autoIncrement()();

  /// Ключ заявки, родившийся во вкладке.
  ///
  /// Длина с запасом: метка сеанса экрана (`newCommandSessionTag`) — это
  /// микросекунды и случайные 32 бита в 36-ричной записи, около двадцати
  /// знаков. Предел стоит не ради места, а затем, чтобы кадр, собранный мимо
  /// экрана, не клал в базу мегабайт вместо ключа.
  TextColumn get intakeKey => text().withLength(min: 1, max: 128)();

  /// Строка `cash_operations`, которой приём записан.
  IntColumn get operationId => integer()();

  /// Сальдо расчётного счёта покупателя **после** приёма, целыми тысячными.
  ///
  /// Тысячными, а не `RealColumn ... map(DecimalConverter())`, которым в этом
  /// дереве лежат деньги постарше: `double` на диске теряет копейки молча
  /// (разбор — в докстринге `GiftCertificate`). Перевод один на дерево —
  /// `MoneyMillis`; P18,S3 (I159) соблюдён, тысячная и есть третий знак.
  ///
  /// Отрицательное число законно: покупатель с долгом больше взноса остаётся
  /// в минусе и после приёма.
  IntColumn get balanceMillis => integer()();

  /// Фискальный признак чека приёма аванса; `null` — чека не было либо он
  /// ещё не дописан (разбор — в докстринге `PrepaymentIntakeDao.rememberFiscal`).
  TextColumn get fiscalSign => text().nullable()();

  /// Почему чек не выписан, хотя был нужен. Деньги при этом приняты.
  TextColumn get fiscalError => text().nullable()();

  /// Секунды эпохи — тем же масштабом, что `cash_operations.docTime`.
  IntColumn get time => integer()();

  @override
  List<Set<Column>> get uniqueKeys => [
    {intakeKey},
  ];
}

/// Память кассы о **выданных** авансах — схема v52, ревизия 2026-09-19.
///
/// # Почему своя таблица, а не колонка рода в [PrepaymentIntakes]
///
/// Потому что единственный заслон обеих памятей — **уникальный ключ**, а
/// ключ приносит вкладка. Одна таблица на два действия означала бы одно
/// пространство ключей на приём и на выдачу, и кадр приёма с ключом, уже
/// занятым выдачей, получил бы в ответ **исход выдачи**: «принято», номер
/// чужой проводки, сальдо от другой операции — и ни одной записанной
/// копейки. Разделить их внутри одной таблицы можно только парой
/// `{ключ, род}` в уникальном ключе, а это перестройка живой таблицы
/// (`ALTER TABLE` в sqlite уникальных ключей не меняет) ради того, что
/// второй таблицей достаётся созданием.
///
/// Второй довод — тот же, по которому память приёма не стала колонкой в
/// `cash_operations`: здесь хранится **исход**, и исход выдачи отвечает на
/// другой вопрос. Сальдо после выдачи меньше, чем было; фискальный признак
/// принадлежит документу **возврата** аванса, а не чеку приёма. Одна строка
/// на оба рода читалась бы как «аванс», пока кто-нибудь не сверил бы знак.
///
/// # Что стоило бы её отсутствие
///
/// Ровно то же, что измерено у приёма 2026-09-18, и на выдаче дороже: провод
/// рвётся **после** того, как деньги выданы из ящика, ответ до вкладки не
/// доезжает, экран показывает отказ — и кассир, поверив экрану, выдаёт
/// вторую такую же сумму. У приёма расхождение видно сверкой сальдо; здесь
/// из ящика ушли живые деньги дважды.
///
/// # Удаления нет
///
/// Тот же довод, что у [PrepaymentIntakes]: строка объясняет, почему у
/// покупателя именно такое сальдо, и стереть её значит вернуть дефект —
/// следующий повтор того же ключа выдаст деньги второй раз.
@DataClassName('PrepaymentRefundRow')
class PrepaymentRefunds extends Table {
  IntColumn get id => integer().autoIncrement()();

  /// Ключ заявки, родившийся во вкладке. Предел длины — тот же и по той же
  /// причине, что у `PrepaymentIntakes.intakeKey`.
  TextColumn get refundKey => text().withLength(min: 1, max: 128)();

  /// Строка `cash_operations` рода «расход», которой выдача записана.
  IntColumn get operationId => integer()();

  /// Сальдо расчётного счёта покупателя **после** выдачи, целыми тысячными
  /// (`MoneyMillis`, P18,S3 — I159). Тот же перевод, что у приёма.
  IntColumn get balanceMillis => integer()();

  /// Фискальный признак документа **возврата** аванса; `null` — документа не
  /// было (настройка выключена, узла нет).
  TextColumn get fiscalSign => text().nullable()();

  /// Почему документ не выписан, хотя был нужен. Деньги при этом выданы.
  TextColumn get fiscalError => text().nullable()();

  /// Секунды эпохи — тем же масштабом, что `cash_operations.docTime`.
  IntColumn get time => integer()();

  @override
  List<Set<Column>> get uniqueKeys => [
    {refundKey},
  ];
}
