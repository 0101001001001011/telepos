import 'package:drift/drift.dart';

/// Задание печати на диске — схема v29
/// (`lib/data/database/app_database.dart`).
///
/// Хранит ровно то, что несёт `PrintJob` (`lib/domain/print/print_job.dart`),
/// и существует затем, чтобы задание пережило перезапуск процесса: удалённая
/// задачей 1 очередь держала задания в памяти, и потому неудачная печать
/// исчезала вместе с процессом.
///
/// Имя класса данных задано явно: без него drift сгенерировал бы класс
/// `PrintJob`, столкнувшийся по имени с доменным `PrintJob`, — и любой файл,
/// импортирующий оба, выбирал бы между ними случайно.
@DataClassName('PrintJobRow')
class PrintJobs extends Table {
  /// Ключ идемпотентности, заданный вызывающим (`PrintJob.id`), он же
  /// первичный ключ: два задания с одним идентификатором — это одно задание.
  TextColumn get jobId => text()();

  /// Рабочее место — владелец задания. Положительный `Terminal.id`.
  ///
  /// Внешнего ключа на `Terminals` здесь нет намеренно: удаление терминала не
  /// должно молча уносить непечатанные чеки — задание без владельца всё ещё
  /// видно администратору, а каскад сделал бы его невидимым.
  IntColumn get terminalId => integer()();

  /// Касса, от чьего имени выбит чек (`PrintJob.posId`). Владельцев у задания
  /// два, а не один — так сказано в И29, и обе половины хранятся, иначе
  /// прочитанное обратно задание не смогло бы даже собраться.
  IntColumn get posId => integer()();

  /// Готовый байтовый поток чека целиком (`PrintJob.payloadBytes`).
  BlobColumn get payloadBytes => blob()();

  /// `PrintJob.createdAt` как момент времени — миллисекунды epoch UTC.
  ///
  /// Единица в имени — правило проекта. Целые миллисекунды, а не
  /// drift-овский `dateTime()`: тот по умолчанию хранит **секунды**, то есть
  /// молча срезал бы дробную часть, и срок, прочитанный обратно, означал бы
  /// не тот момент, который записывали.
  IntColumn get createdAtEpochMs => integer()();

  /// `PrintJob.expiresAt` как момент времени — миллисекунды epoch UTC.
  ///
  /// **Момент, а не длительность.** Хранить «30 секунд» значило бы выдавать
  /// заданию свежие тридцать секунд при каждом запуске приложения — то самое
  /// «висит вечно», которое И29 запрещает.
  IntColumn get expiresAtEpochMs => integer()();

  /// Когда строку последний раз писали. Единственное назначение — уборка
  /// выполненных заданий (`PrintJobStore.removeFinishedBefore`): по
  /// `createdAtEpochMs` убирать нельзя, иначе давно созданное и только что
  /// напечатанное задание исчезло бы сразу после подтверждения.
  IntColumn get updatedAtEpochMs => integer()();

  IntColumn get attempts => integer().withDefault(const Constant(0))();

  /// Имя значения `PrintJobState`, а не порядковый номер — общее правило
  /// проекта и прямое требование доки самого перечисления: вставка нового
  /// состояния в середину поменяла бы смысл уже сохранённых заданий, и
  /// поменяла бы молча.
  TextColumn get state => text()();

  TextColumn get failureReason => text().nullable()();

  @override
  Set<Column> get primaryKey => {jobId};
}

/// Память о подтверждённых заданиях — та самая, что делает повтор безопасным.
///
/// **Живёт дольше самих заданий и убирается отдельно.** Внешнего ключа на
/// [PrintJobs] здесь нет и быть не может: строка обязана пережить уборку
/// задания, к которому относится. Каскадное удаление (или уборка «заодно»)
/// дало бы идемпотентность, живущую ровно до первой уборки, а её отказ
/// выглядит как второй фискальный чек у покупателя.
///
/// Правило хранения и его границы описаны в
/// `PrintJobStore.confirmationRetention` и
/// `PrintJobStore.maxRememberedConfirmations`.
class PrintJobConfirmations extends Table {
  /// `PrintJob.id` подтверждённого задания.
  TextColumn get jobId => text()();

  /// Момент **первого** подтверждения — миллисекунды epoch UTC. Повторное
  /// подтверждение того же задания эту отметку не сдвигает: иначе задание,
  /// которое кто-то регулярно перезаписывает, никогда бы не выпало из памяти.
  IntColumn get confirmedAtEpochMs => integer()();

  @override
  Set<Column> get primaryKey => {jobId};
}
