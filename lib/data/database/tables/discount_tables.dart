import 'package:drift/drift.dart';
import 'package:telepos/data/database/converters/decimal_converter.dart';

/// Предел ручной скидки — по роли, с одной строкой умолчания.
///
/// # Почему ключ роль, а не кассир и не товар
///
/// Роль покрывает случай, ради которого предел заводится: «этому нельзя».
/// Пределы по кассиру и по товару названы границей работы в спеке
/// (`2026-09-07-sale-completeness-design.md`, раздел «Границы») — не потому,
/// что их трудно завести, а потому, что таблица с тремя ключами требует
/// правила разрешения конфликтов, а правило требует экрана, на котором его
/// видно. Одна строка на роль плюс умолчание — то, что владелец может
/// прочитать целиком.
///
/// # `-1` — умолчание для всех ролей
///
/// [DiscountLimitRoles.anyRole]. Не отдельная таблица настроек и не колонка
/// в `ThisPosEntries`: умолчание и переопределение обязаны читаться **одним
/// запросом к одной таблице**, иначе «предел роли» и «предел кассы»
/// разъезжаются, и вопрос «сколько же можно кассиру» получает два ответа.
///
/// Миграция v39 кладёт **ровно одну** такую строку со стом процентами: I165
/// говорит, что «предела нет» не существует — существует объявленное
/// значение. Отсутствие строки означало бы, что читателю надо выдумать
/// ответ, а выдуманный ответ невозможно ни увидеть на экране, ни изменить.
///
/// # Почему эта таблица заводится вместе с читателем, сторожем и экраном
///
/// В `ThisPosEntries` уже лежат три колонки без единого читателя —
/// `usersAllowedToRefund`, `usersAllowedToRefundWithoutReceipt`,
/// `usersAllowedToCancelProduct`. Они были заведены, мигрированы и забыты, и
/// сегодня их единственное упоминание в `lib/` — собственное объявление.
/// `DiscountLimits` стала бы четвёртой такой, если бы вошла в дерево без
/// `LocalDiscountPolicy` (читатель), без `discount_authority_test.dart`
/// (сторож) и без `discount_limits_screen.dart` (экран). Поэтому все четыре
/// вошли одной работой — это записано и в спеке, и в заголовке задачи 12.
class DiscountLimits extends Table {
  /// `UserRole.index`, либо [DiscountLimitRoles.anyRole] у строки умолчания.
  IntColumn get role => integer()();

  /// Сколько процентов от стоимости строки кассир этой роли может уступить
  /// **сам**. Сто — «сколько угодно», и это объявленное значение, а не
  /// пустота (I165).
  ///
  /// Процент, а не деньги: `double` под [DecimalConverter] здесь не нарушает
  /// правила P18,S3, потому что правило про деньги, а это доля. Сравнение с
  /// денежной суммой идёт **умножением** стоимости строки на процент, а не
  /// делением суммы на стоимость, — то есть деньги ни разу не проходят через
  /// `double` (`LocalCartService._authorizeDiscount`).
  RealColumn get maxPercentPerLine =>
      real().map(const DecimalConverter()).withDefault(const Constant(100.0))();

  /// Выше этого процента скидка требует подтверждения старшего.
  ///
  /// `NULL` — «подтверждение не требуется вовсе», и это умолчание миграции:
  /// касса, поднявшаяся на v39, ведёт себя как вчера.
  ///
  /// **Честный предел на сегодня:** механизма подтверждения в дереве нет —
  /// он назван I166 и разбирается отдельной работой (`RoleIdentificationService`
  /// ждёт своего вызывающего). Поэтому колонка сегодня даёт **отказ**
  /// `approval_required` с названным порогом, а не диалог с кодом старшего.
  /// Это не заглушка: порог, который никто не назначил, ничего не меняет, а
  /// назначенный — останавливает скидку и говорит, почему. Когда появится
  /// подтверждение, читателю колонки менять нечего.
  RealColumn get approvalAbovePercent =>
      real().nullable().map(const DecimalConverter())();

  @override
  Set<Column> get primaryKey => {role};
}

/// Значения колонки `role`, не являющиеся ролью.
abstract final class DiscountLimitRoles {
  /// Строка умолчания: действует для роли, у которой своей строки нет.
  ///
  /// `-1`, а не `null`: ключ таблицы обязан быть сравним, а `NULL` в
  /// первичном ключе sqlite позволяет **несколько** строк умолчания —
  /// ровно тот случай, когда ответ предела начинает зависеть от порядка
  /// выборки.
  static const int anyRole = -1;
}

/// Происхождение скидки в **проданном** чеке — задача 13.
///
/// # Зачем таблица, если скидка и так видна
///
/// Она видна разностью: `priceBefore − price`. Разность не помнит, откуда
/// взялась, и подарок акции в проданном чеке неотличим от того, что кассир
/// уступил рукой. Отсюда два вопроса, на которые касса ответить не может
/// ни одним запросом: «сколько мы отдали акциями за месяц» и «кто разрешил
/// эту скидку». Второй задаёт владелец, и задаёт он его про деньги.
///
/// Вывести происхождение задним числом нечем: акций в базе нет вовсе — они
/// чистая функция от строк и таблицы `Promotions`, считаемая при сборке
/// снимка (докстринг `LocalCartService`). К моменту, когда чек продан,
/// корзины уже не существует.
///
/// # Пишется в транзакции `SaleUseCaseImpl.perform`
///
/// Не в `prepare`: тот стоит **до** «занятия чека» и до денег и
/// повторяется на каждой попытке оплаты — строки происхождения копились бы
/// от каждого отказа терминала. И не в `finalize`: его больше нет (задача
/// 9). Одним оборотом с ценами строк — иначе чек, не состоявшийся из-за
/// нарушения ключа платежей, оставил бы за собой происхождение скидки,
/// которой не было.
///
/// # Строка на источник, а не на строку чека
///
/// [saleProductId] не уникален: у одной строки чека может быть несколько
/// источников. Сегодня их не бывает больше одного — акция раздаёт подарки
/// только строкам без ручной скидки (`LocalCartService._applyPromotions`),
/// — но правило это чужое и может измениться, а форма, рассчитанная на
/// один источник, менялась бы миграцией.
class SaleDiscounts extends Table {
  IntColumn get id => integer().autoIncrement()();

  IntColumn get receiptNo => integer()();

  IntColumn get posId => integer()();

  /// Строка чека (`SaleProducts.id`), к которой относится скидка.
  IntColumn get saleProductId => integer()();

  /// `DiscountOrigin`: ручная, акция, правило, лояльность.
  IntColumn get origin => integer()();

  /// Что именно её дало — строка `Promotions` у акции, строка справочника
  /// правил, когда он появится. `null` у ручной: источника у неё нет, и
  /// подставлять ноль значило бы указать на несуществующую строку.
  IntColumn get sourceId => integer().nullable()();

  /// Сколько снято со строки **целиком**, не с единицы. Деньги P18,S3.
  RealColumn get amount => real().map(const DecimalConverter())();

  IntColumn get time => integer()();
}

/// Аудит скидки: кто, сколько, кому, по какому чеку — **включая отказы**.
///
/// # Почему это отдельная таблица, а не колонки в [SaleDiscounts]
///
/// Одной таблицей это не сделать, и довод не в удобстве. Аудит обязан
/// пережить строку чека: скидка, которой **отказали**, чека не получит
/// никогда, а именно она и интересна проверяющему — «кассир девять раз
/// пробовал дать сорок процентов». Скидка, применённая к отложенному и
/// потом удалённому чеку, исчезла бы вместе с ним.
///
/// Поэтому аудит пишется **в момент команды**, а не в момент продажи, и
/// ключа на чек у него нет: [receiptNo] и [saleProductId] — след, а не
/// связь.
///
/// # Почему таблица заводится вместе с читателем и сторожем
///
/// В `ThisPosEntries` уже лежат три колонки без единого читателя. Эта
/// таблица стала бы четвёртой такой, если бы вошла в дерево без
/// `SaleDiscountDao.auditFor` (читатель) и без
/// `discount_provenance_test.dart` (сторож).
class DiscountAuditEntries extends Table {
  IntColumn get id => integer().autoIncrement()();

  /// Кто просил. `null` — «сеанса не было»: браузерная вкладка без входа
  /// доходит до кассы и получает отказ по праву, и записать этот отказ
  /// нужнее, чем прочие.
  IntColumn get userId => integer().nullable()();

  /// `UserRole.index` просившего; `-1` — роль неизвестна, тем же смыслом,
  /// что у `DiscountAuthority.roleIndex`.
  IntColumn get roleIndex => integer().withDefault(const Constant(-1))();

  /// Чек и строка, к которым относилась попытка. Оба могут быть `null` —
  /// у отказа «нет такой строки» их взять неоткуда.
  IntColumn get receiptNo => integer().nullable()();

  IntColumn get posId => integer().nullable()();

  IntColumn get saleProductId => integer().nullable()();

  /// Покупатель, которому уступили. `null`, если чек безымянный.
  IntColumn get customerLocalId => integer().nullable()();

  /// Сколько просили — деньгами, на строку целиком.
  RealColumn get amount => real().map(const DecimalConverter())();

  /// Сколько это было в процентах от стоимости строки — тем же числом,
  /// которым мерился предел (`LocalCartService._authorizeDiscount`).
  ///
  /// Хранится **рядом** с суммой, а не вместо неё: предел объявлен
  /// процентом, а деньги отдаются суммой, и восстановить одно из другого в
  /// отчёте нельзя — стоимость строки к тому времени могла измениться.
  RealColumn get percent => real().map(const DecimalConverter())();

  /// Прошла ли попытка. `false` — отказ; причина в [refusalCode].
  BoolColumn get allowed => boolean()();

  /// Код отказа (`cart_discount_forbidden`, `discount_over_limit`,
  /// `approval_required`), `null` у прошедшей.
  TextColumn get refusalCode => text().nullable()();

  /// Чей предел решил — теми же словами, которыми `DiscountCap.source`
  /// объясняет их кассиру. Записывается и у прошедшей: «разрешено пределом
  /// кассы по умолчанию» и «разрешено пределом роли Кассир» — разные
  /// факты, и различить их потом будет нечем, если предел изменят.
  TextColumn get capSource => text().nullable()();

  IntColumn get time => integer()();
}
