/// Налоговая настройка кассы — таблицами, а не кодом.
///
/// # Зачем
///
/// Решение заказчика 2026-09-21: «под каждый штат разработкой заниматься мы
/// не будем; пресеты потом сделаем, но они как всегда устареют, поэтому
/// пользователь должен иметь возможность всё установить сам».
///
/// # Ставка не хранится — она ВЫВОДИТСЯ
///
/// Разбор мировой практики (`docs/internal/research/2026-09-21-tax-configuration-models.md`)
/// показал, что первая наша попытка — ставка числом у товара и плоский
/// список долей — расходится с тем, как это устроено везде. Ставка нигде не
/// лежит у товара. Она выводится из четырёх вещей:
///
/// * **где** продали — юрисдикция места продажи;
/// * **что** продали — налоговая категория товара;
/// * **когда** продали — у ставки есть срок действия;
/// * **как** продали — правило источника (для кассы в зале вырождается в
///   «по месту продавца»).
///
/// Отсюда три таблицы: [TaxJurisdictions] — «где», [TaxCategories] — «что»,
/// [TaxRules] — их пересечение во времени.
library;

import 'package:drift/drift.dart';
import 'package:telepos/data/database/converters/decimal_converter.dart';

/// Уровень юрисдикции в иерархии.
///
/// Не перечисление Dart, а целое в базе: уровни у стран разные, и
/// перечисление означало бы выпуск версии продукта ради страны, где между
/// штатом и городом есть ещё один орган.
abstract class TaxJurisdictionLevel {
  static const int country = 0;
  static const int state = 1;
  static const int county = 2;
  static const int city = 3;
  static const int district = 4;
}

/// Орган, взимающий свою долю налога.
///
/// Строка названа `TaxJurisdictionRow`, а не `TaxJurisdiction`: последнее
/// занято домашним понятием чека (`receipt_print_service.dart`). Два имени
/// на одно понятие в одном коде — ловушка: импорт молча берёт не то.
///
/// # Почему иерархия, а не список
///
/// В США ставка складывается: штат + округ + город + спецрайоны, и на чеке
/// требуется разбивка. Плоский список хранил бы доли, но не отношения между
/// ними, а отношения решают: в Колорадо, Луизиане и Алабаме города с
/// самоуправлением администрируют свою часть сами и **могут облагать то,
/// что штат освободил**. Денвер берёт свои 5,15 % с еды для дома, которую
/// штат не облагает вовсе.
///
/// Без иерархии этот случай не выражается: пришлось бы либо облагать еду
/// целиком, либо освобождать целиком — и то и другое неверно.
@DataClassName('TaxJurisdictionRow')
class TaxJurisdictions extends Table {
  IntColumn get id => integer().autoIncrement()();

  /// Название так, как его печатают на чеке: «CO State», «Denver», «RTD».
  ///
  /// Не переводится: это имя органа, а не слово интерфейса.
  TextColumn get name => text().withLength(min: 1, max: 64)();

  /// Родитель. `null` — корень (страна).
  ///
  /// Самоссылка без внешнего ключа: drift в SQLite оставляет
  /// `PRAGMA foreign_keys` выключенным, и объявленный ключ создавал бы
  /// видимость проверки, которой нет. Целостность держит
  /// `TaxJurisdictionDao`, а цикл ловит сторож.
  IntColumn get parentId => integer().nullable()();

  /// Уровень, см. [TaxJurisdictionLevel]. Нужен для подсказок в интерфейсе
  /// («выберите штат»), а не для расчёта: расчёт идёт по [parentId].
  IntColumn get level =>
      integer().withDefault(const Constant(TaxJurisdictionLevel.country))();

  /// Порядок печати внутри одного родителя.
  IntColumn get sortOrder => integer().withDefault(const Constant(0))();

  /// Выключенная юрисдикция не печатается и в сумму не входит.
  BoolColumn get isActive => boolean().withDefault(const Constant(true))();

  /// Касса стоит в этой юрисдикции.
  ///
  /// Отметок несколько: город **и** спецрайоны. Предки добавляются сами и
  /// отмечаться не обязаны — доля штата взимается и без упоминания.
  ///
  /// Хранится отметкой, а не полем «где касса» в настройке, потому что
  /// юрисдикций у кассы больше одной: RTD и SCFD накрывают несколько
  /// городов сразу и предками Денвера не являются. Одно поле выразило бы
  /// только город, и касса недобрала бы 1,10 %.
  BoolColumn get isTillLocation =>
      boolean().withDefault(const Constant(false))();
}

/// Налоговая категория товара: «еда для дома», «готовая еда», «лекарства».
///
/// # Почему категория, а не ставка у товара
///
/// Так устроена [библиотека определений
/// SSUTA](https://www.streamlinedsalestax.org/Shared-Pages/State-taxability-matrix):
/// штаты заполняют матрицу «определение товара → облагается или нет», и то
/// же самое делает Приложение III директивы ЕС.
///
/// Довод не в подражании, а в том, что ставка у товара ломает сеть из двух
/// точек в разных штатах: один каталог, а ставка у одного и того же молока
/// разная. Пришлось бы вести два каталога или править ставки в каталоге при
/// каждом изменении в любом штате.
class TaxCategories extends Table {
  IntColumn get id => integer().autoIncrement()();

  /// Устойчивый код: по нему пресеты попадают в категорию, не завися от
  /// названия, которое пользователь вправе переименовать.
  TextColumn get code => text().withLength(min: 1, max: 48)();

  TextColumn get title => text().withLength(min: 1, max: 96)();

  /// Категория товаров, у которых своей не проставлено.
  ///
  /// Ровно одна — держит `TaxCategoryDao`, проверяет сторож. Ноль означал
  /// бы товар без облагаемости вовсе.
  BoolColumn get isDefault => boolean().withDefault(const Constant(false))();

  @override
  List<Set<Column>> get uniqueKeys => [
    {code},
  ];
}

/// Что делает юрисдикция с категорией.
abstract class TaxRuleKind {
  /// Облагается по ставке.
  static const int taxed = 0;

  /// Облагается по нулевой ставке: в отчётности присутствует, налог ноль.
  static const int zero = 1;

  /// Освобождено: вне налоговой базы.
  ///
  /// Не то же, что ноль, и это различие не наша выдумка — ЕС разводит их
  /// формально по праву вычета, а отчётность по ним разная.
  static const int exempt = 2;
}

/// Правило: что эта юрисдикция делает с этой категорией и с какого дня.
///
/// # Почему у ставки дата
///
/// Ставки меняются по датам — в Колорадо дважды в год, 1 января и 1 июля.
/// Чек, перепечатанный задним числом, обязан считаться по ставке **того
/// дня**. Без даты перепечатка тихо посчитала бы по сегодняшней, и
/// расхождение всплыло бы в сверке, а не на кассе.
@DataClassName('TaxRuleRow')
class TaxRules extends Table {
  IntColumn get id => integer().autoIncrement()();

  IntColumn get jurisdictionId => integer()();

  /// `null` — правило для всех категорий, у которых нет своего.
  ///
  /// Так выражается обычный случай: «штат берёт 2,9 % со всего, кроме
  /// еды» — одно правило без категории и одно для еды.
  IntColumn get categoryId => integer().nullable()();

  IntColumn get kind =>
      integer().withDefault(const Constant(TaxRuleKind.taxed))();

  /// Доля в процентах. Дробная: 2.90, 5.15, 0.10.
  RealColumn get ratePercent => real().map(const DecimalConverter())();

  /// С какого дня действует. Обязательна.
  DateTimeColumn get validFrom => dateTime()();

  /// По какой день включительно. `null` — бессрочно.
  DateTimeColumn get validTo => dateTime().nullable()();
}
