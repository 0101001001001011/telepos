import 'package:drift/drift.dart';
import 'package:telepos/data/database/converters/decimal_converter.dart';

/// Намерения оплаты QR/СБП — задача 22, схема v42.
///
/// # Почему таблица, а не память экрана
///
/// Потому что подтверждение приходит **после** того, как касса спросила,
/// и «после» здесь не метафора: между вопросом и ответом покупатель
/// открывает приложение банка, ищет очки, вводит ПИН. За это время касса
/// может быть перезагружена (свет), вкладка терминала закрыта (кассир
/// ушёл на другой чек), а сеть — пропасть и вернуться.
///
/// Память экрана всё это не переживает. Деньги покупателя — переживают.
/// Именно этот зазор и есть тот класс беды, который в дереве **уже
/// случался однажды**: очередь фискализации завели ровно потому, что чек,
/// не доехавший до оператора, исчезал вместе с процессом.
///
/// # Уникальный ключ по [intentKey] — это и есть идемпотентность
///
/// Не «проверить, нет ли уже такого» кодом: проверка кодом — это гонка с
/// собой, и вторая вкладка проходит её условие целиком, ровно как прошёл
/// его второй гонщик у `payments` до задачи 8. База умеет запретить
/// вторую строку **атомарно**, и здесь она это делает.
///
/// Ключ **наш**, а не провайдера: [providerIntentId] приходит ответом, то
/// есть на круг сети позже той секунды, в которую и случается двойное
/// создание.
///
/// # Чего в этой таблице НЕТ
///
/// **Строки оплаты.** Намерение — не платёж. Платёж появляется в
/// `Payments` тогда и только тогда, когда чек закрыт, и связь между ними
/// — [settledReceiptNo]/[settledAt]. Пока их нет, а [status] уже `paid`,
/// это **деньги без чека**, и они обязаны быть видны на экране разбора, а
/// не выведены сложением двух запросов.
@DataClassName('PaymentIntentEntry')
class PaymentIntents extends Table {
  IntColumn get id => integer().autoIncrement()();

  /// Ключ идемпотентности, придуманный кассой до первого обращения.
  ///
  /// Уникален — см. [uniqueKeys]. Повтор находит строку, а не заводит
  /// вторую.
  TextColumn get intentKey => text().withLength(min: 1, max: 128)();

  /// Короткое имя провайдера. Уезжает в `Payments.providerCode`.
  TextColumn get providerCode => text().withLength(min: 1, max: 64)();

  /// Ид намерения **на той стороне**. Пуст, пока провайдер не ответил, —
  /// и строка, застрявшая в этом виде, разбирается по [intentKey], а не
  /// забывается.
  TextColumn get providerIntentId => text().nullable()();

  /// `QrIntentStatus` **стабильным кодом-строкой**, а не индексом члена.
  ///
  /// На диске лежат намерения, пережившие перезагрузку и обновление
  /// сборки; перестановка членов в объявлении не имеет права переназвать
  /// оплаченное отменённым.
  TextColumn get status => text().withLength(min: 1, max: 32)();

  /// Сколько просили. `Decimal` P18,S3 (I159).
  RealColumn get amount => real().map(const DecimalConverter())();

  /// Сколько провайдер подтвердил. Может быть **меньше** [amount].
  RealColumn get paidAmount =>
      real().map(const DecimalConverter()).nullable()();

  /// Код, который показывают покупателю.
  TextColumn get qrPayload => text().nullable()();

  IntColumn get posId => integer().nullable()();
  IntColumn get receiptNo => integer().nullable()();
  IntColumn get terminalId => integer().nullable()();

  IntColumn get createdAt => integer()();
  IntColumn get expiresAt => integer().nullable()();
  IntColumn get confirmedAt => integer().nullable()();

  /// Когда **касса перестала ждать**.
  ///
  /// Отдельно от [status] намеренно: провайдер про нашу сдачу не знает и
  /// отвечает `paid`. Слить его ответ и наше решение в одно поле значит
  /// потерять разницу между «он сказал» и «мы решили» — а разбирает беду
  /// человек, и ему нужна именно она.
  IntColumn get abandonedAt => integer().nullable()();

  /// Когда деньги легли строкой в чек.
  IntColumn get settledAt => integer().nullable()();
  IntColumn get settledReceiptNo => integer().nullable()();

  /// Сколько по этому намерению **вернули покупателю** — v51, ревизия
  /// 2026-09-19, дыра 3.
  ///
  /// # Зачем столбец, а не один статус
  ///
  /// Потому что возврат бывает частичным, и чаще всего он частичный:
  /// раскладка возврата отдаёт безналичной строке `min(принесла, осталось
  /// вернуть)`, и с чека «700 наличными + 600 QR» возврат на 300 уходит на
  /// QR целиком, оставляя 300 на намерении. Написать такому намерению
  /// `reversed` значило бы соврать — денег на нём ещё половина; оставить
  /// `paid` и не записать ничего значило бы промолчать о том, что часть уже
  /// ушла. Столбец говорит **сколько**, а [status] переводится в `reversed`
  /// только когда вернулось всё.
  ///
  /// `Decimal` P18,S3 (I159) — тем же преобразователем, что [amount].
  RealColumn get reversedAmount =>
      real().map(const DecimalConverter()).nullable()();

  /// Когда провайдер подтвердил возврат — и **условие идемпотентности**
  /// записи ([PaymentIntentDao.markReversed] пишет только по
  /// `reversed_at IS NULL`, тем же приёмом, что `markSettled` по
  /// `settled_at`).
  IntColumn get reversedAt => integer().nullable()();

  TextColumn get refusalCode => text().nullable()();
  TextColumn get refusalMessage => text().nullable()();

  /// Сколько раз провайдер подтверждал это намерение.
  ///
  /// Второе подтверждение денег второй раз не берёт; число здесь стоит
  /// затем, чтобы это было **видно**, а не выведено из молчания.
  IntColumn get confirmations => integer().withDefault(const Constant(0))();

  @override
  List<Set<Column>> get uniqueKeys => [
    {intentKey},
  ];
}
