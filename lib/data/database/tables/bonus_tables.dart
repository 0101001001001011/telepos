import 'package:drift/drift.dart';
import 'package:telepos/data/database/converters/decimal_converter.dart';

/// Журнал движений бонусного счёта — задача 13, шаг 6.
///
/// # Что было вместо него
///
/// Одно число в `accounts.value`, переписываемое на месте. «Кто, когда, по
/// какому чеку» не записано **нигде**: начисление и списание оставляли за
/// собой только новый остаток. Отсюда две беды, измеренные до этой таблицы:
///
/// 1. Возврат чека не мог сторнировать начисленное, потому что «сколько
///    начислено по этому чеку» неоткуда прочитать. Пересчёт по нынешней
///    ставке (`this_pos_entries.cashback_rate`) дал бы **правдоподобное
///    неверное число**: ставка к моменту возврата может быть другой.
///    Проба с числами — `test/domain/usecases/refund/refund_bonus_sign_test.dart`.
/// 2. Расхождение между кассами было и тихим, и неограниченным: остаток
///    перезаписывался целиком, и последняя доставка выигрывала.
///
/// # Знак — в роде движения, не в сумме
///
/// [amount] неотрицательна всегда; направление называет
/// `BonusEntryKind.signOf`. Довод — в докстринге рода: `SUM(amount)` без
/// разбора рода дала бы число, похожее на правду.
///
/// # Идемпотентность приёма чужих записей
///
/// [originPosId] + [originEntryId] — кто запись породил и под каким номером
/// **у себя**. Ключ по паре: повторная доставка той же записи не меняет
/// ничего, а порядок доставки на баланс не влияет — сумма от порядка
/// слагаемых не зависит. Это и есть вариант C сведения (реплицируется
/// журнал, баланс считает каждый).
///
/// Сломанный `_rev` пуш-очереди журналу **не мешает**, и чинить это
/// отправкой `_rev` не надо: для неизменяемой записи конфликт означает «эта
/// запись уже там».
///
/// # Названная цена варианта C
///
/// Две кассы, торгующие оффлайн, могут списать один остаток дважды: обе
/// видели его целым. Журнал этого не предотвращает — он делает это видимым
/// записью `BonusEntryKind.overspend` с причиной.
class BonusEntries extends Table {
  IntColumn get id => integer().autoIncrement()();

  /// Бонусный счёт (`accounts.id`), по которому движение.
  ///
  /// Счёт, а не покупатель: у покупателя бонусный счёт один, но связь
  /// хранится у покупателя (`agents.cashback_account_id`), и класть сюда
  /// вторую копию значило бы завести второй ответ на вопрос «чьи это
  /// бонусы».
  IntColumn get accountId => integer()();

  /// `BonusEntryKind` — род движения и его знак.
  IntColumn get kind => integer()();

  /// Сумма движения, **всегда неотрицательная**. Деньги P18,S3 (I159).
  RealColumn get amount => real().map(const DecimalConverter())();

  /// Чек, породивший движение. `null` у стартового остатка и у записи
  /// перерасхода — им чека не из чего взять, и выдумывать его нельзя.
  IntColumn get receiptNo => integer().nullable()();

  IntColumn get posId => integer().nullable()();

  /// Возврат, породивший движение (`refunds.local_id`).
  IntColumn get refundLocalId => integer().nullable()();

  /// Кто. `null` — «записала не рука»: миграция, приём чужой записи,
  /// сведение. Пустое здесь честнее выдуманного нуля: пользователь с
  /// идентификатором 0 существует.
  IntColumn get userId => integer().nullable()();

  /// Когда, секундами эпохи — тем же масштабом, что `payments.time`.
  IntColumn get time => integer()();

  /// Касса, породившая запись, и её номер **у той кассы**.
  ///
  /// Пара уникальна: см. раздел про идемпотентность в докстринге таблицы.
  IntColumn get originPosId => integer()();

  IntColumn get originEntryId => integer()();

  /// Почему — словами, для отчёта. Заполняется там, где число само за себя
  /// не говорит: перерасход, стартовый остаток, сторно.
  TextColumn get reason => text().nullable()();

  /// Состояние отправки — тем же смыслом и теми же числами, что
  /// `payments.state`: `1` = «ожидает отправки».
  IntColumn get state => integer().nullable()();

  @override
  List<Set<Column>> get uniqueKeys => [
    {originPosId, originEntryId},
  ];
}
