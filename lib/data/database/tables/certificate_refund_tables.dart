import 'package:drift/drift.dart';

/// Журнал связи «возврат → сертификат» — схема v48, решение заказчика
/// 2026-09-16.
///
/// # Зачем журнал, если и так всё видно
///
/// Не видно. Возврат товара, оплаченного сертификатом, больше **не
/// возвращает деньги на ту же бумажку** (решение 2): старый сертификат
/// остаётся погашенным навсегда, а покупателю выпускается **новый** на
/// сумму, ранее закрытую сертификатом (решение — практика Спортмастера,
/// М.Видео и Magnum). После такой операции в базе лежат два сертификата,
/// и связь между ними не выводится ниоткуда: у нового свой номер, свой
/// остаток и свой чек выпуска, а у старого — только ноль на остатке,
/// неотличимый от честно потраченного.
///
/// Без записанной связи **повторный возврат по тому же чеку удвоил бы
/// деньги**: касса второй раз не нашла бы следов первого выпуска и
/// выписала бы вторую бумажку на ту же сумму. Frontol отказался от
/// возврата по сертификатам целиком именно из-за этой непрозрачности; у
/// нас она закрывается проверяемым ограничением, а не соглашением.
///
/// # Ключ — не украшение, а сам заслон
///
/// [uniqueKeys] по паре «возврат и исходная бумажка» — **вторая линия**
/// защиты от двойного выпуска, ровно тем же приёмом и с тем же доводом,
/// что уникальность номера в `GiftCertificates`. Первая линия — проверка
/// перед выпуском, она объясняет кассиру словами; между проверкой и
/// вставкой есть окно, и закрывает его только ключ.
///
/// `Refunds` уже держит уникальность по паре `{saleReceiptNo, salePosId}`,
/// то есть второй возврат того же чека записан быть не может. Довод
/// «значит, и здесь ключ лишний» отвергнут сознательно: он верен ровно до
/// первого возврата **без чека** и до первой правки соседней таблицы, а
/// цена ошибки здесь — выпущенные из воздуха деньги.
///
/// # Удаления нет
///
/// Тот же довод, что у `GiftCertificates`: строка объясняет, откуда взялся
/// сертификат, который живёт три года. Отозвать бумажку можно
/// (`CertificateStatus.cancelled`), стереть её происхождение — нет.
@DataClassName('CertificateRefundLinkRow')
class CertificateRefundLinks extends Table {
  IntColumn get id => integer().autoIncrement()();

  /// Возврат, которым эта связь заведена (`Refunds.localId`).
  IntColumn get refundLocalId => integer()();

  /// Номер **исходной** бумажки.
  ///
  /// У [CertificateRefundReason.issued] — сертификат, которым был оплачен
  /// возвращаемый товар; у [CertificateRefundReason.redeemed] — сертификат,
  /// проданный возвращаемым чеком.
  TextColumn get sourceNumber => text().withLength(min: 1, max: 64)();

  /// Номер **нового** сертификата. `null` — выпуска не было (гашение при
  /// возврате продажи самой бумажки).
  TextColumn get issuedNumber => text().nullable()();

  /// Сумма, целыми тысячными — тем же масштабом и по той же причине, что
  /// остаток в `GiftCertificates`: деньги на диске не бывают `double`
  /// (I159), а перевод живёт в `MoneyMillis`.
  IntColumn get amountMillis => integer()();

  /// [CertificateRefundReason] **стабильным кодом-строкой**, а не индексом
  /// члена: тот же довод, что у `CertificateStatus`.
  TextColumn get reason => text().withLength(min: 1, max: 16)();

  /// Секунды эпохи — тем же масштабом, что `payments.time`.
  IntColumn get time => integer()();

  @override
  List<Set<Column>> get uniqueKeys => [
    {refundLocalId, sourceNumber},
  ];
}

/// Почему связь заведена — решения заказчика 2026-09-16.
///
/// Код-строка на диске, не индекс: строки переживают перестановку членов в
/// объявлении, а в базе они лежат годами.
enum CertificateRefundReason {
  /// Возвращён товар, оплаченный сертификатом: старый остался погашенным,
  /// выпущен **новый** на закрытую им сумму (решение 2).
  issued,

  /// Возвращён чек, которым сертификат был **продан**: бумажка погашена
  /// немедленно, нового выпуска нет (решение 1).
  redeemed;

  String get code => name;

  static CertificateRefundReason? byCode(String? value) {
    for (final v in values) {
      if (v.name == value) return v;
    }
    return null;
  }
}
