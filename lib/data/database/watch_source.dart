/// Источник изменений кассы: **сигнал от базы, значение от чтения**.
///
/// # Зачем это, а не `Selectable.watch()` drift
///
/// Потоковый запрос drift делает обе вещи разом — слушает таблицы и сам
/// перевыполняет запрос, — и это выглядит короче. Мерилось 2026-08-05, и
/// короче оно только на вид:
///
/// - **Под `testWidgets` `watch()` не отдаёт ни одного значения.** Проверено
///   отдельно: `db.select(t).watch().first` не завершается ни за один
///   `pump()`, а `db.tableUpdates(...)` в том же тесте срабатывает, и обычное
///   `Future`-чтение возвращается. Экран, ждущий первого значения, остаётся с
///   крутящимся индикатором навсегда — `pumpAndSettle` не сходится, и три
///   сквозных теста мастера настройки падали именно так. В поле это тот же
///   белый экран, только со спиннером.
/// - Значение приходит **строкой drift**, а не доменным объектом, и
///   перевод всё равно пишется снаружи. Выигрыш был бы только в строке кода.
///
/// Здесь роли разделены: `tableUpdates` говорит **что** изменилось,
/// а чтение — уже готовым методом репозитория — говорит **чем** оно стало.
/// Второго определения запроса не заводится: читает та же функция, что
/// отвечает на одноразовый вопрос, поэтому вопрос и подписка не могут дать
/// разных ответов.
///
/// # Своей шины событий не заводится, и это важно
///
/// Соблазн был: пусть репозитории сами объявляют «я записал». Тогда запись,
/// прошедшая мимо объявления, разошлась бы с тем, что видит терминал, и
/// разошлась бы молча. `tableUpdates` будит от самой записи — зазору неоткуда
/// взяться.
library;

import 'dart:async';

import 'package:drift/drift.dart';

import 'package:telepos/data/database/app_database.dart';

/// Значение сейчас и при каждом изменении любой из [tables].
///
/// [read] обязано быть тем же чтением, которым отвечает одноразовый вопрос:
/// вопрос и подписка, читающие по-разному, — это два ответа на один вопрос.
///
/// Отказ чтения уезжает ошибкой потока, а не проглатывается: подписчик обязан
/// узнать причину, а не просто перестать получать обновления.
Stream<T> watchTables<T>(
  AppDatabase db,
  List<ResultSetImplementation<dynamic, dynamic>> tables,
  Future<T> Function() read,
) {
  late final StreamController<T> out;
  StreamSubscription<void>? signal;

  // Чтения не накладываются друг на друга, и последнее из них всегда
  // случается после последнего сигнала. Без этого обновления, пришедшие
  // подряд, читались бы вперемешку, и подписчик увидел бы предпоследнее
  // состояние как последнее — экран показывал бы отменённый заказ живым.
  var reading = false;
  var pending = false;

  Future<void> emit() async {
    if (reading) {
      pending = true;
      return;
    }
    reading = true;
    try {
      do {
        pending = false;
        final value = await read();
        if (out.isClosed) return;
        out.add(value);
      } while (pending);
    } on Object catch (error, stackTrace) {
      if (!out.isClosed) out.addError(error, stackTrace);
    } finally {
      reading = false;
    }
  }

  out = StreamController<T>(
    onListen: () {
      // Подписка на сигнал заводится **до** первого чтения: изменение,
      // случившееся между ними, иначе потерялось бы навсегда — первое чтение
      // его уже не застало бы, а сигнала о нём никто бы не слушал.
      signal = db
          .tableUpdates(TableUpdateQuery.onAllTables(tables))
          .listen((_) => unawaited(emit()));
      unawaited(emit());
    },
    onCancel: () {
      // Отменяем — забытая подписка держала бы чтение базы ради экрана,
      // которого больше нет, — но **не ждём**, и это не небрежность.
      //
      // `Stream.first` завершается не тогда, когда пришло значение, а тогда,
      // когда завершилось будущее отмены (`dart:async`, `_cancelAndValue`).
      // Отмена подписки drift под `pumpAndSettle` не завершается: измерено
      // 2026-08-05, три сквозных теста мастера настройки падали именно так —
      // значение приходило, экран оставался с крутящимся индикатором навсегда,
      // и `pumpAndSettle` сдавался. В поле это тот же белый экран, только со
      // спиннером.
      //
      // Ждать здесь нечего по существу: отмена — уборка, её итог никому не
      // нужен, и никакое решение от него не зависит.
      final pending = signal;
      signal = null;
      if (pending != null) unawaited(pending.cancel());
    },
  );

  return out.stream;
}
