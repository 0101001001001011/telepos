/// Живые подписки кассы и то, как они снимаются.
///
/// # Отписки как события не существует
///
/// Терминал не может её прислать, и это не недоделка, а следствие приёма.
/// Касса читает сообщение до конца, прежде чем оно станет событием (иначе
/// половина сообщения выглядела бы как целое), — значит запрос она видит
/// только после того, как терминал закрыл свою половину отправки. Событие
/// `streamClosed` приходит **сразу за запросом**, одинаково для одноразового
/// вопроса и для часовой подписки. Терминал не может одновременно держать
/// половину отправки открытой, чтобы касса увидела запрос, и закрывать её ради
/// отписки.
///
/// Поэтому уход узнаётся двумя способами, и оба здесь:
///
/// 1. **По отказу записи** — [deliver]. Терминал закрыл свою половину приёма;
///    очередное обновление отвечает [RkQuicStatus.peerGone], и подписка
///    снимается.
/// 2. **По закрытию сессии** — [removeSession]. Вкладку закрыли, крышку
///    опустили, сеть пропала.
///
/// # Следствие, которое не надо «чинить»
///
/// Молчащая подписка не узнаёт об ушедшем терминале, пока ей нечего слать.
/// Это допустимо: простаивающая подписка стоит одной записи в карте, а
/// настоящий уход закрывает сессию, чей приход гарантирован пределом простоя
/// (И153). Сердцебиение ради этого не заводится — оно добавило бы трафик и ещё
/// одно состояние, ничего не закрыв.
///
/// # Снятие означает отмену источника
///
/// Забыть подписку, не отменив её, значило бы оставить работать таймер, запрос
/// к базе или слушателя очереди печати ради экрана, которого больше нет. Счёт
/// [live] считает именно живые: то, что отменено, из карты ушло.
library;

import 'dart:async';

import 'package:rk_quic/rk_quic.dart';
import 'package:telepos/domain/wire/wire_frame.dart';

class TillSubscriptions {
  /// Ключ — пара (сессия, поток): один обмен и есть одна подписка, номера
  /// потоков уникальны только внутри своей сессии.
  final Map<(int, int), StreamSubscription<void>> _live = {};

  /// Сколько подписок живо прямо сейчас.
  int get live => _live.length;

  void add(int sessionId, int streamId, StreamSubscription<void> subscription) {
    // Повторное `add` на тот же поток означало бы две подписки в один обмен —
    // возможно только при ошибке в разборе. Старая отменяется, а не теряется.
    final previous = _live[(sessionId, streamId)];
    if (previous != null) unawaited(previous.cancel());
    _live[(sessionId, streamId)] = subscription;
  }

  /// Снимает подписку этого обмена. Повторный вызов — не ошибка: снятие
  /// приходит с двух сторон сразу (отказ записи и закрытие сессии), и порядок
  /// между ними не определён.
  Future<void> removeStream(int sessionId, int streamId) async {
    await _live.remove((sessionId, streamId))?.cancel();
  }

  /// Снимает все подписки сессии разом.
  Future<void> removeSession(int sessionId) async {
    final keys = _live.keys.where((key) => key.$1 == sessionId).toList();
    for (final key in keys) {
      await _live.remove(key)?.cancel();
    }
  }

  /// Снимает всё — при остановке провода.
  Future<void> removeAll() async {
    final all = _live.values.toList();
    _live.clear();
    for (final subscription in all) {
      await subscription.cancel();
    }
  }

  /// Пишет кадр подписчику и снимает его, если писать больше некуда.
  ///
  /// Возвращает статус записи значением: вызывающему полезно знать, дошло ли
  /// обновление, а бросать здесь нельзя — это путь исполнения обычного
  /// изменения состояния кассы, и исключение в нём остановило бы источник, а
  /// не только этого подписчика.
  ///
  /// Снимается на **любом** неуспехе, не только на [RkQuicStatus.peerGone]:
  /// запись, которая не легла, не легла — и подписка, чьи обновления не
  /// доходят, это подписка, которой нет. Различать причины здесь незачем,
  /// причина уже названа статусом и попадёт в лог вызывающего.
  Future<RkQuicStatus> deliver(
    QuicServer server, {
    required int sessionId,
    required int streamId,
    required WireFrame frame,
  }) async {
    if (!_live.containsKey((sessionId, streamId))) {
      // Гонка, которая обязательно случится: обновление источника и закрытие
      // сессии приходят одновременно. Про этот поток уже решено, что его нет,
      // и писать в него — значит держать ушедший терминал дольше уговора.
      return RkQuicStatus.unknownHandle;
    }

    final status = await server.sendOn(sessionId, streamId, frame.encode());
    if (status != RkQuicStatus.ok) {
      await removeStream(sessionId, streamId);
      // Закрытие — попытка вежливости, а не условие: поток, отказавший на
      // записи, обычно уже закрыт с той стороны, и статус здесь ничего не
      // добавит.
      unawaited(server.closeStream(sessionId, streamId));
    }
    return status;
  }
}
