import 'dart:async';

import 'package:telepos/domain/stock/stock_changes.dart';

/// Кассовая половина [StockChanges] — пункт 12 ревизии 2026-09-19.
///
/// Один счётчик на процесс кассы. Его поднимает то, что действительно
/// двигает остаток, а читают все рабочие места разом: экраны самой кассы —
/// через `StockRevision`, браузерные терминалы — подпиской провода
/// `stock.revision`.
///
/// # Почему в памяти, а не таблицей
///
/// Это сообщение, а не правда. Правда об остатке лежит в товарах, и
/// подписанный перечитывает её сам; номер ревизии нужен ровно на время
/// жизни процесса. Строка в базе завела бы вторую правду, которую пришлось
/// бы чистить, и пережила бы перезагрузку кассы, ничего этим не сказав:
/// экран, построенный заново, и так читает свежий остаток.
///
/// # Почему широковещательный поток
///
/// Подписчиков много и они приходят в разное время: экран каталога кассы,
/// экран продажи, каждая открытая вкладка. Одиночный поток отдал бы
/// сообщение первому и отказал остальным.
///
/// # Чего это НЕ закрывает
///
/// **Вторую кассу.** Счётчик живёт в процессе одной кассы, и продажа на
/// соседней кассе его не поднимает — там свой процесс и своя база.
/// Согласование между кассами — это синхронизация (пункт 18 ревизии,
/// `project_telepos_couchdb_sync_broken`), и подменять её счётчиком в
/// памяти значило бы выдать «рабочие места одной кассы» за «магазин».
class LocalStockChanges implements StockChanges, StockChangeSink {
  final _controller = StreamController<int>.broadcast();

  int _revision = 0;

  /// Текущий номер — для первого кадра подписки.
  int get revision => _revision;

  @override
  Stream<int> watch() async* {
    // Текущее значение **первым**, затем изменения. Без него подписчик,
    // пришедший после события, не узнал бы номера вовсе, а род `Watch` на
    // проводе обязан нести текущее значение первым кадром.
    yield _revision;
    yield* _controller.stream;
  }

  @override
  void stockChanged() {
    _revision += 1;
    if (!_controller.isClosed) _controller.add(_revision);
  }

  Future<void> dispose() => _controller.close();
}
