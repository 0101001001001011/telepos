  /// Одна команда в полёте на рабочее место (I161).
  ///
  /// Очередь — цепочка `Future`, а не таймер и не пул: [body] запускается
  /// микрозадачей сразу за исходом предыдущей команды, поэтому десять
  /// сканов подряд проходят за столько же кругов провода, сколько один, и
  /// ни одной задержки сверх ответов кассы не копится.
  Future<CartView> _queued(
    int terminalId,
    CartCommandMeta meta,
    Future<CartView> Function() body,
  ) {
    // Проверка — до постановки в очередь: команда наивного вызывающего не
    // должна уехать даже в отладке.
    assert(_notFromTheSameSnapshot(terminalId, meta));

    final previous = _queues[terminalId] ?? Future<void>.value();
    final result = previous.then((_) => body());
    // Хвост очереди без отказа: следующая команда ждёт **исхода**, а не
    // успеха.
    _queues[terminalId] = result.then<void>((_) {}, onError: (Object _) {});

    // **Вся** бухгалтерия сторожа — внутри `assert`, а не рядом с ним.
    // Круг правки 3: снаружи оставались запись в карту и цепочка с
    // замыканием на каждую команду — они переживают релизную сборку и
    // работают на карту, которую там никто не читает. Это узор «мёртвый
    // код, выглядящий живым», на котором проект уже горел.
    //
    // Тело `assert(() { … return true; }())` в релизе не исполняется вовсе,
    // как и довод `assert` выше. Остаётся одно — пустая карта [_pending] на
    // экземпляр; убрать и её можно было бы только условной компиляцией, и
    // это дороже, чем стоит.
    assert(() {
      _pending[terminalId] = meta;
      // Метка гасится, только если за ней никто не встал: иначе следующая
      // команда сравнивалась бы с пустотой и наивный вызывающий прошёл бы
      // мимо сторожа ровно в том случае, ради которого он заведён.
      unawaited(
        _queues[terminalId]!.then((_) {
          if (identical(_pending[terminalId], meta)) {
            _pending.remove(terminalId);
          }
        }),
      );
      return true;
    }());

    return result;
  }

  /// Сторож наивного вызывающего: две команды одного чека, посчитанные от
  /// **одного и того же** снимка, когда первая ещё не погашена.
  ///
  /// # Почему это `assert`, а не отказ
  ///
  /// Ошибка здесь не в кассе и не в проводе — она в том, кто зовёт контракт,
  /// и видна она только тому, кто пишет экран. В релизе не исполняется ни
  /// эта проверка, ни бухгалтерия меток — обе внутри `assert` (см.
  /// [_queued]); остаётся пустая карта [_pending] на экземпляр, и это вся
  /// цена. Под `flutter test` и в отладочной сборке краснеет на первом же
  /// таком вызове. Отказом это делать нельзя: касса такую
  /// команду примет или отвергнет сама, и подменять её решение здесь значило
  /// бы завести второй источник правды о версии.
  ///
  /// # Три условия, без которых сторож даёт ложную красноту
  ///
  /// 1. **только с непогашенной предыдущей.** Две команды с одной
  ///    `baseVersion` законны, если первая **отвергнута**: отказ версию не
  ///    поднимает. Поэтому метка гасится по исходу, а сравнение идёт с тем,
  ///    что ещё в полёте или в очереди;
  /// 2. **только при одинаковом номере чека.** Версии разных чеков — это
  ///    два разных счётчика, и совпадение чисел ничего не значит
  ///    (`CartCommandMeta`);
  /// 3. **только когда номер чека вообще назван.** `start` с холода
  ///    (`meta.receiptNo == null`) означает «не знаю, что у меня в работе»,
  ///    и касса версию у него не сверяет вовсе — сторожить там нечего.
  ///    Условие найдено не рассуждением: без него две вкладки, зовущие
  ///    `start` первым делом, красили бы сторож на совершенно законном
  ///    вызове.
  ///
  /// Сравнение — на равенство, а не «строго больше»: по той же причине 1
  /// шаг назад после отказа законен.
  ///
  /// # Чего этот сторож НЕ ловит — три дыры, измеренные против кассы
  ///
  /// Круг правки 3 прогнал сторож пятой диверсией против настоящей кассы и
  /// нашёл три обхода. Ни один не закрывается здесь; названы, чтобы
  /// следующий не принял `assert` за полную защиту.
  ///
  /// 1. **Деление по рабочему месту не имеет опоры на проводе.** Два вызова
  ///    с разными `terminalId` из одной вкладки бьют в **одну** корзину
  ///    (`terminalId` на провод не уезжает вовсе — см. докстринг [watch]),
  ///    но получают две очереди и две метки. Измерено: ни одного
  ///    `AssertionError`, касса ответила одним `cart_stale`, в базе одна
  ///    единица из двух. То же деление лежит и в основе «одной команды в
  ///    полёте»: проба «очередь на рабочее место, а не одна на всех»
  ///    (`peakOpen == 2`) закрепляет это как свойство. Деление верно **для
  ///    экрана** — у вкладки рабочее место одно и оно из сеанса — и не
  ///    верно для провода;
  /// 2. **Кассир, который дождался ответа, но взял версию из отставшей
  ///    подписки**, сторожу неотличим от честного: предыдущая команда
  ///    погашена, сравнивать не с чем. Это ровно производственный сценарий,
  ///    и он вне зоны сторожа даже в отладке;
  /// 3. **Первая команда после холодного `start`** проходит мимо условия 3:
  ///    в метке `start` лежит пустой номер чека, и сравнение с ней не
  ///    состоится. Дыра ровно в одну команду — но это самая частая команда
  ///    чека.
  ///
  /// Все три закрывает не `assert`, а контракт: метку должен выдавать сам
  /// снимок, чтобы устаревшую версию нельзя было напечатать руками. См.
  /// раздел «Обязанность вызывающего» в докстринге библиотеки.
  bool _notFromTheSameSnapshot(int terminalId, CartCommandMeta meta) {
    final pending = _pending[terminalId];
    if (pending == null) return true;
    if (meta.receiptNo == null || pending.receiptNo == null) return true;
    if (meta.receiptNo != pending.receiptNo) return true;
    if (meta.baseVersion != pending.baseVersion) return true;

    throw AssertionError(
      'команда «${meta.key}» рабочего места $terminalId посчитана от версии '
      '${meta.baseVersion} чека ${meta.receiptNo} — от той же, что и '
      '«${pending.key}», которая ещё не получила исхода. Очередь даёт '
      'порядок, но версию ведёт вызывающий: i-я команда, поставленная от '
      'снимка версии v, считается от v + i. Иначе касса применит первую и '
      'ответит на остальные `cart_stale` — по одному отказу на скан.',
    );
  }

  /// Один обмен: повтор ровно один раз на обрыв, названный отказ — наружу.
  Future<Res> _ask<Req, Res>(Ask<Req, Res> op, Req request) async {
    try {
      return await _wire.ask(op, request);
    } on Object catch (error, stack) {
      if (!_worthRepeating(error)) {
        Error.throwWithStackTrace(_named(error), stack);
      }
    }

    // Повтор — тем же телом и тем же ключом: касса помнит последний
    // применённый ключ чека и на повтор отвечает тем же снимком, не
    // применяя команду второй раз (правило 3 контракта).
    try {
      return await _wire.ask(op, request);
    } on Object catch (error, stack) {
      Error.throwWithStackTrace(_named(error), stack);
    }
  }

  /// Стоит ли повторять — то есть «вопрос потерян», а не «касса ответила».
  ///
  /// **Сырой отказ транспорта повторяется, и это измерено, а не выбрано по
  /// вкусу.** `WtSession._pump` кладёт отказ чтения в поток как
  /// `addError(error)` **сырым объектом** (`lib/web/wt_session.dart:297`), а
  /// `WtDispatcher.ask` оборачивает только пустой поток (`StateError` →
  /// `no_answer`). Значит обрыв Wi-Fi посреди скана — тот самый сценарий,
  /// ради которого повтор и заведён (шаг 10 спеки, живой сценарий приёмки),
  /// — приходит сюда **не** [WtProtocolError], а ошибкой браузера. Повтор,
  /// различающий только коды провода, в поле не сработал бы ни разу и был
  /// бы зелён во всех пробах.
  ///
  /// Повторять неизвестное безопасно **по построению**: ключ повтора один и
  /// тот же, и касса на него отвечает снимком, а не второй строкой.
  static bool _worthRepeating(Object error) => switch (error) {
    WireRefusal() => false,
    SessionLost() => false,
    WtProtocolError(:final code) => _brokenCodes.contains(code),
    _ => true,
  };

  /// Отказ кассы — [WireRefusal], беда провода — как была.
  ///
  /// **Умолчание, названное кругом правки 1: сюда попадают и беды самой
  /// кассы.** Правило «код не наш → это отказ кассы» переводит в
  /// [WireRefusal] не только названные причины (`cart_stale`, `forbidden`,
  /// `product_not_found`), но и `handler_failed`, `guard_failed`,
  /// `not_a_request` — падение обработчика, падение сторожа, неразобранный
  /// кадр. Измерено: касса отвечает на них обычным кадром отказа, и
  /// отличить их здесь можно только вторым закрытым списком кодов, который
  /// отставал бы от кассы ровно так же, как отставал бы список кодов
  /// отказа.
  ///
  /// Следствие честное, и оно в **обратную** сторону от довода про
  /// [WireRefusal] выше: на кассе падение обработчика доходит до экрана
  /// сырым исключением, а по проводу — названным отказом. Значит «экран не
  /// различает реализаций» неправда **на падениях кассы**: по проводу экран
  /// увидит аккуратную причину там, где на кассе увидел бы аварию.
  ///
  /// Повтора у них при этом нет, и это правильно: обработчик, упавший на
  /// этой команде, упадёт на ней же и во второй раз.
  static Object _named(Object error) =>
      error is WtProtocolError && !_wireCodes.contains(error.code)
      ? WireRefusal(error.code, error.detail)
      : error;
}
