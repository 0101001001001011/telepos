  /// контракту потому, что контракт один на два фронта, и на кассе он
  /// действующий; здесь он честно не нужен.
  Future<CartView> setDiscountPercent(
    int terminalId,
    String lineId,
    Decimal percent,
    CartCommandMeta meta, {
    required DiscountAuthority by,
  }) => _queued(
    terminalId,
    meta,
