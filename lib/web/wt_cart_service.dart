  @override
  /// **Довод `by` по проводу не отправляется — и это не упущение.**
  ///
  /// Полномочия строит касса из сеанса, которым подписан кадр
  /// (`TillOperations._authorityOf`). Отправить их отсюда значило бы
  /// предложить кассе поверить вкладке — ровно то, что запрещено правилом
  /// про `terminalId` в докстринге `CartService`: названное клиентом именем
