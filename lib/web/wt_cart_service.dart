/// Корзина браузерного терминала — вторая реализация контракта
/// `CartService` (задача 12 плана «Продажа с браузерного терминала», шаг 5
/// спеки). Первая — кассовая `LocalCartService`; экран между ними не
/// различает.
///
/// # Это не тонкая обёртка, и вот чем измерена разница
///
/// `WtDispatcher.ask` открывает **свой двунаправленный поток QUIC на каждый
/// запрос** (`wt_dispatcher.dart:76-77`). Из этого следуют две беды, и обе
/// лечатся здесь, а не на кассе:
///
/// - **порядка между потоками нет.** Два быстрых скана уходят двумя
///   потоками и могут доехать до кассы наоборот. Версия в ответе
///   (`cart_stale`) это заметит — но заметит **после** того, как строка
///   легла не туда; версия здесь вторая линия обороны, а не первая. Первая —
///   очередь: следующая команда рабочего места уходит после ответа на
///   предыдущую;
/// - **повтора нет.** Поток умер посреди команды — терминал не знает,
///   применилась она или нет. Повтор безопасен только тем же
///   `CartCommandMeta`: ключ повтора помнит касса (правило 3 контракта), и
///   тот же ключ вернёт тот же снимок вместо второй строки в чеке.
///
/// # Три рода исхода, и путать их нельзя
///
/// | Что случилось | Что видит вызывающий | Повтор |
/// | --- | --- | --- |
/// | касса назвала отказ (`cart_stale`, `forbidden`, `product_not_found`) | [WireRefusal] | никогда |
/// | сеанс истёк (`unauthorized`) | [SessionLost] | никогда |
/// | провод оборвался | [WtProtocolError] или сырой отказ транспорта | ровно один раз |
///
/// **Перевод отказа кассы в [WireRefusal] — не украшение.** Кассовая
/// `LocalCartService` бросает именно его; `WtDispatcher` же переводит кадр
/// отказа в [WtProtocolError] (кроме `unauthorized`). Оставь как есть — и
/// `on WireRefusal` экрана ловил бы причину на кассе и пропускал её по
/// проводу, то есть «экран не различает реализаций» перестало бы быть
/// правдой ровно на отказах, ради названности которых всё и делалось (I144).
///
/// **Повтор ровно один раз.** Второй обрыв — отказ кассиру, а не круг:
/// касса, которая не отвечает дважды, не ответит и на третий раз, а кассир
/// всё это время смотрит в неподвижный экран.
///
/// # Обязанность вызывающего: очередь даёт порядок, но не ведёт версию
///
/// **Это главное, что надо знать, прежде чем звать отсюда что-нибудь**, и
/// названо оно кругом правки 1 задачи 12. Очередь гарантирует, что команды
/// **уйдут и применятся по одной, подряд**. Она не подставляет и не правит
/// [CartCommandMeta.baseVersion] — метку целиком собирает вызывающий, и
/// касса сверяет её строго.
///
/// Отсюда правило для экрана, который шлёт команды **не дожидаясь ответов**
/// (а кассир именно так и сканирует):
///
/// > i-я команда, поставленная в очередь от снимка версии `v`, считается от
/// > `v + i`, а не от `v`. Каждая применённая команда поднимает версию на
/// > единицу, и очередь гарантирует, что промежуточных изменений между ними
/// > не будет.
///
/// Цена ошибки измерена петлёй против настоящей кассы (проба «десять сканов
/// ПРИМЕНЯЮТСЯ»): десять сканов, посчитанных от **одного** снимка, дают
/// исходы `[1, cart_stale ×9]` — в чеке одна единица вместо десяти. Отказы
/// названные, типизованные и безопасные, чек не портится — но **девять
/// сканов кассир потерял**, а очередь при этом отработала безупречно:
/// команды ушли по порядку, каждая дождалась предыдущей.
///
/// **Потеря становится молчаливой не здесь, а на экране** (поправка круга
/// правки 2): отказов ровно девять, и они типизованы. Молча они пропадут
/// тогда, когда экран проглотит их или покажет один раз вместо девяти —
/// значит требование «девять отказов подряд видимы кассиру» адресовано
/// экрану задачи 13, а не этому файлу.
///
/// **Чего делать нельзя ни здесь, ни в задаче 13:** подставлять
/// `baseVersion` из ответа предыдущей команды. Метка означает «состояние,
/// которое кассир видел, когда действовал»; автоподстановка обнулила бы
/// сторож устаревшей версии против второй вкладки того же места — и все
/// пробы остались бы зелёными, потому что проверять стало бы нечего.
/// Настоящее лекарство контрактное: метку должен выдавать сам снимок, чтобы
/// устаревшую версию нельзя было напечатать руками (правка контракта задачи
/// 7). `assert` в [_queued] — временная замена, и замена **неполная**: три
/// измеренные дыры перечислены в [_notFromTheSameSnapshot].
///
/// **У лекарства должен быть владелец и сторож, иначе его не сделают
/// никогда** (оговорка круга правки 3, и она про нас, а не про код). При
/// зелёном наборе и работающем `assert` задача выглядит закрытой, а
/// требование «когда-нибудь в задаче 8 или 13» не принадлежит никому.
/// Владелец назначен разбором: **задача 13** несёт либо правку контракта,
/// либо сторожа по исходникам «экран нигде не собирает `baseVersion`
/// руками» — по образцу сторожа денег
/// (`test/architecture/money_over_wire_test.dart`). Проба на подставном проводе этого
/// не поймает никогда — там версии никто не сверяет, и ровно поэтому
/// «десять сканов уходят по порядку» переименовано в «УХОДЯТ».
///
/// Второй законный путь — брать версию из ответа на предыдущую команду; он
/// проще, но стоит круга провода на каждый скан.
