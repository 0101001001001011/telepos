/// Коды, которыми `WtDispatcher` называет **свои** беды, а не беды кассы.
///
/// Список закрытый и взят из самого диспетчера (`wt_dispatcher.dart`:
/// `no_answer`, `not_a_frame`, `bad_body`, `stream_ended`, `run_incomplete`,
/// `stream_failed`; `no_session` — из `WtChannel.openStream`). Всё, чего в
/// нём нет, назвала касса, а значит это отказ, а не обрыв.
///
/// Проверка «код не наш» вместо «код из списка отказов корзины» выбрана
/// намеренно: список кодов отказа открыт (задача 10 может завести новый, и
/// заведёт), а список кодов провода закрыт и лежит в одном файле. Ошибись в
/// первую сторону — и новый отказ кассы поехал бы на повтор.
const _wireCodes = {
  'no_answer',
  'not_a_frame',
  'bad_body',
  'stream_ended',
  'run_incomplete',
  'stream_failed',
  'no_session',
};

/// Из бед провода — те, что означают «вопрос не доехал или ответ не
/// вернулся», то есть единственный случай, когда повтор осмыслен.
///
/// `not_a_frame` и `bad_body` сюда не входят: касса **ответила**, разобрать
/// ответ не вышло, и второй такой же ответ разберётся так же. `no_session`
/// не входит потому, что сессию поднимает и перепробует `WtChannel`
/// (`_openWithRetries`), а команда до провода не дошла вовсе — повторять
/// здесь значило бы ставить второй круг попыток поверх первого.
const _brokenCodes = {
  'no_answer',
  'stream_ended',
  'run_incomplete',
  'stream_failed',
};

/// Хвост ключа второго кадра оптового начала — см. [WtCartService.start].
const _wholesaleKeySuffix = '~wholesale';

class WtCartService implements CartService {
  WtCartService(this._wire);

  final WtDispatcher _wire;

  /// Хвост очереди на рабочее место: `Future`, которая завершается, когда
  /// последняя поставленная команда получила исход.
  ///
  /// **Карта, а не одно поле, и не статика.** Одно поле означало бы одну
  /// очередь на все рабочие места — соседний планшет ждал бы чужого скана;
  /// статика означала бы то же самое между вкладками одного процесса.
  /// Сегодня у браузерной вкладки рабочее место одно, и карта на ней всегда
  /// в один элемент — но подпись контракта берёт `terminalId` доводом
  /// каждой команды, и очередь обязана делиться по тому же признаку, по
  /// какому делится корзина.
  ///
  /// Хвост **никогда не отказывает**: исход команды снимается
  /// (`onError`) прежде, чем лечь в карту. Иначе первый же отказ посреди
  /// набора запер бы очередь навсегда, и рабочее место замолчало бы до
  /// перезагрузки вкладки при полностью живой кассе.
  final Map<int, Future<void>> _queues = {};

  /// Метка последней поставленной команды места, пока её исход не известен.
  /// Живёт только ради `assert` в [_queued] — см. [_notFromTheSameSnapshot].
  final Map<int, CartCommandMeta> _pending = {};

  /// Подписка, а не команда: очереди не занимает.
  ///
  /// **Предел, который надо знать: [terminalId] на провод не уезжает.** Чьё
  /// рабочее место — знает **сеанс** кассы (`till_operations.dart:527`), а
  /// кадр с названным местом касса **отвергает** (правило 1 контракта:
  /// иначе «назови чужое место — получи его корзину»). Довод остаётся в
  /// подписи ради одного контракта на две реализации; браузерная получает
  /// корзину своего сеанса и никакую другую.
  @override
  Stream<CartView> watch(int terminalId) =>
      _named$(_wire.watch(SaleOps.cart, null));

  /// **Довод [by] на провод не уезжает** — тем же правилом, что у [defer] и
  /// команд уступки: полномочия, названные вкладкой, полномочиями не
  /// являются (докстринг `DiscountAuthority`). Право `op.deferSale` у этой
  /// подписки проверяет сторож кассы по **сеансу** (`SaleOps.deferredList`,
  /// `SessionAccess(needs: …)`), и отказ приезжает сюда кадром, который
  /// [_named$] превращает в `WireRefusal`.
  ///
  /// В подписи он остаётся ради одного контракта на две реализации: довод
  /// заведён задачей 10 ревизии 2026-09-19 ради **кассы**, где сторожа
  /// провода нет вовсе и проверять право больше некому.
  @override
  Stream<List<DeferredCart>> watchDeferred({required DiscountAuthority by}) =>
      _named$(_wire.watch(SaleOps.deferredList, null));

  /// Тот же перевод отказа, что и у команд, но для подписки.
  ///
  /// **Найдено разбором задачи 13.** Таблица в докстринге этого класса
  /// обещает: «касса назвала отказ → `WireRefusal`». Для команд это делал
  /// [_named], а обе подписки отдавали `WtProtocolError` как есть — то есть
  /// ровно на них обещание не выполнялось. Видно это было на экране: диалог
  /// отложенных рисовал `Error: WtProtocolError(forbidden: sale.deferredList:
  /// нет права op.deferSale)` — код протокола, имя операции и внутренний ключ
  /// права в лицо кассиру.
  ///
  /// Перевод живёт здесь, а не у экрана, по той же причине, по какой он
  /// живёт здесь для команд: `on WireRefusal` у общего экрана обязан ловить
  /// отказ **обеих** реализаций, иначе «экран не различает реализаций»
  /// перестаёт быть правдой ровно на отказах.
  static Stream<T> _named$<T>(Stream<T> source) => source.handleError(
    (Object error, StackTrace stack) =>
        Error.throwWithStackTrace(_named(error), stack),
  );

  /// Вопрос, а не команда: очереди не занимает и ключа повтора не несёт.
  ///
  /// Поставь поиск в очередь — и выдача перестала бы приходить, пока касса
  /// думает над сканом; а кассир печатает как раз тогда, когда сканер
  /// молчит.
  @override
  Future<List<ProductSearchResult>> search(String query) =>
      _ask(SaleOps.search, query);

  /// Начать чек — и, если просили опт, переключить его вторым кадром.
  ///
  /// # Почему два кадра, а не один
  ///
  /// `sale.start` признака опта не несёт вовсе, и это решение задачи 10
  /// (круг правки 1): довод `wholesale` у начала чека был обходом права —
  /// `sale.setWholesale` требует `op.editPrice`, `sale.start` только
  /// `nav.sale`, а результат получался один и тот же. Обход снят снятием
  /// довода, значит оптовый чек с браузера — два кадра.
  ///
  /// Четыре следствия, все проверены пробами:
  ///
  /// 1. **оба кадра занимают одно место в очереди.** Иначе между ними лёг
  ///    бы свой же скан — строка осталась бы по рознице, а снимок смеси цен
  ///    не помечает ничем;
  /// 2. **у второго кадра свой ключ повтора** ([_wholesaleKeySuffix]). Тот
  ///    же ключ касса приняла бы за повтор первого кадра — слот повтора
  ///    один на чек (`Sales.lastCommandKey`), — и опт молча не применился
  ///    бы вовсе;
  /// 3. **отказ второго кадра выносится наверх.** Для самообслуживания и
  ///    беспилотного режима отказ по `op.editPrice` — законный исход
  ///    (`PointModePermissions.effective` отбирает правку цены), и экран
  ///    обязан его показать, а не нарисовать опт по намерению;
  /// 4. **повторяется переключение, а не начало.** Повтор начала завёл бы
  ///    второй чек; каждый кадр здесь повторяет сам себя.
  ///
  /// Чек, который уже оптовый, вторым кадром не трогается: команда сожгла
  /// бы слот повтора и подняла версию, обесценив чужие команды в полёте.
  ///
  /// # Расхождение прав между двумя реализациями — круг правки 1
  ///
  /// Пункт 3 выше называет отказ по `op.editPrice` «законным исходом». Это
  /// правда, но не вся: **здесь у одного действия контракта разные права в
  /// двух реализациях**, то есть «экран не различает реализаций» неправда.
  ///
  /// Кассовая `LocalCartService.start(wholesale: true)` не требует
  /// **ничего**: опт уезжает доводом в `SaleInitiationUseCase`, и права там
  /// никто не спрашивает. Браузерная требует `op.editPrice` — потому что по
  /// проводу опт это отдельная операция `sale.setWholesale` под своим
  /// правом.
  ///
  /// Измерено петлёй (проба «опт: у двух реализаций одного контракта разные
  /// права»): сеанс ровно с `nav.sale` открывает оптовый чек на кассе и
  /// получает `forbidden: sale.setWholesale` по проводу.
  ///
  /// Решение задачи 10 законное — обход, которого нет, нельзя забыть
  /// проверить, — но расхождение существует, и закроет его не эта задача, а
  /// перевод экрана кассы на тот же контракт (задача 8). До тех пор один и
  /// тот же кассир на кассе и на планшете имеет разные возможности, и это
  /// свойство продукта, а не дефект реализации.
  @override
  Future<CartView> start({
    required int terminalId,
    required bool wholesale,
    required CartCommandMeta meta,
  }) => _queued(terminalId, meta, () async {
    final started = await _ask(SaleOps.start, meta);
    if (!wholesale || started.wholesale) return started;

    return _ask(SaleOps.setWholesale, (
      wholesale: true,
      // Версия и номер — из **ответа** на первый кадр, а не из метки: между
      // ними чек уже мог родиться, и метка о нём ничего не знает.
      meta: CartCommandMeta(
        key: '${meta.key}$_wholesaleKeySuffix',
        baseVersion: started.version,
        receiptNo: started.receiptNo,
      ),
    ));
  });

