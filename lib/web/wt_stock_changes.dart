/// Браузерная половина [StockChanges] — пункт 12 ревизии 2026-09-19.
///
/// # Что было
///
/// Счётчик ревизии остатков жил в контейнере **одной вкладки**, и его
/// предел был назван прямо в коде: продажа, проведённая другим рабочим
/// местом, его не поднимает. В магазине с кассой и двумя планшетами
/// остаток на соседнем экране устаревал молча — а «молча» здесь хуже
/// ошибки: цифра выглядит свежей.
///
/// # Чего это НЕ закрывает
///
/// - **Вторую кассу.** Подписка идёт к **своей** кассе: её процесс, её
///   база. Магазин из двух касс согласуется синхронизацией (пункт 18
///   ревизии), и выдать эту подписку за неё нельзя ничем.
/// - **Инвентаризацию и перемещение.** Их проводят экраны самой кассы, и
///   они поднимают счётчик **своего** контейнера напрямую
///   (`inventory_controller.dart`, `movement_controller.dart`). До кассы
///   как процесса это не доходит, значит не доходит и до вкладок.
///   Закрывается тем же `StockChangeSink` в тех двух местах — работа
///   названа, но не сделана: оба пути пишут остаток мимо `PaymentService`
///   и требуют отдельного разбора, кто там владелец записи.
/// - **Возврат.** По той же причине и тем же способом.
class WtStockChanges implements StockChanges {
  WtStockChanges(this._wire);

  final WtDispatcher _wire;

  /// Отказ кассы становится `WireRefusal` с тем же кодом — тем же приёмом,
  /// что у соседей по каталогу (`WtScannerRules`, `WtExpiryWarning`).
  /// Довод: за доменным договором не должно торчать имя транспорта, иначе
  /// подписанный обязан знать, по какому проводу он подписан.
  ///
  /// **Отказ, а не тишина.** Подписка, которая молча ничего не скажет,
  /// неотличима на вкладке от кассы, где остаток не двигали, и кассир
  /// доверял бы старой цифре.
  @override
  Stream<int> watch() => _wire
      .watch(TillOps.stockRevision, null)
      .handleError((Object error) {
        if (error is WtProtocolError) {
          throw WireRefusal(error.code, error.detail);
        }
        throw error;
      });
}
