/// Живая подписка на состояние установки — одна на всё приложение.
///
/// # Зачем это существует
///
/// [StartupStateRepository.watch] отдаёт поток с 2026-08-05, но до сих пор его
/// брали как `watch().first`: одно значение, и подписка тут же снималась. Так
/// делали все три маршрута `createSetupRouter`, и это ровно тот случай, когда
/// провод умеет говорить первым, а экран этого не слышит. Кассир, заведённый на
/// кассе, доезжал до терминала при следующем вопросе — то есть после нажатия,
/// перезахода на маршрут или перезапуска, — а не в момент, когда его завели.
/// Ради этого и менялся транспорт
/// (`docs/internal/superpowers/specs/2026-08-04-webtransport-browser-terminal-design.md`).
///
/// # Почему один провайдер, а не подписка в каждом экране
///
/// Riverpod держит один экземпляр на всех слушателей. Поэтому переход
/// заставка → мастер настройки не стоит ни одного нового вопроса: подписка у
/// них общая, и вторая просто не заводится. Подписка, заведённая экраном «для
/// себя», росла бы ровно с числом переходов, и на кассе каждая из них — это
/// живое чтение базы и открытый поток QUIC, а не строчка в памяти терминала.
///
/// # Почему здесь `autoDispose`, хотя в проекте его нет нигде
///
/// Правило «Riverpod без autoDispose» про **состояние экрана** —
/// про корзину, смену, введённое в мастере: такое обязано пережить перестройку
/// дерева и уход с маршрута, иначе человек теряет работу. Здесь состояния нет
/// вовсе: здесь провод. Умолчание Riverpod — «живёт, пока жив контейнер», и для
/// провода это значит, что касса продолжает читать свою базу и держать поток
/// ради вкладки, которую закрыли. Поэтому решение принято обратное и
/// намеренно: подписка кончается вместе с последним слушателем.
///
/// Дальше провод доводит снятие сам, и это уже проверено:
/// `WtDispatcher.watch` закрывает свой поток на отмене, а касса узнаёт об уходе
/// по отказу записи и снимает подписку (`TillSubscriptions`,
/// `test/web/wt_till_speaks_first_test.dart`). Сторож на эту половину —
/// `test/presentation/screens/setup/setup_live_subscription_test.dart`:
/// уход последнего слушателя обязан отменить поток договора.
library;

import 'dart:async';

import 'package:flutter_riverpod/flutter_riverpod.dart';
import 'package:get_it/get_it.dart';

import 'package:telepos/domain/startup/startup_state_repository.dart';
import 'package:telepos/domain/wire/setup_state.dart';

/// Состояние установки сейчас и при каждом его изменении.
///
/// Отказ приходит `AsyncError`, а не исключением у вызывающего: «касса не
/// ответила» — это третий ответ, и путать его с «касса пуста» нельзя, потому
/// что только один из двух предлагает настроить существующий магазин заново
/// (см. `InitialSetupStep.unreadable`).
final startupStateProvider = StreamProvider.autoDispose<SetupState>((ref) {
  return _endedIsNotAnAnswer(GetIt.I<StartupStateRepository>().watch());
});

/// Подписка, закрывшаяся не сказав ничего, — это отказ, а не тишина.
///
/// Измерено дорого. `Stream.first` на пустом потоке бросает `StateError`,
/// который **не** является `Exception` и мимо `on Exception` проходит
/// насквозь, — ровно эта форма отказа белила экран 2026-08-04. У `AsyncValue`
/// та же беда выглядит иначе и не лучше: без этой обёртки провайдер остался бы
/// `AsyncLoading` навсегда, а на экране это белизна со спиннером.
///
/// Закрытие **после** значений здесь отказом не делается, и это решение, а не
/// упущение. Оно означает «новостей больше не будет», а не «известное неверно»,
/// и превращать его в тупиковый [InitialSetupStep.unreadable] значило бы
/// выбросить сведения, которые касса успела дать. Обрыв живой подписки
/// приезжает сюда настоящим отказом с той стороны — `WtDispatcher` отвечает на
/// него `stream_ended`, — и попадает в ту же ветку `AsyncError`.
///
/// # `spoke` обязан ставиться и на ошибке, не только на значении
///
/// Найдено живой проверкой в браузере 2026-08-22 (задача 22 закрытия долга
/// безопасности, пункт 5): `_probeOf` в `InitialSetupNotifier` примерно на
/// каждом девятом открытии страницы писал ERROR **дважды подряд** на один и
/// тот же отказ. Причина была здесь. `WtDispatcher._exchange` на неудавшемся
/// `openStream()` кладёт в поток ошибку и тут же закрывает его —
/// `controller.addError(...); await controller.close();` — то есть настоящий,
/// единственный отказ провода приходит вместе со своим концом, без единого
/// значения между ними. До этой правки `spoke` ставил только `.map()`, а
/// `.map()` — это свойство `Stream`, не этого файла — не трогает событий
/// ошибки вовсе. Поток, честно сказавший «вот почему», проходил здесь как
/// «закрылся, не сказав ничего», и получал вторую, синтетическую ошибку
/// поверх первой, настоящей: ошибка — тоже ответ кассы, просто плохой, и
/// заявлять, что её не было, было и остаётся неверно. Один
/// `StreamTransformer` с раздельными `handleData`/`handleError` вместо
/// `.map()` перед ним ставит `spoke` на оба рода событий и оставляет
/// поведение из докстрингов выше — «нет значений и нет ошибки» и «есть
/// значение, потом тишина» — нетронутым (см.
/// `test/presentation/controllers/startup/startup_state_provider_test.dart`).
Stream<SetupState> _endedIsNotAnAnswer(Stream<SetupState> source) {
  var spoke = false;
  return source.transform(
    StreamTransformer<SetupState, SetupState>.fromHandlers(
      handleData: (state, sink) {
        spoke = true;
        sink.add(state);
      },
      handleError: (error, stackTrace, sink) {
        spoke = true;
        sink.addError(error, stackTrace);
      },
      handleDone: (sink) {
        if (!spoke) {
          sink.addError(
            StateError('касса закрыла подписку, не сказав ни одного значения'),
          );
        }
        sink.close();
      },
    ),
  );
}
