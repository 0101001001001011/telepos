import 'package:flutter_riverpod/flutter_riverpod.dart';

/// «Деньги смены изменились» — счётчик, на который подписаны экраны смены и
/// истории.
///
/// # Зачем он, если есть `ref.invalidate`
///
/// Затем, что `ref.invalidate(shiftControllerProvider)` — это **импорт**
/// `shift_controller.dart`, а тот тянет базу, а база тянет `dart:ffi`.
/// Измерено задачей 20 на сборке веба: перенос экрана возврата в браузерную
/// таблицу упал не на самом возврате, а на двух строках обновления соседних
/// экранов —
///
/// ```
/// package:drift/drift.dart <- history_controller.dart <- refund_controller.dart
///                          <- refund_screen.dart <- setup_router.dart
///                          <- main_web.dart
/// ```
///
/// То есть контроллер, у которого своих обращений к базе не осталось ни
/// одного, всё равно тащил в браузер всю базу — за компанию с чужим экраном,
/// которого в этой сборке нет вовсе.
///
/// Счётчик разрывает эту связь по направлению: изменивший деньги **сообщает
/// о факте**, а кто на него подписан — его не касается. Экран возврата
/// больше не знает ни про смену, ни про историю.
///
/// # Почему счётчик, а не событие
///
/// Событие надо на что-то доставить, и подписчик, которого сейчас нет в
/// дереве, его пропустит. Число же читается при построении: экран смены,
/// открытый после возврата, увидит новое значение и перечитает себя без
/// всякой доставки.
///
/// # Предел, названный прямо
///
/// Это **не** замена подписке на данные. Он говорит «что-то изменилось», а
/// не «что именно», и годится ровно для того, для чего годился
/// `ref.invalidate`: заставить соседний экран перечитать себя. Настоящая
/// подписка на деньги смены — отдельная работа, и её отсутствие этой правкой
/// не чинится.
class MoneyLedgerRevision extends Notifier<int> {
  @override
  int build() => 0;

  /// Деньги изменились: возврат проведён, оплата принята, смена закрыта.
  void bump() => state = state + 1;
}

final moneyLedgerRevisionProvider = NotifierProvider<MoneyLedgerRevision, int>(
  MoneyLedgerRevision.new,
);
