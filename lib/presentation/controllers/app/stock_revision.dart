import 'package:flutter_riverpod/flutter_riverpod.dart';
import 'package:get_it/get_it.dart';

import 'package:telepos/domain/stock/stock_changes.dart';

/// «Остатки изменились» — второй счётчик ревизии, рядом с
/// `MoneyLedgerRevision` (задача 36).
///
/// # Зачем второй, если есть первый
///
/// `MoneyLedgerRevision` говорит «деньги смены изменились», и подписаны на
/// него смена и история. Путь продажи перечитывал **четыре** провайдера:
/// смену и историю счётчик денег закрыл, а каталог и остатки — нет. Им
/// «деньги изменились» — не повод: остаток двигает и инвентаризация, и
/// перемещение, где денег нет вовсе.
///
/// # Почему счётчик, а не `ref.invalidate`
///
/// Та же причина, что у первого: `ref.invalidate(catalogControllerProvider)`
/// — это **импорт** контроллера, а он тянет базу кассы. В браузере базы нет,
/// и браузерная половина шва `sale_side_effects_web.dart` поэтому была пуста:
/// после продажи с терминала остаток в выдаче поиска на экране терминала
/// оставался прежним. Счётчик разрывает связь по направлению: изменивший
/// остаток сообщает о факте, подписанный перечитывает себя.
///
/// # Кто подписан
///
/// - `CatalogNotifier`, `StockRegistryNotifier` — экраны кассы;
/// - `SaleNotifier` — выдача поиска экрана продажи, на кассе и в браузере
///   (остаток написан в каждой строке выдачи).
///
/// # Предел, который был назван прямо, — и снят пунктом 12 ревизии
/// 2026-09-19
///
/// Здесь стояло: «счётчик живёт в контейнере этого экрана; продажа,
/// проведённая другим рабочим местом, его не поднимает; ревизия по
/// проводу — отдельная работа». Эта работа сделана. Между рабочими
/// местами стоит договор `StockChanges`: на кассе его держит
/// `LocalStockChanges` (один на процесс, его поднимает
/// `LocalPaymentService` по завершении **любой** продажи — своей или
/// приехавшей с планшета), в браузере — `WtStockChanges` поверх подписки
/// `stock.revision`. Счётчик подписан на него и поднимает себя от чужого
/// события так же, как от своего.
///
/// # Почему подписка здесь, а не в экранах
///
/// Подписанных на счётчик трое (каталог, реестр остатков, выдача поиска
/// продажи), и они приходят и уходят с экранами. Подписка в каждом из них
/// означала бы три потока на одно сообщение и три места, где её можно
/// забыть; здесь она одна и живёт ровно столько, сколько живёт счётчик.
///
/// # Чего это НЕ закрывает — названо, а не умолчано
///
/// - **Вторую кассу.** Подписка идёт к своей кассе: её процесс, её база.
///   Магазин из двух касс согласуется синхронизацией (пункт 18 ревизии,
///   сегодня сломанной), и выдать эту подписку за неё нельзя ничем.
/// - **Инвентаризацию и перемещение.** Их проводят экраны самой кассы, и
///   они поднимают **этот** счётчик напрямую ([bump] ниже). До кассы как
///   процесса это не доходит, значит не доходит и до соседних рабочих
///   мест. Закрывается тем же `StockChangeSink` в тех двух местах — но
///   оба пишут остаток мимо `PaymentService`, и кто там владелец записи,
///   разобрано не было. Работа названа, а не сделана.
/// - **Возврат.** По той же причине и тем же способом.
class StockRevision extends Notifier<int> {
  @override
  int build() {
    // Развилка `isRegistered` — **законное состояние**, а не спрятанное
    // отсутствие, и вот почему: договор есть в обеих сборках продукта
    // (`service_locator.dart`, `main_web.dart`), но счётчик обязан
    // работать и без него. Он старше подписки: инвентаризация и
    // перемещение поднимают его напрямую, и контейнер, собранный без
    // провода и без базы кассы, получает ровно то поведение, что было до
    // этой правки, — свои изменения видны, чужие нет. Падение здесь
    // сломало бы экран каталога у сборки, которой подписка не нужна.
    if (GetIt.I.isRegistered<StockChanges>()) {
      final sub = GetIt.I<StockChanges>().watch().listen(
        // Номер кассы сюда не переносится: счётчик отвечает «изменилось»,
        // а не «на сколько». Приравнять его к номеру кассы значило бы
        // молча пропустить изменение, случившееся до подписки.
        (_) => bump(),
        // Обрыв провода счётчик не ломает: подписанный перечитает себя
        // при следующем своём изменении. Пустой обработчик здесь — чтобы
        // отказ не всплыл необработанным и не уронил зону.
        onError: (Object _) {},
      );
      ref.onDispose(sub.cancel);
    }
    return 0;
  }

  /// Остатки изменились: продажа проведена, инвентаризация закрыта, товар
  /// перемещён.
  void bump() => state = state + 1;
}

final stockRevisionProvider = NotifierProvider<StockRevision, int>(
  StockRevision.new,
);
