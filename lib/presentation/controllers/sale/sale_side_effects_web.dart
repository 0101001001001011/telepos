import 'package:flutter_riverpod/flutter_riverpod.dart';

import 'package:telepos/presentation/controllers/app/stock_revision.dart';

/// Браузерная половина шва — см. докстринг `sale_side_effects.dart`.
///
/// Смена, история, каталог и остатки в браузерную таблицу маршрутов не
/// переехали (`lib/app/router/setup_router.dart`), поэтому просить их
/// перечитаться некого — и импортировать их сюда нельзя: каждый тянет базу
/// кассы.
///
/// **Но пустой половина больше не бывает — задача 36.** Остаток написан в
/// каждой строке выдачи поиска экрана продажи, а экран продажи в браузере
/// есть. До задачи 36 эта половина была пуста, и после продажи с терминала
/// выдача показывала остаток, которого уже нет. Сообщение идёт счётчиком
/// (`StockRevision`): он не импортирует ни одного экрана, а подписан на него
/// тот, кто показывает остаток.
///
/// Правда о смене и о чеке живёт на кассе, и она не теряется: браузер
/// узнаёт об изменении корзины подпиской (`sale.cart`), а не тем, что
/// кто-то перечитал провайдер.

/// Смена перечиталась бы — если бы экран смены здесь был.
void refreshShiftAfterSaleStart(Ref ref) {}

/// Продажа завершена: остатки изменились.
void refreshAfterSaleCompleted(Ref ref) {
  ref.read(stockRevisionProvider.notifier).bump();
}
