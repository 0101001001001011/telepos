/// Кого экран продажи просит перечитаться после своих действий.
///
/// # Зачем шов, если это всего лишь `ref.invalidate`
///
/// До задачи 13 `sale_controller.dart` импортировал четыре чужих
/// контроллера — смену, историю, каталог, остатки — ровно ради пяти строк
/// `ref.invalidate(...)`. Каждый из четырёх импортирует базу кассы
/// напрямую — значит экран продажи тянул её **через один прыжок**, не называя ни
/// разу: прямой сторож слоёв (`test/architecture/sale_layering_test.dart`)
/// на этом зелёный, а `flutter build web` лёг бы целиком — в браузере нет
/// ни `dart:io`, ни `package:sqlite3/sqlite3.dart`.
///
/// Разделение здесь не «на всякий случай», а по существу: **на браузерном
/// терминале этих четырёх экранов нет вовсе**. Смена, история, каталог и
/// остатки в браузерную таблицу маршрутов не переехали (`setup_router.dart`),
/// и просить их перечитаться некого. Web-половина шва пуста не потому, что
/// «пока не написали», а потому, что перечитывать нечего.
///
/// # Почему шов, а не провайдер с подменой
///
/// Список провайдеров можно было бы завести значением и подменить в корне
/// (`ProviderScope(overrides: ...)`). Тогда забытая подмена в новой точке
/// входа молча выключала бы обновление соседних экранов на кассе — ровно тот
/// род дефекта, который в этом дереве уже назван «мёртвый код, выглядящий
/// живым». Условный импорт выбирает компилятор, забыть его нельзя.
///
/// Тот же приём, что у `lib/core/platform/host_process.dart` и
/// `lib/core/platform/local_file.dart`: умолчание — нативная половина, ветка
/// `dart.library.js_interop` — браузерная.
library;

export 'sale_side_effects_native.dart'
    if (dart.library.js_interop) 'sale_side_effects_web.dart';
