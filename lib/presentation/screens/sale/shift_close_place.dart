import 'package:flutter/widgets.dart';

/// Где кассир закрывает смену, перевалившую за сутки, — задача 37 плана
/// «Продажа с браузерного терминала».
///
/// # Почему это решает таблица маршрутов, а не экран
///
/// Экран продажи один на кассу и браузер, а экран смены — только у кассы:
/// открытие и закрытие смены с терминала — граница спеки. До задачи 37
/// диалог «смена открыта более 24ч» вёл кнопкой на `/shift` на обеих
/// поверхностях, и в браузерной таблице там стояла заглушка — переход,
/// который кассир мог нажать и упереться в «пока только на кассе».
///
/// Довод **обязательный** у `SaleScreen`: забыть его нельзя по сборке, и
/// каждая таблица маршрутов говорит сама, что у неё есть. Узнавать это внутри
/// экрана (по `HostCapabilities` или по наличию маршрута) значило бы держать
/// в исходнике экрана переход, которого на одной из поверхностей нет.
sealed class ShiftClosePlace {
  const ShiftClosePlace();
}

/// Здесь: у этой таблицы маршрутов есть рабочий экран смены, и [open] ведёт
/// на него.
final class ShiftCloseHere extends ShiftClosePlace {
  const ShiftCloseHere(this.open);

  final void Function(BuildContext context) open;
}

/// На кассе: на этой поверхности экрана смены нет (браузерный терминал), и
/// диалог говорит словами, где закрыть смену, без кнопки перехода.
final class ShiftCloseAtTill extends ShiftClosePlace {
  const ShiftCloseAtTill();
}
