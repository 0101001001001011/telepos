import 'package:get_it/get_it.dart';

import 'package:telepos/domain/services/currency_service.dart';

/// Знак валюты ЭТОЙ кассы — одним местом на всю презентацию.
///
/// # Что измерено 2026-09-22
///
/// В `lib/presentation` было 52 зашитых `₸`: отчёты, история смен, калькуляция
/// блюда, ценники, предпросмотр чека. На американской кассе выручка за день
/// показывалась в тенге — на экране, по которому владелец судит о деньгах.
///
/// Рядом жил второй источник — `CurrencySymbols` в `money_field.dart`: семь
/// валют против двадцати одной в перечислении, и «с» вместо «сом» у Киргизии.
/// Его никто не звал ни разу, и он снят: два списка знаков валют разошлись бы
/// на первой же стране, добавленной в один из них.
///
/// # Почему без развилки `isRegistered`
///
/// Экраны кассовые: `CurrencyService` там зарегистрирован точкой входа. Пустой
/// знак — не «валюты нет», а «мы не спросили», и на экране он выглядел бы
/// оплошностью вёрстки, а не отсутствием настройки. Сборки, где службы нет,
/// у этих экранов не существует; пусть падает проба, а не молчит касса.
String tillCurrencySymbol() => GetIt.I<CurrencyService>().symbol;

/// Код валюты этой кассы (`KZT`, `USD`, …) — для подписей у полей ввода.
String tillCurrencyCode() => GetIt.I<CurrencyService>().code;
