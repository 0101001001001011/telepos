/// Как налог относится к цене — и почему это не одна цифра ставки.
///
/// # Чем это оплачено
///
/// До 2026-09-21 налог в продукте был один: **включённый в цену**. Считался
/// он единственным способом — `vatFromGross`, то есть извлечением из брутто,
/// и другого пути в коде не существовало. Для СНГ и ЕС это верно, для США —
/// нет: там налог **добавляется** к подытогу, на ценнике его не показывают,
/// а в чеке обязаны.
///
/// Найдено при подготовке видеоинструкции для США: касса, настроенная на
/// доллар, печатала чек **без единой строки налога** (`_addVatLines`
/// начинается с `if (!isVatPayer) return;`, а у США ставка ноль) и с
/// баннером «NON-FISCAL RECEIPT», которого в стране без фискализации быть
/// не должно вовсе.
///
/// # Почему уклад, а не флаг
///
/// «Налог сверху или внутри» — не единственное различие, и флаг `bool
/// taxIsExclusive` закрыл бы только его. Уклад — место, куда кладутся и
/// остальные различия по мере того, как они называются: обязателен ли
/// фискальный документ, показывать ли цену с налогом на ценнике, как
/// округляется наличная сдача. Заказчик назвал это прямо 2026-09-21: «у
/// Европы и США вообще другой учёт, не только налоговый, но и операционный».
///
/// Здесь пока три значения — ровно те, что измерены. Класть сюда режимы,
/// которых никто не проверял, значит выдать догадку за поддержку страны.
library;

enum TaxTreatment {
  /// Налог включён в цену: ценник и итог — уже с налогом, в чеке он
  /// выделяется извлечением из брутто. СНГ, Евросоюз.
  inclusive,

  /// Налог добавляется к подытогу: ценник без налога, в чеке отдельной
  /// строкой между подытогом и итогом. США, Канада.
  exclusive,

  /// Налога нет. Не то же самое, что ставка ноль при включённом налоге:
  /// там строка в чеке всё равно нужна, здесь её быть не должно.
  none,
}
