/// Государственная система страны, с которой умеет работать касса.
///
/// # Зачем перечисление, а не «флаг про Казахстан»
///
/// До 2026-09-22 четыре казахстанские системы — ЭСФ, СНТ, ЕСУТД и ИС МПТ —
/// стояли в настройках на кассе ЛЮБОЙ страны, и пятой шла вкладка отчётов
/// «Tax / KZ» с формами 910 и 300. Владелец магазина в США, Германии или
/// Корее видел пять входов в казахстанский документооборот и не мог понять,
/// что это и почему он этого не заполняет.
///
/// Страна у кассы была с самого начала — её просто никто здесь не
/// спрашивал.
///
/// # Почему набор у страны, а не сравнение с `CountryCode.kzt`
///
/// Сравнение со страной читается как «это казахстанская особенность» и
/// закрывает дорогу остальным: у России есть «Честный знак» и УПД, у ЕС —
/// электронные счета-фактуры по директиве, у Турции — e-Fatura. Мы их не
/// реализуем, и объявлять их было бы ложью; но когда дойдёт до них, страна
/// получит свой набор ЗДЕСЬ, а экраны менять не придётся.
///
/// # Чего перечисление НЕ означает
///
/// Не «страна требует», а «касса умеет». Пустой набор у Германии говорит о
/// нас, а не о немецком законе: электронная счёт-фактура там существует, и
/// её отсутствие здесь — наш предел, а не свойство страны.
library;

enum NationalSystem {
  /// Электронная счёт-фактура. В Казахстане — ЭСФ (ИС ЭСФ КГД).
  electronicInvoice,

  /// Сопроводительная накладная на товар. В Казахстане — СНТ.
  goodsNote,

  /// Электронная накладная на перевозку. В Казахстане — ЕСУТД.
  transportWaybill,

  /// Маркировка товаров. В Казахстане — ИС МПТ (ismet.kz / Tañba).
  productMarking,

  /// Отчётные формы налоговой. В Казахстане — 910 и 300.
  taxForms,
}
