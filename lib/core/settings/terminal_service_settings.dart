import 'package:shared_preferences/shared_preferences.dart';

import 'package:telepos/core/net/listen_scope.dart';

/// Ключ, под которым решение оператора лежит в настройках **этой машины**.
///
/// Одно место на писателя (`terminal_service_settings_screen.dart`) и на
/// читателя (`lib/main.dart`), по образцу [kCustomerScreenPrefsKey]: пока
/// строка была бы написана в двух файлах, опечатка в одном из них выглядела
/// бы как «настройка не сохраняется», а не как опечатка.
const kTerminalServicePrefsKey = 'serve_browser_terminals';

/// Обслуживает ли эта касса браузерные терминалы — и, следовательно, открывает
/// ли она порт в сеть магазина.
///
/// `docs/system-architecture.md`, И154 и И155: сервер поднимается при каждом
/// запуске (иначе корень магазина не выписывался бы, и установщику нечего было
/// бы положить в доверенные), а от решения владельца зависит только область
/// прослушивания — касса без поручения слушает петлю и не объявляет себя.
///
/// # Почему это решение оператора, а не флаг сборки и не роль запуска
///
/// До 2026-08-06 здесь стояло `const bool.fromEnvironment('TELEPOS_API')`, и
/// эта величина не задавалась **нигде**: ни в сборке кассы, ни в CI, ни в
/// установщике. То есть локальный сервер не поднимался ни у одного заказчика,
/// а вместе с ним не выписывался и корень магазина — он создаётся при первом
/// подъёме хранилища сертификатов. Установщик, умеющий поставить корень в
/// доверенные, находил пустой каталог (см. `docs/internal/windows-installer.md`,
/// «Чего ещё нет»).
///
/// Заменить условие на «всегда» было нельзя: сервер открывает порт, а
/// `docs/system-architecture.md`, раздел 16, говорит прямо — «Новая установка
/// не открывает наружу ничего. Каждая открытая возможность — **сознательное
/// включение владельцем**, а не состояние из коробки». То же записано и на
/// самом [ListenScope]: касса без терминалов не обязана быть достижимой с
/// чужой машины.
///
/// Роль запуска (`--server`, `--kiosk`, см. `resolveHostCapabilities`) этим
/// решением быть не может по двум причинам. Первая — смысл: `--server` означает
/// «данные есть, устройств нет» (`HostCapabilities.server`), а обычная касса с
/// планшетом в зале — это касса с устройствами, то есть совсем другая роль по
/// той же оси. Вторая — долговечность: роль живёт в аргументах ярлыка, и
/// пережить переустановку ей нечем, тогда как решение «у меня есть планшет»
/// принимается один раз и обязано пережить и перезапуск, и обновление.
///
/// # Почему в настройках машины, а не в базе магазина
///
/// База уезжает в резервную копию и приезжает на другую машину. Решение о том,
/// какие сокеты открывает **этот** компьютер, ехать вместе с ней не должно:
/// восстановление копии с кассы, обслуживавшей планшеты, молча открыло бы порт
/// на машине, у которой планшетов нет. Тот же довод, по которому здесь же
/// живёт выбор монитора для экрана покупателя (`CustomerScreenChoice`).
class TerminalServiceChoice {
  const TerminalServiceChoice({required this.enabled});

  /// Умолчание для новой установки и для всякого неразобранного значения.
  ///
  /// Выключено: испорченная настройка не имеет права открыть порт наружу —
  /// ровно тот же довод, по которому [CustomerScreenChoice.disabled] не
  /// открывает окно на живой кассе (И30).
  static const disabled = TerminalServiceChoice(enabled: false);

  final bool enabled;

  /// Область прослушивания, которая из этого решения следует.
  ///
  /// Пара «решение → область» живёт здесь, а не в `main.dart`, потому что её
  /// нужно проверить, а `main.dart` под тестом не запускается: там окно,
  /// граф DI и настоящие сокеты.
  ListenScope get scope =>
      enabled ? ListenScope.everywhere : ListenScope.loopback;

  /// Решение этого запуска: настройка оператора, но `--headless` сильнее её.
  ///
  /// # Почему касса без окна обслуживает терминалы всегда
  ///
  /// `--headless` — это заявление на входе (И10): «интерфейс этого процесса не
  /// здесь». Такая касса не рисует ничего и не может: окна у неё нет вовсе.
  /// Оставить её на петле значило бы поставить кассу, до которой не дойдёт ни
  /// один терминал, включая тот единственный, ради которого её и запустили без
  /// окна. Включить её потом тоже некому: экран настройки живёт в десктопном
  /// маршрутизаторе, а у процесса без окна его не существует.
  ///
  /// Правило «сознательное включение владельцем» это не нарушает, а исполняет
  /// другим способом: флаг `--headless` пишет тот, кто ставит службу, и пишет
  /// его ровно затем, чтобы кассу обслуживали снаружи. Из коробки его нет ни у
  /// одной установки — обычный ярлык кассы запускается без аргументов.
  static TerminalServiceChoice resolve(
    SharedPreferences prefs, {
    required bool headless,
  }) => headless ? const TerminalServiceChoice(enabled: true) : read(prefs);

  /// Читает то, что последним записал экран настройки терминалов.
  ///
  /// Хранится обычным `bool`, а не JSON-объектом: у решения ровно одно поле, и
  /// заворачивать его в документ значило бы завести разбор, который может
  /// сломаться, вокруг величины, у которой ломаться нечему.
  static TerminalServiceChoice read(SharedPreferences prefs) {
    try {
      return TerminalServiceChoice(
        enabled: prefs.getBool(kTerminalServicePrefsKey) ?? false,
      );
    } catch (_) {
      // `getBool` бросает, если под ключом лежит значение другого типа —
      // например, строка от более старой или более новой версии. Открывать
      // порт по неразобранной настройке нельзя, поэтому здесь отказ приходит
      // умолчанием, а не исключением.
      return disabled;
    }
  }

  /// Записывает решение оператора.
  ///
  /// Здесь же, а не в экране: читатель и писатель одного ключа, разъехавшиеся
  /// по файлам, — это два разных представления одной величины, и расходятся
  /// они молча.
  static Future<void> write(SharedPreferences prefs, {required bool enabled}) =>
      prefs.setBool(kTerminalServicePrefsKey, enabled);
}
