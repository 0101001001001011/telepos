import 'package:shared_preferences/shared_preferences.dart';

/// Приборы, которые касса умеет изобразить сама.
///
/// Перечисление, а не одно булево: следом за принтером идут весы и дисплей
/// покупателя (`docs/internal/superpowers/plans/2026-09-19-builtin-emulators.md`,
/// порядок), и добавление второго прибора не должно переписывать ни хранение,
/// ни экран.
enum BuiltinEmulatorKind {
  /// Чековый принтер ESC/POS. Денежный ящик — здесь же: команда `ESC p`
  /// приходит тем же сокетом, отдельного прибора у него нет.
  receiptPrinter,

  /// Весы. Адресуются путём порта, а не сокетом; встроенный эмулятор садится
  /// на обычный файл — см. `serial_port_path.dart`.
  scale,

  /// Дисплей покупателя. Тем же способом, что весы.
  customerDisplay,

  /// Фискальный оператор (WebKassa). Сокет, как у принтера, — но с запретом,
  /// которого нет ни у одного прибора: **включается только пока касса не
  /// боевая**.
  ///
  /// Довод не в осторожности, а в разнице последствий. Эмулятор железа в
  /// худшем случае отправляет чек в окно вместо бумаги — это видно в ту же
  /// секунду. Касса, «фискализующая» в подделку, выглядит работающей и
  /// выдаёт покупателю бумажку без документа: беда обнаруживается через
  /// недели, у налогового органа. Решение заказчика 2026-09-19 — запрет по
  /// **данным**, а не по намерению; проверка и её довод живут на
  /// `BuiltinEmulatorHost.refusalFor`.
  fiscalOperator,

  /// Провайдер оплаты по QR/СБП. Сокетом, как принтер, — только HTTP.
  ///
  /// Его «привязка» живёт **не** в `device_bindings`: у провайдера свой адрес
  /// (`QrProviderSettings.baseUrl`, строка `qr_provider_configs`), и вписывать
  /// его надо туда. Это не исключение из правила «привязка — единственный
  /// источник правды», а то же правило: у провайдера источник просто другой,
  /// и второго рядом мы не заводим.
  qrProvider,
}

/// Ключ настройки **этой машины** для одного прибора.
///
/// Одно место на писателя и на читателя — по образцу
/// [kTerminalServicePrefsKey]: пока строка написана в двух файлах, опечатка в
/// одном выглядит как «настройка не сохраняется», а не как опечатка.
String builtinEmulatorPrefsKey(BuiltinEmulatorKind kind) =>
    'builtin_emulator_${kind.name}';

/// Какие встроенные эмуляторы включил оператор на **этой** машине.
///
/// # Почему это не флаг сборки, в отличие от [kEmulatorsEnabled]
///
/// Флаг сборки существует ради того, чтобы из магазинной сборки **выпали
/// подставные классы**: виртуальные профили устройств, `EmulatedSpoolerPrinter`
/// и `EmulatedScanner`. Они опасны именно тем, что встают на место настоящего
/// драйвера, и «печать прошла» на них перестаёт что-либо значить. Это измерено
/// и записано (`device_catalog_module.dart`, `docs/internal/testing-notes.md`).
///
/// Встроенный эмулятор — другой зверь, и риск у него другой. Он не подменяет
/// ни одного класса: он открывает **настоящий серверный сокет**, а касса
/// попадает на него, только если этот адрес вписан в привязку прибора руками.
/// Убери сокет — и касса честно скажет «принтер не отвечает». Поэтому он едет
/// в обычной сборке, и это прямое требование заказчика 2026-09-19: «эмулятор
/// должен быть встроенный, сразу в нашем приложении, а то это ещё что-то
/// ставить надо будет; у нас всё в комплексе — и для диагностики, и для
/// проверки шаблона чека при настройке».
///
/// Из этого следует и запрет: **`kEmulatorsEnabled` этой настройкой не
/// заменяется и в неё не сливается**. Ветка `if (kEmulatorsEnabled)` обязана
/// остаться константной, иначе подставные классы вернутся в магазинную сборку
/// через чёрный ход. Сторож — `builtin_emulator_guards_test.dart`.
///
/// # Почему в настройках машины, а не в базе магазина
///
/// База уезжает в резервную копию и приезжает на другую машину. Решение о том,
/// какие сокеты открывает **этот** компьютер, ехать вместе с ней не должно —
/// тот же довод, по которому здесь живут [TerminalServiceChoice] и выбор
/// монитора для экрана покупателя.
class BuiltinEmulatorChoice {
  const BuiltinEmulatorChoice(this.enabled);

  /// Умолчание новой установки и всякого неразобранного значения: ничего не
  /// поднято. Испорченная настройка не имеет права открыть сокет.
  static const none = BuiltinEmulatorChoice(<BuiltinEmulatorKind>{});

  final Set<BuiltinEmulatorKind> enabled;

  bool isEnabled(BuiltinEmulatorKind kind) => enabled.contains(kind);

  /// Читает решение оператора по всем приборам сразу.
  ///
  /// Неразобранное значение под ключом одного прибора гасит **этот** прибор, а
  /// не всю настройку: испорченная запись про весы не имеет права молча
  /// погасить принтер, на который уже смотрит привязка.
  static BuiltinEmulatorChoice read(SharedPreferences prefs) {
    final on = <BuiltinEmulatorKind>{};
    for (final kind in BuiltinEmulatorKind.values) {
      try {
        if (prefs.getBool(builtinEmulatorPrefsKey(kind)) ?? false) {
          on.add(kind);
        }
      } catch (_) {
        // `getBool` бросает, если под ключом лежит значение другого типа —
        // например, строка от другой версии. Отказ приходит умолчанием.
      }
    }
    return BuiltinEmulatorChoice(on);
  }

  static Future<void> write(
    SharedPreferences prefs,
    BuiltinEmulatorKind kind, {
    required bool enabled,
  }) => prefs.setBool(builtinEmulatorPrefsKey(kind), enabled);
}
