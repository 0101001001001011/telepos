/// Язык кассы — держатель выбора, и только он.
///
/// # Почему здесь, а не рядом со службой печати
///
/// Первая редакция положила держатель в `lib/data/services/`, и
/// `locale_provider.dart` из `lib/core` стал импортировать слой данных.
/// Сторожа поймали это сразу и в двух местах: `layering_test` — нарушением
/// И5, `browser_routes_test` — тем, что экран продажи потянул слой данных в
/// браузерную сборку по цепочке из шести импортов. Второе хуже первого:
/// собранная страница не собралась бы вовсе.
///
/// Здесь лежит только выбор языка — `AppLocale`, то есть ядро. Словарь по
/// нему строит слой данных (`receipt_strings.dart`), и направление
/// зависимости получается правильным: данные знают о ядре, ядро о данных —
/// нет.
library;

import 'app_locale.dart';

/// Язык, на котором касса говорит с человеком вне экрана.
///
/// Это чек, X- и Z-отчёт, сертификат — и **записи, которые касса заводит
/// сама**: имя счёта обязательств, строка расходника в заказ-наряде. У
/// экрана язык берётся из `AppLocalizations.of(context)`; здесь его взять
/// неоткуда, а слово всё равно увидит человек.
///
/// Прежде класс назывался `TillLanguage` — по первому и тогда
/// единственному применению. Имя перестало быть правдой, когда через него
/// пошли записи, которые никто не печатает.
///
/// До 2026-09-21 печать языка не знала вовсе: каждая строка на бумаге была
/// русским литералом, независимо от настройки кассы. Нашлось на съёмке
/// видеоинструкции — вкладка диагностики показывает чек текстом, и в
/// английском ролике он оказался русским.
///
/// Умолчание русское намеренно: касса, которую не обновляли и не
/// перенастраивали, печатает ровно так же, как печатала. Менять язык
/// бумаги молча нельзя — его видит покупатель, а не только кассир.
class TillLanguage {
  TillLanguage._();

  static AppLocale current = AppLocale.ru;
}
