/// Как ЭТА КАССА пишет дату и числа — держатель выбора, и только он.
///
/// # Что измерено 2026-09-22
///
/// Чек всегда печатал `ДД.ММ.ГГГГ` — условие СНГ. Для американца
/// «05.09.2026» это девятое мая, а не пятое сентября: дата не просто
/// непривычна, она читается ДРУГИМ днём, и на чеке нет ничего, что сказало
/// бы, какое из двух прочтений верное.
///
/// Разделители чисел при этом были объявлены дважды — у страны и у валюты,
/// сорок шесть значений, — и не читались НИ ОДНИМ местом продукта.
/// Дубликат у валюты снят: как писать число — свойство страны, а не денег.
///
/// # Почему не «печатные» условия
///
/// Первая редакция звалась `PrintConventions` и служила только бумаге. В
/// тот же день пробный проход главы 7 показал `Opened: 22.09.2026` на
/// АМЕРИКАНСКОЙ кассе: экраны форматировали дату сами — восемнадцатью
/// собственными форматировщиками в двадцати девяти файлах, и все в порядке
/// СНГ. Бумага и экран обязаны писать дату одинаково, иначе кассир сверяет
/// чек с экраном и видит разные числа.
///
/// # Почему здесь, а не рядом со службой печати
///
/// Тот же довод, что у [TillLanguage] по соседству: `lib/core` не имеет
/// права знать слой данных, иначе браузерная сборка потянет базу по цепочке
/// импортов и не соберётся. Здесь лежит только ВЫБОР.
///
/// # Умолчание — прежнее поведение
///
/// Касса, которую не обновляли и не перенастраивали, пишет ровно так же,
/// как писала. Менять вид документа молча нельзя.
library;

class TillConventions {
  const TillConventions({
    required this.dateFormat,
    required this.decimalSeparator,
    required this.thousandSeparator,
  });

  /// Шаблон даты: `d`, `M`, `y` — день, месяц, год.
  ///
  /// Не `intl`: чек собирается слоем данных, который в браузерной сборке
  /// недоступен, а шаблон нужен строкой и здесь, в ядре.
  final String dateFormat;

  final String decimalSeparator;
  final String thousandSeparator;

  /// Условия кассы. Ставятся при загрузке страны на запуске.
  static TillConventions current = const TillConventions(
    dateFormat: 'dd.MM.yyyy',
    decimalSeparator: ',',
    thousandSeparator: ' ',
  );

  /// Дата по шаблону этой кассы.
  String formatDate(DateTime dt) {
    final d = dt.day.toString().padLeft(2, '0');
    final m = dt.month.toString().padLeft(2, '0');
    final y = dt.year.toString();
    return dateFormat
        .replaceAll('yyyy', y)
        .replaceAll('dd', d)
        .replaceAll('MM', m)
        // Однобуквенные — после двухбуквенных: иначе `d` съел бы первую
        // букву `dd`, и шаблон рассыпался бы.
        .replaceAll('d', dt.day.toString())
        .replaceAll('M', dt.month.toString());
  }

  /// Дата и время: время везде одинаково, разнится только дата.
  String formatDateTime(DateTime dt) {
    final h = dt.hour.toString().padLeft(2, '0');
    final min = dt.minute.toString().padLeft(2, '0');
    return '${formatDate(dt)} $h:$min';
  }
}
