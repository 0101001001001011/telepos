import 'package:flutter/material.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';
import 'package:telepos/core/locale/locale_provider.dart';

/// Выбор темы: светлая, тёмная или как в системе.
///
/// Заведён 2026-08-04, когда выяснилось, что `AppTheme.dark` написана целиком —
/// со своими семантическими цветами — и **не подключена ничем**:
/// `telepos_app.dart` жёстко ставил `theme: AppTheme.light`, а `darkTheme` и
/// `themeMode` отсутствовали вовсе. Тёмная тема была мёртвым кодом, выглядящим
/// живым.
///
/// # Умолчание — светлая, а не системная (2026-08-27)
///
/// Оживление мёртвого кода поставило умолчанием `ThemeMode.system`, и это
/// вышло за пределы того, что оживляли. Согласованная спека называется
/// «**Светлая** тема в стиле Telegram» (`docs/internal/superpowers/specs/
/// 2026-08-03-telegram-light-redesign-design.md`): по ней рисовали экраны, по
/// ней меряли контрасты, её показывали заказчику. Тёмную по этой спеке не
/// рисовал никто.
///
/// Следствие было измерено на собранной кассе 2026-08-27: на машине с тёмной
/// ОС продукт открывался тёмным, и в нём имя выбранного кассира давало
/// контраст **1.12:1** (белое по светло-голубой плашке-константе), а названия
/// плиток настроек — **1.35:1**. То есть системная тема показывала заказчику
/// то, чего в продукте не проектировали.
///
/// Второе, что это вскрыло: **переключателя темы в интерфейсе нет вовсе** —
/// `setMode` не вызывается ни из одного экрана (проверено поиском по `lib/`).
/// Значит «как в системе» было не выбором пользователя, а единственным
/// способом получить тёмную тему, причём случайным.
///
/// Поэтому отсутствие записи означает теперь **светлую**, а не системную.
/// Тёмная и системная остаются достижимы значением — код готов к
/// переключателю, когда его заведут, — но продукт по умолчанию выглядит так,
/// как согласовано.
///
/// Устроен по образцу [localeProvider]: тот же способ хранения, та же
/// нечувствительность к мусору в хранилище. Одинаковые вещи должны выглядеть
/// одинаково — иначе следующий будет гадать, чем они отличаются.
const _key = 'theme_mode';

final themeModeProvider = NotifierProvider<ThemeModeNotifier, ThemeMode>(
  ThemeModeNotifier.new,
);

class ThemeModeNotifier extends Notifier<ThemeMode> {
  @override
  ThemeMode build() {
    final prefs = ref.watch(sharedPreferencesProvider);
    return _parse(prefs.getString(_key));
  }

  Future<void> setMode(ThemeMode mode) async {
    final prefs = ref.read(sharedPreferencesProvider);

    // Системная пишется ИМЕНЕМ, а не отсутствием записи.
    //
    // До 2026-08-27 было наоборот: отсутствие означало системную. Приём был
    // верен ровно до того, как выяснилось, что умолчание продукта — светлая
    // (см. докстринг выше): «не выбирал» и «выбрал системную» стали разными
    // состояниями, и различить их отсутствием записи больше нечем.
    await prefs.setString(_key, mode.name);

    state = mode;
  }

  /// Неизвестное имя и отсутствие записи означают **светлую** — умолчание
  /// продукта.
  ///
  /// В хранилище может лежать что угодно — от прошлой версии, от чужой руки.
  /// Отказ приходит значением (И144): касса, не открывшая смену из-за строки
  /// в настройках, — цена, несоизмеримая с поводом. Мусор поэтому не роняет
  /// приложение и не выдумывает тёмную, а даёт согласованный вид.
  static ThemeMode _parse(String? raw) {
    return switch (raw) {
      'light' => ThemeMode.light,
      'dark' => ThemeMode.dark,
      'system' => ThemeMode.system,
      _ => ThemeMode.light,
    };
  }
}
