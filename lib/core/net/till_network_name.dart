import 'dart:io';

/// Как эта машина называет себя в сети магазина.
///
/// Берётся из имени хоста, а не из настройки, потому что имя уже есть:
/// `till-3.local` разрешается в машину по имени `till-3`, и вторая, отдельно
/// настраиваемая строка была бы вторым местом, где можно ошибиться. Кто
/// переименовывает кассу — переименовывает машину.
///
/// Приводится к допустимому виду, потому что операционная система разрешает в
/// имени хоста что угодно — пробелы, кириллицу, подчёркивания, — а метка DNS
/// не разрешает. Пустой или непригодный результат заменяется постоянным
/// именем, а не пустотой: с пустой меткой сертификат не выписался бы вовсе и
/// утащил бы за собой страницу.
///
/// # Почему это здесь, а не в `main.dart`
///
/// Значение спрашивают трое: подъём кассы (лист, объявление mDNS, имя в
/// документе), стенд провода и **экран настройки терминалов** — оператору
/// показывают адрес, который он наберёт на планшете. Пока функция жила в
/// `main.dart`, третьему пришлось бы импортировать точку входа приложения из
/// слоя представления, то есть протащить в экран `dart:io`, весь граф DI и
/// запуск сокетов ради одной строки.
String tillNetworkName() {
  final raw = Platform.localHostname.toLowerCase().split('.').first;
  final cleaned = raw
      .replaceAll(RegExp('[^a-z0-9-]'), '-')
      .replaceAll(RegExp('-+'), '-')
      .replaceAll(RegExp(r'^-|-$'), '');
  return cleaned.isEmpty ? 'telepos-till' : cleaned;
}
