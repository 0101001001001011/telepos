import 'dart:io';

/// «Этот адрес ведёт в тот же самый компьютер».
///
/// # Зачем отдельный файл, а не выражение по месту
///
/// Пометка «за этим портом эмулятор» определяется **адресом**, а не состоянием
/// выключателя: касса, направленная на эмулятор, запущенный руками из
/// командной строки, ничем не отличается от кассы со включённым встроенным — и
/// обязана быть помечена так же (`2026-09-19-hardware-diagnostics.md`,
/// поправка о пометке). Значит один и тот же вопрос задаётся из нескольких
/// мест: с экрана диагностики, с экрана настроек эмуляторов, по каждому
/// прибору. Написанный по месту, он расходится — и расходится молча, потому
/// что «плашка не зажглась» выглядит как исправная касса.
///
/// # Петля — это не одна строка
///
/// `127.0.0.1` пишет наш экран настроек, `localhost` пишут руками, `::1` —
/// система, а весь `127.0.0.0/8` отвечает тот же стек. Все они ведут в один и
/// тот же процесс на этой машине.
///
/// # Чего это НЕ доказывает
///
/// **Что за портом действительно эмулятор.** Доказывается ровно обратное и
/// более слабое: собеседник живёт на этом же компьютере. Настоящий прибор,
/// подключённый через локальный мост или туннель, будет помечен так же — и это
/// сознательный перекос в сторону лишней пометки: не назвать эмулятор
/// эмулятором дороже, чем назвать им честный мост.
///
/// Обратное тоже верно: адрес **вне** петли ничего не говорит о том, что
/// собеседник настоящий. Эмулятор, поднятый на соседней машине с `0.0.0.0`,
/// этой проверкой не ловится вовсе.
bool isLoopbackHost(String address) {
  final host = address.trim();
  if (host.isEmpty) return false;
  if (host.toLowerCase() == 'localhost') return true;
  // Скобки адреса IPv6 из URL: `[::1]`.
  final bare = host.startsWith('[') && host.endsWith(']')
      ? host.substring(1, host.length - 1)
      : host;
  return InternetAddress.tryParse(bare)?.isLoopback ?? false;
}

/// То же про ссылку целиком: `http://127.0.0.1:8890` — петля.
///
/// Неразобранная ссылка — **не** петля: строка, которую не понял разборщик
/// URI, не понята и кассой, и объявлять её местной значило бы угадывать.
bool isLoopbackUrl(String url) {
  final uri = Uri.tryParse(url.trim());
  if (uri == null) return false;
  final host = uri.host;
  // `Uri.host` пуст у строки без схемы (`127.0.0.1:8890` разбирается как
  // схема `127.0.0.1`). Такой адрес спрашиваем как голый хост.
  return isLoopbackHost(host.isEmpty ? url : host);
}
