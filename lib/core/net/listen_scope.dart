/// Насколько широко слушает касса — и, главное, на каких семействах адресов.
///
/// # Почему это перечисление, а не строка адреса
///
/// Строка `'0.0.0.0'` называет одно семейство, и это оказалось дефектом, а не
/// мелочью. Измерено 2026-08-06 на Windows 11: `localhost` и имя машины
/// разрешаются **сначала в IPv6** — `desktop-n89srfh.local` даёт `fe80::…`
/// первым адресом, а `192.168.1.210` четвёртым. Слушатель, поднятый только на
/// IPv4, для браузера при этом просто молчит: Chrome сообщал
/// `QUIC_NETWORK_IDLE_TIMEOUT` с `num_undecryptable_packets: 0` — то есть слал
/// и не получил ни одного пакета в ответ.
///
/// Дефект был парным. Слушатель QUIC починили — перестала открываться сама
/// страница: `ApiServer` слушал так же узко, и браузер отдавал `ERR_FAILED`.
///
/// **`curl` этого не показывает.** В том же состоянии он отвечает 200 по всем
/// адресам, потому что выбирает семейство иначе, чем браузер. Проверкой
/// работоспособности терминала он не является — только браузер.
///
/// # Почему намерение, а не адрес
///
/// «Петля» и «все адреса» — это решение о безопасности: касса без терминалов
/// не обязана открывать порт наружу, и молчаливое расширение здесь хуже, чем
/// неудобство. А вот каким сокетам это решение соответствует — величина не
/// одна и не общая: у `dart:io` это `InternetAddress`, у `rk_quic` — строка
/// `"адрес:порт"`, и число сокетов у [loopback] и [everywhere] тоже разное
/// (см. ниже). Записанный адресом выбор смешивал бы намерение с его
/// исполнением, и именно на этом смешении оба слушателя и оказались
/// однобокими.
enum ListenScope {
  /// Обе петли — `127.0.0.1` и `::1` — и больше ничего.
  ///
  /// Порт в сеть не открывается: касса, не ждущая терминалов, не должна быть
  /// достижима с чужой машины.
  ///
  /// **Здесь сокетов два, и одним не обойтись.** Измерено: слушатель на `::1`
  /// не принимает соединение на `127.0.0.1`. Двойной стек одного сокета
  /// работает через адреса вида `::ffff:127.0.0.1`, а `::1` — это другой
  /// адрес, а не подсеть, покрывающая IPv4. Слушать одну петлю из двух значило
  /// бы воспроизвести ровно тот дефект, ради которого это перечисление
  /// появилось, — только внутри одной машины: на Windows `localhost` — это
  /// `::1`, а на многих Linux `/etc/hosts` ставит первым `127.0.0.1`.
  loopback,

  /// Все адреса обоих семейств: `::` с выключенным `IPV6_V6ONLY`, что
  /// покрывает и `0.0.0.0`.
  ///
  /// **Здесь сокет один.** Измерено на Windows 11: `HttpServer.bind` на `::`
  /// (Dart выставляет `v6Only: false` по умолчанию) принимает соединения и по
  /// `::1`, и по `127.0.0.1`.
  ///
  /// Сторожит этот сокет не адрес, а сертификат: и страницу, и сессию
  /// WebTransport открывает только тот, кому лист этой кассы предъявлен и
  /// принят.
  everywhere,
}
